// ФОРМА паспорта — то, что добавляется СВЕРХУ анатомии (`PWEB-2`, `PWEB-24`, `PWEB-34`, страница
// раздела «Паспорт компонента»).
//
// ## Дом переехал (`PWEB-110`, пересматривает `PWEB-26`)
//
// Форма жила в ките (`packages/ui`) с самого первого паспорта — не привилегией, а исторической
// случайностью: первый паспорт был выписан там. `PWEB-26` заранее назвал момент переезда — второй
// поставщик паспортов — и оставил критерий: что из формы общее для ЛЮБОГО поставщика, а что
// оказалось особенностью КИТА. Второе в переезд не идёт.
//
// Проверено по всей форме: НИ ОДНА строка здесь не зависит от Ark, Zag или от того, какие
// компоненты есть у конкретного кита. Особенность кита — это `PASSPORTS` (реестр: какие
// компоненты есть у ЭТОГО кита) и `passportOf` (читатель реестра); оба остались в `packages/ui`.
// Здесь — форма и решающие функции, общие для любого поставщика.
//
// ## Паспорт режется на два среза (`PWEB-115`)
//
// Найдено на настоящей сборке `apps/reference`: приложение, которое НИКОГДА не читает сборку и
// `means`, всё равно везёт их текст в браузер целиком — потому что паспорт был ОДНИМ
// неразличимым объектом, а `generateSkinCss` брала его как есть. Это техническая проблема
// (неразличимый объект), а не концептуальная («сборке не место в паспорте»): `RenderTree` и
// `baseAssemblyOf` (то, что сборку действительно читает) зовёт только редакторский код, никогда —
// приложение.
//
// Решение не обещание, а ГРАНИЦА МОДУЛЕЙ. Проверено экспериментом на настоящем Rolldown (Vite 8):
// сузить один и тот же ТИП мало — бандлер не выкидывает неиспользуемое ПОЛЕ внутри объекта,
// который сам остаётся живым через использованную привязку. Выкидывает он неиспользуемый
// ЭКСПОРТ — отдельную привязку верхнего уровня, помеченную `/*@__PURE__*/` как не имеющую
// побочных эффектов. Значит срез должен разойтись на ДВЕ функции с ДВУМЯ отдельными возвращаемыми
// значениями, а не на два поля одного:
//
//  • **срез рантайма** — этот файл. Ровно то, что читают `generateSkinCss`/`checkOutfit`/
//    `assemble`: анатомия, состояния и их признак, ось вариаций и её признак, настройки и их
//    признак и зависимость, переменные (`name`/`setBy`, без `means`);
//  • **срез редактора** — `passport-editor.ts` (подпуть `./editor`). Всё, что читает только
//    человек или редакторская механика: `means` целиком, род (`genus`), группа (`group`),
//    пакет (`package`), правило вложенности (`accepts`) и СБОРКИ — теперь их СКОЛЬКО УГОДНО, а не
//    одна.
//
// Объявляющий вызывает ОБЕ функции, но экспортирует их РАЗНЫМИ привязками, и вторую — с
// `/*@__PURE__*/` (разбор — в шапке `passport-editor.ts`). Тогда тот, кто импортирует только
// паспорт (приложение), не тянет за собой редакторскую привязку вовсе — и бандлер вправе её
// выбросить, потому что она НИЧЕМ не используется, а не потому, что кто-то пообещал её не трогать.
//
// ## Ядро паспорта не наше и не переписывается
//
// Части и адреса объявляет `@zag-js/anatomy` — самостоятельный пакет, приезжающий вместе с Ark
// UI. Одно объявление порождает ОБЕ стороны обещания сразу: `attrs`, которые кит ставит на узел,
// и `selector`, которым цепляется скин. Разъехаться им негде по построению, а не по
// договорённости, — ради этого свойства библиотека и взята.
//
// Своей формы паспорта здесь нет и заводиться не должна: скин и редактор не имеют права
// различать, чей компонент перед ними. Компонент Ark приносит анатомию с собой, наш —
// объявляет ТОЙ ЖЕ функцией.
//
// ## Чего в анатомии нет — и только это добавляется рантайму
//
// Анатомия знает части и адреса. Механике скина этого мало, и сверху добавляется ровно столько:
//
//   1. словарь состояний части — какие бывают, ЧЕМ выражены и всегда ли признак приезжает;
//   2. ось вариаций — что одно имя вариации у компонента есть, и чем оно выражено;
//   3. настройки — чем компонент МОЖЕТ БЫТЬ, какие значения принимает и что от чего зависит;
//   4. переменные, которые кит кладёт на узел, — что они есть и кто их ставит.
//
// Больше здесь ничего быть не должно. Вид, пропы поведения и перечень имён вариаций паспортом
// не являются. Назначение части человеческими словами, род компонента, группа в перечне и
// сборка — не рантайм, они за подпутём `./editor`.

import { createAnatomy, type AnatomyPart } from "@zag-js/anatomy";

/**
 * `createAnatomy`, РЕЭКСПОРТОМ — а не вторым npm-именем на один и тот же поток (`PWEB-112`).
 *
 * Форма уже держит `@zag-js/anatomy` под тип (`AnatomyPart`, выше); реэкспорт функции ничего не
 * весит и не дублирует — пакет без своих зависимостей, а версия обновляется САМА вместе с этой.
 *
 * Продукт со своими компонентами объявляется той же формой, что и кит (страница «Паспорт
 * компонента»): объявляй он анатомию через `@zag-js/anatomy` напрямую, у него оказалось бы два
 * разных npm-имени на один и тот же поток — своё и китовое, — и версии между ними разошлись бы
 * молча на первом же обновлении одной из сторон. Здесь имя одно: `createAnatomy` берут оттуда же,
 * откуда `definePassport`.
 */
export { createAnatomy };

/**
 * То, что паспорту нужно от анатомии: перечень частей и адреса.
 *
 * Это НЕ вторая форма паспорта, а самая узкая запись зависимости: `AnatomyInstance` из
 * `@zag-js/anatomy` подходит сюда как есть, а читателю паспорта не нужны ни `omit`, ни
 * `rename` — они принадлежат объявлению, а не чтению.
 */
export interface PassportAnatomy<Part extends string = string> {
  /** Перечень частей, читаемый машиной. */
  keys: () => Part[];
  /** На каждую часть — `attrs` для узла и `selector` для стиля. */
  build: () => Record<Part, AnatomyPart>;
}

/**
 * Чем состояние или вариация видны В РАЗМЕТКЕ.
 *
 * Без этого поля словарь состояний — просто слова: скин порождает из адреса селектор, и ему
 * нужно знать, за что цепляться, а редактору — чем выставить состояние в предпросмотре.
 *
 * Два начертания, и оба настоящие:
 *  • `attribute` — атрибут на узле (`data-disabled`, `aria-busy="true"`);
 *  • `pseudo` — псевдокласс, который ставит браузер (`:hover`, `:focus-visible`, `:active`).
 *
 * Псевдокласс не подменить атрибутом: наведения и клавиатурного фокуса компонент не знает —
 * их знает браузер, и объявить их иначе значило бы соврать данными.
 */
export type PassportMark =
  | {
      readonly kind: "attribute";
      /** Имя атрибута: `data-disabled`, `aria-busy`, `data-variant`. */
      readonly name: string;
      /** Значение, если состояние выражено именно им. Без значения — важно само наличие. */
      readonly value?: string;
    }
  | {
      readonly kind: "pseudo";
      /** Псевдокласс вместе с двоеточием: `:hover`. */
      readonly name: string;
    };

/**
 * Состояние части — момент, в который её вид отличается.
 *
 * Имена берутся из словаря Zag (`data-state`, `data-disabled`, `data-focus`, `data-current`,
 * `data-highlighted`) плюс псевдоклассы браузера. Новое имя заводится ТОЛЬКО решением и только
 * если в словаре подходящего нет.
 *
 * Человеческое имя состояния (`means`) — за подпутём `./editor` (`PWEB-115`): рантайму оно не
 * нужно, а держи его здесь — оно бы неотличимо путешествовало вместе с рантаймом до браузера.
 */
export interface PassportState {
  /** Имя состояния — оно уезжает в адрес правила скина: `hover`, `disabled`. */
  readonly name: string;
  /** Чем выражено в разметке. */
  readonly mark: PassportMark;
  /**
   * КОГДА признака на узле нет, хотя состояние действует (`PWEB-97`).
   *
   * Молчание — обычный случай и правильное умолчание: у подавляющего большинства состояний
   * признак приезжает всегда, и требовать от каждого объявляющего сказать об этом вслух значило бы
   * завести обязательное поле ради одного исключения. Объявлено — паспорт утверждает ОБРАТНОЕ и
   * обязан назвать обстоятельства, при которых узел остаётся без признака. Текст здесь человеку;
   * машине — сам факт объявления: `addressesView` решает по НАЛИЧИЮ поля, а не по словам в нём.
   *
   * Почему такое состояние вообще объявляется, а не умалчивается. Оно нужно ДВУМ читателям, и
   * нужно им противоположное:
   *
   *  • **виду** признак адресом не годится. Правило скина по нему молча не применилось бы ровно
   *    там, где признака нет, и одевающий узнал бы об этом глазами, а не машиной. Читатель под вид
   *    такие состояния отбрасывает (`addressesView`, `coordinateOf`);
   *  • **движению** отсутствие признака — ВЕРНЫЙ ОТВЕТ, а не пробел: признака нет потому, что
   *    перехода не было, и проигрывать движению нечего. Умолчи паспорт о состоянии вовсе — движение
   *    не узнало бы о нём ничего и анимировать было бы нечем.
   *
   * Правило «признак, которого может не быть, адресом быть не может» этим не отменяется, а
   * становится проверяемым: разницу между двумя чтениями держит ЭТО поле, а не молчание паспорта.
   * Молчание неотличимо от «поставщик не посмотрел», и по нему ни один читатель решения не примет.
   */
  readonly absentWhen?: string;
}

/**
 * Годится ли состояние АДРЕСОМ ВИДА.
 *
 * Признак, которого может не быть, адресом быть не может: правило по нему применилось бы через
 * раз — на тех же узлах, что и всегда, но не на всех. Само состояние при этом законно и объявлено:
 * оно принадлежит движению, где отсутствие признака и есть ответ (`PassportState.absentWhen`).
 *
 * Правило живёт рядом с формой по той же причине, что решения читаются рядом с рантаймом: читателей
 * под вид уже несколько — мост `coordinateOf`, механика скина, — и решай каждый «годится ли признак
 * адресом» по-своему, второе решение разъехалось бы с первым молча, оставаясь зелёным.
 *
 * @param state состояние части
 */
export function addressesView(state: PassportState): boolean {
  return state.absentWhen === undefined;
}

/**
 * ПЕРЕМЕННАЯ, которую кит кладёт на узел (`PWEB-89`).
 *
 * Zag меряет высоту раскрытия и кладёт на узел содержимого `--height` и `--width`. Без них
 * анимации раскрытия НЕ СУЩЕСТВУЕТ: `auto` не анимируется, а придумать число за чужое
 * содержимое нельзя.
 *
 * Форма попросить их у кита не может, и это правильно: скин, дёргающий поставщика за внутреннее
 * устройство, разъедется с ним на первом же выпуске. Но раз кит их кладёт и на них
 * рассчитывает — они НАБЛЮДАЕМЫ, а значит паспорту принадлежат. Исчезнут у поставщика —
 * расхождение поймает машина, а не человек, у которого перестало открываться плавно.
 *
 * Анимацию при этом пишет СКИН, а не кит: наше дело — сделать высоту адресуемой.
 *
 * Что означает переменная человеку (`means`) — за подпутём `./editor` (`PWEB-115`).
 */
export interface PassportVariable {
  /** Имя кастом-свойства вместе с двумя дефисами: `--height`. */
  readonly name: string;
  /**
   * Кто её ставит.
   *
   * Два начертания, и они не равны: `kit` — свойство появляется само, и на него можно
   * рассчитывать; `consumer` — его обязан положить тот, кто ставит компонент, и скин, написанный
   * в расчёте на него, у забывчивого потребителя молча не сработает. Разница видна в данных,
   * потому что редактор обязан её показать, а не догадаться.
   */
  readonly setBy: "kit" | "consumer";
}

/**
 * НАСТРОЙКИ — чем компонент МОЖЕТ БЫТЬ (`PWEB-89`).
 *
 * Перечень имён ЗАКРЫТ и живёт здесь по той же причине, что перечень групп в редакторском срезе:
 * настройка — это общий словарь, а не выдумка одного поставщика. Разные компоненты называют одно и
 * то же одним именем, и только поэтому редактор умеет показать «положение» у гармошки и у
 * разделителя одним средством. Дай мы поставщику свободу имён — получили бы `orientation`,
 * `direction`, `axis` и `vertical` в одном ките.
 *
 * **Настройка — не вариация вида.** Вариацию (`главная`, `тихая`) придумывает автор скина, и это
 * решено. Настройка меняет ПОВЕДЕНИЕ, РАЗМЕТКУ и ДОСТУПНОСТЬ: вертикальная гармошка и
 * горизонтальная — разные клавиши и разные `aria`. Её знает тот, кто компонент написал.
 *
 * **Настройка — и не состояние.** `disabled` в перечне НЕТ намеренно, хотя проп такой у кнопки и
 * у гармошки есть: отключённость уже объявлена СОСТОЯНИЕМ на частях (`data-disabled`,
 * `:disabled`), у неё своя ось и свои средства показа. Объяви мы её ещё и настройкой — у одного
 * свойства стало бы два объявления, и первый же пульт показал бы его дважды.
 *
 * Новая настройка заводится ТОЛЬКО решением — как новое имя состояния и новая группа.
 */
export const SETTINGS = {
  orientation: "Положение",
  multiple: "Несколько сразу",
  collapsible: "Можно закрыть всё",
} as const satisfies Readonly<Record<string, string>>;

/** Имя настройки — ключ закрытого перечня. */
export type PassportSettingName = keyof typeof SETTINGS;

/** Одно допустимое значение настройки-выбора. Что оно значит человеку — за подпутём `./editor`. */
export interface PassportSettingOption {
  /** Значение, которое уезжает в проп. */
  readonly value: string;
}

/**
 * Какие значения настройка принимает.
 *
 * Два начертания, и оба настоящие: признак включают или не включают, выбор берут из перечня.
 * Свести их к одному (перечню из «да» и «нет») значило бы соврать о типе пропа — редактор
 * показал бы список там, где нужен выключатель.
 */
export type PassportSettingValues =
  | { readonly kind: "flag" }
  | { readonly kind: "choice"; readonly options: readonly PassportSettingOption[] };

/**
 * ЗАВИСИМОСТЬ настройки от ДРУГОЙ настройки того же компонента (`SKINED-7`).
 *
 * У гармошки `collapsible` перестаёт что-либо решать, когда `multiple` включена: Zag пускает
 * закрыть последний раскрытый раздел, если включено ХОТЯ БЫ ОДНО из двух (`canToggle = collapsible
 * || multiple`), — при `multiple: true` закрытие уже разрешено, и значение `collapsible` на
 * поведение не влияет. Это факт о ПОВЕДЕНИИ компонента, тот же род знания, что и сама настройка, и
 * его знает поставщик — не пульт, который гадал бы по именам.
 *
 * Поле называет ЧУЖОЕ имя и ОДНО его значение — то, при котором эта настройка теряет действие.
 * Не текст объяснения: ответ обязан быть вычислимым (`settingApplies`), а не написанным для
 * человека, — иначе каждый пульт решал бы зависимость по-своему и расходился со вторым, оставаясь
 * зелёным.
 */
export interface PassportSettingDependency {
  /** Имя настройки, от чьего значения зависит эта. Из закрытого перечня, как и имя самой настройки. */
  readonly on: PassportSettingName;
  /** Значение `on`, ПРИ КОТОРОМ эта настройка теряет действие. */
  readonly redundantWhen: string | boolean;
}

/**
 * Настройка компонента: какие значения принимает и что действует без неё.
 *
 * Что она делает человеку (`means`) — за подпутём `./editor` (`PWEB-115`).
 */
export interface PassportSetting {
  /** Какие значения принимает. */
  readonly values: PassportSettingValues;
  /**
   * Что действует, когда настройка не названа.
   *
   * Умолчание обязательно по той же причине, по которой оно обязательно у оси вариаций: без него
   * «горизонтальная» и «не указано» окажутся двумя разными положениями, совпадающими по
   * договорённости, которой нет ни в одном файле.
   */
  readonly byDefault: string | boolean;
  /**
   * Чем настройка ВИДНА в разметке — тем же типом, что состояние (`PassportState.mark`).
   *
   * Необязательно: настройка меняет ПОВЕДЕНИЕ и не обязана иметь видимый след. Проверено на
   * живом ките (`PWEB-104`): `data-multiple` и `data-collapsible` у гармошки не существуют
   * вовсе, а `data-orientation` есть. Вывести адрес из ИМЕНИ настройки нельзя — правило дало бы
   * два мёртвых адреса из трёх, — поэтому объявляющий называет его явно, как назвал бы состояние.
   *
   * Значение поля форма не толкует: адресом скина оно становится в механике скина, а не здесь.
   */
  readonly mark?: PassportMark;
  /**
   * От какой настройки эта зависит — необязательно, большинство настроек независимы.
   *
   * `settingApplies` — единственный законный читатель поля: пульт спрашивает данными, а не
   * сравнивает имена настроек сам, иначе решение про `multiple` и `collapsible` осело бы в
   * витрине частным случаем и не сработало бы у следующего поставщика с той же формой.
   */
  readonly dependsOn?: PassportSettingDependency;
}

/**
 * Настройки компонента — ключами, а не перечнем, и ключи сверяются с его ПРОПАМИ.
 *
 * `Extract<keyof Props, PassportSettingName>` — это ровно те имена закрытого перечня, которые
 * компонент действительно принимает. Отсюда обе проверки сразу, и обе типом:
 *
 *  • настройка, которой у компонента НЕТ, не наберётся — такого ключа в записи не существует;
 *  • настройка, которая у компонента ЕСТЬ и не объявлена, — недостача обязательного ключа.
 *
 * Вторая половина и есть та, ради которой запись сделана ключами: поставщик выпустит новую
 * версию, у компонента появится `collapsible` — и паспорт покраснеет у нас, а не окажется
 * неполным у двадцати потребителей.
 */
export type PassportSettings<Props> = Readonly<
  Record<Extract<keyof Props, PassportSettingName>, PassportSetting>
>;

/**
 * Объявляет настройки компонента, сверяя ключи с его пропами.
 *
 * Отдельная функция, а не поле со своим типом-параметром, — потому что тип пропов из объявления
 * не выводится, а частичного вывода у TypeScript нет: назови мы его в `definePassport`, пришлось
 * бы писать руками и перечень частей, который сегодня выводится из анатомии.
 *
 * @param settings настройки по именам — ровно те из закрытого перечня, что компонент принимает
 */
export function defineSettings<Props>(settings: PassportSettings<Props>): PassportSettings<Props> {
  return settings;
}

/**
 * Действует ли настройка `name` при ТЕКУЩИХ значениях, или её перебила чужая (`SKINED-7`).
 *
 * Ответ вычисляется, а не описывается словами: `dependsOn` называет чужое имя и значение, при
 * котором своя настройка теряет действие, а эта функция сравнивает его с фактическим значением
 * настройки-источника. Значение источника, которого нет в `values`, берётся его же умолчанием —
 * тем же доводом, что у `byDefault`: «не выставлено» и «выставлено умолчанием» обязаны быть одним
 * положением, а не двумя, совпадающими по неписаной договорённости.
 *
 * Живёт рядом с формой по той же причине, что и `addressesView`: правило одно на всех
 * читателей паспорта — витрину, редактор, следующий пульт, — и решай каждый «действует ли
 * настройка» по-своему, второе решение молча разъехалось бы с первым.
 *
 * @param settings настройки компонента — записью, как их отдаёт паспорт
 * @param name имя проверяемой настройки
 * @param values текущие значения настроек — то, что выставил человек в витрине или редакторе
 */
export function settingApplies(
  settings: Readonly<Record<string, PassportSetting>>,
  name: string,
  values: Readonly<Record<string, unknown>>,
): boolean {
  const dependency = settings[name]?.dependsOn;

  if (!dependency) return true;

  const source = settings[dependency.on];
  const actual = values[dependency.on] ?? source?.byDefault;

  return actual !== dependency.redundantWhen;
}

/**
 * Добавка к части анатомии: то, чего сама анатомия не знает и что нужно РАНТАЙМУ.
 *
 * Имя части здесь — НЕ новое объявление, а ключ анатомии: тип `Part` приходит из неё, и часть,
 * которой в анатомии нет, не наберётся.
 *
 * Назначение части человеку (`means`) и правило вложенности (`accepts`) — за подпутём `./editor`
 * (`PWEB-115`): ни то, ни другое `generateSkinCss`/`checkOutfit`/`assemble` не читают.
 */
export interface PassportPart<Part extends string = string> {
  /** Часть анатомии, к которой относится добавка. */
  readonly name: Part;
  /** Словарь состояний ЭТОЙ части. */
  readonly states: readonly PassportState[];
  /**
   * Переменные, которые появляются НА УЗЛЕ этой части (`PWEB-89`).
   *
   * Живут у части, а не у компонента, потому что кладутся на конкретный узел: `--height` Zag
   * ставит на содержимое раздела и больше нигде. Объяви мы их у компонента — скин не знал бы,
   * куда целиться, и целился бы в корень.
   *
   * Не объявлено — переменных у части нет. Пустой перечень значил бы то же самое, поэтому поле
   * необязательное: у подавляющего большинства частей их не бывает вовсе.
   */
  readonly variables?: readonly PassportVariable[];
}

/**
 * ОСЬ вариаций: у компонента есть ОДНО имя вариации, выраженное ОДНИМ атрибутом.
 *
 * Перечня имён здесь нет и быть не может. Имена создаёт человек в редакторе вместе со скином:
 * `<Button variant="главная">`. Объяви их кит — и в паспорте оказалось бы то, чего нельзя
 * проверить на живом компоненте, а смена скина ломала бы разметку потребителя.
 *
 * Второй оси тоже нет: два атрибута в разметке означали бы, что дизайн собирают в приложении,
 * а сборка вида («опасное, и при этом тихое») происходит в редакторе.
 *
 * Умолчание — что действует, когда атрибута нет, — называет СКИН, а не паспорт (страница
 * «Паспорт компонента»).
 *
 * Что ось значит человеку (`means`) — за подпутём `./editor` (`PWEB-115`).
 */
export interface PassportVariantAxis {
  /** Чем выражена в разметке. Пишет её ПОТРЕБИТЕЛЬ, кит пропускает насквозь. */
  readonly mark: PassportMark;
}

/** Паспорт компонента — срез РАНТАЙМА: ровно то, что читают `generateSkinCss`/`checkOutfit`/`assemble` (`PWEB-115`). */
export interface ComponentPassport<Part extends string = string> {
  /** Имя компонента. Снято с анатомии, руками не повторяется. */
  readonly component: string;
  /** Части и адреса — взятой функцией, не нашей формой. */
  readonly anatomy: PassportAnatomy<Part>;
  /** Имя корневой части — с неё начинается дерево. */
  readonly root: Part;
  /** Добавка к каждой части анатомии. */
  readonly parts: readonly PassportPart<Part>[];
  /** Ось вариаций — что она есть. Имена принадлежат скину. */
  readonly variantAxis: PassportVariantAxis;
  /**
   * Чем компонент МОЖЕТ БЫТЬ — настройки по именам закрытого перечня (`PWEB-89`).
   *
   * Здесь запись уже свободная (`Record<string, …>`), а не сверенная с пропами: сверка — работа
   * ОБЪЯВЛЕНИЯ (`defineSettings`), а читателю паспорта тип пропов недоступен и не нужен. Пустая
   * запись — законное состояние: у компонента настроек нет.
   */
  readonly settings: Readonly<Record<string, PassportSetting>>;
}

/**
 * То, что объявляет компонент: анатомия плюс добавка. Имя компонента снимается с анатомии.
 *
 * Срез РАНТАЙМА (`PWEB-115`): пакет, род, группа и сборка — за `PassportEditorSpec` в
 * `passport-editor.ts`, объявляются ВТОРЫМ вызовом (`defineEditorInfo`), не этим.
 */
export interface PassportSpec<Part extends string> {
  readonly anatomy: PassportAnatomy<Part>;
  readonly root: Part;
  readonly parts: readonly PassportPart<Part>[];
  readonly variantAxis: PassportVariantAxis;
  /**
   * Настройки — объявленные через `defineSettings`, чтобы ключи сверились с пропами.
   *
   * ОБЯЗАТЕЛЬНО, и умолчания у поля нет (`PWEB-92`).
   *
   * Пустая запись — это УТВЕРЖДЕНИЕ «настроек у компонента нет», а не забывчивость. Оставь мы
   * поле необязательным — паспорт без него собирался бы, и в редакторе «настроек нет» стало бы
   * неотличимо от «поставщик не подумал»; заполнение пустым за того, кто не объявил, и есть тот
   * разъезд, который здесь снимается.
   *
   * Обязательность держит ТИП, а не проба: проба в границах одной зоны стерегла бы только своих
   * поставщиков, а форма паспорта общая — по ней объявляется и продуктовый пакет со своей
   * таблицей. Цена этой строгости — одна строка у каждого объявляющего, и она уплачена.
   */
  readonly settings: Readonly<Record<string, PassportSetting>>;
}

/**
 * Собирает паспорт компонента — СРЕЗ РАНТАЙМА.
 *
 * Здесь ровно одна работа, которую нельзя оставить объявляющему: имя компонента СНИМАЕТСЯ с
 * анатомии, а не пишется рядом ещё раз. Написанное дважды разъезжается — и разъехалось бы
 * молча: скин цепляется за `data-scope` из анатомии, а редактор показывал бы второе имя.
 *
 * Проверок группы и сборки здесь больше нет (`PWEB-115`): оба поля переехали в
 * `defineEditorInfo`, и обе проверки — вместе с ними, в тот же файл.
 *
 * @param spec анатомия компонента и добавка к ней
 */
export function definePassport<Part extends string>(
  spec: PassportSpec<Part>,
): ComponentPassport<Part> {
  const parts = spec.anatomy.build();
  const first = Object.values<AnatomyPart>(parts)[0];

  if (!first) {
    throw new Error("анатомия без частей: паспорту нечего объявлять");
  }

  const component = first.attrs["data-scope"];

  // Перечень настроек закрыт: поставщик вправе приехать сборкой без TypeScript, и тогда
  // единственное, что стоит между «своим» именем настройки и перечнем витрины, — эта проверка.
  // Умолчания здесь НЕТ намеренно (`PWEB-92`): `spec.settings ?? {}` заполняло бы пустым за
  // того, кто не объявил, — то есть ровно тем, от чего уходим. Обязательность держит ТИП; отказ
  // на исполнении — вторая половина, и она про поставщика без TypeScript. Без неё он получил бы
  // безымянный `TypeError` из первого же обхода записи.
  if (!spec.settings) {
    throw new Error(
      "паспорт без настроек: объяви `settings` — пустая запись `{}` это ответ «настроек нет», " +
        "а её отсутствие неотличимо от забывчивости",
    );
  }

  const strange = Object.keys(spec.settings).filter((name) => !Object.hasOwn(SETTINGS, name));

  if (strange.length > 0) {
    throw new Error(
      `настройки не из перечня: ${strange.join(", ")}; допустимы: ${Object.keys(SETTINGS).join(", ")}`,
    );
  }

  // Зависимость называет ЧУЖОЕ имя настройки, и имя обязано существовать у ЭТОГО ЖЕ компонента —
  // иначе `settingApplies` спрашивал бы значение настройки, которой в записи нет, и молча читал бы
  // `undefined` вместо умолчания чужой настройки.
  for (const [name, setting] of Object.entries(spec.settings)) {
    const on = setting.dependsOn?.on;

    if (on !== undefined && !Object.hasOwn(spec.settings, on)) {
      throw new Error(`настройка «${name}» зависит от «${on}», которой у компонента нет`);
    }
  }

  // Переменная без двух дефисов — не кастом-свойство, а опечатка: скин порождает из неё
  // `var(--…)`, и «height» вместо «--height» дал бы мёртвое правило, зелёное на вид.
  for (const part of spec.parts) {
    for (const variable of part.variables ?? []) {
      if (!variable.name.startsWith("--")) {
        throw new Error(
          `переменная «${variable.name}» части «${part.name}» не кастом-свойство: имя обязано ` +
            `начинаться с двух дефисов`,
        );
      }
    }
  }

  return {
    // `data-scope` — то самое имя, которым компонент подписан на КАЖДОМ своём узле. Берём его
    // оттуда же, откуда его возьмёт скин.
    component,
    anatomy: spec.anatomy,
    root: spec.root,
    parts: spec.parts,
    variantAxis: spec.variantAxis,
    settings: spec.settings,
  };
}
