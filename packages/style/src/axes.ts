/** Ось по имени токена — вход для потребителя, который строит ползунок. */
export function axisOf(token: string): Axis | undefined {
  return AXES.find((axis) => axis.token === token);
}

/** Как граница выглядит одной строкой: число с единицей либо честное «границы нет». */
const show = (bound: AxisBound, unit: string): string =>
  bound.value === null
    ? `нет (${bound.kind})`
    : `${bound.value}${unit === "множитель" ? "" : unit} (${bound.kind})`;

/**
 * Границы осей комментарием в поставку.
 *
 * Зачем дублировать таблицу в CSS, раз она есть в поверхности: семена задаёт тот, кто пишет
 * тему, а тему пишут в CSS. Отправить его за границами в TS-модуль значит отправить его никуда
 * — он их не найдёт и подставит свои, что уже однажды и случилось. Токенов блок не объявляет
 * ни одного: это знание об осях, а не новая ось.
 */
export function axesCss(): string {
  const width = Math.max(...AXES.map((axis) => axis.token.length));
  const rows = AXES.map(
    (axis) =>
      `     --${axis.token.padEnd(width)}  пол ${show(axis.floor, axis.unit)} · потолок ${show(axis.ceiling, axis.unit)}`,
  );

  return [
    "/* ГРАНИЦЫ ОСЕЙ. «Границы нет» — такой же ответ, как число: связывающей нормы не существует,",
    "   и любое значение законно. «Предел поддержки» и «практический предел» — НЕ требования",
    "   доступности: за ними кончаются наши пробы или меняется геометрия, а не соответствие",
    "   норме. Нормой связаны только границы с пометкой «норма»; причина каждой и ссылка на",
    "   критерий — в `AXES` (`src/axes.ts`), там же полные формулировки.",
    "   Диапазоны НЕПРЕРЫВНЫ: «правильных» ступеней у базы нет ни у одной оси, ползунок законен.",
    "",
    ...rows,
    "*/",
  ].join("\n");
}
