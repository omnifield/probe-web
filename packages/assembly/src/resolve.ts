// Изменено при переносе: возвращается `unknown` вместо «либо компонент, либо ветка» — решение
// о том, компонент ли это, принимает вызывающий. Причина — реестр механики хранит не только
// компоненты (см. `registry.ts`), и разрешатель не должен знать, что именно он достал.

/**
 * Реестр компонентов — рекурсивная карта, в которой адрес через точку ведёт к компоненту.
 *
 * ```
 * { button: Button, accordion: { root: Root, item: Item, itemTrigger: Trigger } }
 * ```
 *
 * `accordion.itemTrigger` → `registry.accordion.itemTrigger`. Глубина произвольная: так
 * адресуются и компонент целиком, и его часть, и компонент внутри чужого пространства имён
 * (`ui.button`) — одной формой, без второго вида адреса.
 *
 * **Значения не типизируются компонентом намеренно.** Что лежит по адресу — дело поставщика
 * карты; отрисовка проверит и отдаст запасной вид, если по адресу оказалось не то.
 */
export type ComponentMap = { [key: string]: unknown };

/**
 * Память разрешений — на каждый реестр своя.
 *
 * Ключ — ССЫЛКА на сам реестр, поэтому слабая карта: забыл потребитель реестр — память ушла
 * вместе с ним, сама, без нашего участия. Значение — карта `адрес → найденное`, включая
 * `undefined` для промахов: промах стоит столько же, сколько попадание, и пересчитывать его
 * заново так же расточительно.
 *
 * **Условие:** реестр считается неизменяемым. Правка реестра после первого разрешения
 * оставит память несвежей. На практике реестр собирается один раз при запуске — условие
 * выполнимо, и оно записано здесь, а не подразумевается.
 */
const memory = new WeakMap<ComponentMap, Map<string, unknown>>();

/**
 * Разрешает адрес через точку: `'accordion.itemTrigger'` → `map.accordion.itemTrigger`.
 *
 * Возвращает `undefined`, если по пути чего-то нет, — и это НЕ ошибка: решение, что делать с
 * неразрешённым адресом, принимает отрисовка, а она отдаёт явный запасной вид.
 *
 * Помнит найденное (см. `memory`). На дереве в сотню узлов отрисовка зовёт разрешение
 * десятки раз за пересборку; без памяти каждый раз это разбор строки и спуск по карте.
 *
 * @param map реестр компонентов
 * @param address адрес через точку
 */
export function resolveAddress(map: ComponentMap, address: string): unknown {
  if (!address) return undefined;

  let known = memory.get(map);
  if (!known) {
    known = new Map();
    memory.set(map, known);
  }
  if (known.has(address)) return known.get(address);

  let current: unknown = map;
  for (const segment of address.split(".")) {
    if (current == null) {
      known.set(address, undefined);
      return undefined;
    }
    current = (current as ComponentMap)[segment];
  }

  known.set(address, current);
  return current;
}
