// ПАЛИТРЫ У ПАНЕЛИ НЕТ, и это не пробел. Надеваемый набор значений снят с поставки: палитра без
// рецептов — половина скина, а половин у скина не бывает. Панель — инструмент, скина у неё нет
// и не будет, поэтому свой цвет она задаёт сама, литералами, в `panel.css`.
//
// Из базового слоя берётся сброс и РАЗМЕРНЫЕ шкалы: у них есть подстраховки, и без палитры они
// работают. Цветовые роли без неё пусты — на них панель не опирается.
import "@omnifield/probe-web-style/base.css";
import "./panel.css";

import { render } from "solid-js/web";

import { Panel } from "./panel.jsx";

// ВОССТАНОВЛЕНИЯ ДО ПЕРВОГО КАДРА ЗДЕСЬ БОЛЬШЕ НЕТ, и это не упущение.
//
// Оно стояло против вспышки: режим ставился до отрисовки, чтобы человек не увидел светлое
// перед тёмным. Ставить теперь нечего — режим стал половиной скина, а на первом кадре скина
// нет: перечень приезжает из службы позже. Вспышке взяться неоткуда, потому что и вида нет.
//
// Восстановление живёт в панели, где список уже известен.

const root = document.getElementById("root");
if (!root) throw new Error("нет #root — панель монтировать некуда");

render(() => <Panel />, root);
