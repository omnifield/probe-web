// МОДЕЛЬ ТЕМЫ — то немногое, что нужно записать, чтобы вид можно было ПОСТАВИТЬ, и функция,
// делающая из неё файл. Решение — `kb:PROBEWEB-15`, решение 2.
//
// ПОЧЕМУ ЭТО МЕСТО ПРАВИЛЬНОЕ. Генератор родился в зоне `skin` (`products/skin`), но никакой
// специфики производства оформлений в нём нет: он знает семена, мету, плотность и правки
// тёмной пары — всё это понятия базы, и считает их `buildThemeTokens`, который живёт здесь же.
// Пока генератор стоял в `products/`, каждый, кому нужен вид из модели — пульт, `runtime`,
// выгрузка поставки, — привязывался к зоне, которой предстоит уехать отдельным продуктом
// (`kb:PROBEWEB-5`).
//
// ЧЕГО В МОДЕЛИ НЕТ И НЕ БУДЕТ. Человеческого названия, происхождения и идентификатора записи
// в службе: это понятия стенда и хранилища, а не вида. Светлого/тёмного режима тоже нет —
// режим выбирает пользователь, и одна и та же модель обязана работать в обоих.

import { DENSITY_TOKEN } from "./dimension.js";
import { PALETTE_ATTRIBUTE, paletteCss } from "./palette.js";
import {
  type ThemeMetaToken,
  type ThemeSeeds,
  type ThemeTokens,
  buildThemeTokens,
} from "./tokens.js";
import { trace } from "./trace.js";

/**
 * Тема как ЗАПИСЬ: минимум значений, из которых считается всё остальное.
 *
 * Имена полей — те же, в которых модель уже лежит в службе пресетов: у формы один источник,
 * и переименование здесь означало бы преобразование на каждом стыке.
 */
export interface ThemeModel {
  /** Устойчивое имя темы: уезжает в атрибут `data-theme` и обычно в имя файла. */
  id: string;
  /** Семена шкал — по одному значению на шкалу; двенадцать ступеней считает база. */
  seeds: ThemeSeeds;
  /** Мета: скругление, шаг интервалов, кегль, высота контрола, границы, трекинг, тени. */
  meta?: Partial<Record<ThemeMetaToken, string>>;
  /**
   * Правки отдельных ступеней ТЁМНОЙ пары — вкус конкретной темы, а не лестницы базы.
   *
   * Только тёмной: светлая половина остаётся тем, что посчитано из семян. Тема, которой
   * нужно править и светлую, правит семя — иначе обещания контраста перестают что-то значить.
   */
  darkOverrides?: Partial<ThemeTokens>;
  /**
   * Множитель интервалов, высот контролов и кегля. Единица — как в базе (`DENSITY_DEFAULT`),
   * диапазон поддержки — от `DENSITY_FLOOR` (выведен из нормы) до `DENSITY_CEILING`.
   */
  density: string;
}

/**
 * Модель темы как CSS — форма, в которой тема уезжает в приложение.
 *
 * ПОЧЕМУ ИМЕННО CSS ПЕРВИЧЕН: «указать тему и поставить» обязано работать без сборки и без
 * единой строки JS — подключил файл, поставил атрибут, получил вид. Модель остаётся
 * источником, из которого файл рождается, но потребителю нужен именно файл.
 *
 * Плотность попадает в ТОТ ЖЕ блок, что и остальные значения: она такое же значение вида, как
 * скругление, и отдельный блок означал бы, что тема переносится в два приёма и половина может
 * отстать.
 *
 * ```ts
 * const css = themeModelToCss({ id: "ocean", seeds, density: "1" });
 * // [data-theme="ocean"] { … }  +  [data-theme="ocean"].dark, … { … }
 * ```
 *
 * @param model тема как данные
 * @returns готовый файл: светлая пара с плотностью и тёмная пара под классом `dark`
 */
export function themeModelToCss(model: ThemeModel): string {
  const done = trace(`themeModelToCss(${model.id})`);

  // Плотность в контракт темы не входит (это ось, а не токен палитры — `DENSITY_NOTE`),
  // поэтому в набор значений она добавляется здесь и приведением, а не расширением типа.
  const light = {
    ...buildThemeTokens(model.seeds, "light", model.meta),
    [DENSITY_TOKEN]: model.density,
  } as ThemeTokens;

  const dark = {
    ...buildThemeTokens(model.seeds, "dark", model.meta),
    ...model.darkOverrides,
  } as ThemeTokens;

  const css = [
    `/* Тема «${model.id}» — значения вида, отчуждаемые файлом.`,
    `   Подключение: этот файл плюс атрибут ${PALETTE_ATTRIBUTE}="${model.id}" на <html>.`,
    `   Тёмная пара включается классом dark, как и у любой другой темы. */`,
    "",
    paletteCss(model.id, "light", light),
    "",
    paletteCss(model.id, "dark", dark),
    "",
  ].join("\n");

  done();
  return css;
}

