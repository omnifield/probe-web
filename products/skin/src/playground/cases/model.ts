// Модель показа: СЕМЕЙСТВО и его КЕЙСЫ.
//
// Форма выбрана по образцу, который назвал user (страницы компонентов Ant Design): на странице
// компонента не ручки оформления, а перечень случаев — «базовый», «отключён», «недопустимое
// значение», «длинный текст». Каждый случай подписан и объяснён, потому что показывать вид без
// повода бессмысленно: смотреть надо на то, как компонент держится в конкретном условии.
//
// РАЗДЕЛЕНИЕ ОБЯЗАННОСТЕЙ (решение user 2026-08-17):
//   • вкладка «Всё» — базовые случаи всех семейств плюс панель настройки скина;
//   • вкладка семейства — только кейсы, без ручек: там смотрят на компонент, а не крутят тему.
//
// Первый кейс каждого семейства обязан быть базовым: именно он попадает на вкладку «Всё».

import type { JSX } from "solid-js";

export interface Case {
  id: string;
  /** Короткое имя случая — то, что видно в заголовке блока. */
  title: string;
  /** Зачем этот случай показан. Пусто — случай говорит сам за себя. */
  note?: string;
  render: () => JSX.Element;
}

/**
 * Группы по смыслу (решение user 2026-08-17): валить тридцать семейств в одну кучу нельзя —
 * витрина превращается в свалку, и найти в ней нужное дольше, чем открыть код.
 *
 * Порядок групп — от простого к составному: сначала то, чем действуют, потом то, чем вводят,
 * дальше обратная связь, всплывающее и структура. Это же порядок и на витрине.
 */
export const GROUPS = ["Действия", "Ввод", "Обратная связь", "Всплывающее", "Навигация", "Структура"] as const;

export type Group = (typeof GROUPS)[number];

export interface Specimen {
  id: string;
  title: string;
  /** Смысловая группа: по ней витрина разбита на разделы, а вкладки упорядочены. */
  group: Group;
  /** Зацепки кита, которые показывает семейство. Ими сверяется полнота покрытия. */
  slots: string[];
  /** Кейсы; первый — базовый, он же идёт на вкладку «Всё». */
  cases: Case[];
}
