// ДЕФОЛТНАЯ ПАЛИТРА ЗОНЫ — данные, а не рантайм.
//
// Зона делает готовый вид, а вид это правила ПЛЮС значения. Правила лежат в `src/skin`
// (только CSS), значения — здесь. Разделение не формальность: правила у нас одни на всех, а
// палитр может быть сколько угодно, и подключаются они порознь.
//
// Почему палитра вообще может жить у нас: слой `style` палитр в себе не держит намеренно —
// «набор палитр это контент приложения». Он даёт механику (семена → двенадцать ступеней,
// обещания контраста, `registerTheme`), мы даём конкретные значения.
//
// ИСТОЧНИК: тема «Twitter» из редактора tweakcn (`tweakcn.com/editor/theme`), выбрана user
// 2026-08-16. Взяты из неё ДВА семени и форма скругления; всё остальное считает база.

import {
  buildThemeTokens,
  type ThemeDefinition,
  type ThemeMetaToken,
  type ThemeTokens,
} from "@omnifield/probe-web-style";

/**
 * Семена палитры — по одному значению на шкалу.
 *
 * `brand` и `danger` взяты у источника дословно. `neutral` у него семенем не выражен: там
 * плоский набор, где нейтраль задана порознь фоном, границей и текстом. Сведено к одному
 * семени по тону источника (~248°, холодная синева) с малой цветностью — так серый перестаёт
 * быть мёртвым и держит родство с голубым акцентом.
 */
const SEEDS = {
  brand: "oklch(0.6723 0.1606 244.9955)",
  danger: "oklch(0.6188 0.2376 25.7658)",
  neutral: "oklch(0.62 0.012 248)",
} as const;

/**
 * Мета: форма и шрифты.
 *
 * Скругление источника (`1.3rem`) взято как есть — оно и делает узнаваемый вид. Шрифты
 * источника (Open Sans) НЕ берём: шрифт это файл, а решения о поставке шрифтов в зоне пока
 * нет, и объявить семейство, которого у потребителя не окажется, значит молча съехать на
 * подстановку. Остаётся системный набор базы.
 */
const META: Partial<Record<ThemeMetaToken, string>> = {
  radius: "1.3rem",
};

/**
 * СМЯГЧЕНИЕ ТЁМНОЙ ПАРЫ — решение user 2026-08-16: «фон слишком чёрный, шрифт ярко-белый,
 * бьёт по глазам».
 *
 * У источника тёмный фон — чистый чёрный (`oklch(0 0 0)`), то есть ровно та жалоба в
 * предельном виде; брать его дословно нельзя. Лестница базы мягче (0.175), но пара с текстом
 * 0.955 всё равно даёт около пятнадцати к одному — втрое выше требуемого нормой минимума
 * 4.5:1 (WCAG 2.2, 1.4.3), и на большой площади это утомляет.
 *
 * Поэтому сдвинуты ТРИ крайние ступени тёмной шкалы: два нижних фона вверх, верхний текст
 * вниз. Назначение ступеней при этом не меняется — модель базы остаётся в силе, меняются
 * значения, а это и есть предмет палитры. Что обещания контраста уцелели, проверяет
 * `test/palette.test.ts` — теми же порогами, которыми их проверяет база.
 *
 * Сдвиг живёт здесь, а не в базе, потому что это вкус конкретной палитры. Если окажется, что
 * жёсткая пара мешает всем, — это уже находка про лестницу базы и заявка в `style`.
 */
const DARK_SOFTENING: Record<string, string> = {
  "neutral-1": "oklch(0.205 0.008 248)",
  "neutral-2": "oklch(0.23 0.009 248)",
  // Поднята следом за фонами, и не по вкусу, а вынужденно: у базы сильная граница держит свои
  // 3:1 к ступени 2 ВПРИТЫК (3.02). Подняв фон и оставив границу на месте, мы получили 2.84 —
  // то есть увели палитру из соответствия 1.4.11. Поймала проба, не глаз.
  "neutral-8": "oklch(0.53 0.0074 248)",
  "neutral-12": "oklch(0.92 0.006 248)",
};

function darkTokens(): ThemeTokens {
  return { ...buildThemeTokens(SEEDS, "dark", META), ...DARK_SOFTENING } as ThemeTokens;
}

/** Палитра целиком. Регистрируется `registerTheme()`, включается атрибутом `data-theme`. */
export const TWITTER_THEME: ThemeDefinition = {
  name: "twitter",
  light: buildThemeTokens(SEEDS, "light", META),
  dark: darkTokens(),
};

/** Имя палитры — им же включается атрибут `data-theme`. */
export const TWITTER_THEME_NAME = TWITTER_THEME.name;

/** Смягчённые ступени — публикуются для пробы, чтобы она проверяла именно их, а не догадку. */
export const SOFTENED_STEPS = Object.keys(DARK_SOFTENING);
