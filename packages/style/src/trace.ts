// Perf-трейсы стилевого слоя. ВНУТРЕННЕЕ: наружу не экспортируется и в `exports` манифеста
// не объявлено.
//
// Механика повторяет `trace` зоны `runtime` намеренной копией, а не общим модулем:
// направление зависимостей одностороннее, и ради двадцати строк style не имеет права
// зависеть от соседа (`kb:PROBEWEB-4`). Понадобится третья копия — это разговор с
// architect про внутренний общий пакет, а не про импорт наискосок.

/** Глобальный тумблер трейсов: `globalThis.__PROBE_WEB_STYLE_TRACE__ = true`. */
const FLAG = "__PROBE_WEB_STYLE_TRACE__";

type TraceGlobal = typeof globalThis & { [FLAG]?: boolean };

/**
 * Включены ли трейсы. По умолчанию — нет, включает только явный глобальный флаг.
 *
 * Автоопределение по dev-режиму сборщика (`import.meta.env.DEV`) не используется: пакет
 * приезжает потребителю зависимостью, а подстановку в файлы из `node_modules` Vite не
 * делает — условие осталось бы вечно ложным, то есть трейсы были бы мёртвым кодом.
 */
function enabled(): boolean {
  return (globalThis as TraceGlobal)[FLAG] === true;
}

/**
 * Открывает замер. Возвращает функцию закрытия — она и пишет строку в консоль.
 *
 * Замеряется только SETUP: регистрация палитры и создание контроллера. `cn` и
 * `createStyle` живут на горячем пути рендера, и замер там стоил бы дороже измеряемого —
 * их стоимость видна профайлером, а не логом на каждый кадр.
 *
 * @param label имя замеряемого участка
 * @returns закрыть замер и напечатать длительность
 */
export function trace(label: string): () => void {
  if (!enabled()) return () => {};

  const started = performance.now();
  return () => {
    const ms = performance.now() - started;
    console.debug(`[probe-web-style] ${label} — ${ms.toFixed(2)}ms`);
  };
}
