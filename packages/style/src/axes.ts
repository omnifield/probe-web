// ГРАНИЦЫ ОСЕЙ: где у значения край, и есть ли он вообще.
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНОЙ ТАБЛИЦЕЙ. Потребитель, который даёт человеку крутить вид, обязан знать
// границы. У плотности они есть и выведены (`DENSITY_FLOOR` из нормы, `DENSITY_CEILING` —
// честно названный предел поддержки), а у остальных осей не было НИЧЕГО. Молчание читается
// как «база не знает, где край», и потребитель подставляет свой список вместо ползунка —
// именно так панель стенда получила шесть зашитых скруглений и три плотности вместо
// диапазона (`tasker:PROBEWEB-64`, пункт 3).
//
// ОТСУТСТВИЕ ГРАНИЦЫ — ТОЖЕ ОТВЕТ, и он объявляется значением, а не умолчанием: `value: null`
// плюс `kind`, который говорит ПОЧЕМУ её нет. «Границ нет» и «мы не подумали» снаружи
// выглядят одинаково ровно до тех пор, пока первое не записано.
//
// ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ. Ни одного нового токена: таблица описывает УЖЕ существующие оси.
// И ни одного `clamp()` на самой оси — граница объявлена, а не зажата. Зажать значило бы молча
// подменить число, которое поставил потребитель: он получил бы не то, что написал, и не узнал
// бы об этом. Наше дело — сказать, где край; решение остаётся его.

