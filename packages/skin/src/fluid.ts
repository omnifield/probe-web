// ТЕКУЧИЙ РАЗМЕР — семя, объявленное ПОЛЮСАМИ, а не рукописным выражением (`PWEB-80`).
//
// ## Что было не так
//
// Чтобы размер следовал за шириной экрана, автор палитры вписывал выражение руками:
//
//   space: "clamp(0.375rem, 0.32rem + 0.24vw, 0.5rem)"
//
// Механика видела СТРОКУ. Три дыры, и все три настоящие:
//
//   • **наклон никто не считал.** Коэффициент при `vw` выведен человеком, и ошибка в знаке
//     уводит лестницу в обратную сторону — молча: ни одна проверка про это не знала;
//   • **полюса нигде не объявлены.** В каком диапазоне ширин семена согласованы, знал только
//     автор. Второй автор написал бы свои `vw` от других полюсов, и в одном наряде оказались бы
//     две разные сетки;
//   • **проверить нечем.** Для цвета есть счёт читаемости; для размера не было ничего.
//
// Теперь палитра объявляет ПОЛЮСА — значение на узком краю, значение на широком и ширины, между
// которыми оно растёт, — а выражение печатает механика. Обратное чтение тоже работает: по записи
// видно, в каком диапазоне ширин автор согласовал значения.
//
// ## Арифметика и то, на чём она стоит
//
// Наклон и свободный член считаются в пикселях, а печатаются в единице оси:
//
//   наклон  = (значение₂ − значение₁) / (ширина₂ − ширина₁)      · доля от ширины окна
//   свободн = значение₁ − наклон · ширина₁                        · то, что остаётся при 0vw
//
// **Связь `rem` с пикселями взята равной 16 — начальному значению корневого кегля.** Это не наша
// вольность: так считает всякая текучая шкала на рынке, и иначе `clamp()` с `vw` не выражается
// вовсе — разделить длину на длину `calc()` не умеет, а значит перевод неизбежен.
//
// Следствие названо, а не спрятано: человек, увеличивший кегль в браузере, сдвигает полюса
// пропорционально. Это ВЕРНОЕ направление — вся лестница выражена в `rem` и следует за его
// настройкой (WCAG 2.2, 1.4.4), — но полюса при этом наступают на другой ширине окна, чем
// записано. Записанные ширины описывают человека с умолчанием, а не всех.
//
// ## Почему не всякая ось бывает текучей
//
// `vw` — ДЛИНА. Ось, чья единица длиной не является, текучей быть не может:
//
//   • `density` — множитель. `calc(0.9 + 0.05vw)` смешивает число с длиной и недействителен;
//     выразить безразмерное текучее значение через `vw` нельзя вовсе;
//   • `tracking` — `em`, то есть доля кегля САМОГО элемента. Перевести её в пиксели можно только
//     зная этот кегль, а он у каждого узла свой.
//
// Отказ здесь не ограничение вкуса, а невыразимость: мы отвергаем то, что браузер всё равно бы
// выбросил, — но отвергаем НАЗВАННО и до надевания, а не молча на странице.

import { AXES, axisOf } from "@omnifield/probe-web-style";

/** Пикселей в `rem` при начальном корневом кегле. Разбор допущения — в шапке файла. */
const PX_IN_REM = 16;

/** Единицы, в которых текучесть выразима: `vw` длина, и складывать её можно только с длиной. */
const FLUID_UNITS: readonly string[] = ["rem", "px"];

/**
 * СЕМЯ, ОБЪЯВЛЕННОЕ ПОЛЮСАМИ.
 *
 * Читается в обе стороны: «от 0.375rem на 366px до 0.5rem на 1200px». Ни наклона, ни свободного
 * члена автор не пишет — и потому не может ошибиться в них знаком.
 */
export interface FluidSeed {
  /** Значение на УЗКОМ полюсе — в единице своей оси. */
  readonly narrow: string;
  /** Значение на ШИРОКОМ полюсе — в той же единице. */
  readonly wide: string;
  /**
   * Ширины окна, между которыми значение растёт: узкая и широкая.
   *
   * В пикселях: ширина окна — величина пиксельная, и `vw` считается от неё. Записать их в `rem`
   * значило бы спрятать тот же перевод на шаг глубже.
   */
  readonly between: readonly [string, string];
}

/** Объявление размерного семени: постоянное значение либо полюса. */
export type DimensionSeed = string | FluidSeed;

/** Семя объявлено полюсами? */
export function isFluid(seed: DimensionSeed): seed is FluidSeed {
  return typeof seed === "object";
}

/** Число и единица из записи вида `0.5rem`. `null` — запись не разобрана. */
function measure(value: string): { readonly amount: number; readonly unit: string } | null {
  const match = /^\s*(-?\d*\.?\d+)\s*([a-z%]*)\s*$/iu.exec(value);
  if (!match) return null;

  const amount = Number(match[1]);

  return Number.isFinite(amount) ? { amount, unit: match[2] ?? "" } : null;
}

/** Значение в пикселях. Перевод из `rem` — по допущению, названному в шапке. */
function pixels(amount: number, unit: string): number {
  return unit === "rem" ? amount * PX_IN_REM : amount;
}

/** Изъян текучего объявления: имя семени и что это значит. */
export interface FluidRefusal {
  readonly seed: string;
  readonly means: string;
}

/**
 * Что в текучем объявлении не сходится — перечнем, а не первым попавшимся.
 *
 * Проверяется ровно то, что проверяемо, и ни на шаг дальше:
 *
 *  • **единица оси допускает текучесть.** Иначе выражение недействительно, и браузер выбросит
 *    объявление целиком;
 *  • **обе стороны записаны в единице СВОЕЙ оси.** Единицу объявляет зона значений (`AXES`), и
 *    смешение `px` с `rem` на одной оси означало бы, что половина лестницы не следует за
 *    настройкой кегля у человека;
 *  • **ширины возрастают.** Иначе делить не на что;
 *  • **значение не убывает.** Значение при большей ширине не может быть меньше — это арифметика,
 *    а не вкус;
 *  • **нормативный пол на УЗКОМ полюсе.** Пол, выведенный из нормы, имеют две оси, и берётся он
 *    из `AXES` вместе с причиной и ссылкой на критерий — переписывать числами нельзя.
 *
 * Чего здесь НЕТ намеренно: порога «читаемого кегля». У оси `font-size` пола нет, и это
 * измеренный факт зоны значений — минимального размера текста у WCAG 2.2 нет вовсе. Назначить
 * порог самим значило бы решить за автора, каким должен быть вид. Вместо отказа — отчёт
 * (`fluidPoles`): вычисленное значение на каждом полюсе автор видит при записи.
 *
 * @param name имя семени — оно же имя оси
 * @param seed объявление полюсами
 */
export function fluidRefusals(name: string, seed: FluidSeed): readonly FluidRefusal[] {
  const refusals: FluidRefusal[] = [];
  const say = (means: string): void => {
    refusals.push({ seed: name, means });
  };

  const axis = axisOf(name);
  const unit = axis?.unit ?? "";

  if (!FLUID_UNITS.includes(unit)) {
    say(
      `ось «${name}» измеряется в «${unit}», и текучей быть не может: доля ширины окна (\`vw\`) — ` +
        "ДЛИНА, а сложить её можно только с длиной. Браузер выбросил бы такое объявление целиком",
    );
    return refusals;
  }

  const края = [
    { где: "узком", запись: seed.narrow },
    { где: "широком", запись: seed.wide },
  ].map((край) => ({ ...край, разбор: measure(край.запись) }));

  for (const край of края) {
    if (!край.разбор) {
      say(`значение на ${край.где} полюсе «${край.запись}» не разбирается как число с единицей`);
    } else if (край.разбор.unit !== unit) {
      say(
        `значение на ${край.где} полюсе записано в «${край.разбор.unit || "без единицы"}», а ось ` +
          `«${name}» измеряется в «${unit}». Смешение единиц на одной оси означало бы, что ` +
          "половина лестницы не следует за настройкой кегля у человека",
      );
    }
  }

  const ширины = seed.between.map(measure);
  for (const [индекс, ширина] of ширины.entries()) {
    if (!ширина) say(`ширина полюса «${seed.between[индекс]}» не разбирается как число с единицей`);
    else if (ширина.unit !== "px") {
      say(
        `ширина полюса записана в «${ширина.unit || "без единицы"}», а ширины объявляются в ` +
          "пикселях: ширина окна величина пиксельная, и доля от неё считается от неё же",
      );
    }
  }

  if (refusals.length > 0) return refusals;

  const узкая = ширины[0]!;
  const широкая = ширины[1]!;
  const низ = края[0]!.разбор!;
  const верх = края[1]!.разбор!;

  if (широкая.amount <= узкая.amount) {
    say(
      `ширины полюсов не возрастают: ${seed.between[0]} → ${seed.between[1]}. Между ними ничего ` +
        "не растёт, и делить не на что",
    );
  }

  if (верх.amount < низ.amount) {
    say(
      `значение убывает: ${seed.narrow} на узком полюсе против ${seed.wide} на широком. Значение ` +
        "при большей ширине не может быть меньше — это арифметика, а не вкус",
    );
  }

  // Нормативный пол — на УЗКОМ полюсе: именно там текучее значение меньше всего.
  const пол = AXES.find((ось) => ось.token === name)?.floor;
  if (пол?.kind === "норма" && пол.value !== null && низ.amount < пол.value) {
    say(
      `на узком полюсе ${seed.narrow} ниже пола ${пол.value}${unit}, выведенного из нормы ` +
        `(${пол.norm ?? "норма"}). ${пол.why}`,
    );
  }

  return refusals;
}

/** Вычисленное значение семени на полюсе: в единице оси и в пикселях. */
export interface FluidPole {
  readonly value: string;
  readonly px: number;
}

/** Что автор увидит на краях — обе стороны разом. */
export interface FluidReport {
  readonly seed: string;
  readonly narrow: FluidPole;
  readonly wide: FluidPole;
}

/**
 * ОТЧЁТ О ПОЛЮСАХ — то, чем заменён отказ там, где отказывать не по чему.
 *
 * Пола у кегля нет, и назначать его самим нельзя: минимального размера текста у нормы нет вовсе.
 * Но одиннадцать пикселей на узком полюсе автор обязан увидеть ПРИ ЗАПИСИ, а не найти на
 * телефоне. Механика сообщает, а не запрещает — то же правило, что для читаемости.
 *
 * Пиксели названы рядом со значением намеренно: `0.6875rem` человеку ничего не говорит, а
 * «11 px» говорит сразу. Перевод — по тому же допущению о корневом кегле, что и вся арифметика.
 */
export function fluidPoles(name: string, seed: FluidSeed): FluidReport | null {
  const низ = measure(seed.narrow);
  const верх = measure(seed.wide);
  if (!низ || !верх) return null;

  return {
    seed: name,
    narrow: { value: seed.narrow, px: pixels(низ.amount, низ.unit) },
    wide: { value: seed.wide, px: pixels(верх.amount, верх.unit) },
  };
}

/** Печатает число коротко: без хвоста нулей, но и без потери значащих цифр. */
function число(amount: number): string {
  return String(Number(amount.toFixed(4)));
}

/**
 * Печатает текучее выражение из полюсов.
 *
 * `clamp()` берётся именно ради краёв: между полюсами значение растёт, а за ними — стоит. Без
 * зажима лестница уезжала бы в обе стороны без предела, и на очень широком экране семя интервалов
 * выросло бы до неприличного.
 *
 * Порядок аргументов зажима — от меньшего к большему, и это не украшение: `clamp()` при
 * перепутанных краях молча возвращает нижний, то есть выражение осталось бы действительным и
 * неверным. Возрастание проверено отказом до печати.
 */
export function fluidExpression(seed: FluidSeed): string {
  const низ = measure(seed.narrow)!;
  const верх = measure(seed.wide)!;
  const узкая = measure(seed.between[0])!;
  const широкая = measure(seed.between[1])!;

  const низPx = pixels(низ.amount, низ.unit);
  const верхPx = pixels(верх.amount, верх.unit);

  const наклон = (верхPx - низPx) / (широкая.amount - узкая.amount);
  const свободныйPx = низPx - наклон * узкая.amount;
  const свободный = низ.unit === "rem" ? свободныйPx / PX_IN_REM : свободныйPx;

  return `clamp(${seed.narrow}, ${число(свободный)}${низ.unit} + ${число(наклон * 100)}vw, ${seed.wide})`;
}
