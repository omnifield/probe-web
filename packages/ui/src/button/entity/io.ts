// ВХОД/ВЫХОД КНОПКИ — паспорт формы (PWEB-180 продолжение), РАНТАЙМ, не редакторская проза.
//
// Здесь, а не в `playground/` (постановка user, 2026-08-29: «io должен быть в ентити — это
// часть сущности, а не плэйграунда»), тем же водоразделом, что уже проведён у `passport.ts`:
// `entity/` — контракт, по которому компонент работает, `playground/` — то, что видит и
// настраивает человек в редакторе, и ничего из второго не нужно первому.
//
// Раньше вместо этого лежал `playground/data.ts` — литеральные `DataPreset` с прозой на
// человека («короткая подпись — обычный случай»). Компонент больше не возит с собой кучу
// текста — он возит `io`, а тем, чем витрина заполняется содержимым по этой форме, займётся
// скин-редактор (механика чтения этого файла — отдельный, следующий заход).
//
// Схема пишется инструментом `packages/io` (`z`, реэкспорт `zod` — см. его же `src/index.ts`,
// «через этот пакет, не напрямую»), НЕ раскрытым `zod` заново: пакет для этого и заведён.
//
// Форма снята с настоящего поведения кнопки, не выдумана заново: `passport.ts`'s `selfAssembly`
// читает ровно `/label`, `/data-variant`, `/payload` на входе и отдаёт `payload` как есть на
// клике — это одно и то же поведение, смотрящее с другой стороны, не второе независимое
// описание того же контракта.

import { z } from "@omnifield/probe-web-io";

/** Что кнопка ждёт на входе — то, что резолвит её собственный `selfAssembly`. */
export const input = z.object({
  label: z.string(),
  "data-variant": z.string().optional(),
  payload: z.unknown().optional(),
});

/** Что кнопка отдаёт наружу по клику — `payload` как есть, кнопка его не решает и не трогает. */
export const output = z.object({
  payload: z.unknown().optional(),
});
