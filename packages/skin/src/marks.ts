// Каждое объявлено ЗДЕСЬ и ровно один раз: литерал, разбросанный по вызывающим, — это тихая
// связь, которая переживает переименование и начинает врать (тот же довод, по которому зона
// значений вынесла `BASE_MARKER` на поверхность). Наружу они выходят потому, что ими
// пользуются ЧУЖИЕ механики: редактор ставит принудительный признак, механика сборки ставит
// признак узла, приложение включает тёмную пару.
//
// Своё и чужое здесь разного качества, и разница названа честно.

/**
 * Слой каскада, в котором лежит СКИН.
 *
 * Слой, а не вес селектора. Требование канона — правка образца обязана перебивать скин, — а по
 * весу выходит наоборот: координата даёт две единицы (`[data-scope][data-part]`), имя узла одну
 * (`[data-node]`). Чинить это утяжелением селектора значило бы решать вопрос каскада вкусом
 * записи: следующее правило с лишним атрибутом сломало бы порядок молча.
 *
 * Слои решают это по построению: правило из более позднего слоя перебивает правило из раннего
 * НЕЗАВИСИМО от веса. Оба порождённых текста объявляют порядок первой же строкой
 * (`LAYER_ORDER`), поэтому он не зависит от того, какой файл подключили раньше.
 *
 * Сверено с рынком 2026-08-20: каскадные слои — базовая возможность всех движков с марта 2022
 * (Chrome/Edge 99, Firefox 97, Safari 15.4), полифил `@csstools/postcss-cascade-layers`
 * существует и используется в пробе этой зоны как ПРОВЕРКА, а не как поставка.
 */
export const SKIN_LAYER = "probe-web-skin";

/**
 * Слой каскада, в котором лежат ПРАВКИ ОБРАЗЦА — правила по имени узла.
 *
 * Объявляется ПОСЛЕ скина, поэтому перебивает его при любом весе селектора.
 */
export const SKETCH_LAYER = "probe-web-sketch";

/**
 * Объявление порядка слоёв — первая строка КАЖДОГО порождённого текста.
 *
 * Повтор безвреден: порядок задаёт первое объявление, последующие ничего не меняют. Именно
 * поэтому оно стоит в обоих текстах, а не в одном «главном»: подключить их могут в любом
 * порядке и по отдельности, а порядок слоёв обязан быть один и тот же в любом случае.
 */
export const LAYER_ORDER = `@layer ${SKIN_LAYER}, ${SKETCH_LAYER};`;

/**
 * ПРИНУДИТЕЛЬНЫЙ ПРИЗНАК СОСТОЯНИЯ — то, чем предпросмотр показывает состояние, которого
 * данными выставить нельзя.
 *
 * Три состояния кнопки — псевдоклассы: наведение, нажатие, клавиатурный фокус. Их ставит
 * браузер, и редактор не может включить их ни атрибутом, ни пропом. Значит правило обязано
 * цепляться ещё и за признак, который поставить МОЖНО, — и делает это ТОТ ЖЕ генератор, что
 * делает поставку.
 *
 * Форма — перечень имён в одном атрибуте (`data-force="hover active"`), сверяется через `~=`.
 * Одно состояние — один токен; узел бывает сразу в нескольких, и второго атрибута под это
 * заводить не пришлось.
 *
 * Имена в перечне — имена СОСТОЯНИЙ из паспорта (`hover`), а не псевдоклассы (`:hover`): имя
 * состояния переживает смену кита, а разметка нет (`button.anatomy.ts` объявляет ровно это).
 */
export const FORCE_ATTRIBUTE = "data-force";

/**
 * Признак узла в разметке — то, чем адресуется ПРАВКА ОБРАЗЦА.
 *
 * ЧУЖОЕ ИМЯ. Ставит его механика сборки при отрисовке (`packages/assembly`, `render.tsx`), а
 * закреплено оно решением 2026-08-20 на странице «Скин»: «Имя закреплено и меняться не должно:
 * с первого сохранённого образца оно становится ключом в записи».
 *
 * Здесь оно записано вторым — и это названный пробел, а не выбор: у имени нет одного дома.
 * Правильно было бы, чтобы его объявляла та зона, что его СТАВИТ, а мы импортировали; наружу
 * она его не отдаёт, а дописывать чужую зону нельзя — вопрос поднят архитектору.
 *
 * ЧТОБЫ РАСХОЖДЕНИЕ НЕ БЫЛО ТИХИМ, стоит шовная проба (`test/seams.test.tsx`): она рисует узел
 * НАСТОЯЩЕЙ механикой сборки и спрашивает, попадает ли в него наш селектор. Переименуют у
 * хозяина — проба краснеет в тот же прогон. Без неё отказа бы не было вовсе: правило просто
 * перестало бы срабатывать, а чинить пошли бы вид.
 */
export const NODE_ATTRIBUTE = "data-node";

/**
 * Класс тёмной пары на корне документа.
 *
 * ЧУЖОЕ ИМЯ, ровно как `NODE_ATTRIBUTE`. Его объявляют и ставят зоны `runtime`
 * (`skin-root.ts`) и `style` (`palette.ts`), а нам оно нужно, потому что канон требует от
 * значения скина следовать за режимом: пара для тёмного — ответственность скина, а не набора
 * значений.
 *
 * Светлая половина — ОТСУТСТВИЕ класса, а не второй класс. Форма селектора взята у зоны
 * значений (`paletteSelector`): класс может стоять и на самом корне, и на предке внутри него.
 *
 * Расхождение стережёт та же шовная проба: она затемняет корень НАСТОЯЩИМ `applySkin()` из
 * `runtime` и спрашивает, цепляется ли порождённая тёмная половина.
 */
export const DARK_CLASS = "dark";
