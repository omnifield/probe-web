import type { Form, SlotRecipe } from "@omnifield/probe-web-skin/model";

/**
 * СЕТКА. Две части, состояний нет.
 *
 * МИНИМУМ КОЛОНКИ — СТУПЕНЬ ИНТЕРВАЛА (`--space-32`), А НЕ ЧИТАЕМОЙ КОЛОНКИ (`--column-*`), КАК
 * БЫЛО ДО ЭТОГО. Шкала колонки посеяна СРЕДНЕЙ ШИРИНОЙ ЗНАКА (`packages/style/src/dimension.ts`,
 * семя `column`) — её младшая ступень, `column-24`, это уже 24 знака ЧИТАЕМОГО ТЕКСТА, то есть
 * ≈24rem (384px) и выше. Годится для колонки ФОРМЫ (`<Grid><Field/><Field/></Grid>`, пример в
 * `components/index.tsx`), но сетка — компонент общего назначения, и у витрины тот же паспорт
 * кладёт в ячейку ЛЮБОЕ содержимое, вплоть до одной маленькой кнопки: на типичном экране от
 * читаемой колонки в 512px входит РОВНО ОДНА дорожка, она тянется на всю ширину, и любое
 * содержимое в ней выглядит потерянным в пустоте (найдено вживую, `products/skin`, галерея
 * случаев). Шкала интервала (`--space-*`) посеяна шагом сетки (`0.25rem`), а не длиной строки, и
 * её верхняя ступень (`--space-32`, по умолчанию 12–16rem — считает плотность и текучесть) —
 * общепринятая практика для минимума ПЛИТКИ в галерее (Tailwind/Chakra сажают то же самое на
 * шкалу интервала, не на шкалу текста). Форма-в-колонки как в примере `components/index.tsx`
 * этим не сломана: `--space-32` при обычной плотности всё ещё достаточно широк для поля с
 * подписью, а несколько дорожек умещаются на экране, где раньше умещалась одна.
 *
 * ОБЪЁМ ЯЧЕЙКИ («во всю строку» и т. п.) — НЕ ВАРИАЦИЯ И НЕ ЗДЕСЬ. Имя вариации живёт физически
 * ТОЛЬКО на корне (`rules.ts`, `growPart`, `PWEB-103`/`SKINED-5`) — признак на некорневой части,
 * которую ставит потребитель напрямую (как в примере `<GridCell data-variant="…">` в
 * `components/index.tsx`), ни одно правило не заденет: селектор вариации для чужой части всегда
 * читает атрибут ПРЕДКА (root), а не её собственный. Сколько места нужно ОДНОМУ экземпляру среди
 * одинаковых соседей — решение потребителя структуры, а не автора скина: у витрины это теперь
 * `ComponentFootprint` (`packages/skin/src/passport-editor.ts`, `footprintOf`), а не вариация.
 *
 * ТРИ ВАРИАЦИИ: `gallery` (умолчание, дословно повторяет базу — приём с поверхности,
 * `surface/playground/recipe.ts`) — повторяющаяся плитка автозаполнением; `sidebar` —
 * асимметричные две колонки ФИКСИРОВАННОЙ ширины (узкая + всё остальное), нужна каркасу
 * приложения (`products/skin/src/app/app.tsx`: рельсы слева, показ справа); `stack` — одна
 * колонка, две строки (заголовок по содержимому, остальное — в оставшееся место), нужна тому же
 * каркасу для правой половины (хедер сверху, показ снизу). Одной раскладкой колонок три этих
 * случая не выразить: `repeat(auto-fill, …)` даёт СКОЛЬКО УГОДНО одинаковых дорожек, `sidebar` —
 * РОВНО ОДНУ узкую и РОВНО ОДНУ широкую КОЛОНКУ, `stack` — то же самое, но СТРОКАМИ, — три разных
 * вопроса, три разных значения `gridTemplateColumns`/`gridTemplateRows`, а значит три вариации,
 * не настройка одной.
 */
export const recipe: SlotRecipe = {
  base: {
    root: {
      props: {
        display: "grid",
        gap: "var(--space-4)",
        gridTemplateColumns: "repeat(auto-fill, minmax(var(--space-32), 1fr))",
      },
    },
    cell: { props: { display: "block", minWidth: "0" } },
  },
  variants: {
    gallery: {
      root: {
        props: { gridTemplateColumns: "repeat(auto-fill, minmax(var(--space-32), 1fr))" },
      },
    },
    sidebar: {
      root: {
        props: { gridTemplateColumns: "minmax(var(--space-32), var(--column-24)) 1fr" },
      },
    },
    stack: {
      root: {
        props: { gridTemplateColumns: "1fr", gridTemplateRows: "auto 1fr", minBlockSize: "0" },
      },
    },
  },
  defaultVariant: "gallery",
};

/** Форма — запись «имя формы + компонент + рецепт», та же, что примет `assemble`. */
export const form: Form = { name: "сетка-проба", component: "grid", recipe };
