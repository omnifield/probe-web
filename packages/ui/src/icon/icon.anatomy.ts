// ПАСПОРТ значка (`PWEB-107`).
//
// Место под содержимое рода `icon` в паспорте стояло с прошлой волны — `accepts: [{kind:
// "content", genus: "icon"}]` у кнопки и вкладки гармошки, — а самого значка не существовало.
// `FITS.icon = ["icon", "component"]` уже пускал его и в слот под значок, и в слот под
// произвольный компонент; паспорт ниже делает это утверждение проверяемым на живом узле, а не
// декорацией, которую никто не сверяет.

import { createAnatomy } from "@zag-js/anatomy";

import { defineSettings, definePassport } from "../passport-form.js";
// ТИП пропов — только тип: `import type` стирается сборкой, и подпуть `./passport`
// остаётся данными без Solid. Нужен, чтобы ключи настроек сверялись с настоящими пропами.
import type { IconProps } from "./icon.jsx";

/** Части значка. Она одна: значок — это один узел `<svg>`, которым рисует `lucide-solid`. */
export const anatomy = createAnatomy("icon").parts("root");

/** Адреса частей: `attrs` для узла, `selector` для стиля. Считаются один раз — они статичны. */
export const parts = anatomy.build();

/**
 * Паспорт значка.
 *
 * Словарь состояний ПУСТ — тем же доводом, что у поверхности: значок не хранит ничего, чем его
 * вид мог бы отличаться сам по себе. Наведение и фокус принадлежат тому, что его держит
 * (кнопке, триггеру), — объяви мы их здесь, скин получил бы правило, которое никогда не
 * сработает на голом значке.
 *
 * Внутрь ничего не кладут: место занято самим компонентом, `<svg>` рисует `lucide-solid`
 * содержимым, которое паспорту не принадлежит. Пустой перечень — тот же приём, что у занятой
 * части (`admits`, `PWEB-24`).
 */
export const passport = definePassport({
  anatomy,
  // Поставщик назван данными: форма одна на всех, и читатель паспорта не знает имён пакетов
  // заранее. Совпадение с манифестом стережёт проба — иначе строка разъехалась бы молча.
  package: "@omnifield/probe-web-ui",
  // Значок — единственный компонент рода `icon` в ките (`PassportComponentGenus`): он и есть
  // тот кандидат, под который анатомия других частей заводит `accepts: [{kind:"content",
  // genus:"icon"}]`, а не обычный компонент, внутрь которого кладут.
  genus: "icon",
  root: "root",
  parts: [
    {
      name: "root",
      means: "значок — один символ, а не произвольное содержимое",
      states: [],
      accepts: [],
    },
  ],
  variantAxis: {
    // Ось здесь, как у поверхности, несёт весь вид: как значок выглядит рядом с текстом,
    // приглушённый он или акцентный — решает человек в редакторе, кит пропускает насквозь.
    means: "имя вариации значка; его даёт человек в редакторе, кит пропускает насквозь",
    mark: { kind: "attribute", name: "data-variant" },
  },
  // Группу не называем: перечень закрыт (`GROUPS`), и ни одна секция не описывает значок точнее
  // «прочего» без отдельного решения — заводить новую секцию под один компонент здесь не место
  // (`PWEB-34`, «новая группа заводится только решением»). Умолчание рабочее — значок не
  // пропадает из перечня, он в «прочем» (`groupOf`).
  // Настроек из закрытого перечня значок не принимает: `size`/`color`/`strokeWidth` — пропы
  // lucide, проходят насквозь тем же приёмом, что у кнопки, а не решаются словарём `SETTINGS`.
  settings: defineSettings<IconProps>({}),
  // Базовой сборки НЕТ, и это не пробел, а следствие контракта подпути `./passport`: он продан
  // как ДАННЫЕ, читаемые без Solid (README, «Что наружу»). Обязательный проп значка — `icon`,
  // ссылка на компонент `lucide-solid`, — не данные, а код; записать рабочий экземпляр честной
  // сборкой здесь нечем, а подставить произвольный компонент означало бы соврать о том, что
  // сборка эта делает.
});
