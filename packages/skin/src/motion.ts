// ГРАНИЦА «ВИД ПРОТИВ ДВИЖЕНИЯ» — решение зоны, названное ОДИН раз и здесь.
//
// ## Зачем граница вообще понадобилась
//
// Паспорт вправе объявить состояние, чей признак приезжает НЕ ВСЕГДА (`PassportState.absentWhen`,
// `PWEB-97`): раскрытость содержимого гармошки — ровно такое. Двум читателям от одного состояния
// нужно ПРОТИВОПОЛОЖНОЕ, и это не оттенок, а разные ответы на один вопрос:
//
//   • **виду** такой признак адресом не годится. Правило по нему молча не применилось бы ровно на
//     тех узлах, где признака нет, и одевающий узнал бы об этом глазами, а не машиной;
//   • **движению** отсутствие признака — ВЕРНЫЙ ОТВЕТ: перехода не было, проигрывать нечего.
//     Больше того, без `содержимое[open]` анимации раскрытия не написать вовсе — измеренную
//     высоту кит кладёт на тот же узел (`--height`), и второго адреса у неё нет.
//
// Значит адрес остаётся, а вид по нему становится изъяном (`view-unaddressable`). Развести эти два
// чтения можно ровно одним способом: сказать, ЧТО в правиле является движением. Это решение —
// его можно было принять иначе, — и потому оно живёт отдельным местом, а не условием, вписанным
// внутрь обхода. Вписанное в обход, оно повторилось бы у следующего читателя своими словами.
//
// ## РЕШЕНИЕ: движение — это семейства `animation` и `transition`, и только они
//
// Взято у самого CSS, а не выдумано: менять значение во времени объявлением умеют ровно два
// семейства — `animation-*` (CSS Animations 1) и `transition-*` (CSS Transitions 1) вместе со
// своими сокращениями. Третьего средства в каскаде нет, поэтому и перечень закрыт не вкусом.
//
// **Семейство по началу имени, а не перечень имён.** Оба семейства пополняются: `animation-
// composition`, `animation-timeline`, `transition-behavior` — все моложе исходных спецификаций.
// Выпиши мы имена поимённо, каждое новое приезжало бы к автору скина изъяном на законном CSS, а
// починка была бы не у него, а у нас.
//
// ## Что движением НЕ считается — и это тоже решение
//
// `height`, `opacity`, `transform` движением не считаются, хотя движут обычно именно их. Они и
// есть ВИД: написанные под ненадёжным признаком, они остаются тем самым правилом, которое
// применится не на всех узлах. Что именно двигать — сказано в ступенях именованного движения
// (`keyframes`), а те адресуются ИМЕНЕМ, а не состоянием, и под это правило не попадают вовсе.
//
// Из этого же следует, чем автор скина платит за границу: раскрытие пишется движением
// (`animation: раскрытие …`) либо переходом с адреса по НАДЁЖНОМУ предку — и оба пути открыты.

import { cssProperty } from "./property.js";

/**
 * Семейства свойств, которыми выражается ДВИЖЕНИЕ.
 *
 * Отдаётся значением, а не остаётся текстом в разборе: редактор обязан сказать человеку заранее,
 * что законно под ненадёжным признаком, — разбирать для этого строку отказа ему не с руки. Тот же
 * довод, по которому наружу отдан `NOT_SEEDED` и род запрета текучести.
 */
export const MOTION_FAMILIES = ["animation", "transition"] as const;

/**
 * Движение ли это свойство.
 *
 * Имя приводится к CSS-начертанию ТЕМ ЖЕ переводом, которым его печатает генератор
 * (`cssProperty`): `animationName` и `animation-name` — одно свойство, и второе написание перевода
 * разошлось бы с первым на первом же исключении.
 *
 * @param property имя свойства как записано в рецепте — в любом из двух начертаний
 */
export function isMotion(property: string): boolean {
  const name = cssProperty(property);

  return MOTION_FAMILIES.some((family) => name === family || name.startsWith(`${family}-`));
}
