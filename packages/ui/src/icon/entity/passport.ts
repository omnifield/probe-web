// РАНТАЙМ-паспорт значка (`PWEB-107`, `PWEB-115`, разнесено `PWEB-127`) — срез РАНТАЙМА.
//
// Место под содержимое рода `icon` в паспорте стояло с прошлой волны — `accepts: [{kind:
// "content", genus: "icon"}]` у кнопки и вкладки гармошки, — а самого значка не существовало.
// `FITS.icon = ["icon", "component"]` уже пускал его и в слот под значок, и в слот под
// произвольный компонент; паспорт ниже делает это утверждение проверяемым на живом узле, а не
// декорацией, которую никто не сверяет.
//
// Словарь состояний ПУСТ — тем же доводом, что у поверхности: значок не хранит ничего, чем его
// вид мог бы отличаться сам по себе. Наведение и фокус принадлежат тому, что его держит
// (кнопке, триггеру), — объяви мы их здесь, скин получил бы правило, которое никогда не
// сработает на голом значке.
//
// ЭТОТ ФАЙЛ ТОЛЬКО РАНТАЙМ — уезжает в бандл приложения. Срез РЕДАКТОРА — в `playground/index.ts`.

import { defineSettings, definePassport } from "@omnifield/probe-web-skin/model";
// ТИП пропов — только тип: `import type` стирается сборкой, и подпуть `./passport`
// остаётся данными без Solid. Нужен, чтобы ключи настроек сверялись с настоящими пропами.
import type { IconProps } from "../components/index.jsx";
import { anatomy } from "./anatomy.js";

export const passport = definePassport({
  anatomy,
  root: "root",
  parts: [{ name: "root", states: [] }],
  variantAxis: {
    mark: { kind: "attribute", name: "data-variant" },
  },
  // Настроек из закрытого перечня значок не принимает: `size`/`color`/`strokeWidth` — пропы
  // lucide, проходят насквозь тем же приёмом, что у кнопки, а не решаются словарём `SETTINGS`.
  settings: defineSettings<IconProps>({}),
});
