// Ограничители. В ПЕРВОЙ версии, а не «потом»: стенд публичный и без авторизации — писать и
// удалять может любой, кто знает адрес (`PROBEWEB-8`). Без предела хранилище забивают за
// вечер, и чинить это приходится ровно тогда, когда стенд кому-то показывают.
//
// Числа названы здесь вместе с тем, ОТКУДА они взяты, чтобы следующий не менял их гаданием.

/**
 * @typedef {object} Limits
 * @property {number} bodyBytes предел размера одной записи: тело запроса целиком, в байтах
 * @property {number} records предел числа записей в хранилище
 * @property {number} totalBytes предел ЗАНЯТОГО объёма всего хранилища, в байтах
 * @property {number} labelChars предел длины имени, в символах
 * @property {number} descriptionChars предел длины пояснения, в символах
 */

/** @type {Readonly<Limits>} */
export const LIMITS = Object.freeze({
  // 1 МиБ на запись. Прежние 64 КиБ отсчитывались от ОТБОРА — пары условий в пару килобайт.
  // Единица хранения с тех пор другая: это скин целиком (переменные плюс рецепты, по одному на
  // компонент), и он в прежний предел не влезал (`PWEB-13`).
  //
  // Замерено 2026-08-20 с ДВУХ сторон, потому что одного числа тут мало.
  //
  //   • по живому материалу: одежда 31 компонента, написанная зоной `skin` руками на CSS
  //     (1782 правила, 179,6 КиБ исходного текста), в форме рецепта занимает ~105 КиБ; одна
  //     кнопка — ~2,8 КиБ. Проекция на кит целиком (Ark даёт 69 компонентов) — ~235 КиБ;
  //   • по худшему случаю: проба `test/store.test.js` собирает скин, где КАЖДОЕ из четырёх
  //     состояний расписано у каждой из пяти частей, — вчетверо плотнее живого. Такой скин на
  //     весь кит весит 658 КиБ.
  //
  // 1 МиБ накрывает оба: четырёхкратный запас к правдоподобному полному киту и полуторный — к
  // нарочно раздутому. Запас берётся от ОДЕТОГО ЦЕЛИКОМ кита, а не от сегодняшней кнопки:
  // предел, подогнанный под текущий охват, отказал бы ровно в тот день, когда скин дорастёт до
  // полного кита, — и отказал бы посреди сохранения чужой работы.
  //
  // Меряем ТЕЛО ЗАПРОСА целиком, а не только состояние: считать надо то, что реально прилетает
  // в сокет, иначе предел обходится длинным именем.
  bodyBytes: 1024 * 1024,

  // 200 записей. Список пресетов выбирают ГЛАЗАМИ по имени — на второй сотне он перестаёт
  // быть списком независимо от того, сколько там места.
  records: 200,

  // 64 МиБ на всё хранилище. Этот предел ЗАВЕДЁН вместе с предыдущей правкой, и вот почему.
  //
  // Раньше объём тома ограничивался ПРОИЗВЕДЕНИЕМ: 200 × 64 КиБ ≈ 12,5 МиБ — «величина, про
  // которую можно не думать». Произведение работало, пока записи были однородны. Теперь в одном
  // хранилище лежат отборы по паре килобайт и скины по сотне, и то же произведение даёт 200 МиБ:
  // граница, выведенная из двух чисел, ни одно из которых про место на диске не говорит.
  //
  // Стенд публичный и без авторизации — писать может любой, кто знает адрес. Значит место на
  // диске нужно ограничить ПРЯМО, а не следствием. 64 МиБ — это и полсотни полных скинов, и
  // тысячи отборов; упереться в него обычной работой нельзя, а залить том за вечер — уже нет.
  //
  // Отказ у обоих пределов ОДИН (`storage_full`, 409): для того, кто читает ответ, действие
  // одно и то же — удалить ненужное. Разное только в тексте для человека.
  totalBytes: 64 * 1024 * 1024,

  // Имя и пояснение — показываются в списке. Предел здесь не про место, а про то, чтобы одна
  // запись не растянула список на экран; заодно закрывает вставку простыни в поле имени.
  labelChars: 120,
  descriptionChars: 1000,
});

/**
 * Ограничители КАНАЛА К АГЕНТУ (`PROBEWEB-9`).
 *
 * Здесь они стерегут не место на диске, а деньги: каждый вызов оплачен, а адрес публичный.
 *
 * @typedef {object} AgentLimits
 * @property {number} textChars предел длины описания отбора
 * @property {number} fieldsCount предел числа полей в словаре
 * @property {number} perWindow сколько обращений с одного адреса за окно
 * @property {number} windowMs длина окна, мс
 * @property {number} perDay общий дневной предел обращений ко всей службе
 * @property {number} timeoutMs сколько ждём модель
 */

/** @type {Readonly<AgentLimits>} */
export const AGENT_LIMITS = Object.freeze({
  // 500 символов. Описание отбора — фраза, а не документ: «сделки свыше миллиона за квартал,
  // кроме Москвы» это 60 символов. Восьмикратный запас, и при этом длинная простыня не уедет
  // в оплачиваемый запрос.
  textChars: 500,

  // 100 полей. Столько имён ещё имеет смысл передавать модели: на большем словаре она начнёт
  // путать похожие поля, и отбор станет хуже, а не богаче. Заодно предел на объём запроса.
  fieldsCount: 100,

  // Пять обращений в минуту с адреса. Человек, который собирает отбор, за минуту формулирует
  // одну-две фразы; пять — это уже перебор вариантов, и он тоже допустим. Всё, что чаще, —
  // не человек.
  perWindow: 5,
  windowMs: 60_000,

  // 200 обращений в сутки на ВСЮ службу. Это про худший случай, а не про наш расход: при
  // ~1000 токенов на обращение и цене Haiku ($1 за миллион входящих) сутки под завязку стоят
  // центы. Смысл предела в том, что счёт за найденный ботом адрес ИЗВЕСТЕН ЗАРАНЕЕ.
  perDay: 200,

  // 20 секунд. Дольше человек у экрана всё равно не ждёт — он решит, что сломалось.
  timeoutMs: 20_000,
});
