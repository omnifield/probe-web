// РАЗМЕРНЫЕ ШКАЛЫ СКИНА — второй ряд посеваемых значений рядом с цветовыми.
//
// ## Зачем они здесь появились (`PWEB-64`)
//
// Правило владельца продукта: одна механика на один поток, сбоку не лепится ничего, и человек,
// собравший вид в редакторе, обязан увидеть в приложении ТО ЖЕ САМОЕ. Третье и есть причина
// первых двух: любое значение, приезжающее в приложение мимо скина, — это расхождение между
// редактором и приложением, и всплывает оно у человека, а не у нас.
//
// Размерные ступени (`--space-3`, `--radius-md`, кегль, ширины колонок, высоты контролов) до сих
// пор приезжали общим листом зоны значений — то есть мимо скина. Покрасить они ничего не могут,
// но это ВТОРОЙ ПУТЬ к тому же результату, а второго пути не заводится ни для чего.
//
// ## Своей арифметики здесь нет ни одной строки
//
// Форма шкалы — множители, смещения, ось плотности, посадка на сетку — приходит ДАННЫМИ от зоны
// значений (`DERIVED_SCALES`, `GRID_STEP`, `ROUND_SUPPORT_TEST`, `DENSITY_TOKEN`). Та же причина,
// по которой цветные лестницы строит чужой `buildScale`: два ответа на вопрос «сколько это»
// разъехались бы, и правым оказался бы тот, кого спросили последним.
//
// Печатаем мы, а не сосед, и вот почему это не вторая реализация. Его печать (`derivedCss`)
// подставляет в каждую ступень ЗАПАСНОЕ значение — `var(--space, 0.25rem)`, — потому что общий
// лист обязан работать без семени. Скину такое запрещено прямо: умолчание сбоку это ровно тот
// второй путь, ради снятия которого всё и делается. Данные общие, контракт разный.
//
// ## Нет семени — нет значений
//
// Скин, не назвавший семени шкалы, не получает ни одной её ступени. Не «получает базовые», не
// «берёт как раньше» — НЕ ПОЛУЧАЕТ. Правило, адресующее ступень непосеянной шкалы, становится
// изъяном записи (`unknown-value`), и порождение отказывает с названной причиной.
//
// Это и есть ответ на вопрос «что делает скин, не назвавший семени», и выбран он потому, что
// любой другой ответ заводит умолчание заново: запасное значение в генераторе, `var(--x, …)` в
// ступени, «ряд по умолчанию» — всё это одно и то же под разными именами. Отсутствие значения —
// состояние, и оно НАЗЫВАЕТСЯ.
//
// ## Что скину НЕ принадлежит
//
// Граница проходит не по категории значения, а по тому, **решение ли это автора скина**.
//
// Посеваемое — решение: цвет, скругление, шаг интервалов, кегль, плотность. Поменял семя —
// поменялся вид, и это ровно то, ради чего человек садится в редактор.
//
// А вот **шкала слоёв** (`--z-dropdown`, `--z-dialog`, …) решением автора НЕ является, и здесь её
// нет намеренно. Порядок «диалог выше затемнения, затемнение выше поповера» — это контракт
// сосуществования компонентов, а не вид: скин, поменявший его, ломает РАБОТУ (диалог уезжает под
// собственное затемнение), а канон запрещает скину менять поведение. Двух законных ответов у
// этого вопроса нет — есть один рабочий и один сломанный, а значит и вкусу тут места нет.
// Где ей жить после снятия общего листа — cross-zone решение, заявка поднята.
//
// Нормированные ряды без семени (`--leading-*`, `--weight-*`, `--control-target-min`) сюда тоже
// не едут: посеять их нечем, значит и пересеять нельзя, значит это не шкала. Скин, которому они
// нужны, объявляет их ЛИТЕРАЛАМИ — путь литералов объявлен опорным и законен всегда, а редактор
// кладёт туда готовый ряд, взяв его у зоны значений данными. Механика при этом не подставляет
// ничего, и это то же самое правило, что и выше.

import {
  DENSITY_TOKEN,
  DERIVED_SCALES,
  GRID_STEP,
  ROUND_SUPPORT_TEST,
  type DerivedScale,
  type DerivedStep,
} from "@omnifield/probe-web-style";

import type { Skin, SkinVariables } from "./recipe.js";
import { trace } from "./trace.js";

/** Шкала по имени семени — перечень соседа, а не наш список. */
const BY_SEED = new Map<string, DerivedScale>(DERIVED_SCALES.map((scale) => [scale.seed, scale]));

/** Имена семян, которые скин вправе назвать: размерные шкалы плюс ось плотности. */
export const SIZE_SEEDS: readonly string[] = [
  ...DERIVED_SCALES.map((scale) => scale.seed),
  DENSITY_TOKEN,
];

/**
 * Ссылка на семя — БЕЗ запасного значения.
 *
 * Ровно это и отличает набор скина от общего листа: там `var(--space, 0.25rem)`, здесь
 * `var(--space)`. Семя объявлено скином рядом, поэтому подстраховывать нечего, а подстрахуй мы —
 * завели бы умолчание в обход скина заново.
 */
function ref(name: string): string {
  return `var(--${name})`;
}

/** Значение одной ступени: множитель, смещение или литерал — как объявила шкала. */
function stepValue(scale: DerivedScale, step: DerivedStep): string {
  if ("value" in step) return step.value;

  const seed = ref(scale.seed);

  // Смещение нулевое — это само семя: `calc(var(--radius))` работал бы, но лишняя обёртка
  // читается как «здесь что-то считается», а здесь ничего не считается.
  if ("offset" in step) return step.offset ? `calc(${seed} ${step.offset})` : seed;

  const parts = [seed];
  if (step.factor !== 1) parts.push(String(step.factor));
  if (scale.density) parts.push(ref(DENSITY_TOKEN));

  return parts.length === 1 ? seed : `calc(${parts.join(" * ")})`;
}

/** Та же ступень, посаженная на сетку. `null` у шкалы, которая на сетку не садится. */
function snappedValue(scale: DerivedScale, step: DerivedStep): string | null {
  return scale.snap ? `round(nearest, ${stepValue(scale, step)}, ${GRID_STEP})` : null;
}

/** Шкалы скина в порядке, объявленном зоной значений: он же порядок блоков в выводе. */
function declaredScales(variables: SkinVariables | undefined): DerivedScale[] {
  const sown = variables?.dimensions ?? {};
  return DERIVED_SCALES.filter((scale) => sown[scale.seed] !== undefined);
}

/** Семя шкалы, названное скином, — то, что уезжает в объявление и в остальные ступени. */
export interface SizeSeed {
  readonly name: string;
  readonly value: string;
}

/** Изъян размерного набора: имя, место и что это значит. */
export interface SizeRefusal {
  readonly seed: string;
  readonly means: string;
}

/**
 * Семена и ступени, которые скин ОБЪЯВЛЯЕТ: имя без `--` → значение.
 *
 * Значение здесь — выражение (`calc(var(--space) * 3 * var(--density))`), а не число: посчитать
 * его может только браузер, у которого есть корневой кегль и настройка человека. Считать самим
 * значило бы заморозить `rem` в момент порождения.
 *
 * Ступени с посадкой на сетку сюда НЕ попадают: они второе объявление того же имени и живут под
 * `@supports` (`sizeBlocks`). Перечень имён от этого не меняется — на то они и второе объявление.
 */
export function sizeValues(skin: Skin): Map<string, string> {
  const done = trace(`sizeValues(${skin.name})`);
  const values = new Map<string, string>();

  for (const [seed, value] of Object.entries(skin.variables?.dimensions ?? {})) {
    if (BY_SEED.has(seed) || seed === DENSITY_TOKEN) values.set(seed, value);
  }

  for (const scale of declaredScales(skin.variables)) {
    for (const step of scale.steps) values.set(step.name, stepValue(scale, step));
  }

  done();
  return values;
}

/**
 * Что в размерном наборе не сходится.
 *
 * Два случая, и оба — изъян ЗАПИСИ, а не поломка счёта:
 *
 *  • **имя семени неизвестно.** Шкалы с таким именем нет ни у нас, ни у зоны значений, и молча
 *    проглотить его нельзя: человек написал `spacing` вместо `space` и получил бы скин без
 *    интервалов, а чинить пошёл бы вид;
 *  • **шкала масштабируется плотностью, а плотность не названа.** Ступень ссылается на
 *    `var(--density)`, и без объявления браузер выбрасывает ВСЮ ступень как недействительную.
 *    Геометрия не ухудшается — она исчезает, и исчезает молча. Подставить плотность за человека
 *    нельзя (это умолчание в обход), поэтому называем.
 */
export function sizeRefusals(variables: SkinVariables | undefined): readonly SizeRefusal[] {
  const sown = variables?.dimensions ?? {};
  const refusals: SizeRefusal[] = [];

  for (const seed of Object.keys(sown)) {
    if (BY_SEED.has(seed) || seed === DENSITY_TOKEN) continue;
    refusals.push({
      seed,
      means:
        `размерной шкалы «${seed}» не существует. Объявленные семена: ${SIZE_SEEDS.join(", ")}`,
    });
  }

  const density = sown[DENSITY_TOKEN] !== undefined;
  if (!density) {
    for (const scale of declaredScales(variables).filter((scale) => scale.density)) {
      refusals.push({
        seed: scale.seed,
        means:
          `шкала «${scale.seed}» масштабируется плотностью, а семя «${DENSITY_TOKEN}» не названо. ` +
          "Каждая её ступень ссылается на необъявленное имя, и браузер выбросит ступень целиком — " +
          "геометрия не ухудшится, а исчезнет",
      });
    }
  }

  return refusals;
}

/**
 * Печатает размерный набор скина: объявления семян, ступени и подстраховку сетки.
 *
 * Подстраховка — ТА ЖЕ форма, что у общего листа, и по той же причине: значение шкалы со `snap`
 * объявляется дважды. Первым — без округления: его берёт браузер, который `round()` не
 * поддерживает, и получает дробное, но ЖИВОЕ значение. Вторым, под `@supports`, — то же значение
 * на сетке: его берёт браузер с поддержкой, потому что `@supports` веса не добавляет и побеждает
 * объявление, стоящее позже. Порядок обязателен именно поэтому.
 *
 * Это не запасное значение и не умолчание: оба объявления считают ОДНО И ТО ЖЕ семя скина, и
 * второе отличается от первого только посадкой на сетку.
 *
 * @param skin скин целиком
 * @param indent отступ блока — печатаем внутри слоя, как и остальные значения
 */
export function sizeBlocks(skin: Skin, indent: string): string[] {
  const values = sizeValues(skin);
  if (values.size === 0) return [];

  const blocks: string[] = [
    [
      `${indent}:root {`,
      ...[...values].map(([name, value]) => `${indent}  --${name}: ${value};`),
      `${indent}}`,
    ].join("\n"),
  ];

  const snapped = declaredScales(skin.variables).flatMap((scale) =>
    scale.steps
      .map((step) => [step.name, snappedValue(scale, step)] as const)
      .filter((pair): pair is readonly [string, string] => pair[1] !== null),
  );

  if (snapped.length > 0) {
    blocks.push(
      [
        `${indent}@supports ${ROUND_SUPPORT_TEST} {`,
        `${indent}  :root {`,
        ...snapped.map(([name, value]) => `${indent}    --${name}: ${value};`),
        `${indent}  }`,
        `${indent}}`,
      ].join("\n"),
    );
  }

  return blocks;
}
