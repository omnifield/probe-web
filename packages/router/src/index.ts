// Единственная точка входа в роутинг probe-web (`PROBEWEB-4`).
//
// Приложение НЕ импортирует `@tanstack/solid-router` напрямую — ни в ручных маршрутах, ни
// (это единственное, что здесь настраивается снаружи) в порождённом `routeTree.gen.ts`,
// который зовёт `import { createFileRoute } from "@omnifield/probe-web-router"` (см.
// `routesDirectory`/шаблон в `./vite.ts`). Единый путь резолва даёт единый экземпляр модуля:
// `RouterProvider` и `useNavigate` в разных файлах обязаны видеть один и тот же контекст,
// а не две копии пакета из-за двух разных спецификаторов импорта.
//
// Полный реэкспорт, а не отбор по имени — здесь другая задача, чем у `ui` (та кладёт СВОЮ
// разметку поверх kobalte). У роутинга своей разметки нет: весь смысл пакета — быть тем самым
// единственным путём резолва, а не фильтровать поверхность вендора. Ручная выборка из ~80
// экспортов только развела бы дрейф: TanStack добавит хук минорным выпуском — мы забудем его
// сюда дописать, и приложение упрётся в стену без единой причины.
export * from "@tanstack/solid-router";

/**
 * Дефолты роутера, вынесенные в одно место, чтобы каждое приложение probe-web не подбирало их
 * заново.
 *
 * Литерал, а не функция-обёртка над `createRouter()`. Причина не вкусовая: `createRouter()` —
 * та самая точка, где TypeScript выводит ТИП дерева маршрутов из аргумента и привязывает его к
 * `Register` (`declare module` в `router.ts` потребителя). Обёртка эту связь рвёт — сверено
 * (`TanStack/router#1943`: контекст-типизация ломалась именно на обёрнутом вызове, а не на
 * прямом). Поэтому приложение зовёт `createRouter({ ...defaultRouterOptions, routeTree })`
 * САМО — обёртки нет, есть только объект, который можно безопасно разложить спредом.
 */
export const defaultRouterOptions = {
  /** Подгрузка соседних маршрутов по наведению/фокусу на `<Link>` — рыночный дефолт TanStack. */
  defaultPreload: "intent",
  /** Подгруженное протухает мгновенно: снимает риск открыть с ним устаревшую страницу. */
  defaultPreloadStaleTime: 0,
  /** Позиция скролла восстанавливается при навигации назад/вперёд — без этого прыгает в (0,0). */
  scrollRestoration: true,
} as const;
