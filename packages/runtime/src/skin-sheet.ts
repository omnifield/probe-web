// Лист стилей надетого скина. ВНУТРЕННЕЕ — см. шапку `skin-root.ts`.
//
// ПОЧЕМУ ОБЫЧНЫЙ ТЕГ, А НЕ КОНСТРУИРУЕМЫЙ ЛИСТ. Сверено с рынком 2026-08-20: конструируемые
// листы (`CSSStyleSheet` + `document.adoptedStyleSheets`) есть во всех движках с марта 2023 и
// считаются сегодня основным способом отдать документу стили строкой. Не берём по проверяемой
// причине, а не по вкусу: принятые листы стоят в каскаде ПОСЛЕ всех листов документа и потому
// перебивают их всегда. Задача требует обратного — «статическая страница, подключившая файл
// скина сама и без этой механики, выглядит ТАК ЖЕ»; у такой страницы скин это обычный лист в
// голове документа, и совпасть с ним может только обычный лист. Побочно тег ещё и виден в
// инструментах разработчика, то есть человек может проверить, что именно на нём надето.
//
// Тег СВОЙ у каждого переключателя, а не общий на модуль. Общий пережил бы перезапуск модуля
// при горячей замене: старый экземпляр снимал бы тег, который уже успел завести новый.

/** Метка нашего листа. Человеку в инструментах разработчика и нам — чтобы отличить свой. */
const OWNER_ATTR = "data-web-core-skin";

export interface SkinSheet {
  /** Кладёт текст скина в свой лист, заводя его при первой надобности. */
  put(css: string): void;
  /** Снимает свой лист из документа. Повторный вызов безвреден. */
  drop(): void;
  /** Стоит ли наш лист в документе сейчас. */
  attached(): boolean;
}

/**
 * Заводит владельца одного листа стилей.
 *
 * Смена скина — это ЗАМЕНА ТЕКСТА в уже стоящем листе, а не «снять один тег, повесить другой».
 * Разница видна глазом: между снятием старого и разбором нового браузер успевает нарисовать
 * кадр голого кита, и переключение скина мигает.
 */
export function makeSkinSheet(): SkinSheet {
  let el: HTMLStyleElement | undefined;

  /** Наш лист, стоящий в документе. Его могли снять снаружи — тогда заводим заново. */
  function sheet(): HTMLStyleElement {
    if (el === undefined || !el.isConnected) {
      el = document.createElement("style");
      el.setAttribute(OWNER_ATTR, "");
      document.head.append(el);
    }
    return el;
  }

  return {
    put(css: string): void {
      sheet().textContent = css;
    },

    drop(): void {
      el?.remove();
      el = undefined;
    },

    attached(): boolean {
      return el !== undefined && el.isConnected;
    },
  };
}
