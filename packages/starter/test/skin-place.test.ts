// НАЗВАННОЕ МЕСТО ДЛЯ СКИНА (`tasker:PROBEWEB-53`, контракт механики `kb:PROBEWEB-13`,
// инварианты `kb:SKIN-7`).
//
// Скелет обязан объявлять пресет и режим сам: с `kb:PROBEWEB-18` палитра цепляется к документу
// ТОЛЬКО по имени, `:root` не красится ничем, и приложение, не назвавшее палитру, выходит
// нецветным. Пробы здесь сторожат три вещи, каждая из которых ломается молча:
//
//   • ПОРЯДОК подключения — пресет перед ступенями даёт вид, посчитанный от умолчаний
//     («скин почти работает» — хуже явной поломки);
//   • ЛИТЕРАЛЫ ЧУЖИХ ЗОН — имя палитры и имя токена-маркера принадлежат `style`, а этот файл
//     кладётся потребителю классом `placed-once` и не обновляется НИКОГДА: литерал здесь
//     переживёт переименование и разъедется молча, починить его можно только руками;
//   • НЕОБЯЗАТЕЛЬНОСТЬ ОФОРМЛЕНИЯ — приложение без единого файла скина обязано запускаться
//     (инвариант 4).
//
// ПОЧЕМУ ЛИТЕРАЛЫ МОЖНО ДЕРЖАТЬ ЗДЕСЬ, А В ШАБЛОНЕ НЕЛЬЗЯ. Проба живёт в нашем репозитории и
// едет нашими выпусками: разъедется — покраснеет у нас, до публикации. Шаблон живёт у
// потребителя и не едет никуда.

import { describe, expect, it } from "vitest";

import { readTemplate } from "./source.js";

const STYLE = "@omnifield/probe-web-style";
const RUNTIME = "@omnifield/probe-web-runtime";

/** Точка входа без строчных комментариев: судим КОД, а не пояснение над ним. */
const main = readTemplate("main.tsx").replace(/^\s*\/\/.*$/gm, "");

/** Разметка без комментариев — по той же причине. */
const html = readTemplate("index.html").replace(/<!--[\s\S]*?-->/g, "");

/** Позиция подстроки в коде точки входа; -1 значит «нет вовсе». */
const at = (needle: string): number => main.indexOf(needle);

/**
 * Имена, принадлежащие ЧУЖИМ зонам, у которых есть экспорт. Каждое сопровождается тем, чем его
 * обязан звать скелет: проба не просто запрещает строку, а называет замену.
 */
const FOREIGN_LITERALS: readonly (readonly [string, string])[] = [
  // Идентификатор дефолтной палитры (`kb:PROBEWEB-18`).
  ['"default"', `DEFAULT_PALETTE из ${STYLE}`],
  ["'default'", `DEFAULT_PALETTE из ${STYLE}`],
  // Имя токена-маркера базы (`kb:PROBEWEB-13`).
  ["--control-target-min", `BASE_MARKER из ${STYLE}`],
  // Опознание пресета и режима на корне — шов `kb:SKIN-5`, его держит рантайм у себя.
  ["data-theme", `restoreSkin()/applySkin() из ${RUNTIME}`],
  // Ключ хранилища выбора — внутреннее рантайма, потребителю его знать не нужно.
  ["probe-web:skin", `умолчание restoreSkin() из ${RUNTIME}`],
];

describe("названное место: приложение объявляет пресет и режим", () => {
  it("стоит в точке входа и зовёт механику рантайма", () => {
    // Место названо и прокомментировано — первый пункт заявки `skin` (`kb:PROBEWEB-13`).
    // Потребитель не должен догадываться, куда это писать.
    expect(main).toContain(`restoreSkin({ presets: [DEFAULT_PALETTE] });`);
  });

  it("берёт имя палитры экспортом стилевого слоя, а не строкой", () => {
    expect(main).toContain(`import { BASE_MARKER, DEFAULT_PALETTE } from "${STYLE}";`);
  });

  it("объясняет себя прямо в файле", () => {
    // Дока доезжает к потребителю только тем, что лежит рядом: README обвеса у него не
    // окажется, а этот файл окажется. Над строкой обязано стоять пояснение — почему имя на
    // корне, почему порядок значим, почему имя, а не литерал.
    const raw = readTemplate("main.tsx");
    const place = raw.indexOf("restoreSkin({");
    const comment = raw.slice(0, place).split(/\n\s*\n/).at(-1) ?? "";
    expect(comment).toMatch(/^\s*\/\//);
    expect(comment.split("\n").length).toBeGreaterThan(3);
  });
});

describe("порядок подключения — не декоративный", () => {
  it("базовый слой идёт перед ступенями палитр", () => {
    // Обратный порядок даёт вид, посчитанный от умолчаний. Мутация «переставить две строки
    // местами» обязана красить эту пробу.
    expect(at(`import "${STYLE}/base.css";`)).toBeGreaterThanOrEqual(0);
    expect(at(`import "${STYLE}/base.css";`)).toBeLessThan(at(`import "${STYLE}/themes.css";`));
  });

  it("оба CSS-подпутя идут перед объявлением пресета", () => {
    // Пресет, поставленный раньше файлов, красить нечем: правило палитры ещё не приехало.
    expect(at(`import "${STYLE}/themes.css";`)).toBeLessThan(at("restoreSkin({"));
  });

  it("пресет и режим встают до монтирования", () => {
    // Класс режима после первого кадра — вспышка светлой темы перед тёмной (инвариант 3).
    // Раньше монтирования — самое раннее, до чего дотягивается скелет, не зашивая литералов.
    expect(at("restoreSkin({")).toBeLessThan(at("mount("));
  });
});

describe("проверка порядка — ДРУГАЯ точка, а не та же самая", () => {
  it("питается именем маркера, а не строкой", () => {
    expect(main).toContain("checkStyleOrder({ marker: BASE_MARKER });");
  });

  it("стоит ПОСЛЕ монтирования", () => {
    // Постановке пресета стили не нужны вовсе, поэтому её зовут как можно раньше. Проверке
    // они нужны по определению — она спрашивает вычисленное значение токена на корне, и
    // рано звать её бессмысленно. Слитые в одну точку, они тянут друг друга в разные стороны.
    expect(at("checkStyleOrder({")).toBeGreaterThan(at("mount("));
  });
});

describe("ни одного литерала чужой зоны в скелете", () => {
  for (const [literal, instead] of FOREIGN_LITERALS) {
    it(`не держит «${literal}» — вместо него ${instead}`, () => {
      // Файл `placed-once`: обвес в него больше не заглянет, и переименование у соседа
      // чинится у уже созданных продуктов только правкой руками.
      expect(main, "main.tsx").not.toContain(literal);
      expect(html, "index.html").not.toContain(literal);
    });
  }
});

describe("оформление остаётся необязательным", () => {
  it("не подключает ни одного файла оформления", () => {
    // Инвариант 4: приложение без единого файла `skin` обязано запускаться и быть пригодным
    // к работе. Слот для пресета и оформления в шаблоне ЗАКРЫТ комментарием — открывает его
    // потребитель, когда поставщик у него появится.
    for (const specifier of [...main.matchAll(/import\s+"([^"]+)";/g)].map((m) => m[1])) {
      expect(specifier, specifier).toMatch(new RegExp(`^${STYLE}/`));
    }
  });

  it("называет слот словами, чтобы его было где открыть", () => {
    // Без названного слота потребитель откроет импорт там, где придётся, — и порядок,
    // ради которого всё это писано, сломается на первом же пресете.
    const raw = readTemplate("main.tsx");
    expect(raw).toMatch(/^\s*\/\/\s*import\s+"<[^>]+>\/presets\//m);
    expect(raw).toMatch(/^\s*\/\/\s*import\s+"<[^>]+>\/skin\.css";/m);
  });
});
