// ПОРОЖДЕНИЕ CSS-АРТЕФАКТОВ ЗОНЫ. Раньше склейка жила в сборочном сценарии, и порождать CSS
// умела только сборка — то есть в разработке приложение видело результат ПРОШЛОЙ сборки, а
// правка токена или перечня доезжала до глаз только следующей ручной командой (`PWEB-20`).
//
// Здесь это обычный модуль зоны, и зовётся он тремя разными местами одинаково:
//   • сборочный сценарий (`scripts/build-css.mjs`) — пишет `dist/css/*.css` для поставки;
//   • дев-сервер — порождает CSS В МОМЕНТ ЗАПРОСА, из текущих исходников (зацеп в дев-сервере
//     живёт в зоне `build`: подпуть `/generate` для того и объявлен на поверхности);
//   • пробы — сверяют порождённое с тем, что уехало в поставку.
//
// Функции ЧИСТЫЕ: ни файловой системы, ни путей, ни аргументов. Сборка, дев-сервер и
// установка потребителя зовут их из разных мест, и любой из этих входов, потребовавший знать
// нашу раскладку, немедленно стал бы вторым источником правды о ней.
//
// Сверка с рынком (2026-08-19): порождение по запросу через плагин дев-сервера и виртуальный
// модуль — устоявшийся приём, так работают UnoCSS (`virtual:uno.css`) и `@tailwindcss/vite`.
// Оттуда взята РАСКЛАДКА: генерация — чистая функция пакета, зацеп — плагин, который зовёт её
// на запрос и инвалидирует при правке исходников. Своего изобретаем ровно нашу склейку.
//
// СКЛЕИВАТЬ БОЛЬШЕ НЕЧЕГО (`PWEB-66`): в листе остался один сброс, и порождение сводится к
// шапке плюс ручная часть. Прежде здесь был значимый ПОРЯДОК блоков — плотная шкала
// объявлялась дважды, и второе объявление побеждало тем, что стояло позже. Ушло вместе со
// шкалой; печатает её теперь скин, у себя и по своим правилам.

import { trace } from "../trace.js";
import { WRITTEN_BASE } from "./written.js";

/**
 * Базовый слой целиком: шапка и ручная часть. Собирать больше нечего — в листе остался один
 * сброс (`PWEB-66`).
 *
 * Функция при этом осталась, и не по инерции: порождение обязано быть ОДНОЙ дорогой к листу,
 * иначе дев-сервер и сборка снова начнут отдавать разное (`PWEB-20`). Сегодня она короткая —
 * это свойство листа, а не признак лишнего звена.
 *
 * @returns содержимое `base.css`
 */
export function baseCss(): string {
  const done = trace("baseCss");

  const css = [
    `/* @web-core/style — БАЗОВЫЙ СЛОЙ, подпуть \`@web-core/style/base.css\`.

   ТОЛЬКО СБРОС (\`PWEB-66\`). Ни одного кастом-свойства, ни одного значения, ни одного
   запасного варианта. Базовый слой снимает решения браузера и своих не вносит.

   Снятие шло тремя заходами: сперва шесть объявлений вида на \`body\` (\`PWEB-39\`), потом
   35 семантических ролей, 28 устаревших имён и \`color-scheme\` (\`PWEB-61\`), теперь
   остаток — длительности и кривые, размерные шкалы с блоком \`@supports\`, шкала слоёв,
   межстрочные, начертания, пол нормы, границы осей.

   PWEB-122 дописал в лист единственное добавление с тех пор, как он стал чистым сбросом:
   \`appearance: none\` на кнопках. Живой Chromium показал \`appearance: auto\` поверх
   \`background: transparent\`, который ставит скин, — браузер красит кнопку своим сплошным
   видом мимо скина. То же основание, что у \`box-sizing\`: снимаем решение браузера.

   ЗНАНИЕ НЕ УШЛО, ушла ПЕЧАТЬ. Форма шкалы, шаг сетки, проверка поддержки \`round()\`, имя
   оси плотности и границы осей живут данными на поверхности зоны: из них печатает скин и по
   ним строят ползунки. Значение, объявленное этим листом, приезжало БЫ всем и молча — а
   просивших его не осталось ни одного во всём дереве.

   ФАЙЛ ПОРОЖДЁН \`src/css/generate.ts\`, править бесполезно: следующее порождение перезапишет.
   В разработке он порождается ПО ЗАПРОСУ, то есть отражает текущие исходники, а не прошлую
   сборку (\`PWEB-20\`). */`,
    WRITTEN_BASE.trimEnd(),
  ].join("\n\n");

  done();
  return `${css}\n`;
}

