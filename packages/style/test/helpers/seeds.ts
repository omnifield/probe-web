import { themeModelToCss, type ThemeModel } from "../../src/model.js";
import { DENSITY_DEFAULT } from "../../src/dimension.js";
import { buildThemeTokens, type ThemeSeeds, type ThemeTokens } from "../../src/tokens.js";

// СЕМЕНА ПРОБ — фикстура, а не поставка (`PWEB-50`).
//
// Прежде пробы брали `DEFAULT_SEEDS` из самой зоны: удобно и незаметно неправильно. Гейт,
// стоящий на поставляемом наборе, проверяет не механику, а НАШ вкус, и вместе с набором из
// поставки он бы просто исчез. Теперь семена принадлежат пробам: своё значение — свой файл.
//
// Значения подобраны как ТИПОВОЙ вход, а не как чей-то бренд: почти ахроматичный нейтральный,
// тёмный сдержанный акцент, красный с настоящей цветностью — так вход покрывает и серую ветку
// математики, и цветную.

/** Семена, на которых считают пробы зоны. */
export const SEEDS: ThemeSeeds = {
  // Светлота нейтрального семени выше текстовой ступени намеренно: сплошной нейтральный
  // (вторичная кнопка) обязан отличаться от второстепенного текста, а ступень 11 решается
  // из порога и падает примерно на 0.54.
  neutral: "oklch(0.62 0.004 285)",
  brand: "oklch(0.28 0.006 285)",
  danger: "oklch(0.505 0.196 27)",
};

/** Светлая половина фикстуры. */
export const LIGHT: ThemeTokens = buildThemeTokens(SEEDS, "light");

/** Тёмная половина фикстуры — СВОЯ шкала того же семени, а не инверсия светлой. */
export const DARK: ThemeTokens = buildThemeTokens(SEEDS, "dark");

/** Имя палитры-фикстуры. Своего имени у зоны больше нет — это имя проб. */
export const PALETTE = "probe";

/** Модель-фикстура: то, из чего проба делает файл палитры. */
export const MODEL: ThemeModel = { id: PALETTE, seeds: SEEDS, density: DENSITY_DEFAULT };

/**
 * Файл палитры, порождённый из фикстуры.
 *
 * Раньше этот текст читался с диска (`dist/css/themes.css`) — теперь такого артефакта нет, и
 * пробы, которым нужна ПАЛИТРА для сверки, порождают её тем же вызовом, каким её породил бы
 * потребитель. Проверяется способ, а не наш бывший набор.
 */
export const paletteFile = (): string => themeModelToCss(MODEL);
