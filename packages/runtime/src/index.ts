/**
 * Идентификатор точки монтирования. Часть ЗАМОРОЖЕННОЙ поверхности наравне с самим
 * экспортом: он живёт в `index.html` потребителя, а тот — `placed-once`.
 */
const ROOT_ID = "root";

/**
 * Живые приложения по узлу-хозяину: узел → `dispose` его корня.
 *
 * `render()` создаёт владеющий контекст (`createRoot`) и отдаёт `dispose`; выбросить эту
 * функцию — значит потерять единственную ручку управления вычислениями корня
 * (`solid-docs-ownership`: без явного `dispose` вычисления не управляются и текут). В
 * сигнатуре `mount()` её вернуть нельзя — тип точки заморожен как `void`, — поэтому ручку
 * держит зона, и держит её здесь.
 *
 * Почему `WeakMap` по узлу, а не модульная переменная: переменная пережила бы сам узел и
 * вечно держала бы замыкание над оторванным от документа деревом. Ключ-узел умирает —
 * умирает и запись.
 */
const mounted = new WeakMap<Element, () => void>();

/**
 * Монтирует Solid-приложение в документ.
 *
 * Точку монтирования рантайм ищет САМ — элемент `#root`. В сигнатуре её нет намеренно:
 * иначе заморозился бы заодно способ разметки страницы, а он обязан двигаться.
 *
 * Повторный вызов на том же `#root` — это HMR или перезапуск: прежний корень сначала
 * **уничтожается** (`dispose`), и только потом монтируется новый. Инвариант зоны — «один
 * документ, одно приложение»: `#root` в контракте один, и складывать в него корни стопкой
 * значит держать живыми вычисления, до которых уже никто не дотянется.
 *
 * @param root корневой компонент приложения
 * @throws если в документе нет `#root` — падаем внятно, а не молча в пустую страницу
 */
export function mount(root: () => JSX.Element): void {
  const done = trace("mount");

  const host = document.getElementById(ROOT_ID);
  if (!host) {
    throw new Error(
      `[probe-web-runtime] mount(): в документе нет элемента #${ROOT_ID}. ` +
        `Точку монтирования рантайм ищет сам — добавь в index.html <div id="${ROOT_ID}"></div>.`,
    );
  }

  mounted.get(host)?.();
  mounted.set(host, render(root, host));

  done();
}

