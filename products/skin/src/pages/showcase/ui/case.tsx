// КАРТОЧКА СЛУЧАЯ — компонент в условии, нарисованный МЕХАНИКОЙ.
//
// Отрисовка — тот же `RenderTree`, которым рисует потребитель. Второго способа превратить дерево
// в вид не существует, и именно поэтому витрина отвечает за то, что увидит человек.
//
// РАСКЛАДКА — ПОТОК (`Flow`/`FlowItem`), НЕ СЕТКА. Первая попытка стояла на `Grid`/`GridCell`, и
// это оказалось неверным выбором инструмента, а не мелкой правкой рецепта: сетка держит дорожки
// ОБЩИМИ по всем строкам (`packages/ui/src/grid/entity/anatomy.ts`) — ровно то, что нужно форме
// с выровненными колонками, и ровно то, чего НЕ нужно галерее случаев, где кнопка стоит рядом с
// гармошкой. Уравнивание дорожки под самый широкий случай либо растягивало мелкий компонент на
// чужую ширину, либо не давало крупному вписаться — и то и другое видно живьём (`img/image1.png`,
// `img/image2.png`, user 2026-08-27). Поток КАЖДЫЙ элемент меряет по его собственному
// содержимому и переносит строку сам, без общей дорожки, — карточка ВСЕГДА в размер своего
// компонента, а не подогнана под чужой (тот же довод, по которому `grid/entity/passport.ts`
// объясняет, зачем сетка вообще понадобилась ВТОРЫМ компонентом раскладки: там, где выравнивание
// не нужно, поток — то, что было нужно с самого начала).
//
// ОБЪЁМ КАРТОЧКИ ПО-ПРЕЖНЕМУ БЕРЁТСЯ У ПОСТАВЩИКА (`ComponentFootprint`, `footprintOf`,
// `packages/skin/src/passport-editor.ts`), но под потоком у него осталась ровно одна законная
// работа: `wide` — «непременно во всю строку» (таблица, карусель) — форсирует перенос своим
// классом (`case--wide`, ниже). `compact`/`regular` под потоком неотличимы: обычный элемент И БЕЗ
// ТОГО меряется по своему содержимому, вторично объявлять это классом было бы дублировать то, что
// поток уже делает сам. Поле остаётся объявленным (реальный факт о компоненте, тем же приёмом,
// что `genus`/`group`) — использовать его целиком или частично решает уже ТА раскладка, что
// читает его в моменте.
//
// СВОЙ КЛАСС, А НЕ ВАРИАЦИЯ СКИНА: имя вариации живёт физически ТОЛЬКО на корне компонента
// (`rules.ts`, `growPart`, `PWEB-103`/`SKINED-5`) — признак на некорневой части (`FlowItem`),
// которую ставит потребитель напрямую, ни одно правило скина не заденет.

import { RenderTree, type DispatchedEvent } from "@omnifield/probe-web-assembly";
import { FlowItem } from "@omnifield/probe-web-ui";
import { Show } from "solid-js";

import type { ShowcaseCase } from "../../../entities/catalog/model/cases.js";
import { editorInfoOf } from "../../../entities/catalog/model/providers.js";
import { REGISTRY } from "../../../entities/catalog/model/registry.js";

export function Case(props: {
  component: string;
  item: ShowcaseCase;
  /** Данные для биндинга/повтора (`PWEB-156`) — одна ось на всю галерею, см. `cases.ts`'s `Slice.data`. */
  data?: unknown;
  /** Одна точка входа для событий узла (`PWEB-157`) — не задана, узлы с `on` просто молчат наружу. */
  dispatch?: (event: DispatchedEvent) => void;
}) {
  // Не назвал объём — «обычный»: тем же умолчанием, что и `footprintOf` самой механики (середина,
  // а не крайность). Второй копии умолчания здесь не заводим — оно читалось бы значением, которое
  // объявил компонент, хотя он промолчал.
  const footprint = () => editorInfoOf(props.component)?.footprint ?? "regular";

  // ОПИСАНИЕ СВЕРХУ, КОМПОНЕНТ НИЖЕ (решение user 2026-08-23): человек сперва читает, на что
  // смотрит, и уже потом смотрит. Обратный порядок заставлял угадывать, что за карточка перед
  // ним, и искать подпись под ней.
  return (
    <FlowItem as="figure" class="case" classList={{ "case--wide": footprint() === "wide" }}>
      <figcaption class="case__caption">
        <b class="case__title">{props.item.title}</b>

        <Show when={props.item.at.state !== null}>
          <span class="case__state">{props.item.at.state}</span>
        </Show>
      </figcaption>

      <div class="case__stage">
        <RenderTree tree={props.item.tree} registry={REGISTRY} data={props.data} dispatch={props.dispatch} />
      </div>
    </FlowItem>
  );
}
