// ГЕЙТ СОВПАДЕНИЯ: вид, собранный для РЕДАКТОРА, и вид, приехавший в ПРИЛОЖЕНИЕ, — один и тот же.
//
// Шестой пункт потока — критерий приёмки всего продукта: человек собрал вид в редакторе и обязан
// увидеть в приложении ТО ЖЕ САМОЕ. Без этой пробы он остаётся словами.
//
// ## Дорог к виду две, и они не одинаковые по устройству
//
//   запись скина
//     ├─ РЕДАКТОР:   порождение → ВЛОЖЕННАЯ форма → живой лист, на каждое движение ручки
//     └─ ПРИЛОЖЕНИЕ: оборот через хранилище → порождение → ПЛОСКАЯ форма → лист → надет
//
// Развести их молча может каждое из трёх различий: две формы вывода; оборот записи через JSON
// (потерянное поле, порядок ключей, значение, которого JSON не знает); порядок правил в каскаде.
//
// ## ПОЧЕМУ ЖИВОЙ БРАУЗЕР, И ЧЕМ ЗА ЭТО ПЛАТИМ
//
// Скин живёт в каскадном слое, а `jsdom` слои ИГНОРИРУЕТ ЦЕЛИКОМ — не упорядочивает, а
// выбрасывает. Значит сравнить результат двух дорог он не может В ПРИНЦИПЕ: обе покажутся
// пустыми, и проба будет зелёной оттого, что сравнивать нечего.
//
// Текстовая сверка это не замена, а другой вопрос: обе формы законно различаются НАПИСАНИЕМ, и
// совпадение строк здесь не предмет. Предмет — вычисленный вид.
//
// **Цена названа честно: прогон поднимает настоящий Chromium**, и это дороже обычной пробы. Она
// оправдана ровно тем, что иначе главное обещание продукта непроверяемо (граница — в README
// `@omnifield/live-check`: гейтом только когда предмет НАШЕ обещание и проверить нечем иначе).
//
// ## Чего эта проба НЕ проверяет
//
// Чужой редактор. У нас его нет, и ставить свою готовность в зависимость от чужих сроков нельзя.
// Проверяется, что сходятся ДВЕ ДОРОГИ НАШЕЙ МЕХАНИКИ, — редактор ходит первой, приложение
// второй, и если сходятся они, то расхождению взяться неоткуда.

import { ask, load, withChrome, type Call } from "@omnifield/live-check";
import { type Outfit } from "@omnifield/probe-web-skin";
import { flattenCss } from "@omnifield/probe-web-skin/flat";
import { FORCE_ATTRIBUTE } from "@omnifield/probe-web-skin/model";
import { PASSPORTS } from "@omnifield/probe-web-ui/passport";
import postcss from "postcss";
import { beforeAll, describe, expect, it } from "vitest";

import { referenceForms, referenceOutfit, referencePalette } from "../src/index.js";
import { assemble, generateSkinCss, части } from "./assembled.js";

/**
 * ДОРОГА РЕДАКТОРА: СБОРКА трёх записей, затем порождение как есть — вложенная форма, браузер
 * разворачивает её сам.
 *
 * Сборка теперь стоит на ОБЕИХ дорогах (`PWEB-78`), и это не удлинение пробы, а её предмет: вид
 * складывается из палитры, форм и наряда, и совпадать обязан СОБРАННЫЙ вид, а не порождение
 * одной записи.
 */
const дорогаРедактора = generateSkinCss(assemble(referenceOutfit, части).skin);

/**
 * ДОРОГА ПРИЛОЖЕНИЯ: запись сначала уезжает в хранилище и приезжает обратно, и только потом
 * порождается — в плоскую форму.
 *
 * Оборот НАСТОЯЩИЙ, а не передача той же ссылки: `JSON.parse(JSON.stringify(...))`. Передай мы
 * ссылку — проверялось бы не то: потерянное при сериализации поле, значение, которого JSON не
 * знает, и съехавший порядок ключей проехали бы мимо, а именно они и разводят вид молча.
 */
const изХранилища = {
  palette: JSON.parse(JSON.stringify(referencePalette)) as typeof referencePalette,
  forms: JSON.parse(JSON.stringify(referenceForms)) as typeof referenceForms,
  outfit: JSON.parse(JSON.stringify(referenceOutfit)) as Outfit,
};
const дорогаПриложения = flattenCss(
  generateSkinCss(
    assemble(изХранилища.outfit, {
      palettes: [изХранилища.palette],
      forms: изХранилища.forms,
    }).skin,
  ),
);

/** Координаты берём у НАСТОЯЩИХ паспортов кита: выдуманные проверяли бы наше представление. */
function координата(component: string, part: string): string {
  return Object.entries(PASSPORTS[component]!.anatomy.build()[part]!.attrs)
    .map(([name, value]) => `${name}="${value}"`)
    .join(" ");
}

/**
 * Узлы замера. Больше одного намеренно, и перечень собран так, чтобы задеть места, где дороги и
 * расходятся: вариацию, состояние и вид по состоянию ПРЕДКА.
 *
 * Состояние берётся принудительным признаком там, где его ставит браузер (наведение): данными
 * псевдокласс не выставить, и генератор порождает пару `:is(:hover, [data-force~="hover"])`
 * ровно для этого.
 */
const УЗЛЫ: readonly { id: string; html: string }[] = [
  {
    id: "кнопка-умолчание",
    html: `<button ${координата("button", "root")} id="кнопка-умолчание">умолчание</button>`,
  },
  {
    id: "кнопка-вариация",
    html: `<button ${координата("button", "root")} data-variant="тихая" id="кнопка-вариация">тихая</button>`,
  },
  {
    id: "кнопка-состояние",
    html: `<button ${координата("button", "root")} ${FORCE_ATTRIBUTE}="hover" id="кнопка-состояние">наведена</button>`,
  },
  {
    id: "кнопка-отключена",
    html: `<button ${координата("button", "root")} data-disabled id="кнопка-отключена">отключена</button>`,
  },
  {
    id: "поверхность-вариация",
    html: `<div ${координата("surface", "root")} data-variant="приподнятая" id="поверхность-вариация">поверхность</div>`,
  },
  {
    // Содержимое раскрытого раздела: вид приходит от состояния ПРЕДКА, а не своего. Дорога,
    // потерявшая адрес по предку, разошлась бы ровно здесь и больше нигде.
    id: "гармошка-по-предку",
    html:
      `<div ${координата("accordion", "root")}>` +
      `<div ${координата("accordion", "item")} data-state="open">` +
      `<div ${координата("accordion", "itemContent")} id="гармошка-по-предку">содержимое</div>` +
      `</div></div>`,
  },
];

/** Свойства замера: то, чем скин на самом деле одевает, а не всё подряд. */
const СВОЙСТВА = [
  "background-color",
  "color",
  "border-top-color",
  "border-top-width",
  "border-radius",
  "padding-left",
  "padding-top",
  "min-height",
  "font-size",
  "font-weight",
  "line-height",
  "letter-spacing",
  "opacity",
  "gap",
] as const;

/** Что документ показывает на этих узлах — использованные значения, а не текст объявлений. */
const ЗАМЕР = `(() => {
  const свойства = ${JSON.stringify(СВОЙСТВА)};
  const ответ = {};
  for (const id of ${JSON.stringify(УЗЛЫ.map((узел) => узел.id))}) {
    const узел = document.getElementById(id);
    if (!узел) throw new Error("узла «" + id + "» на странице нет — замер бы соврал молча");
    const стиль = getComputedStyle(узел);
    const пары = {};
    for (const имя of свойства) пары[имя] = стиль.getPropertyValue(имя);
    ответ[id] = пары;
  }
  return JSON.stringify(ответ);
})()`;

type Снимок = Record<string, Record<string, string>>;

/** Страница: лист скина, половина классом на корне, узлы замера. */
function страница(css: string, тёмная: boolean): string {
  return (
    `<!doctype html><html${тёмная ? ' class="dark"' : ""}><head><style>${css}</style></head>` +
    `<body>${УЗЛЫ.map((узел) => узел.html).join("")}</body></html>`
  );
}

/** Расхождения двух снимков: узел и свойство, в которых дороги разошлись. */
function расхождения(первый: Снимок, второй: Снимок): string[] {
  const найдено: string[] = [];

  for (const узел of Object.keys(первый)) {
    for (const свойство of СВОЙСТВА) {
      if (первый[узел]?.[свойство] !== второй[узел]?.[свойство]) {
        найдено.push(`${узел}.${свойство}: «${первый[узел]?.[свойство]}» ≠ «${второй[узел]?.[свойство]}»`);
      }
    }
  }

  return найдено;
}

/**
 * Испорченная дорога приложения — ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ, а не украшение.
 *
 * Без него зелёный прогон значил бы сразу две вещи: «дороги совпали» и «сравнивали пустоту».
 * Порча выбрана самая тихая из возможных: у кнопки-умолчания подменён один цвет заливки. Ни
 * порождение, ни разбор от неё не ломаются — расходится только ВИД, то есть ровно то, что проба
 * и обязана уметь замечать.
 */
const испорченнаяДорога = дорогаПриложения.replace(
  "background: var(--акцент-9)",
  "background: var(--акцент-3)",
);

/**
 * НАРЯД С ТОЧЕЧНОЙ ПРАВКОЙ — материал для проб про границу правки и порядок источников.
 *
 * Свой, а не эталонный: у эталона правок нет намеренно (правка — признание, что палитра
 * компоненту не подошла). Проверять механизм правки на записи, которая им не пользуется, было бы
 * нечем, а заводить правку в эталоне ради пробы значило бы соврать про сам эталон.
 */
const сПравкой: Outfit = { ...referenceOutfit, overrides: { button: { "space-4": "0px" } } };
const дорогаСПравкой = generateSkinCss(assemble(сПравкой, части).skin);

const снимки: Record<string, Снимок> = {};

beforeAll(async () => {
  await withChrome(async (call) => {
    for (const [имя, css, тёмная] of [
      ["редактор-светлая", дорогаРедактора, false],
      ["приложение-светлая", дорогаПриложения, false],
      ["редактор-тёмная", дорогаРедактора, true],
      ["приложение-тёмная", дорогаПриложения, true],
      ["порча-светлая", испорченнаяДорога, false],
      ["правка-светлая", дорогаСПравкой, false],
    ] as const) {
      await load(call, страница(css, тёмная));
      снимки[имя] = JSON.parse(await ask(call, ЗАМЕР)) as Снимок;
    }
  });
}, 120_000);

describe("дороги действительно ДВЕ", () => {
  it("тексты различаются НАПИСАНИЕМ, и различие структурное", () => {
    // Мутация задачи: сравни одну дорогу с собой — краснеет здесь. Формы законно различаются
    // написанием, и именно поэтому сравнение текстов не годится в предмет, а годится сюда.
    //
    // Смотрим структуру, а не длину строк: у редакторской дороги at-правило остаётся ВНУТРИ
    // правила, у прикладной вынесено наверх. Совпади они — дорога сравнивалась бы с собой.
    const вложенных = (css: string): number => {
      let счёт = 0;
      postcss.parse(css).walkRules((rule) => {
        if (rule.nodes.some((node) => node.type === "atrule")) счёт += 1;
      });
      return счёт;
    };

    expect(дорогаПриложения).not.toBe(дорогаРедактора);
    expect(вложенных(дорогаРедактора)).toBeGreaterThan(0);
    expect(вложенных(дорогаПриложения)).toBe(0);
  });

  it("оборот через хранилище настоящий: другие записи, то же содержимое", () => {
    // Оборот идёт у ВСЕХ ТРЁХ записей: наряд ссылается именами, и потеряй хранилище имя формы —
    // сборка отказала бы, а потеряй значение палитры — вид разошёлся бы молча.
    expect(изХранилища.palette).not.toBe(referencePalette);
    expect(изХранилища.palette).toEqual(referencePalette);
    expect(изХранилища.forms).toEqual(referenceForms);
    expect(изХранилища.outfit).toEqual(referenceOutfit);
  });

  it("на обеих дорогах стоит СБОРКА — совпадать обязан собранный вид", () => {
    // Собери одна дорога, а другая возьми готовое — проба сравнивала бы разные предметы и
    // молчала бы ровно там, где сборка и расходится.
    expect(дорогаРедактора).toContain("--акцент-9:");
    expect(дорогаПриложения).toContain("--акцент-9:");
  });
});

describe("вид совпадает — в обеих половинах", () => {
  it("замер не пуст: узлы найдены и одеты", () => {
    // Иначе «расхождений ноль» проходило бы и на странице, где скин не применился вовсе.
    const снимок = снимки["редактор-светлая"]!;

    expect(Object.keys(снимок)).toHaveLength(УЗЛЫ.length);
    expect(снимок["кнопка-умолчание"]?.["background-color"]).not.toBe("rgba(0, 0, 0, 0)");
    expect(снимок["кнопка-вариация"]?.["background-color"]).not.toBe(
      снимок["кнопка-умолчание"]?.["background-color"],
    );
  });

  it("СВЕТЛАЯ: редактор и приложение дают один и тот же вид", () => {
    expect(расхождения(снимки["редактор-светлая"]!, снимки["приложение-светлая"]!)).toEqual([]);
  });

  it("ТЁМНАЯ: и здесь тоже — расхождение может жить в одной половине", () => {
    expect(расхождения(снимки["редактор-тёмная"]!, снимки["приложение-тёмная"]!)).toEqual([]);
  });

  it("половины при этом РАЗНЫЕ — иначе совпадение выше ничего не значило бы", () => {
    expect(расхождения(снимки["редактор-светлая"]!, снимки["редактор-тёмная"]!).length)
      .toBeGreaterThan(0);
  });

  it("ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: сломанная дорога приложения расходится с редакторской", () => {
    const разошлись = расхождения(снимки["редактор-светлая"]!, снимки["порча-светлая"]!);

    expect(разошлись.length).toBeGreaterThan(0);
    expect(разошлись.join(" ")).toContain("кнопка-умолчание.background-color");
  });
});

describe("точечная правка: границы и порядок источников — на живом узле", () => {
  // То, чего текст показать не может. Правка переобъявляет роль на координате компонента, а
  // победит ли она — вопрос каскада и наследования, то есть браузера. `jsdom` слои игнорирует
  // целиком и на такой вопрос не отвечает вовсе.

  // Роль для правки выбрана та, которой пользуются ОБА замеряемых компонента (`space-4` — отступ
  // и у кнопки, и у поверхности). Возьми мы роль, которую сосед не адресует, второй конец пробы
  // оказался бы пустым: он проходил бы и на правке, протёкшей наружу.

  it("ПРАВКА БЬЁТ ФОРМУ: внутри своего компонента роль стала другой", () => {
    const без = снимки["редактор-светлая"]!["кнопка-умолчание"]!["padding-left"];
    const с = снимки["правка-светлая"]!["кнопка-умолчание"]!["padding-left"];

    expect(без).not.toBe("0px");
    expect(с).toBe("0px");
  });

  it("и НЕ ДЕЙСТВУЕТ за его границами: соседний компонент остался при палитре", () => {
    // Второй конец той же пробы, и он важнее первого: правка, протёкшая наружу, — это уже не
    // правка компонента, а вторая палитра, заведённая молча.
    const сосед = снимки["правка-светлая"]!["поверхность-вариация"]!["padding-left"];

    expect(сосед).toBe(снимки["редактор-светлая"]!["поверхность-вариация"]!["padding-left"]);
    expect(сосед).not.toBe("0px");
  });
});

describe("ТЕКУЧИЙ РАЗМЕР на живом окне (`PWEB-80`)", () => {
  // Единственное место, где текучесть вообще проверяема: `vw` считает браузер, `round()` считает
  // браузер, и `jsdom` не умеет ни того, ни другого. Замер идёт на ДВУХ ширинах окна — узкой и
  // широкой, — и на настоящем порождённом листе, а не на рукописном образце.

  /** Отступ кнопки при данной ширине окна: то, что видит человек, а не текст объявления. */
  async function отступ(call: Call, ширина: number): Promise<string> {
    await call("Emulation.setDeviceMetricsOverride", {
      width: ширина,
      height: 900,
      deviceScaleFactor: 1,
      mobile: false,
    });
    await load(call, страница(дорогаРедактора, false));

    return String(
      await ask(
        call,
        `getComputedStyle(document.getElementById("кнопка-умолчание")).paddingLeft`,
      ),
    );
  }

  let узкое = "";
  let широкое = "";

  beforeAll(async () => {
    await withChrome(async (call) => {
      узкое = await отступ(call, 400);
      широкое = await отступ(call, 1400);
    });
  }, 120_000);

  it("значение при узком и широком окне РАЗНОЕ — иначе текучести нет", () => {
    expect(узкое).not.toBe(широкое);
    expect(Number.parseFloat(узкое)).toBeLessThan(Number.parseFloat(широкое));
  });

  it("и на обеих ширинах оно СИДИТ НА СЕТКЕ 0.25rem", () => {
    // Опасение «текучесть развалит сетку» проверено, а не принято на слово: посадка работает
    // ПОВЕРХ текучего значения, и соседние элементы попадают друг в друга при любой ширине.
    for (const [где, значение] of [["узкое", узкое], ["широкое", широкое]] as const) {
      const шаг = Number.parseFloat(значение) / 4;

      expect(Number.isInteger(шаг), `${где}: ${значение} не кратно 4px (0.25rem)`).toBe(true);
    }
  });
});
