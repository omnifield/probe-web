// Средство собрать ЗНАЧЕНИЕ цветовых примитивов. Единственная точка поверхности зоны, которая
// не рендерит узел, а строит данные.
//
// ## Почему это здесь, а не у потребителя
//
// Тип `Color` уже стоит в наших публичных пропах — `value`, `defaultValue`, `onChange` у
// `ColorArea` и `ColorSlider`. То есть он часть поверхности кита независимо от того,
// реэкспортируем мы что-нибудь или нет. А собрать такое значение потребителю нечем: `parseColor`
// живёт у `@kobalte/core`, которого он не объявлял.
//
// **Поверхность, которой нельзя пользоваться, не поверхность.** Требовать от потребителя
// объявить чужую зависимость ради одного примитива значило бы сделать кит не тем, за что
// держатся, а ОДНИМ ИЗ ДВУХ мест, за которые держатся. Опереться на транзитивную установку тоже
// нельзя: строгий менеджер её не разрешит, а раннер такую зависимость внешнит (`PROBEWEB-17`
// — там это замерено на четырёх раскладках).
//
// Решение architect'а 2026-08-18, поправка в `PROBEWEB-4`: **средство собрать значение
// приезжает оттуда же, откуда контракт.** Правило шире случая — если тип третьей стороны попал
// в наш публичный контракт, то средства этот тип построить приезжают из той же поверхности.
//
// ## ЦЕНА, названная прямо
//
// Реэкспорт привязывает поверхность зоны к типу `Color` из `@kobalte/core`, и **мажорное
// изменение kobalte по этому типу становится НАШИМ ломающим изменением** — со всеми
// последствиями обязательства из `PROBEWEB-12`.
//
// Цена не появилась с этой строкой: связь уже есть через пропсы примитивов. Реэкспорт делает её
// ВИДИМОЙ вместо скрытой, а видимую связь можно посчитать при выпуске — скрытую нельзя.
//
// ## Почему только два имени
//
// `@kobalte/core/colors` везёт ещё `normalizeColor`, `getColorChannels`, `normalizeHue` и
// служебные типы каналов. Они наружу НЕ идут: потребителя у них сегодня нет, а поверхность
// растёт по фактическому спросу. Правило поправки требует ровно средства ПОСТРОИТЬ значение,
// а не всей библиотеки цвета.

export { type Color, parseColor } from "@kobalte/core/colors";
