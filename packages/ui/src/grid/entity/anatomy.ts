// ## Частей две
//
// `root` — сетка: дорожки, зазоры и выравнивание задаёт скин. `cell` — место одного элемента, и
// без него нельзя выразить «поле заметок занимает обе колонки»: свойства размещения
// (`grid-column`, `grid-area`) живут на РЕБЁНКЕ, а дети сетки — чужие компоненты. Ячейка
// необязательна: элементы, которым размещение не нужно, кладут в сетку напрямую.

import { createAnatomy } from "@omnifield/probe-web-skin/model";

/** Части сетки: сама сетка и место одного элемента в ней. */
export const anatomy = createAnatomy("grid").parts("root", "cell");

/** Адреса частей: `attrs` для узла, `selector` для стиля. Считаются один раз — они статичны. */
export const anatomyParts = anatomy.build();
