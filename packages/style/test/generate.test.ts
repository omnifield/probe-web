import { readFileSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";

import { baseCss } from "../src/css/generate.js";
import { WRITTEN_BASE } from "../src/css/written.js";
import { readBuilt } from "./helpers/css.js";

// ГЕЙТ ПОРОЖДЕНИЯ ПО ТРЕБОВАНИЮ (`PWEB-20`).
//
// Базовый CSS не лежит написанным — он собирается из перечней в коде. Значит вопрос не «что
// в файле», а «когда файл появляется»: пока породить его умела одна сборка, приложение в
// разработке показывало результат ПРОШЛОЙ сборки, а правка токена доезжала до глаз только
// следующей ручной командой. Ошибка при этом выглядит как ошибка вида — цвет и размеры видны
// глазами, и расхождение спишут на что угодно, кроме устаревшей сборки.
//
// Пробы держат два свойства, и оба проверяемы:
//   1. порождённое ИЗ ИСХОДНИКОВ совпадает с тем, что уехало в поставку, — иначе дев-сервер
//      показывал бы не то, что получит потребитель, и это было бы хуже прежнего;
//   2. порождение ничего не читает с диска — ни прошлой сборки, ни файлов рядом. Именно это
//      делает его вызываемым в момент запроса, из чужой зоны и из установки потребителя.

const sourceDir = resolve(import.meta.dirname, "../src/css");

describe("порождённое совпадает с поставкой", () => {
  // Все остальные гейты зоны (инвариант базового слоя, порядок блоков, маркер, палитра)
  // смотрят на ПОСТАВКУ. Это равенство распространяет их на порождаемое по требованию —
  // иначе пришлось бы держать вторую копию каждого из них.
  it("базовый слой", () => {
    expect(baseCss()).toBe(readBuilt("base.css"));
  });

  // Палитры среди артефактов больше нет: надеваемой палитры по умолчанию у зоны не осталось
  // (`PWEB-50`). Артефакт остался один, и это проверяется отдельно — `pack.test.ts`.
});

describe("порождение не зависит от прошлой сборки", () => {
  it("ни один исходник порождения не читает файлов", () => {
    // Проверяем СВОЙСТВО, а не намерение: чтение файла вернуло бы порождению зависимость от
    // того, откуда его позвали — из исходников, из сборки или из установки, — и «по
    // требованию» снова свелось бы к «после сборки».
    const guilty = readdirSync(sourceDir)
      .filter((entry) => entry.endsWith(".ts"))
      .filter((entry) => /from\s+["']node:fs/.test(readFileSync(join(sourceDir, entry), "utf8")));

    expect(guilty, "порождение читает диск").toEqual([]);
  });

  it("ручная часть входит в порождённое целиком и остаётся модулем", () => {
    // Ручная часть — единственный кусок, написанный руками, и он именно модуль: файла
    // `src/css/base.css` больше нет, иначе зовущему пришлось бы знать путь к нему.
    expect(baseCss()).toContain(WRITTEN_BASE.trimEnd());
    expect(readdirSync(sourceDir)).not.toContain("base.css");
  });

  it("порождение отдаёт РОВНО шапку и ручную часть — побайтово", () => {
    // Прежде проверялось, что каждая ступень доехала из массивов в TS: гейт против возврата
    // ручного списка. Списка больше нет вовсе — лист везёт только сброс (`PWEB-66`).
    //
    // Обязательство осталось другое: порождение не имеет права ДОБАВИТЬ что-нибудь от себя.
    // Сверяем без вырезания комментариев, и это не педантизм — замером показано, что версия со
    // стрипом пропускала возврат печати КОММЕНТАРИЕМ (границы осей уезжали в лист именно так).
    // Комментарий в чужом файле знанием не является, а место в поставке занимает.
    const css = baseCss();
    const header = /^\/\*[\s\S]*?\*\/\n\n/.exec(css);

    expect(header, "шапка порождённого файла пропала").not.toBeNull();
    expect(css.slice(header![0].length)).toBe(`${WRITTEN_BASE.trimEnd()}\n`);
  });

  it("сборочный сценарий только пишет на диск — склейки в нём нет", () => {
    // Место склейки ровно одно. Вернись она в сценарий — порождать CSS снова умела бы только
    // сборка, а дев-сервер получал бы половину файла: гейт задачи держится не тем, что
    // модуль существует, а тем, что мимо него собрать нельзя.
    const script = readFileSync(resolve(import.meta.dirname, "../scripts/build-css.mjs"), "utf8");

    for (const piece of [
      "derivedCss",
      "axesCss",
      "layerCss",
      "themeModelToCss",
    ]) {
      expect(script, `${piece} зовётся мимо порождения`).not.toContain(piece);
    }
  });

  it("порождение повторяемо: два вызова дают один и тот же текст", () => {
    expect(baseCss()).toBe(baseCss());
  });
});
