import { buildScale, type ScaleMode, type ScaleValues } from "../../src/scale.js";

// СЕМЕНА ПРОБ — фикстура, а не поставка (`PWEB-50`).
//
// Прежде пробы брали `DEFAULT_SEEDS` из самой зоны: удобно и незаметно неправильно. Гейт,
// стоящий на поставляемом наборе, проверяет не механику, а НАШ вкус, и вместе с набором из
// поставки он бы просто исчез. Теперь семена принадлежат пробам: своё значение — свой файл.
//
// ПАРА И МОДЕЛЬ ОТСЮДА УШЛИ (`PWEB-66`, вторым заходом). Здесь были `LIGHT`, `DARK`, `MODEL` и
// `paletteFile()` — фикстуры сборщика тем. Сборщика нет: тема как единица отменена, живых
// зовущих у него было ноль. Осталось то, что кормит шкалы, — они на месте, их зовёт скин.

/** Семена, на которых считают пробы зоны. */
export const SEEDS = {
  // Светлота нейтрального семени выше текстовой ступени намеренно: сплошной нейтральный
  // (вторичная кнопка) обязан отличаться от второстепенного текста, а ступень 11 решается
  // из порога и падает примерно на 0.54.
  neutral: "oklch(0.62 0.004 285)",
  brand: "oklch(0.28 0.006 285)",
  danger: "oklch(0.505 0.196 27)",
} as const;

/** Половина шкалы из семени — то, чем пользуются пробы контраста и прозрачности. */
export const half = (seed: keyof typeof SEEDS, mode: ScaleMode): ScaleValues =>
  buildScale(SEEDS[seed], mode);

/**
 * Значения размерных семян, на которых пробы считают числа.
 *
 * ФИКСТУРА, А НЕ ПОСТАВКА. Прежде эти числа лежали полем `fallback` внутри `DERIVED_SCALES` и
 * подставлялись в `var(--семя, …)` базового слоя. Поле снято (`PWEB-66`): рекомендованное
 * значение семени — это вкус, а вкус живёт в эталонном скине; данные о ФОРМЕ шкалы (множители,
 * смещения, плотность, посадка на сетку) остались нетронутыми.
 *
 * Пробам числа всё равно нужны — проверить, что ряд держит отношения и что пол нормы не
 * пробивается, можно только на конкретных значениях. Теперь эти значения принадлежат пробам:
 * своё число — свой файл, ровно как с цветными семенами выше.
 */
export const SIZE_SEEDS: Readonly<Record<string, string>> = {
  radius: "0.5rem",
  space: "0.25rem",
  "font-size": "1rem",
  column: "0.5rem",
  "control-height": "2.5rem",
  "border-width": "1px",
  tracking: "0em",
};
