// ШКАЛА СЛОЁВ: объявленный порядок того, что лежит поверх страницы.
//
// ЗАЧЕМ. Пока слой один, `z-index: 1` работает. Как только слоёв четыре, число из головы
// начинает спорить с чужим числом из головы — и спор выигрывает тот, кто написал больше, а
// не тот, кто прав. Порядок слоёв это КОНТРАКТ, а не деталь реализации каждого компонента:
// диалог обязан быть выше поповера всегда, а не когда повезло с порядком монтирования.
//
// ПОЧЕМУ НЕ ПРОИЗВОДНАЯ ШКАЛА. `z-index` — не размер, а порядковый номер: умножать его на
// семя бессмысленно, а «плотность слоёв» не существует. Поэтому здесь фиксированный ряд с
// НАЗВАННЫМ назначением каждой ступени — как у начертаний и высот строки.
//
// ГРАНИЦА ОТВЕТСТВЕННОСТИ. Мы объявляем ПОРЯДОК. Контекст наложения (`stacking context`)
// создаёт тот, кто рисует слой: `z-index` действует только среди соседей по контексту
// (CSS Position 3, §9), и токен не спасёт слой, вложенный в чужой `transform`. Поэтому слои
// поверх страницы монтируются порталом в корень — это забота зон `ui` и `skin`, не базы.

export interface Layer {
  /** Имя токена (без `--`). */
  name: string;
  /** Значение `z-index`. */
  value: number;
  /** Что именно лежит на этом уровне. */
  purpose: string;
}

