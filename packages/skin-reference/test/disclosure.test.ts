// ГЕЙТ РАСКРЫТИЯ — живым браузером, настоящим указателем и настоящей машиной состояний.
//
// ## Почему этот вопрос не отвечается ничем дешевле
//
// Раскрытие гармошки — единственное место эталона, где вид складывается ТРОИМИ: скин пишет
// движение, кит меряет узел и кладёт меру, а машина раскрывашки решает, когда движение началось и
// кончилось. Разъехаться они могут молча и разъезжались:
//
//   • `jsdom` не считает раскладку вовсе — высоты у него нет, кадров нет, `--height` некому
//     измерить. Проба на нём была бы зелёной на схлопнутом разделе;
//   • текстовая сверка отвечает на другой вопрос. Запись может быть безупречной и по форме, и по
//     проверкам механики — а раздел, открытый изначально, останется схлопнутым, потому что меру в
//     покое кит держит нулём. Ровно это тут и было;
//   • **клик через DOM не годится.** `el.click()` шлёт событие, но машину состояний не двигает
//     так, как её двигает человек: раскрытие идёт через указатель, и проверять надо тот путь,
//     которым ходит человек. Тычок здесь настоящий — `Input.dispatchMouseEvent` по координатам
//     узла.
//
// Это ровно та граница, на которой живой браузер объявлен ГЕЙТОМ, а не ручной проверкой (README
// `@omnifield/live-check`): предмет вопроса — НАШЕ обещание, и проверить его иначе нечем.
//
// ## Координаты тычка снимаются ПЕРЕД КАЖДЫМ тычком
//
// Оплачено при разработке этой пробы: раскрытие двигает раскладку, и второй тычок по координатам,
// снятым до первого, попадает мимо кнопки. Промах МОЛЧАЛИВЫЙ — состояние просто не меняется, кадры
// остаются ровными, и проба на «схлопывания нет» проходит зелёной, ничего не нажав. Поэтому
// координаты берутся заново, а каждый тычок подтверждается сменой состояния пункта.
//
// ## Разметку рисует ОБЪЯВЛЕННАЯ КИТОМ сборка
//
// Дерево берётся у паспорта (`assembly` — «три раздела, первый раскрыт»), а части — из карты кита
// (`KIT`). Своей разметки проба не пишет: написанная здесь, она проверяла бы наше представление о
// ките, а не кит. Первый раздел раскрыт не нами — так объявил поставщик, и это ровно тот случай,
// ради которого гейт заведён.

import { ask, load, withChrome, type Call } from "@omnifield/live-check";
import { PASSPORTS } from "@omnifield/probe-web-ui/passport";
import { build } from "esbuild";
import { createRequire } from "node:module";
import { dirname } from "node:path";
import { beforeAll, describe, expect, it } from "vitest";

import { referenceForms, referenceOutfit, referencePalette } from "../src/index.js";
import { assemble, generateSkinCss, собранный } from "./assembled.js";

const require = createRequire(import.meta.url);

/** Адрес части — из анатомии кита, руками селекторы не пишем. */
function координата(part: string): string {
  const attrs = PASSPORTS["accordion"]!.anatomy.build()[part]!.attrs as Record<string, string>;

  return Object.entries(attrs)
    .map(([имя, значение]) => `[${имя}="${значение}"]`)
    .join("");
}

const СОДЕРЖИМОЕ = координата("itemContent");
const КНОПКА = координата("itemTrigger");
const ПУНКТ = координата("item");

/**
 * НАСТОЯЩИЙ КИТ В БРАУЗЕРЕ — собирается из поставки на месте, а не лежит рядом слепком.
 *
 * Точка входа берёт `solid-js` ТЕМ ЖЕ разрешением, что и сам кит: она собирается из папки его
 * поставки. Своей зависимости на реактивность зона не заводит — эталон это данные, ему Solid не
 * нужен ни на грамм; нужен он только этой странице, и берётся у того, кто его и так тянет.
 */
async function собратьКит(): Promise<string> {
  const вход = require.resolve("@omnifield/probe-web-ui");
  const точка = `
    import { render, createComponent } from "solid-js/web";
    import { KIT } from ${JSON.stringify(вход)};

    const { passport, parts } = KIT["accordion"];

    const рисовать = (узел) =>
      "genus" in узел
        ? узел.value
        : createComponent(parts[узел.part], {
            ...узел.props,
            get children() {
              return (узел.children ?? []).map(рисовать);
            },
          });

    render(() => рисовать(passport.assembly.tree), document.getElementById("корень"));
    window.__собрано = true;
  `;

  const собрано = await build({
    stdin: { contents: точка, resolveDir: dirname(вход), loader: "js" },
    bundle: true,
    format: "iife",
    platform: "browser",
    // Условие `solid` НЕ спрашиваем: оно отдаёт непреобразованный JSX, а трансформации у нас
    // здесь нет. Берём ветку `default` — ту же, которой пользуется потребитель без Solid-сборки.
    conditions: ["browser", "import", "default"],
    write: false,
    logLevel: "silent",
  });

  return собрано.outputFiles[0]!.text;
}

/** Страница: место для листа скина и корень, в который кит рисует свою сборку. */
const СТРАНИЦА =
  '<!doctype html><html><head><style id="скин"></style></head>' +
  '<body><div id="корень"></div></body></html>';

/**
 * Снимок всех трёх разделов: что видно человеку, а не что написано в правиле.
 *
 * `обрезано` — главный ответ пробы: содержимое, чей текст не помещается в свою же коробку,
 * человеку показано НЕ ЦЕЛИКОМ. Схлопнутый раздел отвечает здесь «да» независимо от того, чем его
 * схлопнули.
 */
const СНИМОК = `(() => {
  const разделы = [...document.querySelectorAll('${СОДЕРЖИМОЕ}')];
  if (разделы.length !== 3) throw new Error("разделов не три — кит собрал не то, и замер бы соврал");

  return JSON.stringify(разделы.map((узел) => {
    const стиль = getComputedStyle(узел);
    return {
      высота: Math.round(узел.getBoundingClientRect().height * 100) / 100,
      видно: узел.clientHeight,
      всего: узел.scrollHeight,
      обрезано: узел.scrollHeight > узел.clientHeight + 0.5,
      движение: стиль.animationName,
      // НАЗНАЧЕНО и ИДЁТ — разные вопросы, и о вспышке отвечает второй. Спрашиваем браузер, а не
      // вычисляем сами: на спрятанном узле движение не заводится вовсе, и знает об этом он.
      идёт: узел.getAnimations().length,
      спрятан: узел.hidden,
      мера: узел.style.getPropertyValue("--height"),
      пункт: узел.closest('${ПУНКТ}').getAttribute("data-state"),
    };
  }));
})()`;

/** Начать съёмку высот по кадрам — всех трёх разделов сразу. */
const СЪЁМКА = `(() => {
  const разделы = [...document.querySelectorAll('${СОДЕРЖИМОЕ}')];
  window.__кадры = [];
  const шаг = () => {
    window.__кадры.push(разделы.map((узел) => Math.round(узел.getBoundingClientRect().height * 10) / 10));
    if (window.__кадры.length < 40) requestAnimationFrame(шаг);
  };
  requestAnimationFrame(шаг);
  return true;
})()`;

const КАДРЫ = "JSON.stringify(window.__кадры)";
const ЖДАТЬ = (мс: number) => `new Promise((ok) => setTimeout(() => ok(true), ${мс}))`;

interface Раздел {
  высота: number;
  видно: number;
  всего: number;
  обрезано: boolean;
  движение: string;
  идёт: number;
  спрятан: boolean;
  мера: string;
  пункт: string | null;
}

interface Протокол {
  /** Что видно сразу после сборки — до единого тычка. */
  приЗагрузке: Раздел[];
  /** Высоты по кадрам в ПОКОЕ: страница собралась и никто её не трогал. */
  покой: number[][];
  /** Высоты по кадрам во время переключения разделов настоящим тычком. */
  переключение: number[][];
  /** Что видно после того, как всё улеглось. */
  после: Раздел[];
}

/** Сколько РАЗНЫХ высот приняла эта колонка кадров: одна — движения не было. */
function различных(кадры: number[][], индекс: number): number {
  return new Set(кадры.map((кадр) => кадр[индекс]!)).size;
}

/** Настоящий тычок указателем по кнопке раздела — с координатами, снятыми ЗАНОВО. */
async function тык(call: Call, номер: number): Promise<void> {
  const где = JSON.parse(
    await ask(call, `JSON.stringify(document.querySelectorAll('${КНОПКА}')[${номер}].getBoundingClientRect())`),
  ) as { x: number; y: number; width: number; height: number };

  const точка = { x: Math.round(где.x + где.width / 2), y: Math.round(где.y + где.height / 2) };

  for (const type of ["mousePressed", "mouseReleased"] as const) {
    await call("Input.dispatchMouseEvent", {
      ...точка,
      type,
      button: "left",
      clickCount: 1,
      buttons: type === "mousePressed" ? 1 : 0,
    });
  }
}

/** Один прогон: поднять страницу под этим листом и этой настройкой движения, снять протокол. */
async function прогон(call: Call, кит: string, css: string, тише: boolean): Promise<Протокол> {
  await call("Emulation.setEmulatedMedia", {
    features: [{ name: "prefers-reduced-motion", value: тише ? "reduce" : "" }],
  });
  await load(call, СТРАНИЦА);
  await ask(call, `document.getElementById("скин").textContent = ${JSON.stringify(css)}; true`);
  await ask(call, `${кит}\n;true`);
  await ask(call, "new Promise((ok) => requestAnimationFrame(() => requestAnimationFrame(ok)))");

  // ПОКОЙ: съёмка идёт сразу после сборки и до единого тычка — здесь ловится вспышка.
  await ask(call, СЪЁМКА);
  await ask(call, ЖДАТЬ(500));
  const покой = JSON.parse(await ask(call, КАДРЫ)) as number[][];
  const приЗагрузке = JSON.parse(await ask(call, СНИМОК)) as Раздел[];

  // ПЕРЕКЛЮЧЕНИЕ: тычок по второй кнопке раскрывает второй раздел и закрывает первый — оба
  // движения в одном жесте, ровно как у человека. Гармошка объявлена без `collapsible`, и
  // подменять её настройки ради удобства пробы значило бы проверять не тот экземпляр.
  await ask(call, СЪЁМКА);
  await тык(call, 1);
  await ask(call, ЖДАТЬ(700));
  const переключение = JSON.parse(await ask(call, КАДРЫ)) as number[][];
  const после = JSON.parse(await ask(call, СНИМОК)) as Раздел[];

  return { приЗагрузке, покой, переключение, после };
}

/**
 * МУТАЦИЯ ЗАДАЧИ — прежняя запись: высота приезжает правилом по НАДЁЖНОМУ предку.
 *
 * Одна строка, и она же весь дефект: в покое кит держит меру нулём, значит `height: var(--height)`
 * кладёт ноль на раздел, который человек видит раскрытым. Запись при этом остаётся законной —
 * механика её пропускает, — и в этом всё дело: непроверяемо это было именно потому, что запись
 * безупречна, а схлопнут раздел.
 */
const прежняя = referenceForms.map((form) => {
  if (form.component !== "accordion") return form;

  const recipe = JSON.parse(JSON.stringify(form.recipe)) as typeof form.recipe;
  const предок = recipe.base!["itemContent"]!.ancestors![0]!;

  return {
    ...form,
    recipe: {
      ...recipe,
      base: {
        ...recipe.base,
        itemContent: {
          ...recipe.base!["itemContent"]!,
          ancestors: [{ ...предок, style: { props: { ...предок.style.props, height: "var(--height)" } } }],
        },
      },
    },
  };
});

const эталон = generateSkinCss(собранный.skin);
const сМутацией = generateSkinCss(
  assemble(referenceOutfit, { palettes: [referencePalette], forms: прежняя }).skin,
);

const протоколы: Record<string, Протокол> = {};

beforeAll(async () => {
  const кит = await собратьКит();

  await withChrome(async (call) => {
    протоколы["эталон"] = await прогон(call, кит, эталон, false);
    протоколы["тише"] = await прогон(call, кит, эталон, true);
    протоколы["мутация"] = await прогон(call, кит, сМутацией, false);
  });
}, 180_000);

describe("раздел, раскрытый ИЗНАЧАЛЬНО, показан целиком", () => {
  it("текст помещается в свою коробку — ничего не обрезано", () => {
    const первый = протоколы["эталон"]!.приЗагрузке[0]!;

    expect(первый.обрезано).toBe(false);
    expect(первый.высота).toBeGreaterThan(0);
    // Мера в покое НУЛЕВАЯ, и это не поломка кита, а его устройство: он ставит её на время
    // раскрытия. Раз так — вид в покое не вправе на неё опираться, и здесь видно, что не
    // опирается: высота есть, а меры нет.
    expect(первый.мера).toBe("0px");
  });

  it("соседи при этом закрыты и спрятаны КИТОМ, а не скином", () => {
    // Второй конец того же: «целиком» проверяется на фоне закрытых, иначе проба прошла бы и на
    // странице, где раскрыты все три.
    for (const раздел of протоколы["эталон"]!.приЗагрузке.slice(1)) {
      expect(раздел.спрятан).toBe(true);
      expect(раздел.пункт).toBe("closed");
    }
  });

  it("МУТАЦИЯ ЗАДАЧИ: верни высоту в правило по предку — раздел схлопывается", () => {
    // Положительный контроль. Без него зелёный прогон значил бы сразу две вещи: «раздел цел» и
    // «замер ничего не различает».
    const первый = протоколы["мутация"]!.приЗагрузке[0]!;

    expect(первый.обрезано).toBe(true);
    expect(первый.видно).toBeLessThan(протоколы["эталон"]!.приЗагрузке[0]!.видно);
  });
});

describe("вспышки при загрузке нет", () => {
  it("в покое высоты не шевелятся ни на кадр", () => {
    // Движение, адресованное надёжным предком, проигрывалось бы и здесь — на разделе, который
    // никто не раскрывал. Признак раскрытости у содержимого приезжает только с настоящим
    // раскрытием, и в покое его нет.
    for (const индекс of [0, 1, 2]) {
      expect(различных(протоколы["эталон"]!.покой, индекс), `раздел ${индекс + 1}`).toBe(1);
    }
  });

  it("и ни одно движение НЕ ИДЁТ — при том что закрытым оно назначено", () => {
    // Разница названа, потому что она несущая: у закрытых разделов правило `закрытие` назначено
    // и в покое — признак закрытости приезжает всегда. Не проигрывается оно оттого, что узел
    // спрятан КИТОМ (`hidden`), а на спрятанном узле движение не заводится вовсе. Спрашиваем об
    // этом браузер (`getAnimations()`), а не вычисляем сами.
    const разделы = протоколы["эталон"]!.приЗагрузке;

    for (const раздел of разделы) expect(раздел.идёт).toBe(0);

    expect(разделы[0]!.движение).toBe("none");
    expect(разделы[1]!.движение).toBe("закрытие");
    expect(разделы[1]!.спрятан).toBe(true);
  });
});

describe("раскрытие и закрытие идут КАДРАМИ — от настоящего указателя", () => {
  it("тычок доехал до машины состояний: разделы поменялись местами", () => {
    // Проверяется первым: промах указателя молчалив, и без этой строки все пробы ниже проходили
    // бы на странице, где ничего не нажималось.
    const после = протоколы["эталон"]!.после;

    expect(после[0]!.пункт).toBe("closed");
    expect(после[1]!.пункт).toBe("open");
  });

  it("раскрываемый раздел идёт кадрами, а не прыжком", () => {
    expect(различных(протоколы["эталон"]!.переключение, 1)).toBeGreaterThan(5);
  });

  it("закрываемый — тоже: закрытие это движение, а не исчезновение", () => {
    // До `PWEB-98` закрытие шло двумя значениями: машина раскрывашки, не увидев ИМЕНОВАННОГО
    // движения, немедленно объявляла его законченным и прятала узел. Переход она не видит.
    expect(различных(протоколы["эталон"]!.переключение, 0)).toBeGreaterThan(5);
  });

  it("раскрытый тычком выглядит так же, как раскрытый изначально", () => {
    // Обе дороги к одному виду обязаны сойтись. Разойдись они — человек увидел бы, что раздел
    // «после нажатия» и «с самого начала» одеты по-разному, и был бы прав.
    const изначально = протоколы["эталон"]!.приЗагрузке[0]!;
    const тычком = протоколы["эталон"]!.после[1]!;

    expect(тычком.обрезано).toBe(false);
    expect(тычком.видно).toBe(изначально.видно);
  });
});

describe("МУТАЦИЯ: движение убрано — раздел остаётся целым", () => {
  // Человек, попросивший систему двигать поменьше, просил об этом всерьёз. Проверяется не то, что
  // оговорка написана (это видно и в записи), а то, что раздел от неё не ломается: машина
  // раскрывашки ждёт `animationend`, и движение, убранное неаккуратно, оставило бы её ждать
  // вечно — с разделом, застрявшим наполовину.

  it("движения нет ни на одном разделе", () => {
    for (const раздел of протоколы["тише"]!.приЗагрузке) {
      expect(раздел.движение).toBe("none");
    }
  });

  it("изначально раскрытый по-прежнему показан целиком", () => {
    expect(протоколы["тише"]!.приЗагрузке[0]!.обрезано).toBe(false);
    expect(протоколы["тише"]!.приЗагрузке[0]!.видно).toBe(
      протоколы["эталон"]!.приЗагрузке[0]!.видно,
    );
  });

  it("переключение доходит до конца — мгновенно и целиком", () => {
    const после = протоколы["тише"]!.после;

    expect(после[0]!.пункт).toBe("closed");
    expect(после[1]!.пункт).toBe("open");
    expect(после[1]!.обрезано).toBe(false);
    expect(после[0]!.спрятан).toBe(true);
  });

  it("и идёт БЕЗ кадров — иначе просьбу никто не услышал", () => {
    // Второй конец: раздел «цел» и при движении тоже, значит проба выше сама по себе не отличила
    // бы тихий прогон от обычного.
    expect(различных(протоколы["тише"]!.переключение, 1)).toBeLessThanOrEqual(2);
  });
});
