// Точка входа скелета. Замерзает не файл, а ПОВЕРХНОСТЬ, которую он трогает (kb:PROBEWEB-4):
// mount() и механика скина из рантайма, два имени из стилевого слоя, один примитив из ui и два
// CSS-подпутя. Больше отсюда не зовут ничего — каждая лишняя строка застынет у потребителя
// навсегда, а обвес сюда уже не заглянет.

// ─── ПОРЯДОК ПОДКЛЮЧЕНИЯ. Он не декоративный ────────────────────────────────────────────────
//
//   1. базовый слой — сброс, производные шкалы и токен-маркер, по которому снаружи видно, что
//      база вообще приехала. Ни одного литерального цвета: значения приходят второй строкой;
//   2. ступени палитр — значения токенов; здесь же объявлена палитра, которую называет блок
//      «названное место» ниже;
//   3. пресет оформления — необязателен и твой;
//   4. оформление (скин) — необязательно и твоё.
//
// Пресет, подключённый ПЕРЕД ступенями, проигрывает им в каскаде: получится вид, посчитанный
// от умолчаний, — «скин почти работает», а это хуже явной поломки, потому что чинить такое
// никто не идёт. Ровно этот случай ловит checkStyleOrder() в конце файла.
import "@omnifield/probe-web-style/base.css";
import "@omnifield/probe-web-style/themes.css";
// import "<твой-поставщик-оформлений>/presets/<имя>.css";   // 3 — открой, когда пресет появится
// import "<твой-поставщик-оформлений>/skin.css";            // 4 — открой вместе с ним
//
// Строки 3 и 4 закрыты намеренно, и это не заготовка «на потом»: приложение без единого файла
// оформления обязано запускаться и быть пригодным к работе (kb:SKIN-7, инвариант 4). Оформление
// снимается удалением импорта — остаются примитивы с зацепками, ровно то, чем кит и является.

import { BASE_MARKER, DEFAULT_PALETTE } from "@omnifield/probe-web-style";
import { checkStyleOrder, mount, restoreSkin } from "@omnifield/probe-web-runtime";
import { Button } from "@omnifield/probe-web-ui";

// ═══ НАЗВАННОЕ МЕСТО: чем приложение одето ══════════════════════════════════════════════════
//
// Строка ниже объявляет ПРЕСЕТ и РЕЖИМ. Она обязана быть: палитра цепляется к документу только
// по имени (kb:PROBEWEB-18), `:root` не красится ничем, и документ, не назвавший палитру,
// выходит НЕЦВЕТНЫМ. Не сломанным — геометрия и размеры работают и без палитры, — а именно
// нецветным: var(--primary) и соседи не разрешаются, и браузер молча берёт свои дефолты.
//
// ПОЧЕМУ ИМЯ СТАВИТСЯ НА КОРЕНЬ ДОКУМЕНТА, а не на #root: производные шкалы и роли объявлены в
// `:root` и там же вычисляются, потомки наследуют готовый результат (kb:SKIN-7, инвариант 1).
// Атрибут на контейнере поменял бы переменные, ничего не пересчитав, — половина вида «не
// отреагировала бы» на смену пресета. Корень ищет сама механика, в аргументах его нет.
//
// ПОЧЕМУ DEFAULT_PALETTE, А НЕ СТРОКА. Имя палитры принадлежит стилевому слою, а этот файл
// положен один раз и обвесом больше не обновляется. Литерал здесь — вторая копия чужого имени:
// переименуют её у себя, и твоё приложение станет нецветным молча, а починить это можно будет
// только руками. Ровно то же и с маркером в конце файла.
//
// СВОЙ ПРЕСЕТ вместо дефолтного — назови его идентификатор в перечне. Порядок значим: первый
// считается умолчанием, если человек ещё ничего не выбирал. Не нужен ни один — передай пустой
// перечень: встанет только режим, и приложение останется на голом ките.
//
// РЕЖИМ (светло/темно) функция берёт из запомненного выбора человека, а нет его — из системного
// prefers-color-scheme, и ставит класс на тот же корень. Пресет и режим ортогональны: один и
// тот же пресет живёт в обеих парах, и «тёмный вариант пресета» отдельным пресетом не заводят
// (kb:SKIN-7, инвариант 3).
//
// ПОЧЕМУ ЭТА СТРОКА СТОИТ ЗДЕСЬ, А НЕ ВНУТРИ mount(). Класс режима, поставленный после первого
// кадра, даёт вспышку светлой темы перед тёмной. Это самая ранняя точка, до которой скелет
// дотягивается, не зашивая чужих имён литералами: модуль-точка-входа выполняется до монтирования
// и до любого твоего кода. Полной гарантии «до первого кадра» она НЕ даёт — модульный скрипт
// отложен по стандарту, и браузер вправе показать кадр раньше. Нужна железная гарантия — её
// даёт только обычный (не module) скрипт в <head>, и класть его в этот файл мы не имеем права:
// в нём стояли бы имена чужих зон строками, замороженные у тебя навсегда.
restoreSkin({ presets: [DEFAULT_PALETTE] });

// Кит безголовый: класса по умолчанию у кнопки нет, внешний вид целиком твой. Эту кнопку
// одевает блок <style> в index.html — через зацепку data-slot и токены палитры; там же сказано,
// как перенести оформление в свой файл.
//
// Второй путь — createStyle стилевого слоя, для класса, зависящего от состояния. В скелете он
// не показан намеренно: вызов заморозил бы у тебя ещё одну точку поверхности ради примера.
function App() {
  return <Button>hello, web</Button>;
}

mount(() => <App />);

// ─── ДРУГАЯ ТОЧКА: проверка порядка подключения ──────────────────────────────────────────────
//
// Не сливай её с постановкой пресета выше. Той стили не нужны вовсе — она только пишет на
// корень, и потому её и зовут как можно раньше. Этой они нужны по определению: она спрашивает
// документ, объявлен ли на корне токен, который обязан приехать с базой, — и рано звать её
// бессмысленно.
//
// BASE_MARKER, а не имя токена строкой: какой токен обязан приехать с базой — знание стилевого
// слоя (kb:PROBEWEB-13). Литерал здесь пережил бы переименование и начал бы врать: кричать
// «базы нет» на исправном приложении или, что хуже, молчать на сломанном.
//
// Ничего не роняет и ничего не красит: кричит в консоль и отдаёт разбор значением. Не нужна в
// проде — сними строку, приложение не изменится ни на пиксель.
checkStyleOrder({ marker: BASE_MARKER });
