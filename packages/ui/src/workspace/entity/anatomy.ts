// РАНТАЙМ-анатомия рабочей области — раскладки приложения именованными слотами (`PWEB-154`).
//
// ЗДЕСЬ ТОЛЬКО ЧАСТИ И АДРЕСА — ничего больше, тем же приёмом, что у сетки и потока
// (`grid/entity/anatomy.ts`, `flow/entity/anatomy.ts`). Полный рантайм-контракт — уровнем выше, в
// `passport.ts`. Срез РЕДАКТОРА — ещё шагом дальше, в `playground/index.ts`.
//
// ## Почему это ОТДЕЛЬНЫЙ компонент, а не вариация сетки
//
// У сетки один вид части — `cell`, и ячейки неотличимы адресом: правило скина, написанное на
// `grid.cell`, попадает на все ячейки разом. Каркас приложения (шапка, рельсы, показ, боковая
// панель) — это ЧЕТЫРЕ РАЗНЫЕ роли, каждая со своим видом (у рельсов своя подложка, у шапки своя
// высота, у боковой панели своя ширина), и им нужны четыре РАЗНЫХ адреса, а не один общий,
// различённый порядком детей. Тем же доводом, что у `grid/entity/passport.ts` («правило скина
// адресуется координатой»), это и есть причина заводить пять именованных частей вместо того,
// чтобы городить их вручную из `Grid`/`GridCell` на каждом потребителе (было в `products/skin/src/
// app/app.tsx` до PWEB-154 — два вложенных `Grid`, и порядок детей приходилось помнить).
//
// ## Частей пять
//
// `root` — сама раскладка, держит сетку целиком. `header` — верхняя полоса (не на всю высоту).
// `sidebar` — левая колонка, во всю высоту. `main` — показ, всегда есть. `rightbar` — правая
// колонка; необязательна, и это часть замысла — не смонтирован узел, скин или разметка ничего
// придумывать не обязаны, колонка схлопывается сама (`playground/recipe.ts` объясняет как).
import { createAnatomy } from "@omnifield/probe-web-skin/model";

/** Части рабочей области: сама раскладка и четыре именованных слота. */
export const anatomy = createAnatomy("workspace").parts("root", "header", "sidebar", "main", "rightbar");

/** Адреса частей: `attrs` для узла, `selector` для стиля. Считаются один раз — они статичны. */
export const anatomyParts = anatomy.build();
