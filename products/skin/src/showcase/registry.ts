// РЕЕСТР витрины — то, из чего она собирает и по чему проверяет (`PWEB-31`).
//
// ## Своего перечня компонентов здесь нет
//
// Витрина не ведёт список того, что умеет показывать. Она складывает три вещи, и все три
// приходят СНАРУЖИ:
//
//   • карта компонентов — чем рисовать. Даёт поставщик кита;
//   • паспорта — что о компоненте объявлено. Даёт сам компонент;
//   • правило допуска — по какому правилу читается объявленное. Едет вместе с формой паспорта.
//
// Заведи витрина свой перечень — «флоу один для всех» кончилось бы в тот же день: чужой пакет
// попадал бы в пульт только после правки НАШЕГО кода, то есть с нашего разрешения.
//
// ## Почему кнопка здесь одна
//
// Механика обкатывается на одном компоненте до сквозного прохода (`PWEB-31`, правило обкатки).
// Остальные приезжают волной разноса — по одному, каждый со своей проверкой. Пустое место в
// перечне честнее заглушки: компонента без паспорта одеть нечем, и показывать его в пульте
// одевания значило бы обещать несуществующее.

import { createRegistry, type Registry } from "@omnifield/probe-web-assembly";
import { Button } from "@omnifield/probe-web-ui";
import { admits, PASSPORTS } from "@omnifield/probe-web-ui/passport";

/**
 * Реестр витрины.
 *
 * Паспорт индексируется АДРЕСОМ в карте компонентов, а не именем из самого паспорта: имя
 * (`data-scope`) у кнопки — `button`, а лежать в карте она вправе где угодно. Здесь адрес и имя
 * совпадают, и это частный случай, а не правило.
 */
export const REGISTRY: Registry = createRegistry({
  components: { button: Button },
  passports: { button: PASSPORTS.button },
  admits,
});
