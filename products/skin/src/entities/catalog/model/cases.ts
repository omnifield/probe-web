// СЛУЧАЙ — компонент в условии, ради которого на него стоит смотреть (`PWEB-31`).
//
// ## Случаи порождаются ОСЯМИ, и только ими
//
// Витрина показывает вид: вариации компонента и состояния, в которых он бывает. Всё это —
// координаты, и случай на витрине это координата, поставленная в разметку.
//
// Случаев, названных рукой («длинная подпись», «в узком месте»), здесь НЕТ. Они не координаты:
// длина содержимого не вариация и не состояние, и в потоке вариаций такая карточка отвечает не на
// тот вопрос, с которым сюда приходят. Их место — раздел проверок в редакторе (решение user
// 2026-08-23), и заводить их обратно на витрину нельзя.
//
// ## Дерево случая порождается, а не верстается
//
// Каждый случай начинается с ЭКЗЕМПЛЯРА (`instanceOf`, `./instance.ts`) — дерева частей, поднятого
// у поставщика. Условие накладывается правкой через механику (`updateNode`), а не подстановкой
// полей руками.
//
// ## Состояние ставится на УЗЕЛ ЧАСТИ, а не только на корень
//
// У крупного компонента состояния живут на вложенных частях: наведение на строке таблицы, фокус
// на ячейке. Экземпляр даёт все узлы, и признак ставится на тот, чья часть выбрана. Иначе показать
// вид вложенной части было бы нечем, а её долг одевания — невидим.
//
// ## Файл держит ТОЛЬКО алгоритм осей
//
// Что и как читается о компоненте — в `./shape.ts` (части, состояния, адрес); чем компонент может
// быть — в `./settings.ts`; как из объявленной сборки получается один экземпляр — в
// `./instance.ts`. Здесь — ровно то, что не уместилось ни в одно из них: разворот осей в поток
// случаев.

import type { AssemblyTree } from "@omnifield/probe-web-assembly";
import type { PassportState } from "@omnifield/probe-web-ui/passport";

import { instanceOf } from "./instance.js";
import { passportOf } from "./providers.js";
import { addressOfPart, partsOf, partsWithMark, statesOfPart } from "./shape.js";

export {
  addressOfPart,
  assembliesOf,
  partsOf,
  partsWithMark,
  rootPartOf,
  statesOfComponent,
  statesOfPart,
} from "./shape.js";

/**
 * Ось «ВСЕ» — положение, при котором ось не фиксируется, а разворачивается в поток случаев.
 *
 * Отдельным значением, а не `null` и не отсутствием поля, ровно потому, что «все» и «обычное» —
 * РАЗНЫЕ положения одной оси, и раньше они были склеены. Склейка стоила стартового вида: человек
 * приходил смотреть вариации, а получал их произведение на состояния, и обычный вид кнопки —
 * тот, ради которого он и пришёл, — лежал вперемешку с наведёнными и отключёнными.
 */
export const ANY = "*";

/** Положение оси: названное значение либо «все». */
export type Axis<T> = T | typeof ANY;

/** Координата случая — где он стоит по осям. */
export interface CaseAt {
  /** Часть, к которой случай относится. Не названа — корневая. */
  readonly part?: string;
  /** Вариация; `null` — умолчание, то есть атрибут не поставлен. */
  readonly variant: string | null;
  /** Состояние; `null` — обычное. */
  readonly state: string | null;
}

/** Один случай: компонент, поставленный в координату. */
export interface ShowcaseCase {
  readonly id: string;
  /** Чем условие названо — вариацией, из которой случай и порождён. */
  readonly title: string;
  /** Где случай стоит по осям — по этому его и отбирает фильтр. */
  readonly at: CaseAt;
  /** Дерево случая: образец компонента плюс условие. */
  readonly tree: AssemblyTree;
}

/** Срез осей: что развернуть, а что зафиксировать. */
export interface Slice {
  /**
   * Часть, чьё состояние показываем. НЕ НАЗВАНА — состояния берутся у всех частей сразу.
   *
   * На витрине части нет и быть не должно (решение user 2026-08-23): смотрящий думает
   * «наведение», а не «наведение корневой части». Часть остаётся адресом ВНУТРИ — состояние
   * ставится на тот узел, чья часть его объявила, — но выбирать её человеку незачем.
   */
  readonly part?: string;
  /** Вариация: имя либо {@link ANY} — развернуть по всем. */
  readonly variant: Axis<string>;
  /**
   * Состояние: имя, `null` — ОБЫЧНОЕ (ни одного признака не поставлено), либо {@link ANY}.
   *
   * Три положения, а не два: обычный вид — полноправный выбор, а не «фильтр не задан». С него
   * показ и начинается, потому что всё остальное — отклонения от него.
   */
  readonly state: Axis<string | null>;
  /** Имена вариаций надетого скина — оси взять больше неоткуда. */
  readonly variants: readonly string[];
  /**
   * НАСТРОЙКИ ПОСТАВЩИКА — чем компонент МОЖЕТ БЫТЬ (`PWEB-89`).
   *
   * Не вид и не состояние, а третье: настройка меняет поведение, разметку и доступность —
   * вертикальная гармошка и горизонтальная это разные клавиши и разные `aria`. Знает их тот, кто
   * компонент написал, поэтому перечень берётся у паспорта, а не у нас.
   *
   * Не названы — компонент показывается таким, каким его объявил поставщик своими умолчаниями.
   */
  readonly settings?: Readonly<Record<string, unknown>>;
  /**
   * Имя сборки — какой РАБОЧИЙ ЭКЗЕМПЛЯР показываем, когда их у компонента несколько (сетка:
   * `basic`/`gallery`/`workspace` — разные композиции, не разный вид одной). Не названо — берётся
   * первая объявленная, тем же приёмом, что и раньше единственного выбора (`instance.ts`).
   */
  readonly assembly?: string;
  /**
   * Данные для узлов-биндингов и повтора (`PWEB-156`) — ОДНА ось на всю галерею случаев, не
   * своя у каждого. Выбранный вариант заполнения действует на КАЖДЫЙ случай сразу — вариацию,
   * состояние, что угодно ещё, — а не на отдельную, вынесенную в сторону карточку: интерактивность
   * и данные не выбор одного случая, они принадлежат компоненту целиком (постановка user,
   * 2026-08-27 — «должно идти на все вариации, а не маленько тут маленько тут»).
   */
  readonly data?: unknown;
}

/**
 * Случаи, порождённые ОСЯМИ: вариация × состояние выбранной части.
 *
 * Ось в положении «все» разворачивается, названная — фиксируется. Так один и тот же показ годится
 * и кнопке (десятки мелких случаев), и крупному компоненту (несколько больших): что разворачивать,
 * решает человек, а не наше представление о его размере.
 *
 * Первая вариация — БЕЗ имени: умолчание скина и «атрибут не поставлен» это один адрес, и
 * показывать его надо тем, чем он является.
 *
 * @param component адрес компонента в реестре
 * @param slice срез осей
 */
export function axisCases(component: string, slice: Slice): ShowcaseCase[] {
  const passport = passportOf(component);

  if (!passport) return [];

  const parts = slice.part === undefined ? partsOf(component) : [slice.part];
  const axis = passport.variantAxis.mark;

  // УМОЛЧАНИЯ ОТДЕЛЬНОЙ СТРОКОЙ НЕТ. Скин объявляет умолчание именем, и «атрибут не поставлен»
  // — тот же адрес, что названная умолчательная вариация. Показывать их порознь значило бы
  // обещать два разных вида там, где вид один.
  // БЕЗ ВАРИАЦИЙ — ОДИН СЛУЧАЙ, А НЕ НИ ОДНОГО. Имена вариаций приходят из надетого наряда, и
  // пока он не надет, их нет вовсе. Пустой поток читался бы как поломка витрины, тогда как
  // показывать есть что: голого кита. «Без вариации» — законная координата, а не заглушка.
  const named = slice.variants.length > 0 ? slice.variants : [null];
  const variants: readonly (string | null)[] = slice.variant === ANY ? named : [slice.variant];

  // СОСТОЯНИЯ СОБИРАЮТСЯ ПО ВСЕМ ЧАСТЯМ и склеиваются по имени: «раскрыт» у гармошки объявлен и
  // на пункте, и на указателе, и на кнопке раздела — это ОДНО состояние компонента, показанное
  // тремя частями сразу, а не три разных случая.
  //
  // Часть при этом не теряется: она остаётся адресом, по которому признак ставится на узел.
  const collected = new Map<string, { state: PassportState; part: string }>();

  for (const part of parts) {
    for (const state of statesOfPart(component, part)) {
      if (!collected.has(state.name)) collected.set(state.name, { state, part });
    }
  }

  const states = [...collected.values()];

  // ОБЫЧНОЕ — это `undefined` в перечне: признака не ставится ни одного. Оно идёт ПЕРВЫМ и в
  // положении «все», потому что состояния читаются как отклонения от обычного вида, а отклонение
  // показывать раньше того, от чего оно отклоняется, — значит показывать его без опоры.
  const shown =
    slice.state === ANY
      ? [undefined, ...states]
      : slice.state === null
        ? [undefined]
        : states.filter(({ state }) => state.name === slice.state);

  const cases: ShowcaseCase[] = [];

  for (const variant of variants) {
    // Настройки ложатся ПОД вариацию: вариация — имя вида и принадлежит скину, настройка —
    // поведение и принадлежит поставщику. Совпасть по ключу им негде, а порядок называет, кто
    // кого перекрывает, если однажды совпадут.
    const variantProps = {
      ...(slice.settings ?? {}),
      ...(variant === null || axis.kind !== "attribute" ? {} : { [axis.name]: variant }),
    };

    for (const spot of shown) {
      const state = spot?.state;
      const part = spot?.part ?? slice.part ?? passport.root;

      // ОБЫЧНЫЙ ВИД — один узел (`part`), метки ставить нечего. СОСТОЯНИЕ — на КАЖДУЮ часть,
      // которую кит реально зеркалит той же меткой (`partsWithMark`, `shape.ts`): чекбокс кладёт
      // один признак сразу на четыре узла, и показ с одним отмеченным соврал бы о разметке.
      const addresses =
        state === undefined
          ? [addressOfPart(component, part)]
          : partsWithMark(component, state.mark).map((p) => addressOfPart(component, p));

      cases.push({
        id: `axis:${variant ?? "-"}:${part}:${state?.name ?? "-"}`,
        // ПОДПИСЬ — ВАРИАЦИЯ И СОСТОЯНИЕ, и ничего больше (решение user 2026-08-23). Ни части —
        // это адрес внутри записи, — ни паспортного объяснения: «кнопку держат нажатой» под
        // карточкой с нажатой кнопкой не сообщает ничего, чего не видно.
        title: variant ?? "без вариации",
        at: { part, variant, state: state?.name ?? null },
        tree: instanceOf(component, variantProps, addresses, state?.mark, slice.assembly, slice.data),
      });
    }
  }

  return cases;
}

/**
 * Показ компонента: случаи текущего среза.
 *
 * Отдельного входа сверх осей нет намеренно — см. шапку: витрина показывает координаты, и второй
 * род случаев рядом с ними отвечал бы не на тот вопрос.
 *
 * @param component адрес компонента в реестре
 * @param slice срез осей
 */
export function casesOf(component: string, slice: Slice): ShowcaseCase[] {
  return axisCases(component, slice);
}
