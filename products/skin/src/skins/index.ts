// ИСТОЧНИК СКИНОВ зоны — то, чем витрина кормит механику надевания.
//
// ## Валюта — текст стилей, а не адрес файла
//
// Механика приложения (`runtime`) принимает источник снаружи и не знает про нас ничего. От
// источника ей нужны две вещи: перечень имён и ТЕКСТ стилей по имени. Файла с адресом на этом
// пути не существует ни на одном шаге: хранилище отдаёт скин структурой, а CSS порождает
// генератор — здесь, в браузере, из записи.
//
// ## Порождение зовём, а не повторяем
//
// Своего порождения в зоне нет и заводить его нельзя: две реализации из одной модели дают два
// результата и расходятся молча — в день, когда механика улучшит порядок правил. Здесь только
// вызов и словарь.
//
// ## Словарь значений пустой — и это проверка, а не упущение
//
// Скин «graphite» стоит на СВОИХ переменных, и словарь известных имён ему не нужен: собственные
// переменные скина механика знает всегда. Передай мы сюда наш набор значений — «скин без наших
// значений законен» осталось бы обещанием, которое ничем не проверено.

import { generateSkinCss } from "@omnifield/probe-web-skin";
import type { Skin } from "@omnifield/probe-web-skin/model";
import type { SkinSource } from "@omnifield/probe-web-runtime";
import { passportOf } from "@omnifield/probe-web-ui/passport";

import { GRAPHITE } from "./graphite.js";

/**
 * Скины зоны по имени.
 *
 * Пока один: механика обкатывается на кнопке до сквозного прохода. Второй появится тогда, когда
 * его сделает человек в редакторе, — а не потому, что «одного мало для списка».
 */
export const SKINS: Readonly<Record<string, Skin>> = {
  [GRAPHITE.name]: GRAPHITE,
};

/**
 * Запись скина по имени, либо `undefined`.
 *
 * Нужна витрине не для надевания, а для показа: имена вариаций принадлежат СКИНУ, и взять их
 * можно только из его записи — в паспорте их нет и быть не может.
 *
 * @param name имя скина
 */
export function skinOf(name: string): Skin | undefined {
  return SKINS[name];
}

/**
 * Источник скинов для механики надевания.
 *
 * Отказ на неизвестное имя — исключение, а не пустая строка: пустая строка надела бы «скин»,
 * которого нет, и человек увидел бы голый кит под именем выбранного скина.
 */
export const SKIN_SOURCE: SkinSource = {
  names: () => Object.keys(SKINS),
  css: (name) => {
    const skin = skinOf(name);

    if (!skin) throw new Error(`скина «${name}» в зоне нет — надевать нечего`);

    // Изъян записи здесь тоже исключение, и это решение механики: текст с изъяном рядом оставил
    // бы ровно ту дорогу, из-за которой чинят вид, а не запись.
    return generateSkinCss(skin, passportOf);
  },
};
