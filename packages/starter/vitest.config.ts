import { defineConfig } from "vitest/config";

// Два мира, и различает их не удобство, а предмет пробы:
//
//   • ГРУЗ судится ЧТЕНИЕМ — объявление, состав, поверхность, форма блоков. Документ таким
//     пробам не нужен вовсе, и поднимать его для них значило бы платить за то, чего они не
//     спрашивают;
//   • ГЕЙТ вызов из шаблона ВЫПОЛНЯЕТ — а значит ему нужен настоящий документ с настоящим
//     каскадом: проверка порядка спрашивает вычисленное на корне значение.
//
// Движок гейта — happy-dom, и это не вкус: базовый лист объявляет своё универсальным селектором
// со списком псевдоэлементов, а JSDOM такое правило пропускает целиком (сверено 2026-08-22
// прогоном настоящего `base.css`). Подробности — в шапке `test/gate.test.ts`.
export default defineConfig({
  test: {
    projects: [
      {
        test: {
          name: "груз",
          environment: "node",
          // Только каталог проб. `template/` — это ГРУЗ, а не исходники пакета: там лежат
          // `vite.config.ts` и `main.tsx`, которые собираются у потребителя и здесь не
          // компилируются вовсе. Подобрать их сюда значило бы прогонять чужую сборку.
          include: ["test/**/*.test.ts"],
          exclude: ["test/gate.test.ts"],
        },
      },
      {
        test: {
          name: "гейт",
          environment: "happy-dom",
          include: ["test/gate.test.ts"],
        },
      },
    ],
  },
});
