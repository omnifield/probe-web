/**
 * Условие `@supports`, которым проверяется поддержка `round()`.
 *
 * ПРОВЕРЯЕТСЯ ИМЕННО ТО, ЧЕМ ПОЛЬЗУЕМСЯ: функция `round()`, стратегия `nearest` и шаг сетки —
 * ровно в той форме, в какой они уезжают в ступень. Проверять соседнюю возможность (`calc()`,
 * `mod()`, «математические функции вообще») значило бы получить подстраховку, которая
 * включается и выключается не по тому признаку.
 *
 * ПОЧЕМУ НЕ КАСТОМНОЕ СВОЙСТВО, хотя объявляем мы именно кастомные свойства. Кастомное
 * свойство принимает почти любой поток токенов, поэтому `@supports (--x: round(…))` истинно
 * в любом браузере с поддержкой переменных — проба была бы всегда зелёной и не значила бы
 * ничего (сверено 2026-08-19). Отсюда обычное свойство с типом длины: `width` разбирает
 * значение по-настоящему, и браузер без `round()` отвергает объявление.
 *
 * ПОЧЕМУ БЕЗ `var()`. Объявление, содержащее `var()`, считается действительным на разборе —
 * подставить и проверить браузеру нечего, и условие снова оказалось бы истинным всегда.
 * Поэтому в пробе стоят литералы, а не семя со ссылкой на ось.
 *
 * Шаг берётся из `GRID_STEP`, а не переписан числом: иначе проба проверяла бы форму,
 * которой мы уже не пользуемся.
 */
