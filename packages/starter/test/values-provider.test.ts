// НАБОР ЗНАЧЕНИЙ — ПОСТАВЩИК, А НЕ ФУНДАМЕНТ.
//
// Наш набор значений перестал быть обязательным основанием и стал одним из поставщиков
// базового слоя. Скелет же продолжал предполагать его: он звал проверку
// порядка подключения с НАШИМ маркером безусловно, и потребитель, взявший чужой набор, получал
// в консоль «базы нет» на исправном приложении. Ложное предупреждение хуже отсутствующего: по
// нему идут чинить то, что не сломано, а следующему настоящему верят меньше.
//
// Проверку при этом не выбрасывают — она ловит настоящий дефект (скин без базы даёт вид,
// посчитанный от умолчаний). Меняется БЕЗУСЛОВНОСТЬ её вызова, и пробы здесь сторожат именно её.
//
// ПОЧЕМУ ЭТО ПРОВЕРЯЕТСЯ ТЕКСТОМ, А НЕ ПОВЕДЕНИЕМ. Условие «наш базовый CSS подключён» из
// документа не читается: его признак — тот самый маркер, про который спрашивает проверка, и
// вопрос «звать ли проверку» ответом самой проверки не решается. Значит условие может быть
// только объявленным — набором строк, который потребитель снимает одним движением. Форму этого
// движения и судят пробы: строки набора идут подряд, а его имена больше нигде не нужны,
// поэтому снятый блок оставляет не тихое предупреждение, а красную сборку.
//
// СТРОК СТАЛО ДВЕ, А НЕ ТРИ. Подпуть с надеваемым набором цветов снят с поставки целиком, и
// второго имени у блока не осталось: цвет приходит скином, а скин у потребителя свой.

import { describe, expect, it } from "vitest";

import { readTemplate } from "./source.js";

const STYLE = "@omnifield/probe-web-style";

const raw = readTemplate("main.tsx");

/** Точка входа без строчных комментариев: судим КОД, а не пояснение над ним. */
const main = raw.replace(/^\s*\/\/.*$/gm, "");

/** Значащие строки кода подряд — по ним меряется цельность блока. */
const lines = main
  .split("\n")
  .map((line) => line.trim())
  .filter((line) => line !== "");

/** Сколько раз имя встречается в коде. */
function times(name: string): number {
  return main.split(name).length - 1;
}

describe("наш набор значений снимается одним движением", () => {
  it("занимает две строки подряд и ничем не разбавлен", () => {
    // Разбавленный блок снимают по частям, а «по частям» здесь означает собранное приложение с
    // половиной чужого набора и половиной нашего. Мутация «увести строку имени вниз, к рантайму»
    // обязана красить эту пробу.
    const at = lines.flatMap((line, index) => (line.includes(STYLE) ? [index] : []));
    expect(at).toHaveLength(2);
    expect((at.at(-1) ?? 0) - (at[0] ?? 0)).toBe(1);
  });

  it("не оставляет своему имени второго употребления", () => {
    // Имя стоит ровно дважды: строка импорта и та единственная строка, ради которой оно
    // приехало. Отсюда свойство, ради которого всё и сделано: снятый блок роняет СБОРКУ, а не
    // тишину — потребитель узнаёт об оставшемся хвосте до запуска.
    expect(times("BASE_MARKER")).toBe(2);
  });

  it("не помнит снятого с поставки набора цветов", () => {
    // Надеваемой палитры по умолчанию у стилевого слоя больше нет: ни подпутя, ни имени.
    // Ссылка на них уехала бы к потребителю ненаходимым импортом, а не предупреждением.
    expect(raw).not.toContain("themes.css");
    expect(raw).not.toContain("DEFAULT_PALETTE");
  });

  it("называет чужой набор закрытым слотом, а не одними словами", () => {
    // Путь «значения на стороне» законный, и в скелете он назван местом, куда встаёт файл
    // поставщика. Без слота потребитель откроет импорт где придётся, и порядок подключения,
    // ради которого всё это писано, сломается на первом же чужом наборе.
    const slots = [...raw.matchAll(/^\s*\/\/\s*import\s+"(<[^>]+>[^"]*)";/gm)].map((m) => m[1]);
    const values = slots.filter((slot) => slot !== undefined && !slot.endsWith("/skin.css"));
    expect(values, slots.join(" · ")).toHaveLength(1);
    expect(values[0]).toMatch(/\.css$/);
  });
});

describe("проверка порядка условна, но не выброшена", () => {
  it("зовётся ровно один раз и остаётся в файле", () => {
    // Граница задачи: проверка ловит настоящий дефект — скин без базы даёт вид, посчитанный
    // от умолчаний. Выбросить её значило бы менять не то, что сломано.
    expect(times("checkStyleOrder(")).toBe(1);
  });

  it("питается маркером блока, а не собственным знанием об имени", () => {
    // Имя маркера рантайм принимает аргументом и не знает. Поэтому проверка
    // одинаково работает на чужом наборе — если у того есть свой маркерный токен базы.
    expect(main).toContain("checkStyleOrder({ marker: BASE_MARKER });");
  });

  it("объясняет у себя, что делать при чужом наборе", () => {
    // Развилка обязана стоять В ФАЙЛЕ: README обвеса до потребителя не доезжает, а этот файл
    // доезжает и больше не обновляется. Судим наличие обеих веток — заменить имя маркера или
    // снять строку, — а не формулировку.
    const call = raw.indexOf("checkStyleOrder({ marker");
    const comment = raw.slice(0, call).split(/\n\s*\n/).at(-1) ?? "";
    expect(comment).toMatch(/^\s*\/\//);
    expect(comment.split("\n").length).toBeGreaterThan(3);
    expect(comment).toMatch(/назови/);
    expect(comment).toMatch(/сними/);
  });
});
