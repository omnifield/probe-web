// ПЕРЕМЕННЫЕ ЭТАЛОНА — половина скина, объявленная так, как её объявляет человек в редакторе.
//
// ## Семенами, а не лестницами
//
// Три цветные шкалы названы ОДНИМ значением каждая. Обе половины строит та же механика, что
// строит их для набора значений: ступени назначены, контраст обещан ПОСТРОЕНИЕМ, а не подобран
// и не проверен постфактум.
//
// Выписать лестницы литералами было бы короче на один слой мыслей и дороже на всё остальное:
// пересеваемость — то, ради чего человек садится в редактор. Поменял семя — поменялся весь вид,
// обе половины, с сохранёнными обещаниями. Эталон, написанный литералами, доказывал бы, что
// механика умеет печатать чужие числа, а не что она умеет строить.
//
// Держит это проба, а не абзац: мутация «выпиши лестницу литералами» роняет покрытие семенами.
//
// ## Ряды, ушедшие из общего листа
//
// Длительности, кривые, межстрочные и начертания сняты из базового слоя как выбранный вкус
// (`PWEB-61`, `PWEB-66`). Вкус, отгруженный фреймворком, законен ровно в одном виде — как
// эталонный скин, и вот он.
//
// Они объявлены ЛИТЕРАЛАМИ, и это не небрежность: посеять их нечем. Семя — то, из чего строится
// лестница; у ряда длительностей основания-семени нет, это подобранный ряд (`PWEB-64`, граница
// «что скину не принадлежит»). Значения взяты ТЕ ЖЕ, что подставлял лист: эталон не повод менять
// их заодно — иначе переезд и смена вкуса смешались бы в одну неразбираемую правку.
//
// Лежат они в светлой половине, и этого достаточно: имя без семени объявлено один раз и
// действует в обеих половинах — так же, как в CSS, где тёмный блок переопределяет только
// названное. Длительность и начертание от режима не зависят.
//
// ## Чего здесь НЕТ намеренно
//
// **`--control-target-min`.** Лист вёз его рядом с межстрочными, но это не вкус, а ПОРОГ НОРМЫ
// (WCAG 2.2, 2.5.8 — минимальный размер цели 24×24). Объяви его скин — скин смог бы его
// «поправить», то есть подвинуть норму записью вида. Эталон вместо этого не спорит с нормой
// геометрией: высота контрола берётся ступенью `--control-height-md`, а она при плотности 1
// выше порога с запасом. Сомнение это названо ещё в `PWEB-64` и здесь названо второй раз, потому
// что именно здесь оно стало бы поставкой.
//
// **Шкала слоёв (`--z-*`).** Порядок «диалог выше своего затемнения» — контракт сосуществования
// компонентов, а не вид: скин, поменявший его, ломает работу, а не внешность. Из одетых пятерых
// ни один в слоях не живёт, так что и повода нет.

