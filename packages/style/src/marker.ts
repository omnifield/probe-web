// МАРКЕР ПРИЕЗДА БАЗЫ — токен, по которому снаружи проверяют, что базовый CSS подключён.
//
// ЗАЧЕМ ЭТО ЗДЕСЬ. Проверку порядка подключения делает `runtime` (`checkStyleOrder`), но имя
// маркера она принимает АРГУМЕНТОМ и не знает (`kb:PROBEWEB-13`): знание «какой токен обязан
// приехать с базой» принадлежит нашей зоне. Литерал на той стороне стал бы тихой связью —
// переименуем токен здесь, и проверка там начнёт врать: кричать «базы нет» на исправном
// приложении либо, что хуже, молчать на сломанном. Ни сборка, ни пробы этого не покажут.
//
// Цена ошибки несимметрична: имя уезжает в скелет, а скелет кладётся потребителю классом
// `placed-once` и НЕ ОБНОВЛЯЕТСЯ НИКОГДА. Литерал, попавший туда, чинится только правкой
// руками в каждом уже созданном продукте.
//
// ОБЛАСТЬ ДЕЙСТВИЯ — ТОЛЬКО НАШ НАБОР (`PWEB-3`). Маркер отвечает на вопрос о ПРОИСХОЖДЕНИИ
// значений: «приехала ли наша база». Для того, кто взял этот набор, вопрос осмыслен — база
// молча пропала, а производные посчитались от умолчаний. Для оформления на ЧУЖИХ значениях
// он не значит ничего: маркера там нет и быть не должно, и «маркера нет» — не диагноз.
// Вопрос по существу — другой: следует ли значение за режимом и за выбранной палитрой; его
// держит `test/foreign-values.test.ts`, и наших имён он не знает.

import { CONTROL_TARGET_MIN } from "./dimension.js";

/**
 * Имя токена, которым проверяется ПРИЕЗД БАЗЫ. С двумя дефисами: `checkStyleOrder()` ждёт
 * готовое кастом-свойство и на имя без них отказывает сразу.
 *
 * ЧЕМ ОБЯЗАН БЫТЬ МАРКЕР — три свойства, и все три проверяются пробой (`test/marker.test.ts`),
 * а не соблюдаются на память:
 *
 * 1. **Объявлен базовым слоем** — иначе он не отвечает на вопрос, ради которого заведён.
 * 2. **НИКОГДА не объявлен палитрой.** Маркер, уехавший в палитру, стирает разницу между
 *    «база не приехала» и «палитра не выбрана», а `runtime` различает ровно эти два
 *    состояния (`missing-base` против `no-skin`). После `kb:PROBEWEB-18` документ без
 *    `data-theme` — законное состояние, и на нём маркер обязан находиться.
 * 3. **Значение не зависит от палитры** — литерал, без единого `var()`. Токен, посчитанный
 *    из семени, на документе без палитры разрешается через фолбэк и годился бы тоже, но
 *    литерал отвечает на вопрос «база приехала?» и ни на какой другой.
 *
 * ПОЧЕМУ ИМЕННО ЭТОТ ТОКЕН. `--control-target-min` — пол нормы (WCAG 2.2, 2.5.8), а не наша
 * ступень: он не масштабируется ничем и не является вкусом, поэтому палитра, объявившая его,
 * — дефект по определению, а не законный случай. Запрет «никогда в палитре» держится тут
 * контрактом токенов, а не тем, что сегодня в файле его нет.
 *
 * Имя собирается из самой записи токена, а не переписано строкой: второй копии имени в зоне
 * нет, и переименование двигает маркер само.
 */
export const BASE_MARKER = `--${CONTROL_TARGET_MIN.name}`;
