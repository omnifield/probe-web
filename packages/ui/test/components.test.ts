// Гейт РАСКЛАДКИ: компонент — это папка, а не файл (`PWEB-2`, страница «Устройство»).
//
// Компонент не сводится к своей разметке. Это набор: разметка, анатомия, пробы, объявление
// наружу. Пока они лежали по параллельным папкам, «что такое кнопка» приходилось собирать в
// голове по четырём адресам, а увидеть, чего компоненту не хватает, было нельзя вовсе.
//
// Проба стережёт ровно это свойство. Неполнота обязана быть ВИДНА: папка без анатомии — это
// компонент, который себя не объявил, и в поставку его паспорт не уедет; папка без карты — это
// паспорт, части которого нечем нарисовать; папка без проб — это паспорт, который никто не
// сверял с живым узлом. Всё это молчит: сборка зелёная, типы целые, узнаёт об этом скин.
//
// Перечень папок здесь НЕ ведётся — он читается с диска. Список компонентов, дописываемый
// руками, был бы тем самым общим файлом, ради устранения которого папки и заводились.

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = resolve(here, "..", "src");

/** Папки компонентов. Папка в `src/` — это заявка на компонент, чем бы она ни была заполнена. */
const folders = readdirSync(srcDir, { withFileTypes: true })
  .filter((item) => item.isDirectory())
  .map((item) => item.name)
  .sort();

describe("компонент — это папка", () => {
  it("папки компонентов вообще есть", () => {
    // Иначе перебор ниже шёл бы по пустому списку и был бы зелёным, ничего не проверив.
    // Порог, а не число: папок прибывает волной разноса (`PWEB-7`), и точное число здесь
    // устаревало бы само по себе.
    expect(folders.length).toBeGreaterThan(0);
  });

  describe.each(folders)("%s", (folder) => {
    // Имена файлов внутри папки повторяют её имя, а не зовутся `component.tsx`: в редакторе с
    // десятком открытых вкладок «index/index/index» неразличимы, и это единственная причина.
    it.each([
      [`${folder}.tsx`, "разметка и поведение"],
      [`${folder}.anatomy.ts`, "части, адреса и добавка паспорта"],
      // Карта частей (`PWEB-84`). Папка без неё — паспорт, части которого нечем нарисовать:
      // сборка такой компонент в поставку не пустит, и здесь неполнота видна раньше сборки.
      [`${folder}.kit.ts`, "чем рисуется каждая часть"],
      [`${folder}.test.tsx`, "пробы рядом с предметом"],
      ["index.ts", "что уезжает наружу"],
    ])("несёт `%s` — %s", (file) => {
      expect(existsSync(join(srcDir, folder, file))).toBe(true);
    });

    // НАСТРОЙКИ ОБЪЯВЛЯЮТСЯ ЧЕРЕЗ `defineSettings<Пропы>` (`PWEB-89`), и это не стилистика.
    //
    // Сверка ключей с настоящими пропами компонента живёт ровно там: `defineSettings<AccordionProps>`
    // не даёт объявить настройку, которой у компонента нет, и не даёт забыть ту, что есть.
    // Напиши поставщик `settings: {…}` мимо этой функции — обе половины сверки пропадают молча,
    // и паспорт останется неполным, оставаясь зелёным.
    //
    // Само поле `settings` в форме НЕОБЯЗАТЕЛЬНОЕ: форма общая на всех поставщиков, и
    // обязательное поле уложило бы все паспорта, объявленные до сегодня, включая синтетические
    // паспорта соседних зон. Обязательность держится здесь — в границах кита, где она наша.
    it("объявляет настройки через `defineSettings<Пропы>` — иначе сверка с пропами не происходит", () => {
      const анатомия = readFileSync(join(srcDir, folder, `${folder}.anatomy.ts`), "utf8");

      expect(анатомия).toContain("defineSettings<");
    });
  });
});
