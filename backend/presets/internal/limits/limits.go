// Package limits несёт ограничители службы — в первой версии, а не «потом»: стенд публичный и
// без авторизации, писать и удалять может любой, кто знает адрес.
package limits

// Limits — все ограничители одним значением, чтобы пробы могли подставить свои без глобального
// состояния.
type Limits struct {
	// RecordBytes — предел размера ОДНОЙ записи: тело запроса целиком, в байтах.
	RecordBytes int64
	// RecordsPerKind — предел числа записей ОДНОГО вида. Список выбирают глазами по имени — на
	// второй сотне он перестаёт быть списком. Предел стоит НА ВИД, а не на хранилище целиком:
	// сервис теперь generic, и один прожорливый вид не обязан душить лимит всем остальным.
	RecordsPerKind int
	// TotalBytes — предел ЗАНЯТОГО объёма всего хранилища, в байтах. Место на диске общее для
	// всех видов разом, поэтому этот предел — единственный, что остаётся глобальным.
	TotalBytes int64
	// LabelChars / DescriptionChars — пределы длины полей, которые показываются в списке.
	LabelChars       int
	DescriptionChars int
}

// Default — числа по умолчанию, годные для дев-стенда. Каждое имеет право быть переопределённым
// окружением при развёртывании (см. cmd/presets) — ограничитель настраивает тот, кто
// разворачивает, а не тот, кто пишет код.
var Default = Limits{
	RecordBytes:      1 << 20,  // 1 МиБ — замерено на скине кита целиком (PWEB-13).
	RecordsPerKind:   200,      // на один вид; смотри комментарий у поля.
	TotalBytes:       64 << 20, // 64 МиБ на всё хранилище.
	LabelChars:       120,
	DescriptionChars: 1000,
}
