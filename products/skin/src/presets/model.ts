// ПРЕСЕТ — полный набор значений вида, отчуждаемый от стенда.
//
// Решение user 2026-08-17: подключается не «палитра» и не «радиус» по отдельности, а ПРЕСЕТ
// целиком. Дальше его можно крутить ручками — тогда он становится изменённым, — и сохранить как
// свой. Свой пресет виден в списке наравне со встроенными.
//
// ЗАЧЕМ ЭТО НУЖНО ЗА ПРЕДЕЛАМИ СТЕНДА, и это главное: пультов будет много, они похожи, но делают
// разное. Вид для них должен задаваться ОДНИМ указанием — «поставь этот пресет», — а не
// переносом десятка настроек руками. Механика приложения при этом не меняется: как персонажу
// меняют одежду, а не тело.
//
// ЧТО ВХОДИТ В ПРЕСЕТ:
//   • семена шкал — из каждого база строит двенадцать ступеней с обещаниями контраста;
//   • правки отдельных ступеней тёмной пары, если пресет их смягчает;
//   • мета: скругление, шаг интервалов, базовый кегль, высота контрола, толщина границы, трекинг;
//   • плотность.
//
// ЧТО НЕ ВХОДИТ:
//   • светлый/тёмный режим — это выбор пользователя, а не свойство пресета: один и тот же пресет
//     обязан работать в обоих;
//   • подключено ли оформление вообще — это не поле пресета, а СЛЕДСТВИЕ его наличия: есть
//     пресет — оформление стоит, нет пресета — кит голый (решение user 2026-08-18). Отдельной
//     ручки у оформления нет, иначе возможно состояние «правила вида есть, пресета нет»;
//   • варианты кнопок и прочая поверхность зоны — они одинаковы для всех пресетов, иначе пресет
//     менял бы не вид, а поведение.
//
// ── ГДЕ ЖИВЁТ ГЕНЕРАТОР CSS ────────────────────────────────────────────────────────────────
//
// В БАЗЕ (`themeModelToCss` из `@omnifield/probe-web-style`), а не здесь: решение `kb:PROBEWEB-15`,
// решение 2. Своей сборки строки в зоне НЕТ и заводить её нельзя — две реализации из одной модели
// дают два результата, и расходятся они молча, в день улучшения формулы ступеней.
//
// Здесь остаётся МОДЕЛЬ ПРЕСЕТА — она про стенд и его ручки: название, происхождение,
// идентификатор записи службы, состояние ручек и признак «изменён». Базе эти понятия не нужны.
// Шов между тем и другим — ровно одна функция `modelOf()`: пресет стенда → модель темы базы.

import type {
  ThemeDefinition,
  ThemeMetaToken,
  ThemeModel,
  ThemeTokens,
} from "@omnifield/probe-web-style";
import { buildThemeTokens } from "@omnifield/probe-web-style";

/** Семена шкал: по одному значению на шкалу. */
export interface PresetSeeds {
  brand: string;
  neutral: string;
  danger: string;
}

/** Мета-значения пресета. Пусто — берётся умолчание базы. */
export type PresetMeta = Partial<Record<ThemeMetaToken, string>>;

export interface Preset {
  /** Устойчивый идентификатор: он уезжает в атрибут `data-theme` и в имя файла. */
  id: string;
  /**
   * Идентификатор ЗАПИСИ в службе, если пресет пришёл оттуда.
   *
   * Их двое намеренно. Служба выдаёт свой идентификатор — UUID, и он опознаёт ЗАПИСЬ: по нему её
   * удаляют и перезаписывают. Но в `data-theme` уезжает имя ТЕМЫ, и оно обязано оставаться
   * читаемым: `data-theme="twitter"` человек видит в разметке своего приложения, а
   * `data-theme="5fdbea2d-4afc-..."` не говорит ему ничего.
   */
  recordId?: string;
  title: string;
  /** Откуда пресет взялся. Нужно для отчёта и для запрета правки встроенных. */
  origin: "встроенный" | "свой";
  seeds: PresetSeeds;
  meta?: PresetMeta;
  /** Правки ступеней тёмной пары: вкус конкретного пресета, а не лестницы базы. */
  darkOverrides?: Record<string, string>;
  /** Множитель интервалов и высот. Единица — как в базе. */
  density: string;
}

/** Значения пресета, которые меняются ручками. По ним же считается «изменён». */
export interface PresetState {
  brand: string;
  radius: string | undefined;
  density: string;
}

/** Состояние, в котором пресет находится сразу после подключения. */
export function stateOf(preset: Preset): PresetState {
  return {
    brand: preset.seeds.brand,
    radius: preset.meta?.radius,
    density: preset.density,
  };
}

/** Изменён ли пресет: сравниваются ровно те значения, которыми крутят ручки. */
export function isDirty(preset: Preset, state: PresetState): boolean {
  const base = stateOf(preset);
  return (
    base.brand !== state.brand || base.radius !== state.radius || base.density !== state.density
  );
}

/**
 * ШОВ С БАЗОЙ: пресет стенда (плюс состояние ручек) → модель темы.
 *
 * Отсюда берут вид ВСЕ: файл поставки (`themeModelToCss`), конверт службы и семя. Одно место
 * означает, что «унесённый пресет» и «пресет на экране» собраны из одних и тех же значений —
 * второе такое место разошлось бы с первым молча.
 *
 * Что НЕ уезжает: `title`, `origin`, `recordId` — понятия стенда и записи, а не вида
 * (`kb:PROBEWEB-15`, решение 2).
 */
export function modelOf(preset: Preset, state?: PresetState): ThemeModel {
  const meta = { ...preset.meta, ...(state?.radius ? { radius: state.radius } : {}) };

  return {
    id: preset.id,
    seeds: { ...preset.seeds, brand: state?.brand ?? preset.seeds.brand },
    ...(Object.keys(meta).length === 0 ? {} : { meta }),
    // Приведение здесь, а не в типе: модель стенда держит правки тёмной пары свободной картой —
    // она приходит из чужого JSON службы и разбирается, а не объявляется (`presets-api.ts`).
    ...(preset.darkOverrides === undefined
      ? {}
      : { darkOverrides: preset.darkOverrides as Partial<ThemeTokens> }),
    density: state?.density ?? preset.density,
  };
}

/**
 * Тема пресета для регистрации в слое `style`.
 *
 * Ступени считает БАЗА из семян: у неё закреплено назначение ступеней и проверены обещания
 * контраста. Пресет добавляет только правки тёмной пары, и за них отвечает проба зоны.
 *
 * Плотности здесь нет намеренно: она не токен палитры, а ось, и стенд ставит её на корень
 * отдельно. В ФАЙЛ поставки она попадает — этим занимается генератор базы.
 */
export function themeOf(preset: Preset, state?: PresetState): ThemeDefinition {
  const model = modelOf(preset, state);

  return {
    name: model.id,
    light: buildThemeTokens(model.seeds, "light", model.meta),
    dark: {
      ...buildThemeTokens(model.seeds, "dark", model.meta),
      ...model.darkOverrides,
    } as ThemeTokens,
  };
}

/**
 * Имя темы из человеческого названия: латиница, нижний регистр, дефисы.
 *
 * Оно уезжает В ИМЯ ФАЙЛА и в атрибут: «Янтарный пульт» как `data-theme` сработает, а как имя
 * файла в чужой сборке — уже вопрос удачи. Поэтому название человеческое, а имя темы латинское.
 */
export function slugOf(title: string, taken: readonly string[] = []): string {
  const latin = [...title.toLowerCase()].map((char) => CYRILLIC[char] ?? char).join("");
  const base = latin.replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "preset";

  if (!taken.includes(base)) return base;
  for (let n = 2; n < 100; n += 1) {
    if (!taken.includes(`${base}-${n}`)) return `${base}-${n}`;
  }
  return `${base}-${taken.length}`;
}

const CYRILLIC: Record<string, string> = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z", и: "i", й: "i",
  к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f",
  х: "h", ц: "c", ч: "ch", ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};
