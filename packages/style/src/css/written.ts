// РУЧНАЯ ЧАСТЬ БАЗОВОГО СЛОЯ — теперь он весь ручной, потому что в нём остался один сброс.
//
// ПОЧЕМУ СТРОКОЙ В МОДУЛЕ, А НЕ ФАЙЛОМ `.css` РЯДОМ (`PWEB-20`). Базовый CSS обязан
// порождаться ПО ТРЕБОВАНИЮ — в момент запроса, отражая текущие исходники, а не результат
// прошлой сборки. Значит порождение зовёт не только наш сборочный сценарий, но и дев-сервер,
// а он живёт в другой зоне. Ручная часть отдельным файлом заставила бы каждого зовущего знать
// путь к ней и уметь его прочитать: знание нашей раскладки уехало бы наружу.
//
// ─────────────────────────────────────────────────────────────────────────────────────────
// В ЛИСТЕ НЕ ОСТАЛОСЬ НИЧЕГО, КРОМЕ СБРОСА (`PWEB-66`). Два объявления, ни одного
// кастом-свойства.
//
// Снятие шло тремя заходами, и каждый следующий снимал то, что после предыдущего переставало
// иметь основание:
//
//   PWEB-39 — шесть объявлений вида на `body`: пять из них НАСЛЕДОВАЛИСЬ, то есть база
//             одевала кит мимо всякого скина;
//   PWEB-61 — 35 семантических ролей, 28 устаревших имён и `color-scheme`: имя, называющее
//             вид, — решение, и оно принадлежит скину;
//   PWEB-66 — остаток: длительности и кривые, размерные шкалы с блоком `@supports`, шкала
//             слоёв, межстрочные, начертания, пол нормы, комментарий границ осей.
//
// ПОЧЕМУ УШЁЛ И ОСТАТОК, хотя он «просто значения». Значение, объявленное листом, — это
// значение, которое приехало ВСЕМ и молча: потребитель, ничего не просивший, получает
// тридцать кастом-свойств на корне и не может от них отказаться. А печатать их некому:
// ссылок на них по всему дереву не осталось ни одной, скин печатает свои сам.
//
// ЗНАНИЕ ПРИ ЭТОМ ОСТАЛОСЬ ЦЕЛИКОМ. Ушла ПЕЧАТЬ в лист, а не форма шкалы: `DERIVED_SCALES`,
// `GRID_STEP`, `ROUND_SUPPORT_TEST`, `DENSITY_TOKEN` и `AXES` живут данными и экспортируются
// — из них печатает скин и по ним строят ползунки. Снести их значило бы сломать соседа не
// сборкой, а видом, то есть тише всего.
//
// ЗАПАСНЫХ ЗНАЧЕНИЙ НЕТ НИГДЕ. Ни одного `var(--что-то, умолчание)`: нет значения — это
// состояние, и оно называется, а не подменяется похожим.

/**
 * ЗАПИСЬ СБРОСА, которой предъявляют приезд базы: свойство и его значение вместе.
 *
 * Парой, а не двумя константами, и это условие формы, а не оформление. Свойство без значения —
 * ровно та проверка, которая ВРЁТ ЗЕЛЁНЫМ: `box-sizing` есть у каждого элемента всегда, и
 * «свойство нашлось» не отличает наш лист от его отсутствия. Отличает `border-box` против
 * браузерного `content-box`.
 *
 * Отсюда и выбор носителя: у `margin` умолчание браузера тоже отличается, но оно у одного
 * `body`, а `box-sizing` в сбросе стоит на всём — спросить его можно на любом узле.
 *
 * ВТОРОЙ КОПИИ ЗНАЧЕНИЯ В ЗОНЕ НЕТ: этой же записью печатается сам сброс ниже. Правка сброса
 * двигает пару сама, а пара — то, что уезжает наружу (`BASE_MARKER`, `src/marker.ts`).
 */
export const RESET_PROOF = { property: "box-sizing", value: "border-box" } as const;

/** Ручная часть базового CSS. `String.raw` — чтобы текст ехал ровно таким, как написан. */
export const WRITTEN_BASE = String.raw`/* СБРОС, и больше в этом файле нет ничего. Снимаем решения браузера, своих не вносим:
   ни одного кастом-свойства, ни одного значения, ни одного запасного варианта. */
*,
::before,
::after {
  ${RESET_PROOF.property}: ${RESET_PROOF.value};
}

body {
  margin: 0;
}
`;
