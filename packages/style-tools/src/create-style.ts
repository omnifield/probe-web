import { type Accessor, createMemo, splitProps } from "solid-js";

import { cn } from "./cn.js";

/**
 * Вариант-функция: то, что возвращает `cva()`. Тип объявлен структурно, а не импортом из
 * CVA, — чтобы `createStyle` принимал и рукописную функцию вариантов тоже.
 */
export type VariantFn<P> = (props: P) => string;

/**
 * Реактивная обвязка вариантов для компонента: читает пропсы ВНУТРИ мемо, поэтому смена
 * варианта пересчитывает класс, а не застывает на значении момента вызова. Префикс
 * `create*` — конвенция Solid для реактивного примитива (`kb:PROBEWEB-4`).
 *
 * Проп `class` потребителя идёт ПОСЛЕДНИМ аргументом `cn` — значит при конфликте утилит
 * выигрывает он, а не вариант. Это единственный способ переопределить стиль компонента
 * снаружи, и потому он часть контракта, а не деталь реализации.
 *
 * @param variants функция вариантов (обычно результат `cva()`)
 * @param props пропсы компонента; `class` из них к `variants` не попадает
 */
export function createStyle<const P extends Record<string, unknown>>(
  // `NoInfer` — чтобы форму пропсов задавал ВЫЗОВ, а не сигнатура `cva()`: её параметр
  // необязателен, и вывод по нему притащил бы в `P` ещё и `undefined`.
  // `const` — чтобы `{ size: "lg" }` осталось литералом и вариант проверился по имени, а
  // не расширилось до `string`, где компилятор уже ничего не ловит.
  variants: VariantFn<NoInfer<P>>,
  props: P & { class?: string | undefined },
): Accessor<string> {
  // `class` вынимаем ДО вызова вариантов: CVA умеет приклеивать его сам, и без разделения
  // он попал бы в строку дважды. Пары одинаковых классов `tailwind-merge` не схлопывает —
  // он разрешает конфликты, а не чистит дубли, и в атрибуте остался бы мусор.
  const [local, rest] = splitProps(props, ["class"]);

  return createMemo(() => cn(variants(rest as unknown as P), local.class));
}
