// ПОРОЖДЕНИЕ CSS-АРТЕФАКТОВ ЗОНЫ. Раньше склейка жила в сборочном сценарии, и порождать CSS
// умела только сборка — то есть в разработке приложение видело результат ПРОШЛОЙ сборки, а
// правка токена или перечня доезжала до глаз только следующей ручной командой (`PWEB-20`).
//
// Здесь это обычный модуль зоны, и зовётся он тремя разными местами одинаково:
//   • сборочный сценарий (`scripts/build-css.mjs`) — пишет `dist/css/*.css` для поставки;
//   • дев-сервер — порождает CSS В МОМЕНТ ЗАПРОСА, из текущих исходников (зацеп в дев-сервере
//     живёт в зоне `build`: подпуть `/generate` для того и объявлен на поверхности);
//   • пробы — сверяют порождённое с тем, что уехало в поставку.
//
// Функции ЧИСТЫЕ: ни файловой системы, ни путей, ни аргументов. Сборка, дев-сервер и
// установка потребителя зовут их из разных мест, и любой из этих входов, потребовавший знать
// нашу раскладку, немедленно стал бы вторым источником правды о ней.
//
// Сверка с рынком (2026-08-19): порождение по запросу через плагин дев-сервера и виртуальный
// модуль — устоявшийся приём, так работают UnoCSS (`virtual:uno.css`) и `@tailwindcss/vite`.
// Оттуда взята РАСКЛАДКА: генерация — чистая функция пакета, зацеп — плагин, который зовёт её
// на запрос и инвалидирует при правке исходников. Своего изобретаем ровно нашу склейку.
//
// ПОРЯДОК СКЛЕЙКИ ЗНАЧИМ: плотная шкала объявлена дважды — без округления и под `@supports`
// с ним, — и второе объявление побеждает только потому, что стоит позже. Блок, переехавший
// вперёд, сломает это молча; порядок держит проба, а не соглашение.

import { axesCss } from "../axes.js";
import { derivedCss } from "../dimension.js";
import { layerCss } from "../layer.js";
import { trace } from "../trace.js";
import { WRITTEN_BASE } from "./written.js";

/** Шапка порождённого блока: откуда он взялся и почему его бесполезно править руками. */
const generated = (what: string): string =>
  `/* ─────────────────────────────────────────────────────────────────────────────
   ${what}
   ПОРОЖДЕНО \`src/css/generate.ts\` из данных зоны. Править бесполезно — перезапишет.
   ───────────────────────────────────────────────────────────────────────────── */`;

/**
 * Базовый слой целиком: ручная часть плюс блоки, собранные из перечней в коде.
 *
 * Перечни ступеней, осей, слоёв и ролей уже существуют данными в TS — второй их копией
 * текстом файл разъехался бы на первой правке. Поэтому здесь склейка, а не список.
 *
 * @returns содержимое `base.css`
 */
export function baseCss(): string {
  const done = trace("baseCss");

  const css = [
    `/* @omnifield/probe-web-style — БАЗОВЫЙ СЛОЙ, подпуть \`@omnifield/probe-web-style/base.css\`.

   ФАЙЛ ПОРОЖДЁН \`src/css/generate.ts\`: написанная руками часть плюс блоки, собранные из
   перечней в коде — размерные шкалы (\`src/dimension.ts\`), границы осей (\`src/axes.ts\`),
   шкала слоёв (\`src/layer.ts\`). Править этот файл бесполезно: следующее порождение
   перезапишет. В разработке он порождается ПО ЗАПРОСУ, то есть отражает текущие исходники,
   а не прошлую сборку (\`PWEB-20\`).

   БАЗОВЫЙ СЛОЙ НЕ ОДЕВАЕТ, И ЭТО ТЕПЕРЬ БУКВАЛЬНО (\`PWEB-61\`). Здесь нет ни одного
   объявления вида: ни цвета, ни начертания, ни семантической роли, ни объявления режима.
   Что осталось адресовано документу — только СБРОС (\`box-sizing\`, \`margin\`): снятие
   решений браузера, а не внесение своих.

   Ушли отсюда: 35 семантических ролей (\`--surface\`, \`--text\`, \`--focus-ring\` и прочие),
   28 устаревших имён прежнего набора (\`--primary\`, \`--card\`, \`--sidebar-*\`) и
   \`color-scheme\`. Первые два были проводкой к ступеням, которых в поставке нет — палитру
   сняли; третье, вопреки прежнему объяснению, не «браузер рисует своё», а НАШЕ решение:
   без него браузер отвечает \`normal\` и рисует светлое при любой настройке человека.

   Имя, которое называет вид, — решение, и оно принадлежит скину. Значение, которое скин
   пересевает, — механизм, и оно здесь: шкалы, оси, слои, длительности.

   Геометрия считается без чего угодно рядом: дефолты размерных шкал подставлены прямо в
   \`var(--семя, …)\`. */`,
    WRITTEN_BASE.trimEnd(),
    generated("Размерные шкалы: производные от семян, ось плотности (`src/dimension.ts`)."),
    derivedCss(),
    generated(
      "Границы осей: где у значения край и есть ли он вообще (`src/axes.ts`).\n   Ни одного токена — знание об уже существующих осях, а не новая ось.",
    ),
    axesCss(),
    generated(
      "Шкала слоёв: объявленный порядок того, что лежит поверх страницы (`src/layer.ts`).",
    ),
    layerCss(),
  ].join("\n\n");

  done();
  return `${css}\n`;
}

