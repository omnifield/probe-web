// независимых токенов. Россыпь означает, что правка формы — это правка каждого значения в
// каждой теме; шкала означает, что тема задаёт одно число, а ступени считаем мы.
//
// ГДЕ ЖИВУТ ЗНАЧЕНИЯ. Семена — данные темы (`ThemeTokens`), ступени — `calc()` в `base.css`.
// Сам блок `base.css` ГЕНЕРИРУЕТСЯ из этого файла: иначе перечень ступеней существовал бы
// двумя копиями (данные здесь, текст там) и разъехался бы на первой правке. Отсюда же берутся
// значения по умолчанию в `var(--seed, …)` — второго места, где записан дефолт, нет.
//
// ПЛОТНОСТЬ — ОСЬ, А НЕ НАБОР. `--density` умножает интервалы, высоты контролов и кегль;
// форму — скругления, толщины границ, трекинг — не трогает (см. `DENSITY_NOTE`).
//
// СЕТКА ДЕРЖИТСЯ ПРИ ЛЮБОМ МНОЖИТЕЛЕ. Произвольная плотность даёт дробь, а от дроби едут
// соседние элементы, посчитанные от разных ступеней; поэтому значение плотной шкалы
// возвращается на сетку `GRID_STEP` функцией `round()`. Исключение одно и названо — кегль
// (см. `GRID_NOTE`).
//
// САМА `round()` ПОДСТРАХОВАНА. Значение шкалы со `snap` объявляется ДВАЖДЫ: первым — без
// округления, вторым — под `@supports`, с посадкой на сетку. Браузер без `round()` берёт
// первое и получает дробное, но живое значение; браузер с поддержкой берёт второе. Порядок —
// часть решения, а не оформление (см. `ROUND_FALLBACK_NOTE`).

/** Ступень производной шкалы. Ровно один из способов задания — множитель, смещение, литерал. */
export type DerivedStep =
  | { name: string; factor: number }
  | { name: string; offset: string }
  | { name: string; value: string };

export interface DerivedScale {
  /** Имя токена-семени (без `--`). */
  seed: string;
  /** Значение семени по умолчанию — оно же подставляется как fallback в `var()`. */
  fallback: string;
  /** Умножается ли шкала осью плотности. */
  density: boolean;
  /**
   * Возвращается ли значение на сетку `GRID_STEP` после умножения плотностью. Поле
   * ОБЯЗАТЕЛЬНОЕ и у неплотных шкал тоже: «сажаем или нет» — объявленное свойство шкалы, а
   * не то, что читатель выводит из отсутствия строки. Сажать неплотную шкалу нечего —
   * её значения на сетку не съезжают; это держит проба.
   *
   * Это же поле задаёт перечень подстраховки `@supports`: два объявления получает ровно та
   * шкала, у которой здесь `true`. Второго списка нет намеренно — он разъехался бы с этим.
   */
  snap: boolean;
  /** Основание шага — объявленное. Уезжает комментарием в сгенерированный CSS. */
  basis: string;
  steps: DerivedStep[];
}

