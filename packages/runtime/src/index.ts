// МЕХАНИКА ПОДКЛЮЧЕНИЯ СКИНА (`kb:PROBEWEB-13`, инварианты `kb:SKIN-7`).
//
// Механика — УДОБСТВО, а не путь к результату. Четыре строки импорта и атрибут на `<html>`
// работают в статической странице без сборки и без единой строки JS; всё, что здесь есть,
// снимает ручную работу и ничего не добавляет к результату. Проверка на месте: приложение,
// НЕ позвавшее ни одной функции ниже, но подключившее файлы, выглядит правильно.
//
// Отсюда три запрета, которые держит эта зона:
//   • ни одного инлайнового стиля и ни одного `!important` (инвариант 6) — мы ставим атрибут и
//     класс на корень, это ВХОДНЫЕ ДАННЫЕ, а не оформление;
//   • поддерево не перемонтируется (инвариант 9) — вид меняется значениями на корне, дерево не
//     трогается вовсе, и `mount()` при смене пресета не зовётся;
//   • на импорте не делается НИЧЕГО (`sideEffects: false` в манифесте) — только функции,
//     которые зовёт приложение. Самоинициализация сделала бы манифест ложью, а трясун вырезал
//     бы то, на что кто-то рассчитывает.
//
// Двух вещей механика НЕ ЗНАЕТ и знать не может — их ей СООБЩАЮТ:
//   • перечень пресетов — он объявлен в `skin`, зоне `products/`, а база не может зависеть от
//     `products/` (`kb:PROBEWEB-4`, направление одностороннее);
//   • маркерная пара базы — она принадлежит `style`; литерал здесь стал бы тихой связью, и
//     переезд маркера — уже случившийся — прошёл бы мимо нас молча, оставив проверку врать.
// Побочная выгода обоих решений одна: чужой поставщик пресетов и чужая база встают в эту
// механику без единой правки.
// ────────────────────────────────────────────────────────────────────────────────────────────

/** Режим: светлая или тёмная пара. Половина СКИНА, а не свойство документа. */
export type SkinMode = "light" | "dark";

/** Что стоит на корне документа. */
export interface SkinChoice {
  /** Идентификатор пресета в `data-theme`; `null` — пресет не стоит, приложение на базе. */
  preset: string | null;
  /**
   * Режим, СТОЯЩИЙ на документе сейчас.
   *
   * На голом приложении он всегда `light`, и это не выбор человека, а отсутствие выбора:
   * тёмная пара выражается классом, а на голом документе класса нет. Что выбрал человек,
   * помнит хранилище, и его выбор встанет, когда наденут скин.
   */
  mode: SkinMode;
  /**
   * Надет ли скин.
   *
   * Здесь же ответ на вопрос «взялся ли режим»: не надет — менять было нечего, и документ не
   * тронут. Ради этого поле и заведено — состояние «менять нечего» обязано быть отличимо от
   * состояния «поменяли», а по одному только `mode` они неразличимы.
   */
  dressed: boolean;
}

/**
 * Правка выбора. Поля НЕЗАВИСИМЫ, и в этом весь смысл инварианта 3: режим не зашит в имя
 * пресета, поэтому сменить одно, не тронув другое, обязано быть возможно.
 *
 * Отсутствующее поле — «не трогай». Для пресета `null` — это не «не трогай», а «сними»:
 * состояние «пресета нет» настоящее, и выразить его надо уметь.
 */
export interface SkinPatch {
  preset?: string | null;
  mode?: SkinMode;
  /**
   * Запомнить ли выбор между заходами. По умолчанию да — это и есть обычный случай «человек
   * выбрал».
   *
   * `false` нужен для случая «поставили ЧУЖОЕ умолчание»: приложение, которое применяет тему,
   * пришедшую снаружи, не должно превращать её в собственный запомненный выбор человека.
   */
  remember?: boolean;
  /** Ключ хранилища, если приложению нужен свой. */
  storageKey?: string;
}

/** Что нужно механике, чтобы восстановить выбор. */
export interface RestoreSkinOptions {
  /**
   * ПЕРЕЧЕНЬ ПРЕСЕТОВ — принимается, а не импортируется и не объявляется (инвариант 11).
   *
   * Форма — обычный массив идентификаторов: ровно то, что механике нужно, и ничего сверх.
   * Названия, семена и файлы пресетов её не касаются — они нужны интерфейсу выбора, а тот
   * берёт их у `skin` напрямую, минуя нас.
   *
   * Служит одному: запомненный идентификатор, которого в перечне больше нет (пресет удалили,
   * поставщика сменили), на корень не ставится. Порядок в перечне ничего не значит — механика
   * из него не выбирает.
   *
   * Пустой перечень — законное состояние «пресетов нет»: приложение остаётся на голом ките
   * (инвариант 4).
   */
  presets: readonly string[];
  /**
   * Чем жить, когда запомненного выбора нет или он больше не годится. ЯВНЫЙ ВЫБОР ПОТРЕБИТЕЛЯ.
   *
   * Не названо — не ставится ничего: не вспомнилось и запасного не назвали, значит нечего.
   * Отсутствие выбора это состояние, и механика его называет, а не заполняет — ни первым из
   * перечня, ни настройкой системы. Заполнить значило бы принять решение за приложение и
   * за человека, а потом выдать его за их.
   */
  fallback?: { preset?: string | null; mode?: SkinMode };
  /** Ключ хранилища, если приложению нужен свой. */
  storageKey?: string;
}

/**
 * МАРКЕР ПРИЕЗДА БАЗЫ — пара: свойство и значение, которое оно обязано принять.
 *
 * Пара, а не имя, и это не удобство. Прежде принималось имя кастом-свойства, а приезд базы
 * предъявлялся тем, что свойство ОБЪЯВЛЕНО. Держалось это на форме имени: `--` отличало наше
 * от браузерного, потому что кастом-свойств браузер не объявляет. Основание ушло вместе с
 * поставщиком: базовый слой стал одним сбросом, кастом-свойств в нём не осталось, и маркером
 * стало обычное свойство — а обычное объявлено ВСЕГДА. «Свойство нашлось» на нём истинно и без
 * нашего листа, то есть проверка врала бы зелёным — худший из отказов.
 *
 * Значение отличает надёжнее любой формы имени: `box-sizing` есть у каждого элемента, но
 * `border-box` на корне бывает только с приехавшим листом. Поэтому обе половины обязательны, и
 * половина без второй — не неполнота, а тихо соврамший гейт.
 */
export interface StyleMarker {
  /** Свойство, по которому спрашивают корень. Кастом-свойство или обычное — всё равно. */
  property: string;
  /** Значение, которое оно принимает ТОЛЬКО с приехавшим базовым листом. */
  value: string;
}

/** Что нужно проверке порядка подключения. */
export interface StyleOrderOptions {
  /**
   * Пара, которой предъявляют приезд базы.
   *
   * Принимается снаружи по той же причине, что и перечень скинов: маркер принадлежит `style`,
   * и обе его половины меняются без нашего ведома — свойство уже переезжало. Литерал здесь
   * пережил бы переезд молча и начал бы врать: кричать на исправном приложении либо, что
   * хуже, молчать на сломанном.
   */
  marker: StyleMarker;
}

/** Чем кончилась проверка порядка подключения. */
export type StyleOrderStatus = "ok" | "missing-base" | "no-skin";

/** Разбор проверки порядка — значением, а не только строкой в консоли. */
export interface StyleOrderReport {
  status: StyleOrderStatus;
  /** Пара, которой проверяли. */
  marker: StyleMarker;
  /** Что на корне НАШЛОСЬ. Пусто — свойства нет вовсе; иначе видно, чем оно занято. */
  seen: string;
  /** Пресет, стоявший на корне в момент проверки. */
  preset: string | null;
  /** Человеку. У `ok` — пусто: сообщать не о чем. */
  message: string;
}

/** Идентификатор пресета, годный для атрибута. Пустая строка — молча пустой `data-theme`. */
function checkedPreset(id: string | null): string | null {
  if (id === null) return null;
  if (id.trim() === "") {
    throw new Error(
      "[probe-web-runtime] applySkin(): идентификатор пресета пуст. " +
        "Снять пресет — это preset: null, а не пустая строка.",
    );
  }
  return id;
}

/**
 * Одета ли страница. ЕДИНСТВЕННОЕ место, где живёт этот ответ.
 *
 * Спрашиваем документ, а не зону скина и не свою память: скин надет ровно тогда, когда на
 * корне стоит его опознание. Заведи мы второй ответ — флаг в модуле, поле в переключателе, —
 * они разошлись бы на первой же странице, которая оделась руками.
 */
function dressed(): boolean {
  return readWorn() !== null;
}

/**
 * Ставит режим на документ, ЕСЛИ его есть куда ставить.
 *
 * Режим — половина скина, и на голом приложении второй половины нет: футболку красят после
 * того, как сшили. Поэтому переключатель на голой странице не меняет ни пикселя — не потому,
 * что мы промолчали, а потому что менять нечего. Выбор человека при этом не теряется: он
 * лежит в памяти и встанет при надевании.
 *
 * @returns взялся ли режим
 */
function applyMode(mode: SkinMode): boolean {
  if (!dressed()) return false;
  writeDark(mode === "dark");
  return true;
}

/**
 * Ставит пресет и режим на корень документа и (по умолчанию) запоминает выбор.
 *
 * Поля правки независимы: `applySkin({ mode: "dark" })` не трогает `data-theme`, а
 * `applySkin({ preset: "dense" })` не трогает режим. Дерево не перемонтируется — меняются
 * только значения на корне, поэтому открытые панели, фокус и ввод переживают смену вида
 * (инвариант 9).
 *
 * **РЕЖИМ БЕЗ НАДЕТОГО СКИНА НЕ ДЕЛАЕТ НИЧЕГО.** Он половина скина, а не свойство документа:
 * цвета у того, чего не сшили, быть не может. Голая страница от переключателя не меняется ни
 * на пиксель, и узнать это можно по `dressed` в ответе. Выбор при этом ЗАПОМИНАЕТСЯ — человек
 * его сделал, — и встанет сам, когда скин наденут.
 *
 * @param patch что изменить; отсутствующее поле остаётся как было
 * @returns что стоит на корне ПОСЛЕ правки — вместе с ответом, одета ли страница
 * @throws если идентификатор пресета — пустая строка
 */
export function applySkin(patch: SkinPatch): SkinChoice {
  const done = trace("applySkin");

  if (patch.preset !== undefined) writePreset(checkedPreset(patch.preset));
  if (patch.mode !== undefined) applyMode(patch.mode);

  const choice = readSkin();

  if (patch.remember !== false) {
    // Запоминается ВЫБРАННОЕ, а не стоящее на документе. Разница видна ровно на голой
    // странице: режим туда не встал, и запиши мы `choice.mode`, выбор человека затёрся бы
    // светлым — тем самым, которого он не выбирал. Режим, который не назвали, не трогается
    // вовсе: запись идёт слиянием, и отсутствующее поле остаётся прежним.
    const record: Remembered = { preset: choice.preset };
    if (patch.mode !== undefined) record.mode = patch.mode;
    remember(patch.storageKey ?? DEFAULT_STORAGE_KEY, record);
  }

  done();
  return choice;
}

/**
 * Что стоит на корне сейчас.
 *
 * Источник ответа — сам документ, а не наша память: атрибут мог поставить кто угодно — соседний
 * скрипт, скелет, разметка страницы, — и правдой является то, что видит CSS.
 */
export function readSkin(): SkinChoice {
  return {
    preset: readPreset(),
    mode: readDark() ? "dark" : "light",
    dressed: dressed(),
  };
}

/**
 * Восстанавливает запомненный выбор на корне документа. ЭТО ТА ФУНКЦИЯ, КОТОРУЮ СКЕЛЕТ ЗОВЁТ
 * ДО ПЕРВОЙ ОТРИСОВКИ.
 *
 * Почему её можно звать до `mount()` и до появления `<body>`:
 *   • она синхронна и не ждёт ничего — ни загрузки бандла, ни готовности документа;
 *   • она не знает про Solid и не трогает `#root` — только `document.documentElement`, а он
 *     существует уже во время разбора страницы;
 *   • она не спрашивает вычисленные стили, поэтому ей не нужен ни один подключённый лист
 *     (этим она отличается от `checkStyleOrder()`, которой стили нужны по определению).
 *
 * Зачем так рано: класс режима, поставленный после первого кадра, даёт вспышку светлой темы
 * перед тёмной (инвариант 3). `mount()` зовётся после загрузки бандла, то есть заведомо позже
 * первого кадра, и закрыть вспышку изнутри `mount()` нельзя — это работа скелета
 * (`tasker:PROBEWEB-53`).
 *
 * Ничего не запоминает: восстановление — не выбор человека, и записывать его как выбор значило
 * бы придумать за него решение, которого он не принимал.
 *
 * @returns что встало на корень
 */
export function restoreSkin(options: RestoreSkinOptions): SkinChoice {
  const done = trace("restoreSkin");

  const remembered = recall(options.storageKey ?? DEFAULT_STORAGE_KEY);
  const fallback = options.fallback ?? {};

  const known = remembered?.preset !== null && remembered?.preset !== undefined
    ? options.presets.includes(remembered.preset)
    : false;

  // Не вспомнилось и приложение не назвало запасного — значит НЕЧЕГО, и обе половины молчат
  // одинаково. Запасное — явный выбор потребителя, и других источников у выбора нет.
  const preset = known ? (remembered?.preset ?? null) : (fallback.preset ?? null);
  const mode = remembered?.mode ?? fallback.mode;

  writePreset(checkedPreset(preset));

  // Режим — только на одетую страницу. На голой его НЕТ: режим это половина скина, а скина
  // нет — половине не от чего быть.
  if (mode !== undefined) applyMode(mode);

  done();
  return readSkin();
}

/**
 * Проверяет порядок подключения: приехал ли на корень базовый CSS.
 *
 * Пресет без базы даёт вид, где производные посчитаны от умолчаний. Выглядит это как «скин
 * почти работает» — ХУЖЕ явной поломки, потому что чинить такое никто не идёт. Проверка
 * дешёвая: приняло ли на корне маркерное свойство то значение, которое даёт ему только база.
 *
 * Что проверка ВИДИТ и чего не видит, чтобы на неё не рассчитывали сверх меры: она отвечает на
 * «база приехала или нет», а не на «в каком порядке склеены листы». Настоящий порядок правил в
 * каскаде из DOM не читается; ловится следствие, ради которого правило и заведено, — молча
 * пропавшая база под стоящим пресетом.
 *
 * Не бросает и не останавливает приложение: механика — удобство, и диагностика вида не имеет
 * права ронять работающее приложение потребителя. Кричит в `console.error` и отдаёт разбор
 * значением — что с ним делать (упасть в dev, показать плашку, промолчать), решает приложение.
 *
 * @throws если у пары пуста любая половина — половина без второй врёт зелёным, а не отказывает
 */
export function checkStyleOrder(options: StyleOrderOptions): StyleOrderReport {
  const done = trace("checkStyleOrder");
  const { marker } = options;

  // Отказ стоит на ПОЛНОТЕ ПАРЫ: пустое значение сравнялось бы с «свойства нет» и сделало бы
  // зелёным ровно тот случай, ради которого проверка заведена.
  if (marker.property.trim() === "" || marker.value.trim() === "") {
    throw new Error(
      "[probe-web-runtime] checkStyleOrder(): маркер — ПАРА, свойство и его значение, и " +
        `здесь пуста одна из половин (свойство «${marker.property}», значение ` +
        `«${marker.value}»). Свойство без ожидаемого значения — проверка, которая врёт ` +
        "зелёным: обычное свойство объявлено всегда, и «оно нашлось» истинно без нашего листа.",
    );
  }

  const preset = readPreset();
  const seen = readToken(marker.property);

  // Сравнение ТОЧНОЕ. Значение — обещание листа, а не примета: «похоже» здесь означало бы, что
  // мы сами придумали, насколько похоже считается приездом.
  const arrived = seen === marker.value.trim();

  const status: StyleOrderStatus = arrived ? "ok" : preset === null ? "no-skin" : "missing-base";

  // «Ни базы, ни пресета» — это ГОЛЫЙ КИТ, заявленное свойство продукта (инвариант 4), а не
  // поломка. Кричать на него значило бы объявить оформление обязательным.
  const message =
    status === "missing-base"
      ? `[probe-web-runtime] порядок подключения нарушен: пресет «${preset}» стоит, ` +
        `а базового CSS нет — на корне ${marker.property} обязан быть «${marker.value}», ` +
        `а он ${seen === "" ? "не объявлен вовсе" : `равен «${seen}»`}. Производные посчитаны ` +
        "от умолчаний, и вид будет «почти правильным» — это хуже явной поломки. Порядок " +
        "импортов: базовый CSS → ступени темы → пресет → оформление."
      : "";

  if (status === "missing-base") console.error(message);

  done();
  return { status, marker, seen, preset, message };
}

