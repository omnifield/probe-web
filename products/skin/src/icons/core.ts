// ЯДРО НАБОРА ЗНАЧКОВ — то, что зона привозит с собой.
//
// Значок в probe-web это CSS-МАСКА, а не компонент и не шрифт. Узел получает переменную `--icon`
// с картинкой, а одно общее правило делает остальное:
//
//   [data-icon] { inline-size: 1em; block-size: 1em;
//                 background-color: currentColor; mask-image: var(--icon); }
//
// Отсюда два свойства, ради которых форма и выбрана:
//   • РАЗМЕР — `1em`, то есть значок сам следует за кеглем контрола (`--font-size-*`, `data-size`);
//   • ЦВЕТ — `currentColor`, то есть значок берёт роль у того, внутри чего стоит.
// Ни одного правила «этот значок в этой кнопке такого размера» не нужно и быть не должно.
//
// ПОЧЕМУ НЕ КОМПОНЕНТЫ И НЕ ШРИФТ. Поставка зоны — только CSS (`kb:PROBEWEB-11`), а значки-
// компоненты означали бы JS в поставке и зависимость потребителя от нашего пакета в рантайме.
// Иконочный шрифт даёт одну картинку на глиф, ломает подбор шрифта у ассистивных технологий и
// требует ПЕРЕГЕНЕРАЦИИ при добавлении своего значка. Маска не требует ничего: своя иконка это
// одна строка CSS, и она встаёт наравне со встроенными.
//
// ОТКУДА КАРТИНКИ. Lucide (ISC, 1836 значков, сетка 24, обводка 2) — набор экосистемы, из которой
// взята наша дефолтная тема, и линия та же, что у ориентира Radix Themes. Берётся он не пакетом в
// поставку, а генератором: `@iconify-json/lucide` лежит в devDependencies, а результат — готовый
// `src/skin/icons.css` в репозитории. У потребителя ни строки JS и ни одной зависимости.
//
// ПОЧЕМУ ЯДРО, А НЕ ВЕСЬ НАБОР. Замер: значок как правило CSS весит в среднем 457 Б, ядро из
// сорока с небольшим — 18 КБ, весь Lucide — 987 КБ. Отдавать потребителю килобайт на значок,
// которого он не просил, незачем: нужного нет в ядре — добавляется по имени тем же генератором.

