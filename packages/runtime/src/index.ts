//
// Скелет едет к потребителю классом `placed-once`: положен один раз и НИКОГДА не
// обновляется. Значит вызов `mount()` в его `main.tsx` живёт вечно ровно в той форме, в
// какой его туда положили. Менять сигнатуру нельзя без мажора и разговора с architect.
//
// ЗАМОРОЖЕНЫ ровно две вещи — сигнатура `mount()` и идентификатор `#root`. Запрета на соседние
// экспорты из этого не следует, и механика скина ниже едет ИМЕНОВАННЫМИ ЭКСПОРТАМИ ЭТОЙ ЖЕ
// точки: подпуть у пакета остаётся один, отдельного пакета не заводим (`PROBEWEB-13`,
// разрешение architect от 2026-08-19 в `PROBEWEB-52`). Но замерзают и они — форма
// вызова, которую скелет впишет к себе, останется у всех уже созданных продуктов навсегда.

