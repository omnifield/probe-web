import { type ClassValue, clsx } from "clsx";
import { twMerge } from "tailwind-merge";

/**
 * Канонический комбинатор классов: `clsx` собирает условные формы (строки, массивы,
 * объекты, ложные значения), `tailwind-merge` разрешает КОНФЛИКТЫ утилит — из `p-2 p-4`
 * остаётся `p-4`.
 *
 * Почему не одним `clsx`: без разрешения конфликтов «переопределение через проп `class`»
 * не работает — в атрибуте оказываются оба класса, а выигрывает тот, что раньше в CSS,
 * то есть порядок правил вместо порядка аргументов. Это и есть причина, по которой
 * `tailwind-merge` здесь несущий, а не украшение.
 *
 * Инструмент НЕОБЯЗАТЕЛЕН: оформление вправе не брать его вовсе — ни этот пакет, ни набор
 * значений не являются условием законности скина (`PWEB-3`).
 */
export function cn(...inputs: ClassValue[]): string {
  return twMerge(clsx(inputs));
}
