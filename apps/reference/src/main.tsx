// Точка входа. Повторяет скелет потребителя (`packages/starter/template/main.tsx`) буква в
// букву по СОСТАВУ вызовов: тот же CSS-подпуть, тот же `mount`. Это не совпадение и не вкус —
// скелет едет к потребителю классом `placed-once` и больше не обновляется, поэтому ровно эта
// форма обязана быть проверена сборкой здесь, а не у него.
//
// Подпуть ОДИН (`PWEB-52`). Второй вёз надеваемую палитру по умолчанию, и её больше нет:
// палитра без рецептов — половина скина, а половин у скина не бывает. Из базового слоя
// приезжает сброс и размерные шкалы — они работают без палитры, у них есть подстраховки.
// Цвет приезжает СКИНОМ, а скина здесь нет: страница голая, и это её рабочее состояние.
import "@omnifield/probe-web-style/base.css";
// Второй строкой — оформление ПОТРЕБИТЕЛЯ: кит безголовый, и без этого файла страница
// поднимется без раскладки. У потребителя это место его собственного CSS.
import "./app.css";

import { mount } from "@omnifield/probe-web-runtime";

import { App } from "./app";

// Точку монтирования рантайм ищет сам — `#root` из `index.html`. В сигнатуре её нет, и
// приложение о ней не знает: знает только разметка.
mount(() => <App />);
