// ИМЯ СВОЙСТВА в двух начертаниях — одно место перевода на всю зону.
//
// Взятая форма рецепта пишется верблюжьим начертанием (`borderWidth`), CSS понимает дефисное
// (`border-width`), и принимаем мы оба. Читателей у этого перевода двое — печать и счёт
// читаемости, — и второе его написание разошлось бы с первым на первом же исключении.

/**
 * Имя свойства в CSS-начертании.
 *
 * Кастом-свойства не трогаются: `--моё-имя` — уже имя, а не запись. Дефисное начертание
 * проходит насквозь: заглавных в нём нет.
 *
 * @param name имя свойства как записано в рецепте
 */
export function cssProperty(name: string): string {
  return name.startsWith("--") ? name : name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}
