// НАДЕВАНИЕ И СНЯТИЕ СКИНА + ПРОВЕРКА ПОРЯДКА ПОДКЛЮЧЕНИЯ.
//
// ПЕРЕЕХАЛО СЮДА ИЗ `@web-core/runtime` (было `PROBEWEB-13`/`SKIN-7`, здесь — продолжение той
// же механики, не новая). `runtime` держала это ради контракта `mount()`/`#root` по соседству —
// повод уже не действует (`runtime` со временем уходит целиком, `mount()`/`#root` не наш
// предмет), а сама механика ВСЕГДА была про скин: надевает переменные и правила вида, порождённые
// печатью `packages/skin`, и ничего из `runtime` реально не требовала — солид ей был нужен только
// для `createSkinConnection` (`../solid.ts`, отдельный подпуть, тем же приёмом, что `@web-core/
// style` держит `/solid` рядом с движком без фреймворка).
//
// Скин — это вид целиком: переменные и правила вида, одной единицей. Приложение обязано уметь
// четыре вещи: назвать ИСТОЧНИК скинов, надеть нужный по имени, снять его и не потерять выбор
// между заходами.
//
// Три границы, которые механика держит и которые в ней проверяются пробами:
//   • ИСТОЧНИК ПРИНИМАЕТСЯ, А НЕ ЗАШИВАЕТСЯ. Ни про адрес хранилища, ни про конкретного
//     поставщика скинов механика не знает никогда — чужой поставщик встаёт сюда без единой правки;
//   • МЕХАНИКА НЕОБЯЗАТЕЛЬНА. Приложение, подключившее файл скина само, обязано выглядеть так
//     же, как одетое отсюда. Механика снимает ручную работу, а не является путём к результату;
//   • БЕЗ СКИНА ПРИЛОЖЕНИЕ РАБОТАЕТ. Голый кит — законное состояние продукта, а не отказ.
//
// РЕЖИМ — ПОЛОВИНА СКИНА, и потому живёт здесь же. Второй двери к нему нет: половину называют
// при надевании, и это единственный способ её поставить.

import { DEFAULT_STORAGE_KEY, recall, remember, type Remembered } from "./memory.js";
import { readDark, readToken, readWorn, writeDark, writeWorn } from "./root.js";
import { makeSkinSheet } from "./sheet.js";
import { trace } from "../trace/index.js";

/** Режим: светлая или тёмная пара. Половина СКИНА: у голого приложения его нет. */
export type SkinMode = "light" | "dark";

/**
 * МАРКЕР ПРИЕЗДА БАЗЫ — пара: свойство и значение, которое оно обязано принять.
 *
 * Пара, а не имя, и это не удобство. Прежде принималось имя кастом-свойства, а приезд базы
 * предъявлялся тем, что свойство ОБЪЯВЛЕНО. Держалось это на форме имени: `--` отличало наше
 * от браузерного, потому что кастом-свойств браузер не объявляет. Основание ушло вместе с
 * поставщиком: базовый слой стал одним сбросом, кастом-свойств в нём не осталось, и маркером
 * стало обычное свойство — а обычное объявлено ВСЕГДА. «Свойство нашлось» на нём истинно и без
 * нашего листа, то есть проверка врала бы зелёным — худший из отказов.
 *
 * Значение отличает надёжнее любой формы имени: `box-sizing` есть у каждого элемента, но
 * `border-box` на корне бывает только с приехавшим листом. Поэтому обе половины обязательны, и
 * половина без второй — не неполнота, а тихо соврамший гейт.
 */
export interface StyleMarker {
  /** Свойство, по которому спрашивают корень. Кастом-свойство или обычное — всё равно. */
  property: string;
  /** Значение, которое оно принимает ТОЛЬКО с приехавшим базовым листом. */
  value: string;
}

/** Что нужно проверке порядка подключения. */
export interface StyleOrderOptions {
  /**
   * Пара, которой предъявляют приезд базы.
   *
   * Принимается снаружи по той же причине, что и перечень скинов: маркер принадлежит `style`,
   * и обе его половины меняются без нашего ведома — свойство уже переезжало. Литерал здесь
   * пережил бы переезд молча и начал бы врать: кричать на исправном приложении либо, что
   * хуже, молчать на сломанном.
   */
  marker: StyleMarker;
}

/** Чем кончилась проверка порядка подключения. */
export type StyleOrderStatus = "ok" | "missing-base" | "no-skin";

/** Разбор проверки порядка — значением, а не только строкой в консоли. */
export interface StyleOrderReport {
  status: StyleOrderStatus;
  /** Пара, которой проверяли. */
  marker: StyleMarker;
  /** Что на корне НАШЛОСЬ. Пусто — свойства нет вовсе; иначе видно, чем оно занято. */
  seen: string;
  /** Скин, надетый в момент проверки. */
  skin: string | null;
  /** Человеку. У `ok` — пусто: сообщать не о чем. */
  message: string;
}

/**
 * Проверяет порядок подключения: приехал ли на корень базовый CSS.
 *
 * Скин без базы даёт вид, где производные посчитаны от умолчаний. Выглядит это как «скин почти
 * работает» — ХУЖЕ явной поломки, потому что чинить такое никто не идёт. Проверка дешёвая:
 * приняло ли на корне маркерное свойство то значение, которое даёт ему только база.
 *
 * Что проверка ВИДИТ и чего не видит, чтобы на неё не рассчитывали сверх меры: она отвечает на
 * «база приехала или нет», а не на «в каком порядке склеены листы». Настоящий порядок правил в
 * каскаде из DOM не читается; ловится следствие, ради которого правило и заведено, — молча
 * пропавшая база под надетым скином.
 *
 * Не бросает и не останавливает приложение: механика — удобство, и диагностика вида не имеет
 * права ронять работающее приложение потребителя. Кричит в `console.error` и отдаёт разбор
 * значением — что с ним делать (упасть в dev, показать плашку, промолчать), решает приложение.
 *
 * @throws если у пары пуста любая половина — половина без второй врёт зелёным, а не отказывает
 */
export function checkStyleOrder(options: StyleOrderOptions): StyleOrderReport {
  const done = trace("checkStyleOrder");
  const { marker } = options;

  // Отказ стоит на ПОЛНОТЕ ПАРЫ: пустое значение сравнялось бы с «свойства нет» и сделало бы
  // зелёным ровно тот случай, ради которого проверка заведена.
  if (marker.property.trim() === "" || marker.value.trim() === "") {
    throw new Error(
      "[web-core-skin] checkStyleOrder(): маркер — ПАРА, свойство и его значение, и " +
        `здесь пуста одна из половин (свойство «${marker.property}», значение ` +
        `«${marker.value}»). Свойство без ожидаемого значения — проверка, которая врёт ` +
        "зелёным: обычное свойство объявлено всегда, и «оно нашлось» истинно без нашего листа.",
    );
  }

  const skin = readWorn();
  const seen = readToken(marker.property);

  // Сравнение ТОЧНОЕ. Значение — обещание листа, а не примета: «похоже» здесь означало бы, что
  // мы сами придумали, насколько похоже считается приездом.
  const arrived = seen === marker.value.trim();

  const status: StyleOrderStatus = arrived ? "ok" : skin === null ? "no-skin" : "missing-base";

  // «Ни базы, ни скина» — это ГОЛЫЙ КИТ, заявленное свойство продукта (инвариант 4), а не
  // поломка. Кричать на него значило бы объявить оформление обязательным.
  const message =
    status === "missing-base"
      ? `[web-core-skin] порядок подключения нарушен: скин «${skin}» надет, ` +
        `а базового CSS нет — на корне ${marker.property} обязан быть «${marker.value}», ` +
        `а он ${seen === "" ? "не объявлен вовсе" : `равен «${seen}»`}. Производные посчитаны ` +
        "от умолчаний, и вид будет «почти правильным» — это хуже явной поломки. Порядок " +
        "импортов: базовый CSS → скин."
      : "";

  if (status === "missing-base") console.error(message);

  done();
  return { status, marker, seen, skin, message };
}

/**
 * ИСТОЧНИК СКИНОВ — то, что приложение сообщает механике о своих скинах.
 *
 * Обе стороны асинхронны по объявлению и синхронны по возможности: скины приезжают из службы,
 * из памяти редактора или из встроенного перечня, и требовать от всех троих обещание значило бы
 * усложнить простой случай ради сложного.
 *
 * Валютой выбран ТЕКСТ СТИЛЕЙ, а не адрес файла. Причина в том, откуда скин реально берётся:
 * хранилище отдаёт скин структурой (переменные и рецепты), а CSS из неё порождает генератор в
 * браузере — файла с адресом в этом пути не существует ни на одном шаге. Источник, у которого
 * файл всё-таки есть, отдаёт его текст сам и знает, как его достать, — мы за него не гадаем.
 */
export interface SkinSource {
  /**
   * Перечень имён скинов, доступных приложению.
   *
   * Нужен механике ровно для одного: запомненное имя, которого в источнике больше нет (скин
   * удалили, поставщика сменили), надевать нельзя. Всё остальное про скин — название для
   * человека, автор, содержимое — нужно интерфейсу выбора, а тот берёт это у источника сам,
   * минуя нас.
   */
  names(): readonly string[] | Promise<readonly string[]>;

  /** Текст стилей скина по имени. Имени нет — отказ, а не пустая строка: см. `wear()`. */
  css(name: string): string | Promise<string>;
}

/** Чем настраивается переключатель при заведении. */
export interface SkinSwitchOptions {
  /** Ключ хранилища, если приложению нужен свой. */
  storageKey?: string;
  /**
   * Чем жить, когда запомненного нет или оно больше не годится.
   *
   * ЯВНЫЙ ВЫБОР ПОТРЕБИТЕЛЯ, и другого источника у выбора нет. Не названо — не надевается
   * НИЧЕГО, приложение остаётся голым китом: не вспомнилось и запасного не назвали, значит
   * нечего. Заполнить это первым из перечня значило бы выдать за выбор человека порядок,
   * который принадлежит источнику и меняется без ведома их обоих.
   *
   * Половина названа отдельно от скина, потому что и выбирают их отдельно: приложение вправе
   * знать, каким скином жить, и не иметь мнения о половине.
   */
  fallback?: { skin?: string; mode?: SkinMode };
}

/** Чем настраивается одно действие. */
export interface SkinWearOptions {
  /**
   * ПОЛОВИНА, в которой надеть. Названа — ставится она; не названа — встаёт запомненный выбор
   * человека, а не запомнено ничего — не ставится ничего.
   *
   * Половина приезжает сюда, а не отдельной ручкой, потому что она часть скина, а не свойство
   * документа: отдельная ручка была бы вторым ответом на вопрос «во что одета страница».
   */
  mode?: SkinMode;
  /**
   * Запомнить ли выбор между заходами. По умолчанию да — это и есть обычный случай «человек
   * выбрал». `false` — для случая «поставили ЧУЖОЕ умолчание», которое выбором не является.
   */
  remember?: boolean;
}

/** Во что одета страница. */
export interface SkinWorn {
  /** Имя надетого скина. */
  name: string;
  /**
   * Половина, стоящая на документе.
   *
   * Читается с корня, как и имя: тёмная — класс, светлая — его отсутствие. Различить «выбрана
   * светлая» и «половину не называли» документ не может — обе выглядят одинаково, — и здесь
   * стоит то, что видит CSS, а не то, что мы про это думаем.
   */
  mode: SkinMode;
}

/** Надевает и снимает скины одного приложения. Владеет СВОИМ листом стилей. */
export interface SkinSwitch {
  /** Перечень имён из источника — как есть, без нашей сортировки и фильтрации. */
  names(): Promise<readonly string[]>;

  /**
   * Во что одета страница сейчас; `null` — голый кит.
   *
   * Ответ читается с корня документа, а не из нашей памяти: одеться могли и без нас — разметкой
   * страницы, соседним скриптом, — и правдой является то, что видит CSS.
   */
  worn(): SkinWorn | null;

  /**
   * Надевает скин по имени: берёт у источника текст, кладёт его в свой лист и ставит опознание
   * на корень. Дерево при этом не трогается вовсе — открытые панели, фокус и ввод переживают
   * смену вида.
   *
   * Половина ставится вместе со скином: названа в `options.mode` — ставится она, не названа —
   * встаёт запомненная, не запомнено ничего — не ставится ничего.
   *
   * @returns что надето ПОСЛЕ вызова
   * @throws отказ источника — как есть; на корне при этом остаётся то, что было
   */
  wear(name: string, options?: SkinWearOptions): Promise<SkinWorn | null>;

  /** Снимает скин: лист уходит, опознание и половина с корня уходят, остаётся голый кит. */
  takeOff(options?: SkinWearOptions): void;

  /**
   * Восстанавливает запомненный выбор — И СКИН, И ПОЛОВИНУ. Это шестой пункт потока: человек,
   * выбравший их в прошлый заход, обязан увидеть их же.
   *
   * Ничего не запоминает: восстановление — не выбор человека.
   *
   * @returns что надето ПОСЛЕ вызова
   */
  restore(): Promise<SkinWorn | null>;

  /**
   * Снимает СВОЙ лист стилей и забывает его. Опознание на корне НЕ трогает.
   *
   * Для перезапусков (горячая замена), где иначе копились бы листы. Опознание не трогается
   * потому, что к моменту уборки старого экземпляра новый уже мог надеть скин: сняв атрибут,
   * мы соврали бы про чужую работу.
   */
  dispose(): void;
}

/** Имя скина, годное для атрибута. Пустая строка — молча пустой `data-skin` и лист ниоткуда. */
function checkedName(name: string): string {
  if (name.trim() === "") {
    throw new Error(
      "[web-core-skin] wear(): имя скина пусто. " +
        "Снять скин — это takeOff(), а не надевание пустого имени.",
    );
  }
  return name;
}

/**
 * Заводит переключатель скинов поверх источника приложения.
 *
 * На импорте и на заведении не делается НИЧЕГО: ни обращения к источнику, ни узла в документе,
 * ни чтения хранилища. Лист заводится при первом надевании, и до него приложение неотличимо от
 * приложения без механики — это и есть «механика необязательна», выраженное кодом.
 *
 * Экземпляров может быть несколько (стенд, встроенная зона, горячая замена), и каждый владеет
 * своим листом. Общего состояния между ними нет — общим остаётся только документ, и правдой
 * является он.
 */
export function makeSkinSwitch(source: SkinSource, options: SkinSwitchOptions = {}): SkinSwitch {
  const key = options.storageKey ?? DEFAULT_STORAGE_KEY;
  const sheet = makeSkinSheet();

  /**
   * Номер последнего начатого действия.
   *
   * Источник асинхронен, а человек в редакторе щёлкает скины быстрее, чем они приезжают. Без
   * этого счётчика победил бы тот ответ, который пришёл ПОСЛЕДНИМ, а не тот, который выбрали
   * последним, — и на корне оказался бы скин, который человек уже передумал надевать.
   */
  let turn = 0;

  function worn(): SkinWorn | null {
    const name = readWorn();
    return name === null ? null : { name, mode: readDark() ? "dark" : "light" };
  }

  async function wear(name: string, wearOptions: SkinWearOptions = {}): Promise<SkinWorn | null> {
    const done = trace("wear");
    const checked = checkedName(name);
    const mine = ++turn;

    // Отказ источника не глотаем и полусостояния не оставляем: пока текста нет, на корне и в
    // листе остаётся прежнее. Приложение, позвавшее надевание явно, имеет право узнать отказ.
    const css = await source.css(checked);

    // За время ожидания надели или сняли другое — этот ответ протух. Молчаливый выход честнее
    // записи: тот, кто нас обогнал, уже поставил своё, и перебивать его нечем.
    if (mine !== turn) {
      done();
      return worn();
    }

    sheet.put(css);
    writeWorn(checked);

    // Половина: НАЗВАННАЯ сильнее запомненной — её называют сейчас, а запомненную выбрали
    // когда-то. Не названо ни там, ни там — не ставим ничего: придумать за человека выбор,
    // которого он не делал, механике нечем и незачем, а свою половину назовёт сам скин.
    const mode = wearOptions.mode ?? recall(key)?.mode;
    if (mode !== undefined) writeDark(mode === "dark");

    if (wearOptions.remember !== false) {
      // Память — предмет, а не путь: человек выбрал скин и половину, и в следующий заход обязан
      // увидеть их же. Названная половина запоминается вместе со скином, неназванная не
      // трогается — запись идёт слиянием, и прежний выбор человека остаётся прежним.
      const record: Remembered = { skin: checked };
      if (wearOptions.mode !== undefined) record.mode = wearOptions.mode;
      remember(key, record);
    }

    done();
    return worn();
  }

  function takeOff(wearOptions: SkinWearOptions = {}): void {
    const done = trace("takeOff");

    // Снятие обгоняет надевание, которое ещё едет: человек сказал «сними» последним.
    turn += 1;

    sheet.drop();
    writeWorn(null);

    // Голое состояние — целиком голое: режим уходит вместе со скином, чьей половиной он был.
    // Оставь мы класс — на голой странице стоял бы вид, которого не из чего вывести, и
    // переключатель на ней перестал бы быть бездействующим: одно нажатие всё-таки меняло бы
    // документ. Выбор человека при этом остаётся в памяти и вернётся со следующим скином.
    writeDark(false);

    if (wearOptions.remember !== false) remember(key, { skin: null });

    done();
  }

  async function restore(): Promise<SkinWorn | null> {
    const done = trace("restore");
    const remembered = recall(key)?.skin;

    // Скин сняли НАМЕРЕННО — уважаем это и умолчание приложения взамен не надеваем. Иначе снять
    // скин между заходами было бы невозможно: он воскресал бы при каждом запуске.
    if (remembered === null) {
      done();
      return worn();
    }

    const fallback = options.fallback ?? {};
    const known = remembered !== undefined && (await source.names()).includes(remembered);
    const wanted = known ? remembered : fallback.skin;

    if (wanted === undefined) {
      done();
      return worn();
    }

    // Половину `wear()` возьмёт из памяти сам; запасная нужна ровно там, где памяти нет.
    const result = await wear(wanted, { remember: false, mode: recall(key)?.mode ?? fallback.mode });
    done();
    return result;
  }

  return {
    names: async () => source.names(),
    worn,
    wear,
    takeOff,
    restore,
    dispose: sheet.drop,
  };
}
