import { splitProps } from "solid-js";

import { ADDRESS } from "./address.js";

// Цепочка зацепок при композиции `as={…}` (`kb:PROBEWEB-4`, решение architect 2026-08-17).
//
// ## Что чинится
//
// `<DialogTrigger as={Button}>` рендерит ОДИН узел, и `data-slot` на нём был один — тот, что
// пришёл снаружи. Кнопка приезжала голой, и оформлению приходилось повторять её правила в
// каждом файле, где кнопка бывает триггером.
//
// Теперь `data-slot` — СПИСОК имён через пробел, читается `[data-slot~="button"]`. Внешний
// примитив отдаёт свою зацепку внутреннему не атрибутом, а внутренним пропом; внутренний
// собирает список.
//
// ## Почему проп, а не контекст и не символ — обе развилки закрыты замером
//
// **Контекст не годится:** он доходит не только до компонента из `as`, но и до ДЕТЕЙ. У
// `<PopoverTrigger><Spinner /></PopoverTrigger>` спиннер получил бы чужую зацепку, а отличить
// «то, во что я превратился» от «то, что во мне лежит» изнутри нельзя.
//
// **Символьный ключ не годится:** до внутреннего компонента он не доезжает — цепочка
// `splitProps`/`mergeProps` в Solid и `Polymorphic` в kobalte переносят только строковые ключи
// (замерено 2026-08-17).
//
// **Строковый проп течёт в DOM**, если `as` — имя тега: kobalte спредит неизвестные пропы
// атрибутами, и в разметке появляется `__slot="…"`. Утёкший внутренний проп становится частью
// наблюдаемой поверхности, а её потом не убрать.
//
// Поэтому проп передаётся ТОЛЬКО тем компонентам, которые умеют его снять, и узнаются они по
// метке `slotAware`. Всем остальным — тегам, чужим компонентам — не передаётся ничего.
//
// ## Адрес ведёт себя ИНАЧЕ, чем зацепка, и это не непоследовательность
//
// Решение по композиции (`PWEB-14`, `PWEB-25`, страница «Паспорт компонента»): **адрес несёт
// внутренний компонент — тот, чем вещь является визуально; внешний отдаёт поведение и
// состояние.** Значит на одном условии — «мой `as` умеет снять внутренний проп» — здесь висят
// два РАЗНЫХ следствия:
//
//   • `data-slot` внешнего едет ВНИЗ и попадает в список: имена слотов — действующее
//     обязательство зоны, и терять их нельзя (`kb:PROBEWEB-12`, п.7);
//   • адрес внешнего НЕ едет никуда и на узле не появляется: списка имён в адресе не будет ни
//     через разделитель, ни вторым атрибутом. Именно от списка мы и уходим.
//
// И третье, дописанное решением `PWEB-46`: **адрес ставится ПОСЛЕДНИМ и не перебивается ничем**,
// а пришедший снаружи — отбрасывается. Механизм отступления выше держался на признаке «звено
// наше»; с чужим внешним звеном он не работал вовсе — Ark спредит свои пропы на вставленный
// компонент, и адрес гармошки оказывался там, где по решению должен быть адрес кнопки. Порядок
// спреда закрывает это без всякого узнавания: кто рисует узел, тот и ставит адрес, последним.
//
// Список у нас уже был, и он не работал: оформление разрешало «кнопка + триггер» четыре раза
// независимо и каждый раз одинаково — вид брал внутренний, вид внешнего писался исключающим
// себя вручную. Решение закрепляет то, к чему приходили сами.
//
// Состояния при этом не теряются НИЧЕМ: они выражены отдельными атрибутами (`data-expanded`,
// `data-pressed`), а не адресом, и слияние пропов их не вытесняет — проверено на живой
// композиции, а не предположено (`test/composition.test.tsx`).

/** Метка «этот компонент снимает внутренний проп и собирает список зацепок». */
const SLOT_AWARE = Symbol.for("probe-web-ui.slot-aware");

/** Внутренний проп цепочки. Наружу не документируется и в DOM не попадает. */
export interface SlotChainProps {
  /** Зацепки внешнего примитива, отданные вниз по композиции `as={…}`. */
  __slot?: string;
}

/**
 * Помечает примитив как участника цепочки.
 *
 * Метка живёт на самой функции-компоненте, а не в пропах: пропы уходят в DOM, метка — нет.
 */
export function slotAware<C>(component: C): C {
  (component as { [SLOT_AWARE]?: boolean })[SLOT_AWARE] = true;

  return component;
}

/** Умеет ли этот `as` снять внутренний проп. Тег и чужой компонент — не умеют. */
function isSlotAware(as: unknown): boolean {
  return typeof as === "function" && (as as { [SLOT_AWARE]?: boolean })[SLOT_AWARE] === true;
}

/**
 * Готовит зацепки примитива и отделяет внутренний проп от того, что уедет дальше.
 *
 * Возвращает пару: пропы зацепки (ставятся ДО спреда потребителя — значит явный `data-slot`
 * потребителя по-прежнему перебивает всё) и остальные пропы БЕЗ внутреннего.
 *
 * @param props пропы примитива
 * @param own собственное имя зацепки
 */
export function useSlot<P extends SlotChainProps & { as?: unknown }>(props: P, own: string) {
  const [, rest] = splitProps(props, ["__slot"]);

  const chain = () => (props.__slot ? `${own} ${props.__slot}` : own);

  // Список собирает КОНЕЧНОЕ звено — то, которое рендерит узел. Промежуточное отдаёт свои
  // зацепки вниз и своего `data-slot` не ставит: иначе он спредом перебил бы список, который
  // соберёт внутренний примитив, и всё вернулось бы к одному имени.
  const slot = {
    get "data-slot"() {
      return isSlotAware(props.as) ? undefined : chain();
    },
    get __slot() {
      // Вниз отдаём только тем, кто снимет: иначе проп доедет до DOM атрибутом.
      return isSlotAware(props.as) ? chain() : undefined;
    },
  };

  return [slot, rest] as const;
}

/**
 * Снимает с пропов ЧУЖОЙ адрес — ровно пару адресных атрибутов, и больше ничего.
 *
 * Пришедший снаружи адрес отбрасывается, от кого бы ни пришёл: от потребителя, написавшего его
 * руками, или от чужого внешнего звена, которое спредит свои пропы на вставленный компонент.
 * Отличить одно от другого изнутри нельзя — выглядит одинаково, — и различать не нужно: адрес
 * узла ставит тот, кто узел рисует.
 *
 * Всё прочее проходит нетронутым. Состояния внешнего звена выражены ДРУГИМИ атрибутами
 * (`data-state`, `data-focus`, `aria-expanded`), и терять их было бы потерей поведения.
 *
 * @param props пропы примитива
 */
export function dropAddress<P extends object>(props: P): P {
  const [, rest] = splitProps(props as P & Record<(typeof ADDRESS)[number], unknown>, [...ADDRESS]);

  return rest as P;
}

/**
 * Готовит АДРЕСНЫЕ атрибуты примитива и снимает с пропов чужой адрес.
 *
 * Возвращает пару: сам адрес и остальные пропы БЕЗ адреса. Спред обязан идти в этом порядке —
 * `{...rest} {...address}`, — потому что **адрес ставится последним и не перебивается ничем**
 * (`PWEB-46`, страница «Паспорт компонента»).
 *
 * Прежде адрес стоял ДО спреда, чтобы потребитель мог его перебить. Для имён-зацепок это верно —
 * они подсказка оформлению; для адреса анатомии нет: это личность узла, то, что паспорт обещал и
 * во что целится порождённый селектор скина. Дав переписать её, мы дали бы узлу соврать о том,
 * чем он является.
 *
 * Своего адреса не ставит только то звено, которое узел НЕ рисует: стал примитив внешним в
 * композиции с нашим же примитивом (`as` — наш) — адрес принадлежит внутреннему. Пустой результат
 * здесь не потеря: у составленного внешнего вида нет, он им и не был.
 *
 * Значения отдаются геттерами, как и зацепка: `as` — обычный реактивный проп, и посчитать
 * условие один раз значило бы застыть на первом рендере.
 *
 * @param props пропы примитива
 * @param attrs адресные атрибуты его части — из анатомии, не написанные рядом
 */
export function useAddress<P extends object & { as?: unknown }>(
  props: P,
  attrs: Readonly<Record<string, string>>,
) {
  const address: Record<string, string | undefined> = {};

  for (const name of Object.keys(attrs)) {
    Object.defineProperty(address, name, {
      enumerable: true,
      get: () => (isSlotAware(props.as) ? undefined : attrs[name]),
    });
  }

  return [address as Readonly<Record<string, string | undefined>>, dropAddress(props)] as const;
}
