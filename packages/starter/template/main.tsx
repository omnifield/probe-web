// Точка входа скелета. Замерзает не файл, а ПОВЕРХНОСТЬ, которую он трогает (kb:PROBEWEB-4):
// mount() рантайма, один примитив из ui и CSS стилевого слоя. Больше отсюда не зовут ничего —
// каждая лишняя строка застынет у потребителя навсегда, а обвес сюда уже не заглянет.
//
// CSS двумя подпутями, и это не дубль: базовый слой не держит ни одного литерального цвета
// (его инвариант) — он даёт сброс и производные шкалы, а значения приходят темой. Один
// base.css дал бы страницу без цветов: браузер молча отбросил бы неразрешённые var().
// Меняешь тему на свою — вторая строка твоя, правь.
import "@omnifield/probe-web-style/base.css";
import "@omnifield/probe-web-style/themes.css";

import { mount } from "@omnifield/probe-web-runtime";
import { Button } from "@omnifield/probe-web-ui";

// Кит безголовый: класса по умолчанию у кнопки нет, внешний вид целиком твой. Эту кнопку
// одевает блок <style> в index.html — через зацепку data-slot и токены темы; там же сказано,
// как перенести оформление в свой файл.
//
// Второй путь — createStyle стилевого слоя, для класса, зависящего от состояния. В скелете
// он не показан намеренно: вызов заморозил бы у тебя ещё одну точку поверхности ради примера.
function App() {
  return <Button>hello, web</Button>;
}

mount(() => <App />);
