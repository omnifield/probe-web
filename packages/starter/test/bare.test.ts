// ГОЛОЕ ПРИЛОЖЕНИЕ — РАБОЧЕЕ СОСТОЯНИЕ, А НЕ ПУСТОЕ МЕСТО.
//
// Вид приходит скином и больше ниоткуда. Скин — единица: переменные и правила вида вместе, и
// половины у него не бывает. Поэтому поставка не везёт ни надеваемого набора цветов по
// умолчанию, ни режима: цвета у того, чего не сшили, быть не может.
//
// Прежде этот файл сторожил обратное — «названное место», в котором скелет объявлял пресет и
// режим сам. Договорённости, которую он стерёг, больше нет, и пробы переписаны под ту, что
// есть. Пробы здесь сторожат три вещи, каждая из которых ломается молча:
//
//   • СКЕЛЕТ НЕ ОДЕВАЕТ. Ни имени скина, ни режима он на корень не ставит: имя скина у
//     потребителя своё, а режим — половина скина, и на голой странице его некуда ставить.
//     Отсюда же и отсутствие восстановления режима до первого кадра: вспышке взяться неоткуда,
//     потому что вида нет вовсе;
//   • ЛИТЕРАЛЫ ЧУЖИХ ЗОН — имя токена-маркера, опознание скина на корне и ключ хранилища
//     принадлежат соседям, а этот файл кладётся потребителю классом `placed-once` и не
//     обновляется НИКОГДА: литерал здесь переживёт переименование и разъедется молча;
//   • НЕОБЯЗАТЕЛЬНОСТЬ ОФОРМЛЕНИЯ — приложение без единого файла скина обязано запускаться.
//
// ПОЧЕМУ ЛИТЕРАЛЫ МОЖНО ДЕРЖАТЬ ЗДЕСЬ, А В ШАБЛОНЕ НЕЛЬЗЯ. Проба живёт в нашем репозитории и
// едет нашими выпусками: разъедется — покраснеет у нас, до публикации. Шаблон живёт у
// потребителя и не едет никуда.

import { describe, expect, it } from "vitest";

import { readTemplate } from "./source.js";

const STYLE = "@omnifield/probe-web-style";
const RUNTIME = "@omnifield/probe-web-runtime";

/** Точка входа без строчных комментариев: судим КОД, а не пояснение над ним. */
const main = readTemplate("main.tsx").replace(/^\s*\/\/.*$/gm, "");

/** Разметка без комментариев — по той же причине. */
const html = readTemplate("index.html").replace(/<!--[\s\S]*?-->/g, "");

/** Позиция подстроки в коде точки входа; -1 значит «нет вовсе». */
const at = (needle: string): number => main.indexOf(needle);

/**
 * Механика скина из рантайма: скелет не зовёт из неё НИЧЕГО.
 *
 * Она не выброшена и не сломана — её зовёт тот, у кого скин есть. Скелет к таким не относится:
 * поставка скина не везёт, и звать ему нечем.
 */
const DRESSING = ["restoreSkin", "applySkin", "makeSkinSwitch", "readSkin"];

/**
 * Имена, принадлежащие ЧУЖИМ зонам, у которых есть экспорт или хозяин. Каждое сопровождается
 * тем, чем его обязан звать скелет: проба не просто запрещает строку, а называет замену.
 */
const FOREIGN_LITERALS: readonly (readonly [string, string])[] = [
  // Имя токена-маркера базы принадлежит стилевому слою.
  ["--control-target-min", `BASE_MARKER из ${STYLE}`],
  // Опознание скина и пресета на корне — контракт корня, его держит рантайм у себя.
  ["data-skin", `механика скина из ${RUNTIME}`],
  ["data-theme", `механика скина из ${RUNTIME}`],
  // Ключ хранилища выбора — внутреннее рантайма, потребителю его знать не нужно.
  ["probe-web:skin", `умолчание механики скина из ${RUNTIME}`],
];

describe("скелет не одевает приложение", () => {
  for (const name of DRESSING) {
    it(`не зовёт ${name}()`, () => {
      // Звать было бы нечем и не за чем: имени скина у поставки нет, а подставить своё
      // умолчание значит одеть приложение от лица фреймворка.
      expect(main, "main.tsx").not.toContain(`${name}(`);
    });
  }

  it("не восстанавливает режим до первого кадра", () => {
    // Восстановление стояло против вспышки светлой темы перед тёмной. Ставить теперь нечего:
    // режим — половина скина, и на голой странице второй половины нет. Класс тёмной пары
    // скелет не трогает вовсе — ни кодом, ни разметкой.
    expect(main, "main.tsx").not.toMatch(/classList|"dark"|'dark'/);
    expect(html, "index.html").not.toMatch(/class="[^"]*\bdark\b/);
  });

  it("не оставляет корню документа опознания", () => {
    // Голая страница — это ОТСУТСТВИЕ атрибутов на корне, а не пустые значения в них. Соблазн
    // вписать опознание прямо в разметку понятен (так оно встало бы до первого кадра
    // гарантированно) и стоит литерала чужого имени, замороженного у потребителя навсегда.
    const open = /<html\b([^>]*)>/.exec(html)?.[1] ?? "";
    const attributes = [...open.matchAll(/([a-z-]+)=/g)].map((match) => match[1]);
    expect(attributes).toEqual(["lang"]);
  });
});

describe("ни одного литерала чужой зоны в скелете", () => {
  for (const [literal, instead] of FOREIGN_LITERALS) {
    it(`не держит «${literal}» — вместо него ${instead}`, () => {
      // Файл `placed-once`: обвес в него больше не заглянет, и переименование у соседа
      // чинится у уже созданных продуктов только правкой руками.
      expect(main, "main.tsx").not.toContain(literal);
      expect(html, "index.html").not.toContain(literal);
    });
  }
});

describe("порядок подключения — не декоративный", () => {
  it("базовый слой идёт первым импортом-побочкой", () => {
    // Скин, приехавший раньше базы, проигрывает ей в каскаде: получится вид, посчитанный от
    // умолчаний. Слот для скина в шаблоне стоит ПОСЛЕ базы именно поэтому.
    expect(at(`import "${STYLE}/base.css";`)).toBeGreaterThanOrEqual(0);
    expect(at(`import "${STYLE}/base.css";`)).toBeLessThan(at("mount("));
  });

  it("проверка порядка стоит ПОСЛЕ монтирования", () => {
    // Ей нужны вычисленные стили: она спрашивает значение токена на корне, и рано звать её
    // бессмысленно.
    expect(at("checkStyleOrder({")).toBeGreaterThan(at("mount("));
  });
});

describe("оформление остаётся необязательным", () => {
  it("не подключает ни одного файла оформления", () => {
    // Приложение без единого файла скина обязано запускаться и быть пригодным к работе. Слот
    // для скина в шаблоне ЗАКРЫТ комментарием — открывает его потребитель, когда скин у него
    // появится.
    for (const specifier of [...main.matchAll(/import\s+"([^"]+)";/g)].map((m) => m[1])) {
      expect(specifier, specifier).toMatch(new RegExp(`^${STYLE}/`));
    }
  });

  it("называет слот словами, чтобы его было где открыть", () => {
    // Без названного слота потребитель откроет импорт там, где придётся, — и порядок, ради
    // которого всё это писано, сломается на первом же скине.
    expect(readTemplate("main.tsx")).toMatch(/^\s*\/\/\s*import\s+"<[^>]+>\/skin\.css";/m);
  });
});
