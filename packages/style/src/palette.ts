// КАК ПАЛИТРА ЦЕПЛЯЕТСЯ К ДОКУМЕНТУ — единственное место в зоне, где это записано.
// Решение — `kb:PROBEWEB-18`.
//
// ПАЛИТРА ПРИНИМАЕТ ИМЯ, А НЕ СЕЛЕКТОР. Пока селектор был свободной строкой, каждый
// вызывающий решал сам, чем палитра цепляется к документу: `registerTheme()` и
// `themeModelToCss()` собирали `[data-theme="…"]` независимо и совпали по случайности, а
// сборка `themes.css` красила `:root` — и дефолт оказался не палитрой, а привилегией.
// Отсюда следовало главное: снять все пресеты и получить голый кит было нельзя в принципе,
// потому что корень покрашен независимо от того, выбрал ли кто-нибудь пресет.
//
// Поэтому вывод селектора здесь ОДИН, и другого способа объявить палитру в зоне нет: оба
// места зовут `paletteCss()`, а собранных руками строк `[data-theme="…"]` в `src/` не
// остаётся ни одной. Держит это проба `test/palette.test.ts`, а не соглашение: свободный
// селектор, доступный мимо этой функции, вернул бы ровно ту же развилку.

import type { ScaleMode } from "./scale.js";
import { type ThemeTokens, themeToCss } from "./tokens.js";

/**
 * Имя дефолтной палитры.
 *
 * Дефолт — ОБЫЧНАЯ палитра, а не особый случай: `themes.css` объявляет её тем же
 * генератором, что и любой пресет, и приезжает она тем же способом — `data-theme="default"`
 * на `<html>`. Zero-config этим снимается сознательно (`kb:PROBEWEB-18`): документ без
 * атрибута остаётся нецветным не потому, что мы это где-то проверяем, а потому что красить
 * нечему — ни одно правило палитры не подошло. Геометрия при этом работает: её дефолты
 * подставлены прямо в `var(--семя, …)` базового слоя.
 */
export const DEFAULT_PALETTE = "default";

/**
 * Атрибут-носитель имени палитры. Объявлен здесь, а не строкой у каждого, кому он нужен:
 * знание «чем палитра цепляется к документу» одно, и селектор с постановкой атрибута
 * обязаны разъезжаться вместе или не разъезжаться вовсе.
 */
export const PALETTE_ATTRIBUTE = "data-theme";

/**
 * Селектор палитры по её имени — ЕДИНСТВЕННЫЙ вывод селектора в зоне.
 *
 * Тёмная половина — та же палитра ПЛЮС класс режима, в обеих формах носителя: класс может
 * стоять на самом элементе с атрибутом (обычно `<html>`) и на потомке внутри него. Режим
 * при этом остаётся ортогонален палитре (`kb:SKIN-7`, инвариант 3): класс не выбирает
 * палитру, палитра не включает режим — иначе `twitter-dark` снова стал бы отдельной темой.
 *
 * @param name имя палитры; уезжает в атрибут `data-theme` и обычно в имя файла
 * @param mode половина пары, для которой нужен селектор
 */
export function paletteSelector(name: string, mode: ScaleMode): string {
  const attribute = `[${PALETTE_ATTRIBUTE}="${name}"]`;
  return mode === "dark" ? `${attribute}.dark, ${attribute} .dark` : attribute;
}

/**
 * Половина палитры как CSS-блок: селектор из имени плюс значения по строке на токен.
 *
 * Единственная дорога объявить палитру внутри зоны. Форматирование блока живёт в
 * `themeToCss()` (`src/tokens.ts`) и на поверхность не выходит: наружу торчал бы свободный
 * селектор, и правило «палитра принимает имя» держалось бы обещанием, а не машиной.
 *
 * @param name имя палитры
 * @param mode половина пары
 * @param tokens значения этой половины
 */
export function paletteCss(name: string, mode: ScaleMode, tokens: ThemeTokens): string {
  return themeToCss(paletteSelector(name, mode), tokens);
}
