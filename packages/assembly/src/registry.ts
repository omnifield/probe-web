// РЕЕСТР — то, из чего собирают дерево: чем узел рисуется и что о нём объявлено.
//
// ## Реестр приезжает снаружи, а не пишется здесь
//
// Механика не держит собственного перечня компонентов и не заводит своих правил вложенности.
// Правила приезжают ПАСПОРТАМИ — тем, что компоненты объявили о себе сами; карта компонентов
// приезжает от поставщика кита. Механика их только складывает и читает.
//
// Отсюда две половины реестра, и они разные по природе:
//
//   • `components` — ИСПОЛНЕНИЕ: чем узел рисуется. Обычные функции-компоненты Solid;
//   • `passports`  — ПРАВИЛА: что у компонента за части и что в них допустимо.
//
// Половины намеренно не слиты в одну карту. Читатель правил (проверка дерева, хранилище,
// сервер) не должен тянуть за собой Solid и весь кит ради перечня частей; читателю
// исполнения (отрисовка) паспорта не нужны вовсе.
//
// ## Адрес компонента и адрес его корневой части — одно место
//
// `button` и `button.root` указывают на один и тот же узел дерева: узел компонента И ЕСТЬ его
// корневая часть. Разведи мы их — редактор скинов получил бы два разных способа записать одно,
// и сохранённые деревья разъехались бы по способу записи.

import type {
  Admission,
  AdmissionRule,
  ReadablePart,
  ReadablePassport,
} from "./passport-read.js";
import { resolveAddress, type ComponentMap } from "./resolve.js";

/**
 * Реестр: чем рисовать, что объявлено и по какому правилу это читается.
 *
 * Паспорта индексируются АДРЕСОМ компонента в карте компонентов, а не именем из самого
 * паспорта. Имя (`data-scope`) у кнопки — `button`, а лежать в карте она может по адресу
 * `ui.button`: пространство имён — дело того, кто карту собирает. Индекс по адресу снимает
 * догадку «где же она лежит»; совпадение имени с адресом — частный случай, а не правило.
 *
 * Третья половина — правило допуска — приезжает оттуда же, откуда паспорта, и по той же
 * причине: оно принадлежит форме паспорта, а не читателю (см. `passport-read.ts`).
 */
export interface Registry {
  /** Чем узел рисуется. Рекурсивная карта, адрес через точку. */
  readonly components: ComponentMap;
  /** Что о компоненте объявлено — по его адресу в `components`. */
  readonly passports: Readonly<Record<string, ReadablePassport>>;
  /**
   * Пускает ли часть внутрь себя кандидата. Метод, а не поле-функция, — причина в
   * `passport-read.ts`, `AdmissionRule`.
   */
  admits(part: ReadablePart, candidate: Admission): boolean;
}

/**
 * Разобранный адрес узла: какой компонент и какая его часть.
 *
 * `part` здесь всегда назван, даже когда в адресе его не было: узел компонента — это его
 * корневая часть, и дальше по коду частный случай «адрес без части» больше не всплывает.
 */
export interface Address {
  /** Адрес компонента в карте — то, чем он проиндексирован в `passports`. */
  readonly component: string;
  /** Паспорт этого компонента. */
  readonly passport: ReadablePassport;
  /** Имя части. Для адреса компонента целиком — его корневая часть. */
  readonly part: string;
  /** Полный адрес части в карте компонентов: `<component>.<part>` либо сам `component`. */
  readonly address: string;
}

/** Из чего собирается реестр. Все три части приходят снаружи — механика не сочиняет ни одной. */
export interface RegistrySpec extends AdmissionRule {
  /** Карта компонентов: адрес через точку → компонент. */
  readonly components: ComponentMap;
  /** Паспорта по адресу компонента в этой карте. */
  readonly passports: Readonly<Record<string, ReadablePassport>>;
}

/**
 * Собирает реестр из карты компонентов, паспортов и правила допуска.
 *
 * Функция намеренно тонкая: она ничего не выводит и ничем не дополняет входы. Появись здесь
 * хоть одно «а если паспорта нет, возьмём…» — механика начала бы сочинять правила вместо тех,
 * что объявлены, и первым же следствием стал бы редактор, разрешающий вложить недопустимое.
 *
 * Правило допуска — обязательный вход, а не умолчание. Умолчание здесь и было бы тем самым
 * вторым экземпляром правила: он выглядел бы разумно ровно до первого нового рода.
 *
 * @param spec карта компонентов, паспорта и правило допуска
 */
export function createRegistry(spec: RegistrySpec): Registry {
  return {
    components: spec.components,
    passports: spec.passports,
    admits: (part, candidate) => spec.admits(part, candidate),
  };
}

/**
 * Разбирает адрес узла в пару «компонент и часть», либо `undefined` — если такого компонента
 * реестр не знает.
 *
 * Разбор идёт СПРАВА: сначала пробуем весь адрес как компонент, потом отрезаем последний
 * сегмент и пробуем остаток. Именно в таком порядке, потому что пространство имён произвольной
 * глубины (`ui.forms.button`) неотличимо от части по одному лишь виду адреса — отличить их
 * может только паспорт.
 *
 * Части у анатомии плоские (`itemTrigger`, а не `item.trigger`), поэтому отрезается ровно один
 * сегмент. Адрес с двумя неизвестными хвостами — не «часть части», а неизвестный адрес.
 *
 * @param registry реестр
 * @param address адрес узла: `button`, `ui.button`, `accordion.itemTrigger`
 */
export function readAddress(registry: Registry, address: string): Address | undefined {
  if (!address) return undefined;

  const whole = registry.passports[address];
  if (whole) {
    return { component: address, passport: whole, part: whole.root, address };
  }

  const cut = address.lastIndexOf(".");
  if (cut <= 0) return undefined;

  const component = address.slice(0, cut);
  const part = address.slice(cut + 1);
  const passport = registry.passports[component];
  if (!passport) return undefined;

  // Часть, которой нет в анатомии, — не адрес, а опечатка. Молчаливое «ну пусть будет» здесь
  // означало бы узел, который отрисовка не найдёт, а проверка вложенности сочтёт законным.
  if (!passport.anatomy.keys().includes(part)) return undefined;

  // Корневая часть, названная явно, — тот же узел, что компонент целиком. Приводим к одному
  // виду сразу, чтобы дальше по коду двух записей одного места не существовало.
  if (part === passport.root) {
    return { component, passport, part, address: component };
  }

  return { component, passport, part, address };
}

/**
 * Компонент по адресу узла, либо `undefined`.
 *
 * Проверка «функция ли это» — не придирка типов: по адресу может лежать ветка карты
 * (`accordion` как пространство имён), и отрисовать её нечем. Такой узел получает явный
 * запасной вид, как и узел с несуществующим адресом, — исход один, и путь к нему один.
 *
 * @param registry реестр
 * @param address адрес узла
 */
export function resolveComponent(registry: Registry, address: string): unknown {
  const found = resolveAddress(registry.components, address);
  return typeof found === "function" ? found : undefined;
}

/**
 * Адреса компонентов, которые реестр знает.
 *
 * Перечень для того, кто предлагает выбор, — редактора. Что он с ним сделает и как покажет,
 * механику не касается: она отвечает на «откуда берётся перечень допустимого», а не на «что
 * из него выбрать».
 *
 * @param registry реестр
 */
export function knownComponents(registry: Registry): string[] {
  return Object.keys(registry.passports).sort();
}
