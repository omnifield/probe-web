// РАЗВОРАЧИВАНИЕ вложенного CSS в плоский — подпуть `./flat`.
//
// ## Почему это отдельный подпуть, а не опция генератора
//
// За разворачиванием стоит postcss со спутниками, и он попадает в сборку потребителя от одного
// только ИМПОРТА — независимо от того, зовут его или нет. Опция `{ form: "flat" }` на общей
// функции оставила бы его в цепочке у всех, то есть не решила бы ничего: замерено, что витрина с
// ним весит 257,06 КБ, и порождает она CSS на каждое движение ручки.
//
// Отдельный вход решает это по построению, а не обещанием: кто не звал `./flat`, у того postcss
// в сборке взяться неоткуда. Проверяется пробой поверхности по СОБРАННОМУ файлу.
//
// ## Зачем плоская форма нужна вообще
//
// Вложенность CSS — Baseline Widely Available с 11 июня 2026, охват 94,1 %. Девяносто четыре
// процента это не сто: остаётся старый клиент. Плюс файл, уезжающий на диск, и сверка снимком,
// где плоский текст читается человеком построчно.
//
// Поэтому плоскую форму не выбрасываем — переносим туда, где она правда нужна.
//
// ## Обе формы описывают один вид
//
// Здесь нет ни одной строки, знающей про скин, координаты или паспорта: на входе текст, на
// выходе текст. Второго генератора не заведено — сборка рецепта одна, печать одна, а это
// преобразование стоит ПОСЛЕ них обеих. Совпадение форм проверяется сравнением после
// разворачивания, а не тем, что так задумано.

import postcss from "postcss";
import nested from "postcss-nested";

import { prettify } from "./format.js";
import { trace } from "./trace.js";

/** Конвейер разворота. Заводится один раз: пересоздавать его на каждый вызов незачем. */
const pipeline = postcss([nested()]);

/**
 * Разворачивает вложенный CSS в плоский.
 *
 * ```ts
 * import { generateSkinCss } from "@omnifield/probe-web-skin";
 * import { flattenCss } from "@omnifield/probe-web-skin/flat";
 *
 * writeFileSync("ночь.css", flattenCss(generateSkinCss(skin, passportOf)));
 * ```
 *
 * Принимает любой CSS, а не только наш: предмет здесь — форма записи, а не её происхождение.
 *
 * @param css текст со вложенностью
 * @returns тот же CSS плоской формой, с расставленными отступами
 */
export function flattenCss(css: string): string {
  const done = trace("flattenCss");

  // `root` у синхронного конвейера доступен сразу; отступы правим по дереву, а не по строке —
  // регулярное выражение по CSS ошибается на первом же значении со скобками.
  const root = pipeline.process(css, { from: undefined }).root;
  prettify(root);

  done();
  return root.toString();
}
