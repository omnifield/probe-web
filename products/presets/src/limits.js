// Ограничители. В ПЕРВОЙ версии, а не «потом»: стенд публичный и без авторизации — писать и
// удалять может любой, кто знает адрес (`kb:PROBEWEB-8`). Без предела хранилище забивают за
// вечер, и чинить это приходится ровно тогда, когда стенд кому-то показывают.
//
// Числа названы здесь вместе с тем, ОТКУДА они взяты, чтобы следующий не менял их гаданием.

/**
 * @typedef {object} Limits
 * @property {number} bodyBytes предел размера одной записи: тело запроса целиком, в байтах
 * @property {number} records предел числа записей в хранилище
 * @property {number} labelChars предел длины имени, в символах
 * @property {number} descriptionChars предел длины пояснения, в символах
 */

/** @type {Readonly<Limits>} */
export const LIMITS = Object.freeze({
  // 64 КиБ на запись. Отсчитано от живого материала: шесть готовых отборов стенда `tables`
  // занимают вместе ~13 КБ исходного текста — с подписями, пояснениями и отступами. Один
  // пресет это единицы килобайт, и запас здесь тридцатикратный. Меряем ТЕЛО ЗАПРОСА целиком,
  // а не только состояние: считать надо то, что реально прилетает в сокет, иначе предел
  // обходится длинным именем.
  bodyBytes: 64 * 1024,

  // 200 записей. Список пресетов выбирают ГЛАЗАМИ по имени — на второй сотне он перестаёт
  // быть списком независимо от того, сколько там места. Верхняя оценка хранилища при этом
  // 200 × 64 КиБ ≈ 12,5 МиБ: величина, про которую можно не думать.
  records: 200,

  // Имя и пояснение — показываются в списке. Предел здесь не про место, а про то, чтобы одна
  // запись не растянула список на экран; заодно закрывает вставку простыни в поле имени.
  labelChars: 120,
  descriptionChars: 1000,
});

/**
 * Ограничители КАНАЛА К АГЕНТУ (`kb:PROBEWEB-9`).
 *
 * Здесь они стерегут не место на диске, а деньги: каждый вызов оплачен, а адрес публичный.
 *
 * @typedef {object} AgentLimits
 * @property {number} textChars предел длины описания отбора
 * @property {number} fieldsCount предел числа полей в словаре
 * @property {number} perWindow сколько обращений с одного адреса за окно
 * @property {number} windowMs длина окна, мс
 * @property {number} perDay общий дневной предел обращений ко всей службе
 * @property {number} timeoutMs сколько ждём модель
 */

/** @type {Readonly<AgentLimits>} */
export const AGENT_LIMITS = Object.freeze({
  // 500 символов. Описание отбора — фраза, а не документ: «сделки свыше миллиона за квартал,
  // кроме Москвы» это 60 символов. Восьмикратный запас, и при этом длинная простыня не уедет
  // в оплачиваемый запрос.
  textChars: 500,

  // 100 полей. Столько имён ещё имеет смысл передавать модели: на большем словаре она начнёт
  // путать похожие поля, и отбор станет хуже, а не богаче. Заодно предел на объём запроса.
  fieldsCount: 100,

  // Пять обращений в минуту с адреса. Человек, который собирает отбор, за минуту формулирует
  // одну-две фразы; пять — это уже перебор вариантов, и он тоже допустим. Всё, что чаще, —
  // не человек.
  perWindow: 5,
  windowMs: 60_000,

  // 200 обращений в сутки на ВСЮ службу. Это про худший случай, а не про наш расход: при
  // ~1000 токенов на обращение и цене Haiku ($1 за миллион входящих) сутки под завязку стоят
  // центы. Смысл предела в том, что счёт за найденный ботом адрес ИЗВЕСТЕН ЗАРАНЕЕ.
  perDay: 200,

  // 20 секунд. Дольше человек у экрана всё равно не ждёт — он решит, что сломалось.
  timeoutMs: 20_000,
});
