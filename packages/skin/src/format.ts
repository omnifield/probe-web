// ОТСТУПЫ порождённого текста.
//
// ## Зачем это здесь, а не у разворачивателя
//
// Разворот вложенного делает `postcss-nested` — то самое средство, которым разворачивание и
// делается и на котором стоит сам Panda. Отступы он не расставляет: узел, переехавший наверх,
// уносит с собой отступ с прежнего места, и текст выходит рваным без единой пустой строки между
// правилами. Человек этот файл читает — в инструментах разработчика и глазами, когда проверяет,
// что именно на нём надето.
//
// ## Что здесь заменено и что при этом сверено
//
// До 2026-08-20 разворот и отступы делал `expandNestedCss` из `@pandacss/core`. Уход с того
// пакета — решение про ВЕС (9,0 МБ и 33 пакета против 1,1 МБ и 8), и внутри у него лежало ровно
// `postcss([nested(), prettify()])`: то же средство разворота плюс полтора десятка строк
// отступов. Заменены именно эти полтора десятка строк.
//
// **CSS от замены не изменился, и это сверено машиной:** те же 23 правила, те же селекторы, тот
// же порядок, совпадение текста при нормализации пробелов и завершающих точек с запятой.
// Изменились ОТСТУПЫ — и в сторону исправности:
//
//   • у Panda проход отступов зарегистрирован в ОДНОМ конвейере с разворотом и успевает
//     отработать ДО того, как вложенные блоки вынесены наверх. Вынесенный блок уносил отступ с
//     прежнего места, и `@media` выходил съехавшим. Наш проход идёт после разворота;
//   • закрывающая скобка и завершающая точка с запятой у Panda не правились вовсе, отчего блок
//     открывался на одном уровне, а закрывался на другом. Полуисправленные отступы хуже, чем
//     никакие: их читают как ошибку порождения.
//
// Дальше форма закреплена СНИМКОМ (`test/__snapshots__/*.css`): следующая правка вывода придёт к
// человеку диффом на ревью, а не тишиной.

import type { Container, Node } from "postcss";

/** Есть ли у узла дети, по которым можно пройти. */
function walkable(node: Node): node is Container {
  return typeof (node as Container).each === "function";
}

/**
 * Расставляет отступы по дереву: уровень вложенности плюс пустая строка между соседями.
 *
 * Пустая строка ставится только между детьми НЕ-правила — то есть между правилами и блоками, но
 * не между объявлениями внутри правила: разреженный список свойств читать труднее, чем плотный.
 *
 * Уже написанный отступ уважается ровно в одном случае: если в нём есть что-то, кроме пробелов.
 * Пустой, пробельный и многострочный — переписываются.
 *
 * @param node узел-хозяин
 * @param depth уровень вложенности хозяина
 */
function indent(node: Container, depth: number): void {
  node.each((child, index) => {
    const before = child.raws.before;

    if (!before || !before.trim() || before.includes("\n")) {
      const blank = node.type !== "rule" && index > 0 ? "\n" : "";
      child.raws.before = `\n${blank}${"  ".repeat(depth)}`;
    }

    if (!walkable(child)) return;

    indent(child, depth + 1);
    // Закрывающая скобка — тот же уровень, что и открывающая. Правится отдельным полем: у
    // postcss отступ перед `}` это не «отступ последнего ребёнка», а собственный отступ хозяина,
    // и не тронь мы его — блок открывался бы на одном уровне, а закрывался на другом.
    child.raws.after = `\n${"  ".repeat(depth)}`;
    // Последнее объявление в блоке — тоже с точкой с запятой. У вынесенных наверх блоков её не
    // остаётся, и файл выходит разнобойным: часть блоков с ней, часть без.
    child.raws.semicolon = true;
  });
}

/**
 * Приводит отступы всего дерева к порождаемой форме.
 *
 * @param root корень разобранного текста
 */
export function prettify(root: Container): void {
  indent(root, 0);

  // У самого первого узла отступа быть не должно: файл не начинается с пустой строки.
  if (root.first) root.first.raws.before = "";

  // Файл кончается переводом строки, и ровно одним.
  root.raws.after = "\n";
}
