// ТРАССА механики скина — замеры, которые включает потребитель, а не сборка.
//
// Форма взята у зон `runtime` и `assembly` и по той же причине: автоопределение по режиму
// сборщика (`import.meta.env.DEV`) здесь мертво — механика приезжает потребителю зависимостью,
// а подстановку в файлы из `node_modules` Vite не делает.
//
// Предмет замера у этой зоны свой: порождение — это обход рецепта, из которого вырастает текст,
// и вопрос «почему редактор задумывается на каждой правке цвета» решается замером по шагам
// порождения (сборка правил · сборка текста · разворот вложенного), а не общим временем кадра.
// Разворот вложенного вынесен в отдельный замер намеренно: это ЧУЖОЙ шаг (`postcss-nested`), и
// его цену надо видеть отдельно от своей.

/** Тумблер трассы: `globalThis.__PROBE_WEB_SKIN_TRACE__ = true`. */
const FLAG = "__PROBE_WEB_SKIN_TRACE__";

type TraceGlobal = typeof globalThis & { [FLAG]?: boolean };

/** Включена ли трасса. По умолчанию — нет, включает только явный глобальный флаг. */
function enabled(): boolean {
  return (globalThis as TraceGlobal)[FLAG] === true;
}

/**
 * Открывает замер. Возвращает функцию закрытия — она и пишет строку.
 *
 * Выключенная трасса возвращает пустое закрытие, не трогая часы: замер на КАЖДОЕ правило
 * рецепта сам стал бы тем, что он измеряет.
 *
 * @param label имя замеряемого участка
 * @returns закрыть замер и напечатать длительность
 */
export function trace(label: string): () => void {
  if (!enabled()) return () => {};

  const started = performance.now();
  return () => {
    const ms = performance.now() - started;
    console.debug(`[probe-web-skin] ${label} — ${ms.toFixed(2)}ms`);
  };
}

/**
 * Пишет строку трассы без замера времени — для событий, у которых нет длительности: отказ
 * проверки, отброшенное пустое правило, неизвестное имя значения.
 *
 * @param message что произошло
 */
export function note(message: string): void {
  if (!enabled()) return;
  console.debug(`[probe-web-skin] ${message}`);
}
