// РУЧНАЯ часть базового слоя — единственный его кусок, написанный руками. Остальное
// порождается из данных зоны (`src/css/generate.ts`).
//
// ПОЧЕМУ СТРОКОЙ В МОДУЛЕ, А НЕ ФАЙЛОМ `.css` РЯДОМ (`PWEB-20`). Базовый CSS обязан
// порождаться ПО ТРЕБОВАНИЮ — в момент запроса, отражая текущие исходники, а не результат
// прошлой сборки. Значит порождение зовёт не только наш сборочный сценарий, но и дев-сервер,
// а он живёт в другой зоне. Ручная часть отдельным файлом заставила бы каждого зовущего знать
// путь к ней и уметь его прочитать: знание нашей раскладки уехало бы наружу, а генерация
// перестала бы быть чистой функцией и стала бы зависеть от того, откуда её позвали — из
// исходников, из сборки или из установки потребителя.
//
// Цена решения названа честно: этот CSS редактор подсвечивает как строку, а не как CSS.
// Взамен генерация везде одна и та же, и второй копии правды не возникает ни в одном из
// трёх мест, откуда её зовут.
//
// ─────────────────────────────────────────────────────────────────────────────────────────
// БАЗОВЫЙ СЛОЙ НЕ ОДЕВАЕТ. Решение user по `PWEB-39`, 2026-08-21.
//
// Отсюда ушли шесть объявлений вида на `body`: фон, цвет текста, начертание, кегль, высота
// строки, трекинг. Ушли не потому, что ссылались на роли, которых без темы нет, — это было
// лишь то, чем дефект стал ВИДЕН. Ушли потому, что базовый слой ими ОДЕВАЛ.
//
// Пять из шести НАСЛЕДУЮТСЯ. Это и есть суть: база не просто красила документ, она через
// наследование одевала кит. Кнопка, которую не одевал никто, получала от нас цвет текста,
// шрифт, кегль, высоту строки и трекинг — сама собой, ничего не спросив. «Нет скина —
// приложение голое» (`kb:PROBEWEB-11`) держалось на бумаге: голым кит не был никогда, на нём
// была наша одежда, просто невидимая в перечне правил скина.
//
// Шестое, фон, не наследуется — оно делало другое: объявляло страницу НАШЕЙ. Кто красит
// страницу, базовый слой не решает; замер `PWEB-39` показал, что сегодня её не красит никто,
// и это отдельный вопрос с отдельным владельцем.
//
// ЧТО ОСТАЛОСЬ И ПОЧЕМУ ЭТО НЕ ОДЕЖДА:
//
//  • сброс (`box-sizing`, `margin: 0`) — снятие решений БРАУЗЕРА, а не внесение своих. Ничего
//    не наследуется, ни один цвет и ни один размер не приходит от нас;
//  • токены движения — ЗНАЧЕНИЯ, а не применения. Объявленный токен не надет ни на что, пока
//    его не позвали; ровно так же здесь живут производные шкалы;
//  • `color-scheme` — разобран ниже отдельно, потому что строка спорная.
//
// ─────────────────────────────────────────────────────────────────────────────────────────
// ПОЧЕМУ `color-scheme` ОСТАЁТСЯ. Спор настоящий, и обе стороны верны по факту: снимешь —
// голый кит перестанет выглядеть по-разному в двух режимах; оставишь — базовый слой
// продолжает что-то говорить браузеру о виде страницы. Остаётся, и вот на чём.
//
// 1. Это НЕ решение о виде, а ПЕРЕВОД уже принятого приложением решения на язык браузера.
//    Режим выбирает приложение и несёт классом `dark` на корне (зона `runtime`); `color-scheme`
//    говорит браузеру ровно то же самое, слово в слово. Промолчи мы — браузер решит сам и
//    решит НЕЗАВИСИМО: у одного ответа станет два источника. Расхождение двух источников
//    одного ответа — ровно тот дефект, из-за которого шесть строк выше отсюда и уехали.
//
// 2. Сказать это больше НЕКОМУ. Скин? Тогда у приложения без скина режима нет вовсе, а у двух
//    скинов их два — при том что режим ортогонален скину (`kb:SKIN-7`, инвариант 3) и
//    существует независимо от того, надет ли скин. Потребитель? Тогда связь «класс на корне ↔
//    режим браузера» держится соглашением в каждом скелете, а не машиной в одном месте. База —
//    единственный, кто присутствует во ВСЕХ конфигурациях, и связь класса с режимом уже
//    объявлена здесь.
//
// 3. Возражение «голый кит выглядит по-разному в двух режимах» верно по факту и неверно по
//    выводу. Голый кит — это не наш вид, а ОТСУТСТВИЕ нашего вида; что осталось, то и есть вид
//    браузера, а у браузера их два, потому что у человека два режима. Сделать голый кит
//    одинаковым можно только пришпилив один из них — то есть приняв решение о виде, ровно то,
//    которое мы отсюда убираем. `color-scheme: light` для всех — не нейтральность, а выбор
//    светлого, просто необъявленный.
//
// 4. Последствие названо прямо, а не спрятано: от `color-scheme` зависит канва браузера и его
//    же начальный цвет текста, то есть голая страница в тёмном режиме выглядит тёмной. Красит
//    её БРАУЗЕР своим умолчанием — мы лишь сказали, каким из двух. Появится источник — он
//    перекроет умолчание обычным объявлением, спорить не с чем. Снятая строка отняла бы у
//    браузера и это: системные элементы (полосы прокрутки, галочки, автозаполнение) остались бы
//    светлыми на тёмной странице, а потребителю пришлось бы заново выводить то, что мы уже
//    знаем.
//
// ─────────────────────────────────────────────────────────────────────────────────────────
// ИНВАРИАНТ, ставший сильнее прежнего: здесь нет не только литеральных цветов, но и ни одного
// объявления вида на документ. Держит `test/base-css.test.ts`, а не обещание в шапке.
//
// Текст работает без чего угодно рядом: своих значений он не ждёт вовсе, а размерные шкалы
// (порождённый блок ниже) несут дефолт прямо в `var(--семя, …)`, поэтому геометрия считается и
// без палитры.

/** Ручная часть базового CSS. `String.raw` — чтобы текст ехал ровно таким, как написан. */
export const WRITTEN_BASE = String.raw`:root {
  /* Длительности и кривые — theme-independent: палитра их не красит, а согласованность
     движения нужна с первого компонента. Шкалы у них нет намеренно: это не размеры, а
     подобранный ряд, и выводить его из одного числа значило бы придумать основание.

     Это ЗНАЧЕНИЯ, а не применения: ни одно из них ни на что не надето, пока его не позвали. */
  --motion-instant: 75ms;
  --motion-fast: 200ms;
  --motion-normal: 320ms;
  --motion-slow: 400ms;

  --ease-linear: linear;
  --ease-in: cubic-bezier(0.4, 0, 1, 1);
  --ease-out: cubic-bezier(0, 0, 0.2, 1);
  --ease-in-out: cubic-bezier(0.4, 0, 0.2, 1);
}

/* Режим объявляется браузеру — и это перевод выбора приложения, а не наш выбор: класс dark
   ставит зона runtime, а здесь тем же классом сказано то же самое на языке браузера. Скажи
   это кто-то ещё — у одного ответа стало бы два источника; не скажи никто — от режима отстали
   бы системные элементы: полосы прокрутки, галочки, автозаполнение форм. */
:root {
  color-scheme: light;
}

:root.dark,
.dark {
  color-scheme: dark;
}

/* СБРОС: снимаем решения браузера, своих не вносим. Ничего не наследуется. */
*,
::before,
::after {
  box-sizing: border-box;
}

body {
  margin: 0;
}
`;
