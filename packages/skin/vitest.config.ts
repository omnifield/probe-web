import solid from "vite-plugin-solid";
import { defineConfig } from "vitest/config";

// Два проекта, потому что пробы зоны живут в разных мирах:
//
//   • model — модель, сборка рецепта, проверки и порождение текста. Ни документа, ни JSX там
//     нет вовсе: механика превращает ДАННЫЕ в ТЕКСТ и обязана работать там, где документа не
//     существует — в хранилище, в сборке на сервере, в проверке сохранённого скина;
//   • kit   — тот же порождённый текст, надетый на ЖИВУЮ кнопку: настоящий компонент,
//     настоящий паспорт, настоящая разметка. Отдельным проектом из-за конвейера: кит приезжает
//     веткой `solid` — НЕпреобразованным JSX, и трансформацию применяем мы (то же решение и та
//     же причина, что у зон `ui`, `runtime` и `assembly`).
//
// Пресет `@omnifield/probe-web-build/vitest` сюда НЕ подключается: направление зависимостей
// между зонами одностороннее (`kb:PROBEWEB-4`), и пресет не для собственных проб пакета.

export default defineConfig({
  test: {
    projects: [
      {
        test: {
          name: "model",
          environment: "node",
          include: ["test/*.test.ts"],
        },
      },
      {
        plugins: [solid()],
        resolve: { conditions: ["development", "browser"] },
        test: {
          name: "kit",
          environment: "jsdom",
          include: ["test/*.test.tsx"],
          // Весь чужой код идёт через наш конвейер: кит и его основания приезжают
          // непреобразованным JSX, и перечень имён пришлось бы дописывать на каждом уровне
          // чужих зависимостей. Правило общее, а не список — так же, как в зоне `assembly`.
          //
          // Исключение ровно одно и названо: postcss со спутниками. Оно записано ОТРИЦАНИЕМ —
          // «всё, кроме postcss», — а не перечнем нужного: перечень нужного и есть тот список,
          // который пришлось бы дописывать на каждом новом уровне чужих зависимостей.
          //
          // Почему исключение вообще есть: JSX в postcss нет вовсе, зато часть его файлов
          // ссылается на карты исходников, которых в поставке нет, и конвейер печатает об этом по
          // абзацу на каждый прогон. Шум в выводе проб опаснее, чем кажется: в нём тонет
          // настоящая жалоба.
          server: { deps: { inline: [/^(?!.*postcss).*$/] } },
        },
      },
    ],
  },
});
