// ПАСПОРТ потока — одномерной раскладки.
//
// ## Почему «поток», а не «ряд»
//
// Потому что НАПРАВЛЕНИЕ — вид, а не устройство компонента (решение записано в README, раздел
// «Раскладка — это вид»). Ряд и столбец отличаются одним значением, которое задаёт скин; вшей мы
// направление в имя компонента — и получили бы два компонента, различающихся ровно одним
// свойством вида, то есть тот самый список имён, от которого уходим везде.
//
// Поток говорит одно: элементы идут ДРУГ ЗА ДРУГОМ по одной оси. Какой именно, с каким зазором и
// как выровнены — говорит скин по адресу.
//
// ## Частей две, и вторая не про запас
//
// `root` — сам поток. `item` — место ОДНОГО элемента в нём, и без него нельзя выразить
// «поле тянется, кнопка по содержимому»: свойства размещения (`flex`, `align-self`, `order`)
// живут на РЕБЁНКЕ, а дети потока — чужие компоненты. Правило скина, адресующее их, попало бы
// на все сразу; своего узла у отдельного элемента без `item` просто нет.
//
// `item` необязателен: элементы, которым размещение не нужно, кладут в поток напрямую. Обёртка
// на каждый чих — лишние узлы, и паспорт этого не требует.

import { createAnatomy } from "@zag-js/anatomy";

import { defineSettings, definePassport } from "../passport-form.js";
// ТИП пропов — только тип: `import type` стирается сборкой, и подпуть `./passport`
// остаётся данными без Solid. Нужен, чтобы ключи настроек сверялись с настоящими пропами.
import type { FlowProps } from "./flow.jsx";

/** Части потока: сам поток и место одного элемента в нём. */
export const anatomy = createAnatomy("flow").parts("root", "item");

/** Адреса частей: `attrs` для узла, `selector` для стиля. Считаются один раз — они статичны. */
export const parts = anatomy.build();

/**
 * Паспорт потока.
 *
 * Состояний нет ни у одной части: раскладка не хранит ничего. Всё, что у неё есть, — адрес и
 * ось вариаций, и в этом её предмет: она существует, чтобы скину было к чему прицепить правило.
 */
export const passport = definePassport({
  anatomy,
  package: "@omnifield/probe-web-ui",
  genus: "component",
  group: "layout",
  root: "root",
  parts: [
    {
      name: "root",
      means: "поток — элементы идут друг за другом по одной оси; какой именно, говорит скин",
      states: [],
      accepts: [
        { kind: "part", name: "item" },
        { kind: "content", genus: "text" },
        { kind: "content", genus: "component" },
      ],
    },
    {
      name: "item",
      means: "место одного элемента в потоке — им адресуется «этот тянется, остальные по содержимому»",
      states: [],
      accepts: [
        { kind: "content", genus: "text" },
        { kind: "content", genus: "component" },
      ],
    },
  ],
  variantAxis: {
    means: "имя вариации потока; его даёт человек в редакторе, кит пропускает насквозь",
    mark: { kind: "attribute", name: "data-variant" },
  },
  // Настроек из закрытого перечня ряд не принимает: направление у него — раскладочное свойство,
  // то есть ВИД, и приезжает скином (решение «раскладочные свойства это ВИД»).
  settings: defineSettings<FlowProps>({}),
  // Два элемента, а не один: предмет ряда — расстояние МЕЖДУ, а между одним его не бывает.
  assembly: {
    means: "ряд из двух элементов",
    tree: {
      part: "root",
      children: [
        { part: "item", children: [{ genus: "text", value: "Первый" }] },
        { part: "item", children: [{ genus: "text", value: "Второй" }] },
      ],
    },
  },
});
