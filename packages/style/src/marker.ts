// МАРКЕР ПРИЕЗДА БАЗЫ — то, по чему снаружи проверяют, что базовый CSS подключён.
//
// ЗАЧЕМ ЭТО ЗДЕСЬ. Проверку порядка подключения делает `runtime` (`checkStyleOrder`), но имя
// маркера она принимает АРГУМЕНТОМ и не знает (`PROBEWEB-13`): знание «что обязано приехать
// с базой» принадлежит нашей зоне. Литерал на той стороне стал бы тихой связью — переименуем
// здесь, и проверка там начнёт врать: кричать «базы нет» на исправном приложении либо, что
// хуже, молчать на сломанном. Ни сборка, ни пробы этого не покажут.
//
// Цена ошибки несимметрична: имя уезжает в скелет, а скелет кладётся потребителю классом
// `placed-once` и НЕ ОБНОВЛЯЕТСЯ НИКОГДА. Литерал, попавший туда, чинится только правкой
// руками в каждом уже созданном продукте.
//
// ─────────────────────────────────────────────────────────────────────────────────────────
// МАРКЕР ПЕРЕЕХАЛ НА СБРОС (`PWEB-66`), и переехал вынужденно.
//
// Был `--control-target-min` — пол нормы (WCAG 2.2, 2.5.8): не ступень и не вкус, палитра,
// объявившая его, дефект по определению. Свойство хорошее, но носителя не стало: в листе не
// осталось НИ ОДНОГО кастом-свойства, а значит и токена, которым можно предъявить приезд.
//
// Носителем стал сам сброс. Он и есть теперь весь базовый слой, то есть отвечает ровно на тот
// вопрос, ради которого маркер заведён: приехал лист или нет. `box-sizing` взят потому, что
// его значение в сбросе (`border-box`) ОТЛИЧАЕТСЯ от умолчания браузера (`content-box`), —
// по нему видно не только «свойство есть», но и «приехало именно наше».
//
// ПОЭТОМУ НАРУЖУ ЕДЕТ ПАРА, А НЕ ИМЯ. Свойство без ожидаемого значения — ровно та проверка,
// которая ВРЁТ ЗЕЛЁНЫМ: `box-sizing` есть у каждого элемента всегда, и «свойство нашлось» не
// отличает наш лист от его отсутствия. Отличает `border-box` против браузерного `content-box`.
//
// ВЗЯТЬ ОДНО БЕЗ ДРУГОГО НЕЛЬЗЯ — это условие формы, и держится оно тем, что экспорт ОДИН.
// Две константы рядом дали бы потребителю выбрать имя и забыть значение; забытое значение
// здесь не «неполнота», а тихо соврамший гейт.
//
// ТЕКСТОМ МАРКЕР ПО-ПРЕЖНЕМУ ОТВЕЧАЕТ ИМЕНЕМ СВОЙСТВА: эталон ищет его в собранном листе
// подстановкой в строку, и `${BASE_MARKER}` даёт `box-sizing`. Это не хитрость ради
// совместимости, а точное описание: в тексте листа маркер выглядит именно так, а проверять
// живой документ надо парой.
//
// ШОВ С `runtime` НАЗВАН ОТДЕЛЬНО. `checkStyleOrder()` принимает имя кастом-свойства и на
// нашем маркере бросает; починка — принимать эту пару, и пара для того и отдана. Правка не
// здесь: `runtime` и шаблон скелета чужие. Заявка поднята.

import { RESET_PROOF } from "./css/written.js";

/**
 * Чем предъявляют приезд базы: свойство сброса и значение, которое оно обязано иметь.
 *
 * Печатается именем свойства — так маркер выглядит в тексте листа, и так его ищет эталон:
 *
 * ```ts
 * `${BASE_MARKER}:`                                     // "box-sizing:"
 * getComputedStyle(el)[BASE_MARKER.property] === BASE_MARKER.value  // база приехала
 * ```
 */
export interface BaseMarker {
  /** Свойство сброса, по которому спрашивают документ. */
  readonly property: string;
  /** Значение, которое оно принимает ТОЛЬКО с нашим листом. */
  readonly value: string;
  /** Имя свойства — форма, в которой маркер виден в тексте листа. */
  toString(): string;
}

/**
 * Маркер приезда базы — ПАРА, а не имя.
 *
 * ЧЕМ ОБЯЗАН БЫТЬ МАРКЕР — четыре свойства, и все проверяются пробой (`test/marker.test.ts`),
 * а не соблюдаются на память:
 *
 * 1. **Объявлен базовым слоем** — иначе он не отвечает на вопрос, ради которого заведён.
 * 2. **Его значение отличается от умолчания браузера** — иначе проверка истинна всегда.
 * 3. **НИКОГДА не объявлен палитрой.** Маркер, уехавший в палитру, стирает разницу между
 *    «база не приехала» и «палитра не выбрана». Сброс палитрой не объявляется и по
 *    построению: палитра несёт значения, а не правила.
 * 4. **Не зависит ни от палитры, ни от режима** — литерал, без единого `var()`.
 *
 * Обе половины собираются из самой записи сброса (`src/css/written.ts`): второй копии ни имени,
 * ни значения в зоне нет, и правка сброса двигает маркер сама.
 */
export const BASE_MARKER: BaseMarker = Object.freeze({
  property: RESET_PROOF.property,
  value: RESET_PROOF.value,
  toString: () => RESET_PROOF.property,
});
