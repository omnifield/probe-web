// МОДЕЛЬ СКИНА — то, что человек собирает в редакторе и что хранилище держит одной записью.
//
// ## Единица — скин целиком, а не тема и не пресет
//
// **Скин = переменные + рецепты** (страница «Скин»). Отдельной сущности «тема» в устройстве
// нет: набор переменных ничего не одевает, он перекрашивает уже одетое. Существуй они порознь —
// возникло бы состояние «правила вида есть, а откуда они взялись, неизвестно».
//
// ## Форма рецепта взята, а не придумана
//
// Форма — `defineSlotRecipe` из Panda CSS (страница «Основания», раздел 4): части, база,
// вариации, умолчание, пересечения. Берём ФОРМУ, а не сам Panda: он читает исходники и
// генерирует CSS на сборке, а наши скины делает редактор и выбирает приложение — они появляются
// ПОСЛЕ сборки.
//
// Три свойства, ради которых форма и взята:
//
//   1. стиль объявлен ПО ЧАСТЯМ, и части — те же, что в анатомии: шов между китом и одеждой
//      закрывается сам собой;
//   2. умолчание ОБЪЯВЛЕНО, а не подразумевается: голый компонент и компонент с явным именем
//      перестают быть двумя разными адресами;
//   3. пересечения собирает АВТОР РЕЦЕПТА, а не приложение: в разметке одно имя.
//
// ## Чем наша запись отличается от Panda — и почему
//
// **Ось вариаций одна.** У Panda `variants` — карта осей (`size`, `tone`, …). Паспорт объявляет
// ОДНУ ось, выраженную одним атрибутом (`data-variant`), потому что два атрибута в разметке
// означали бы, что дизайн собирают в приложении. Поэтому здесь `variants` — карта ИМЁН, а не
// карта осей, и умолчание — одно имя, а не карта.
//
// **Состояние и предок — координаты, а не условия.** У Panda условие записывается ключом
// (`_hover`) из его собственного словаря. У нас имя состояния приходит из ПАСПОРТА части, и
// селектор порождается из объявленной там разметки. Разница не косметическая: паспортное
// «наведение» проверяемо на живом компоненте, а чужое `_hover` разворачивается в чужой составной
// селектор, которого компонент не обещал (замер `PWEB-28`, Chakra отклонён в том числе за это).

/**
 * Значение свойства.
 *
 * Число печатается КАК ЕСТЬ, единицу называет автор: подстановка `px` — это догадка о свойстве,
 * то есть кусок утилитарного слоя, которого мы не брали. `opacity: 0.5` и `zIndex: 10` при этом
 * остаются выразимыми.
 */
export type StyleValue = string | number;

/**
 * Свободный стилевой объект: свойства и вложенные блоки.
 *
 * **Списка разрешённых свойств нет** — ограничиваем адрес, а не значение (страница «Скин»).
 * Обратный выбор заморозил бы выразительность: реальный вид требует и раскладки, и масок, и
 * преобразований, и движения.
 *
 * Имя свойства принимается в обоих начертаниях: `borderWidth` и `border-width` — одно и то же.
 * Кастом-свойства (`--что-то`) не преобразуются.
 *
 * Вложенный ключ разрешён НЕ любой: только псевдоэлемент (`&::before`) и at-правило
 * (`@media …`). Свободный вложенный селектор отвергается проверкой — он цепляется за
 * внутреннюю структуру разметки или за имя класса, а это внутреннее дело компонента, меняется
 * без предупреждения, и скин, написанный так, ломается молча (страница «Скин», «Почему адрес, а
 * не свободный селектор»). Разворот вложенного в плоский текст делает `postcss-nested`.
 */
export interface StyleObject {
  readonly [property: string]: StyleValue | StyleObject | undefined;
}

/**
 * Вид части БЕЗ уточнения по предку — то, что действует, когда предок уже выбран.
 *
 * Отдельный тип от `PartStyle` не для красоты: он машинно держит правило «предок — уровень
 * ОДИН» (страница «Скин»). Цепочка предков сделала бы правило зависимым от глубины разметки, то
 * есть вернула бы свободный селектор, от которого уходили.
 */
export interface LocalStyle {
  /** Свойства этого адреса. */
  readonly props?: StyleObject;
  /**
   * Уточнение по состоянию ЧАСТИ: имя состояния из паспорта → вид.
   *
   * Вложение разрешено: узел бывает сразу в нескольких состояниях (наведённый отключённый), и
   * `states.hover.states.disabled` — законный адрес их пересечения.
   */
  readonly states?: Readonly<Record<string, LocalStyle>>;
}

/** Вид части, зависящий от состояния ПРЕДКА. */
export interface AncestorStyle {
  /**
   * Часть-владелец: имя части того компонента, внутри которого лежит наша.
   *
   * Компонент предка может быть ДРУГИМ — узел лежит в чужом дереве, а не только в своём,
   * поэтому имя компонента называется отдельно.
   */
  readonly component: string;
  /** Часть предка — ключ его анатомии. */
  readonly part: string;
  /** Состояния предка, при которых правило действует. Пусто — предок в любом состоянии. */
  readonly states?: readonly string[];
  /** Вид. Своего предка у него уже нет — уровень один. */
  readonly style: LocalStyle;
}

/** Вид части целиком: свой адрес плюс уточнения по предку. */
export interface PartStyle extends LocalStyle {
  /**
   * Правила вида «эта часть выглядит так, когда её владелец в таком состоянии» — например,
   * подавленная заливка у отключённого слайдера. Без них часть правил выразить нельзя.
   */
  readonly ancestors?: readonly AncestorStyle[];
}

/** Вид по частям: имя части → её вид. */
export type PartStyles = Readonly<Record<string, PartStyle>>;

/**
 * ПЕРЕСЕЧЕНИЕ — вид на стыке нескольких условий, собранный АВТОРОМ РЕЦЕПТА.
 *
 * Зачем оно нужно, когда вложение уже выражает «опасная при наведении»: вложение — дерево, и
 * правило, общее для НЕСКОЛЬКИХ вариаций сразу, пришлось бы писать в каждой заново. Ровно это
 * и снимает `compoundVariants` у Panda; у нас, при одной оси, пересекаются имена вариаций между
 * собой и с состояниями.
 */
export interface CompoundVariant {
  /** Имена вариаций, на которых правило действует. Пусто — на любой, включая отсутствие имени. */
  readonly variants?: readonly string[];
  /** Состояния части, при которых правило действует. */
  readonly states?: readonly string[];
  /** Вид по частям. */
  readonly style: PartStyles;
}

/**
 * РЕЦЕПТ — скин одного компонента.
 *
 * Части не перечисляются: их перечисляет анатомия, и второй перечень рядом с ней разъехался бы
 * с ней молча. `slots` из формы Panda здесь не нужен ровно потому, что у нас есть паспорт —
 * то, чего у Panda нет и что он вынужден просить у автора.
 */
export interface SlotRecipe {
  /** База — вид, действующий всегда. */
  readonly base?: PartStyles;
  /**
   * Вариации: имя вариации → вид по частям.
   *
   * Имена принадлежат СКИНУ, а не паспорту: их создаёт человек в редакторе. Разные скины вправе
   * знать разные имена — приложение, стоящее на именах одного, при переключении на другой
   * получит незнакомые ему части в базовом виде, то есть беднее, но живым.
   */
  readonly variants?: Readonly<Record<string, PartStyles>>;
  /**
   * Имя вариации, действующей КОГДА АТРИБУТА НЕТ.
   *
   * Обязательно, если вариации объявлены (страница «Паспорт компонента»): иначе «главная» и
   * «атрибут не указан» окажутся двумя разными адресами, совпадающими по договорённости,
   * которой нет ни в одном файле. Порождение делает их ОДНИМ адресом.
   */
  readonly defaultVariant?: string;
  /** Пересечения. */
  readonly compoundVariants?: readonly CompoundVariant[];
}

/**
 * Именованное движение — то, что адресуется из правил по имени.
 *
 * Принадлежит скину ЦЕЛИКОМ, а не одной части (страница «Скин»): одна и та же пульсация
 * используется и загрузкой, и подсветкой, и держать её копию в каждом рецепте значило бы
 * завести две правды об одном движении.
 */
export type Keyframes = Readonly<Record<string, StyleObject>>;

/**
 * Шкала, объявленная семенем.
 *
 * Сплошные ступени и контрастная строятся всегда — это и есть шкала. Остальные ряды по
 * желанию: они нужны не каждому скину, а лишний десяток имён в файле стилей никого не радует.
 */
export interface SeededScale {
  /** Семя — одно значение, из которого строятся обе половины. */
  readonly seed: string;
  /**
   * Параллельная шкала прозрачности: `--<имя>-a1`…`--<имя>-a12`.
   *
   * Нужна там, где сплошная ступень не годится: подсветка ложится на произвольный фон, а не на
   * известный. Сплошным цветом такое не выразить вовсе.
   */
  readonly alpha?: boolean;
  /** Ряд категориальных цветов данных: `--<имя>-chart-1`… */
  readonly chart?: boolean;
  /** Затемнение под слоем: `--<имя>-scrim`. От режима НЕ зависит — оно одно на обе половины. */
  readonly scrim?: boolean;
}

/** Объявление шкалы: одна строка — только семя, всё остальное по умолчанию. */
export type ScaleDeclaration = string | SeededScale;

/**
 * Переменные скина — общие для всего скина значения: палитра, скругление, плотность, шрифты,
 * тени.
 *
 * Имя пишется БЕЗ `--`, как и в зоне значений (`PaletteValues`): начертание одно на оба
 * поставщика, иначе перенос между ними требовал бы преобразования на каждом стыке.
 *
 * ## Два способа объявить, и они смешиваются
 *
 * **Литералами** — человек пишет обе половины сам. Опорный путь: скин, написанный без нашего
 * набора значений, обязан быть законным.
 *
 * **Семенами** — человек называет одно значение на шкалу, обе половины строит та же механика,
 * что строит их для набора значений, и обещания контраста даются построением. Правила при этом
 * адресуют СТУПЕНИ (`var(--бренд-9)`), поэтому скин становится пересеваемым: поменял семя —
 * поменялся весь вид.
 *
 * Смешивать можно: литерал по имени перебивает построенное, и этим же одна правка человека
 * переживает перегенерацию. Порядок наложения и его следствия — `seeds.ts`.
 *
 * **Пара для тёмного режима — ответственность скина.** Действующая граница проходит не по форме
 * значения, а по его поведению: значение вправе быть литералом, но обязано следовать за режимом
 * и за выбранным скином (страница «Скин»).
 */
export interface SkinVariables {
  /**
   * Шкалы, объявленные семенами: имя шкалы → семя либо полное объявление.
   *
   * Что семенем НЕ выводится — объявлено данными в `NOT_SEEDED`, а не оставлено сюрпризом.
   */
  readonly scales?: Readonly<Record<string, ScaleDeclaration>>;
  /**
   * РАЗМЕРНЫЕ шкалы, объявленные семенами: имя семени → значение (`space` → `0.25rem`).
   *
   * Второй ряд посеваемого рядом с цветом (`PWEB-64`). Назвал семя — получил всю лестницу:
   * ступени, ось плотности, посадку на сетку. Не назвал — не получил НИ ОДНОЙ ступени этой
   * шкалы; правило, адресующее её ступень, становится изъяном записи. Умолчания сбоку нет ни в
   * каком виде: до `PWEB-64` эти ступени приезжали приложению общим листом, то есть мимо скина,
   * и это был второй путь к тому же результату.
   *
   * Перечень имён и то, что скину НЕ принадлежит (шкала слоёв, нормированные ряды), — `sizes.ts`.
   */
  readonly dimensions?: Readonly<Record<string, string>>;
  /**
   * Светлая половина литералами. Она же единственная, если тёмной не объявлено.
   *
   * Имя, совпавшее со ступенью объявленной шкалы, перебивает построенное — но только в СВОЕЙ
   * половине.
   */
  readonly light?: Readonly<Record<string, string>>;
  /** Тёмная половина литералами. Не объявлена — тёмная берётся построенной либо у светлой. */
  readonly dark?: Readonly<Record<string, string>>;
}

/** СКИН — единица хранения, выбора и снятия. */
export interface Skin {
  /**
   * Имя скина: уезжает на корень значением `data-skin` и им же зовётся порождённый файл.
   *
   * Форму имени держит ХРАНИЛИЩЕ — `/^[a-z0-9][a-z0-9-]{0,31}$/`, и уникальность тоже его:
   * только оно видит все записи разом (уведомление `owner-presets`, `PWEB-13`). Здесь имя
   * проверяется лишь на пригодность к селектору — второй копии правила формы не заводим.
   */
  readonly name: string;
  /** Переменные. Скин вправе не иметь ни одной: правила вида — вторая половина, не первая. */
  readonly variables?: SkinVariables;
  /** Рецепты: имя компонента (оно же `data-scope`) → его рецепт. */
  readonly recipes: Readonly<Record<string, SlotRecipe>>;
  /** Именованные движения. */
  readonly keyframes?: Keyframes;
}

/**
 * ПРАВКА ОБРАЗЦА — вид ОДНОГО узла, а не координаты.
 *
 * Не скин и в скин не уезжает НИКОГДА (страница «Скин»): она по идентификатору узла, а не по
 * координате. Правилом, а не встроенным стилем, — потому что встроенный перебивает любой скин, и
 * место, поправленное в конструкторе, перестало бы одеваться навсегда.
 *
 * Порождается ТЕМ ЖЕ генератором и уезжает в СВОЙ слой каскада, объявленный после скинового.
 */
export interface SketchEdit {
  /** Имя узла — то, что механика сборки ставит в `data-node` при отрисовке. */
  readonly node: string;
  /** Компонент узла: без него состояния не адресуемы — их словарь живёт в паспорте. */
  readonly component: string;
  /** Часть узла — ключ анатомии. */
  readonly part: string;
  /** Вид. */
  readonly style: PartStyle;
}
