// ИСТОЧНИК СКИНОВ зоны — то, чем витрина кормит механику надевания.
//
// ## Скинов в коде нет вовсе
//
// Ни перечня, ни семени, ни «встроенного на крайний случай». Содержимое живёт в СЛУЖБЕ, и
// только там: скин делает человек, хранилище его держит, витрина показывает. Код зоны отвечает
// на «чем показать и чем одеть», а не на «как выглядит кнопка».
//
// Правило оплачено прошлым поколением зоны — два перечня расходятся молча, — и решением user
// доведено до конца: запасного содержимого нет ни в какой форме. Прочти витрина встроенный скин
// при пустой службе, человек не отличил бы «служба отдала мой скин» от «показываю своё», а
// расхождение нашёл бы у коллеги.
//
// **Цена названа прямо:** служба пуста — витрине нечего надеть, и она это говорит. Скины
// возвращаются тем же путём, которым появились: человеком, через сохранение.
//
// ## Валюта — текст стилей, а не адрес файла
//
// Механика приложения принимает источник снаружи и про нас не знает ничего. Ей нужны две вещи:
// перечень имён и ТЕКСТ стилей по имени. Файла с адресом на этом пути нет ни на одном шаге:
// хранилище отдаёт скин структурой, генератор порождает CSS здесь, в браузере.
//
// ## Словарь значений пустой — и это проверка, а не упущение
//
// Скины продукта стоят на своих переменных, и словарь известных имён им не нужен: собственные
// переменные скина механика знает всегда. Передай мы сюда наш набор значений — «скин без наших
// значений законен» осталось бы обещанием, которое ничем не проверено.

import { generateSkinCss } from "@omnifield/probe-web-skin";
import type { SkinSource } from "@omnifield/probe-web-runtime";
import { passportOf } from "@omnifield/probe-web-ui/passport";

import { listSkins, readSkin, StoreRefused, type SkinRecord } from "./store.js";

export {
  deleteSkin,
  listSkins,
  readSkin,
  saveSkin,
  EMPTY_HINT,
  SERVICE_HINT,
  StoreDown,
  StoreRefused,
  type SkinRecord,
} from "./store.js";

/**
 * Запись службы по имени скина, либо `undefined`.
 *
 * Перечень спрашивается заново, а не берётся из памяти: скин мог появиться у коллеги минуту
 * назад, и надеть его человек вправе сразу.
 *
 * @param name машинное имя скина
 */
async function recordOf(name: string): Promise<SkinRecord | undefined> {
  return (await listSkins()).find((item) => item.name === name);
}

/**
 * Источник скинов для механики надевания.
 *
 * Отказ на неизвестное имя — исключение, а не пустая строка: пустая строка надела бы «скин»,
 * которого нет, и человек увидел бы голый кит под именем выбранного скина.
 */
export const SKIN_SOURCE: SkinSource = {
  names: async () => (await listSkins()).map((item) => item.name),

  css: async (name) => {
    const record = await recordOf(name);

    if (!record) throw new StoreRefused(`скина «${name}» в службе нет — надевать нечего`);

    // Изъян записи механика отвергает целиком, а не отдаёт текст с ошибкой рядом: текст с
    // изъяном оставил бы ровно ту дорогу, из-за которой чинят вид, а не запись.
    return generateSkinCss(await readSkin(record.id), passportOf);
  },
};
