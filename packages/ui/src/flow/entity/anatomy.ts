// РАНТАЙМ-анатомия потока (`разнесено PWEB-127`) — одномерной раскладки.
//
// ЗДЕСЬ ТОЛЬКО ЧАСТИ И АДРЕСА — ничего больше, тем же приёмом, что у гармошки
// (`accordion/entity/anatomy.ts`). Полный рантайм-контракт — уровнем выше, в `passport.ts`.
// Срез РЕДАКТОРА — ещё шагом дальше, в `playground/index.ts`.
//
// ## Частей две, и вторая не про запас
//
// `root` — сам поток. `item` — место ОДНОГО элемента в нём, и без него нельзя выразить
// «поле тянется, кнопка по содержимому»: свойства размещения (`flex`, `align-self`, `order`)
// живут на РЕБЁНКЕ, а дети потока — чужие компоненты. Правило скина, адресующее их, попало бы
// на все сразу; своего узла у отдельного элемента без `item` просто нет.
//
// `item` необязателен: элементы, которым размещение не нужно, кладут в поток напрямую. Обёртка
// на каждый чих — лишние узлы, и паспорт этого не требует.

import { createAnatomy } from "@omnifield/probe-web-skin/model";

/** Части потока: сам поток и место одного элемента в нём. */
export const anatomy = createAnatomy("flow").parts("root", "item");

/** Адреса частей: `attrs` для узла, `selector` для стиля. Считаются один раз — они статичны. */
export const anatomyParts = anatomy.build();
