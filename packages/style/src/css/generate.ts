// уезжавшая подпутём `/themes.css` и надевавшаяся атрибутом на `<html>`. Ушла целиком: палитра
// без рецептов это половина скина, отгруженная фреймворком, а половин у скина не бывает.
//
// Порождать палитру зона по-прежнему УМЕЕТ — `themeModelToCss()` сделает файл из любой модели.
// Не осталось только своей модели: чью палитру порождать, решает тот, кто делает скин.
