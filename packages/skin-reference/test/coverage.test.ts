// ПОКРЫТИЕ И ЧИТАЕМОСТЬ — оба ответа считает МЕХАНИКА, и оба записаны здесь значением.
//
// Считает их не проба: у механики для этого есть `skinGaps` и `skinContrast`, и второй счёт был
// бы вторым ответом на тот же вопрос. Проба спрашивает и сверяет с РЕШЕНИЕМ — тем, что записано
// в шапке `recipes.ts`.
//
// Спрашиваются они по СОБРАННОМУ наряду, а не по форме и не по палитре (`PWEB-78`): контраст
// перестал быть свойством части — форма, написанная под одну палитру, может лечь на другую, и
// читаемость становится свойством СОЧЕТАНИЯ. У части её спросить нечем: у формы нет значений.

import { skinContrast, skinGaps } from "@omnifield/probe-web-skin";
import { PASSPORTS } from "@omnifield/probe-web-ui/passport";
import { describe, expect, it } from "vitest";

import { собранный } from "./assembled.js";

const referenceSkin = собранный.skin;

const паспорта = Object.values(PASSPORTS);

describe("покрытие ПОЛНОЕ — решение автора, проверенное машиной", () => {
  it("непокрытого не осталось ни одного", () => {
    // Решение и его цена — в шапке `recipes.ts`. Коротко: эталон существует ради доказательства,
    // что механика работает целиком, а непокрытая координата это координата, на которой она НЕ
    // ПРОВЕРЕНА — адрес не порождён, каскад не сложен, читаемость не посчитана.
    expect(skinGaps(referenceSkin, паспорта)).toEqual([]);
  });

  it("счёт не слеп: снятое правило всплывает в покрытии", () => {
    // Без этого «пусто» проходило бы и на счёте, который ничего не умеет находить.
    const без = {
      ...referenceSkin,
      recipes: Object.fromEntries(
        Object.entries(referenceSkin.recipes).filter(([name]) => name !== "surface"),
      ),
    };

    expect(skinGaps(без, паспорта).length).toBeGreaterThan(0);
  });

  it("одеты РОВНО те, у кого есть паспорт: лишнего рецепта нет", () => {
    expect(Object.keys(referenceSkin.recipes).toSorted()).toEqual(
      паспорта.map((паспорт) => паспорт.component).toSorted(),
    );
  });
});

describe("читаемость: контраст обещан ПОСТРОЕНИЕМ", () => {
  const ответ = skinContrast(referenceSkin, паспорта);

  it("ни одной пары ниже нормы — ни в светлой половине, ни в тёмной", () => {
    // Обещание даётся построением, а не подбором: ступени назначены зоной значений, и правила
    // адресуют их по назначению. Проба ловит ровно то, что случилось бы, напиши автор правило
    // против назначения ступени, — и случилось бы молча.
    expect(ответ.notes.filter((note) => note.kind === "low")).toEqual([]);
  });

  it("и ни одной неотличимой рамки против собственной заливки", () => {
    expect(ответ.notes.filter((note) => note.kind === "indistinct")).toEqual([]);
  });

  it("НЕПОКРЫТОЕ НАЗВАНО: всё непосчитанное — один класс, и он объявлен", () => {
    // Единственное, что счёт назвать не может, — намеренно невидимая рамка сплошной кнопки.
    // Она держит коробку того же размера, что у обведённой вариации, и «что под полностью
    // прозрачным» значение действительно не говорит. Ответ «посчитать нечем» здесь ВЕРНЫЙ, а не
    // пробел: разбор — в `recipes.ts`, у вариации `главная`.
    const непосчитано = ответ.notes.filter((note) => note.kind !== "low" && note.kind !== "indistinct");

    expect(непосчитано.every((note) => note.property === "border-color")).toBe(true);
    expect(непосчитано.every((note) => note.reason === "translucent")).toBe(true);
    expect(непосчитано).toHaveLength(8);
  });

  it("а что механика не проверяет вовсе — она говорит сама, и мы это не прячем", () => {
    // Контраст рамки против того, что лежит СНАРУЖИ узла, счётом не берётся: снаружи знает
    // дерево, а скин от дерева намеренно независим. Механика объявляет это значением, и эталон
    // не делает вид, что проверено всё.
    expect(ответ.unchecked.length).toBeGreaterThan(0);
  });
});
