// Корень документа как СРЕДА: чтение и запись опознания скина. ВНУТРЕННЕЕ — наружу не
// экспортируется и в `exports` манифеста не объявлено. Публичная поверхность зоны живёт
// целиком в `src/index.ts`: каждый экспорт замерзает навсегда (`kb:PROBEWEB-4`), а
// `dist/index.d.ts` не имеет права содержать реэкспорт-бочку.
//
// Здесь и ТОЛЬКО здесь зашиты два имени — `data-theme` и класс `dark`. Это не оплошность и не
// то же самое, что перечень пресетов или имя маркерного токена: опознание пресета объявлено
// швом (`kb:SKIN-5`, пункт 4) как часть контракта между всеми четырьмя владениями, а перечень
// и маркер принадлежат `skin` и `style` — их мы принимаем снаружи, потому что они меняются
// без нашего ведома.

/** Атрибут опознания пресета на корне. Шов `kb:SKIN-5`, пункт 4. */
const PRESET_ATTR = "data-theme";

/** Класс тёмной пары. Светлая — ОТСУТСТВИЕ класса, а не второй класс. */
const DARK_CLASS = "dark";

/**
 * Корень документа — `<html>`.
 *
 * Именно он, а не `<body>` и не контейнер: производные шкалы объявлены и вычисляются в
 * `:root`, и на контейнере они не пересчитываются (инвариант 1 `kb:SKIN-7`, оплачен
 * неработавшими ручками стенда). Плюс `<html>` существует уже во время разбора страницы —
 * поэтому механику можно позвать до первой отрисовки, когда `<body>` ещё нет.
 */
function root(): HTMLElement {
  return document.documentElement;
}

/** Пресет, стоящий на корне сейчас. `null` — не стоит никакой. */
export function readPreset(): string | null {
  return root().getAttribute(PRESET_ATTR);
}

/** Ставит пресет на корень; `null` — снимает атрибут, возвращая приложение к базе. */
export function writePreset(id: string | null): void {
  const el = root();
  if (id === null) el.removeAttribute(PRESET_ATTR);
  else el.setAttribute(PRESET_ATTR, id);
}

/** Стоит ли тёмная пара. */
export function readDark(): boolean {
  return root().classList.contains(DARK_CLASS);
}

/** Ставит или снимает тёмную пару. */
export function writeDark(dark: boolean): void {
  root().classList.toggle(DARK_CLASS, dark);
}

/**
 * Значение кастом-свойства, ВЫЧИСЛЕННОЕ на корне.
 *
 * Именно вычисленное, а не объявленное нами: вопрос проверки порядка — «приехал ли токен с
 * базовым CSS», и ответ на него даёт каскад, а не наш собственный inline. Токена нет —
 * пустая строка, и это не ошибка чтения, а сам ответ.
 */
export function readToken(name: string): string {
  return getComputedStyle(root()).getPropertyValue(name).trim();
}
