// ПЕРЕМЕННЫЕ, ОБЪЯВЛЕННЫЕ ПАСПОРТОМ, — и почему они не роли (`PWEB-93`).
//
// Паспорт объявляет переменные ЧАСТИ вместе с тем, кто их ставит:
//
//   itemContent → --height  «измеренная высота раскрытого содержимого»  setBy: kit
//
// Кит их кладёт и на них рассчитывает, значит они наблюдаемы — а раз наблюдаемы, скин вправе их
// адресовать: анимация раскрытия иначе не пишется вовсе.
//
// ## Это НЕ роль, и в словарь они не едут
//
// Роль задаёт палитра. Переменную части палитра задать не может и не должна: её ставит кит на
// живом узле, измерив его. Смешай мы их — палитра получила бы обещание, которого не выполнит, а
// «палитра не закрыла словарь» начало бы требовать от неё измеренную высоту.
//
// ## Законна НА СВОЕЙ ЧАСТИ, и только на ней
//
// `--height` объявлен на содержимом гармошки. Правило на кнопке ссылаться на него не вправе:
// там его никто не поставит, и правило приедет на страницу с неразрешимым значением — то есть
// вернётся ровно то, от чего уходим, только тише.
//
// Отсюда и два разных изъяна вместо одного: «объявлена, но не здесь» — другая причина и другая
// починка, чем «такого имени нет вовсе». Первую чинят переносом правила на ту часть (или адресом
// по предку), вторую — объявлением в палитре или в паспорте.
//
// ## `setBy` законности НЕ меняет — и вот почему
//
// `kit` и `consumer` различаются РИСКОМ, а не правом: обе объявлены паспортом, обе наблюдаемы,
// обе адресуемы. Скин, написанный в расчёте на `consumer`, у забывчивого потребителя молча не
// сработает — но это его выбор, а не наша граница: запрети мы такие правила, паспорт объявлял бы
// то, чем нельзя пользоваться.
//
// Второй раз про `setBy` механика не рассказывает намеренно. Кто ставит переменную — факт
// ПАСПОРТА, и отвечает на него паспорт, который редактор и так читает. Перенеси мы это в отчёт
// сборки — завелась бы вторая правда о чужом факте, расходящаяся на первой же правке паспорта.

import type { ComponentPassport } from "@omnifield/probe-web-ui/passport";

import type { PassportLookup } from "./address.js";

/** Где переменная объявлена: компонент и его часть. */
export interface VariableHome {
  readonly component: string;
  readonly part: string;
  /** Кто её ставит — как объявил паспорт. Читается редактором, механикой не толкуется. */
  readonly setBy: string;
}

/** Имя кастом-свойства с двумя дефисами, в каком бы начертании его ни написали. */
function property(name: string): string {
  return name.startsWith("--") ? name : `--${name}`;
}

/**
 * Переменные, объявленные ОДНОЙ частью компонента.
 *
 * @param passport паспорт компонента
 * @param part имя части
 * @returns имена с двумя дефисами; пусто — часть переменных не объявляла
 */
export function partVariables(passport: ComponentPassport, part: string): Set<string> {
  const declared = passport.parts.find((кандидат) => кандидат.name === part)?.variables ?? [];

  return new Set(declared.map((variable) => property(variable.name)));
}

/**
 * ГДЕ ЖИВЁТ каждая объявленная переменная — по всем названным компонентам.
 *
 * Нужна ровно для одного: отличить «объявлена, но не здесь» от «не объявлена вовсе». Без этого
 * оба случая слились бы в один изъян, и человек, поставивший правило не на ту часть, пошёл бы
 * чинить палитру.
 *
 * ПРЕДЕЛ НАЗВАН: видно только те компоненты, которые названы вызывающим. Переменную компонента,
 * которого нет ни в наряде, ни в скине, механика назовёт необъявленной — и это верный ответ для
 * неё: правило всё равно приедет туда, где эту переменную никто не ставит.
 *
 * ОТСУТСТВИЕ ПАСПОРТА здесь пропускается МОЛЧА, и это решение (`PWEB-95`): предмет этой функции —
 * где живут переменные, а не есть ли у компонента паспорт. Отвечать на «паспорта нет вовсе»
 * обязана не она, а те, кого спрашивают о законности записи: проверка наряда (`look.ts`) и сборка
 * правил (`rules.ts`) — обе называют этот случай `unknown-component`. Молчание здесь законно
 * ровно потому, что там сказано; убери тот ответ — и молчание станет утечкой.
 *
 * @param lookup чем найти паспорт по имени компонента
 * @param components имена компонентов, о которых спрашивают
 */
export function variableHomes(
  lookup: PassportLookup,
  components: Iterable<string>,
): Map<string, VariableHome[]> {
  const homes = new Map<string, VariableHome[]>();

  for (const component of components) {
    const passport = lookup(component);
    if (!passport) continue;

    for (const part of passport.parts) {
      for (const variable of part.variables ?? []) {
        const name = property(variable.name);
        homes.set(name, [
          ...(homes.get(name) ?? []),
          { component, part: part.name, setBy: variable.setBy },
        ]);
      }
    }
  }

  return homes;
}

/** Человеку: где имя объявлено на самом деле. */
export function homesText(homes: readonly VariableHome[]): string {
  return homes.map((home) => `${home.component}.${home.part}`).join(", ");
}
