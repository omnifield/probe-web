// ПЕРЕЧЕНЬ ПОВЕРХНОСТИ ЗОНЫ — единственная роль этого файла.
//
// Ролей было две: перечень и подпуть `@web-core/style/values`. Подпуть снят
// (`PWEB-56`, снятие — отдельной правкой): он заводился как вход БЕЗ реактивной части, а
// реактивной части не стало, и корень совпал с ним имя в имя. Две двери к одному и тому же —
// ровно тот второй источник правды, против которого написано остальное в зоне.
//
// ФАЙЛ ПРИ ЭТОМ ОСТАЛСЯ, и это не инерция. Перечень имён живёт в одном месте, а `src/index.ts`
// берёт его целиком одной строкой `export *`. Слей мы их обратно — сэкономили бы файл и
// потеряли различение: здесь ЧТО зона обещает, там КАК это отдаётся наружу. Второе ещё будет
// меняться (подпути `/generate`, `/base.css` живут своей жизнью), первое меняться не должно.
//
// ЭТО ПОВЕРХНОСТЬ, И ОНА ЗАМЕРЗАЕТ. Что попало сюда, то обещано (`PROBEWEB-4`): каждый
// экспорт замерзает навсегда.
//
// CSS через вход НЕ идёт: манифест объявляет `sideEffects: false`, и импорт-побочка была бы
// выброшена tree-shaking'ом. Стили едут подпутём `/base.css`, порождение — `/generate`.

// СБОРЩИКА ТЕМ ЗДЕСЬ НЕТ (`PWEB-66`, вторым заходом). Были `createTheme`, `buildThemeTokens`,
