/**
 * Откуда у границы власть — и есть ли эта власть вообще.
 *
 * Различать обязательно: «нельзя по норме» и «дальше кончаются наши обещания» — разные вещи,
 * и потребитель поступает с ними по-разному. Первое он обязан не дать нарушить, второе может
 * позволить под свою ответственность.
 */
export type BoundKind =
  /** Выведена из нормы доступности. Нарушение = несоответствие, и узнаёт о нём не тот, кто крутил. */
  | "норма"
  /** Дальше кончаются наши пробы и обещания. Норма тут ни при чём. */
  | "предел поддержки"
  /** Свойство геометрии, а не требование. Числом база его назвать не может. */
  | "практический предел"
  /** Связывающей нормы не существует: любое значение законно. */
  | "границы нет";

export interface AxisBound {
  /**
   * Число в единицах оси. `null` — границы нет ЛИБО база не может назвать её числом
   * (см. `kind`: это разные причины, и путать их нельзя).
   */
  value: number | null;
  kind: BoundKind;
  /**
   * Норма, которая границу СВЯЗЫВАЕТ. Не `null` ровно тогда, когда `kind` = «норма» — это
   * держит проба. Поле структурное, а не текстовое, именно поэтому: предел поддержки,
   * объяснённый через норму в свободном тексте, читается как требование, и его начинают
   * соблюдать как требование.
   */
  norm: string | null;
  /** Почему граница там, где она есть — или почему её нет. Читается потребителем. */
  why: string;
}

export interface Axis {
  /** Токен, который крутит потребитель (без `--`). */
  token: string;
  /** Единица оси: `множитель` для безразмерной, иначе единица длины семени. */
  unit: string;
  floor: AxisBound;
  ceiling: AxisBound;
  /**
   * Непрерывен ли диапазон между границами.
   *
   * `true` означает: «правильных» ступеней у базы НЕТ, законно любое значение, ползунок
   * уместен. Потребитель вправе предложить свои три ступени — но выдавать их за базовые не
   * может, а сегодня ему неоткуда узнать, что базовых не существует.
   */
  continuous: boolean;
}

