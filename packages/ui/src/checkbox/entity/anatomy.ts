// РАНТАЙМ-анатомия чекбокса (`PWEB-114`, разнесено `PWEB-127`) — первого компонента ФОРМЫ, из Ark.
//
// ЗДЕСЬ ТОЛЬКО ЧАСТИ И АДРЕСА — ничего больше, тем же приёмом, что у гармошки
// (`accordion/entity/anatomy.ts`). Полный рантайм-контракт — состояния, ось вариаций,
// `definePassport` — уровнем выше, в `passport.ts`, который берёт `anatomy` отсюда. Срез
// РЕДАКТОРА (`means`, род, группа, вложенность, сборка) — ещё шагом дальше, в
// `playground/index.ts`.
//
// Анатомия здесь НЕ объявляется: она приезжает готовой вместе с компонентом. Физически она живёт
// в `@zag-js/checkbox/anatomy` — подпуть без Solid и без машины состояний, только объявление
// частей; Ark свою `checkboxAnatomy` берёт ОТТУДА ЖЕ. Через `@ark-ui/solid/anatomy` не берём по
// тому же довод, что и у гармошки: у этого подпути есть ветка `solid` с файлом `.jsx`, и читатель
// паспорта без Solid (`packages/assembly`) упал бы на «Unknown file extension .jsx».
//
// Анатомия несёт ЧЕТЫРЕ части — `root · label · control · indicator` — и добавка покрывает их
// РОВНО (проверено: `Object.keys(anatomy.build())`, не документацией пакета — тип-декларация
// внутри `@ark-ui/solid` называет ещё и `group`, для `CheckboxGroup`, но у САМОСТОЯТЕЛЬНОГО
// `@zag-js/checkbox`, откуда анатомия взята физически, этой части нет вовсе; расхождение снято
// чтением рантайма, а не типов). `CheckboxGroup` — отдельный компонент, вне предмета `PWEB-114`
// в любом случае: его паспорт заведётся своим объявлением, когда компонент появится.

import { anatomy as checkboxAnatomy } from "@zag-js/checkbox/anatomy";

/** Части и адреса — взятые, не наши. Ровно четыре, и добавка ниже покрывает их все. */
export const anatomy = checkboxAnatomy;

/** Адреса частей: `attrs` для узла, `selector` для стиля. Считаются один раз — они статичны. */
export const anatomyParts = anatomy.build();
