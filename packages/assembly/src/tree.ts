// МОДЕЛЬ дерева — то, из чего собирают и по чему рисуют.
//
// Перенесена из `packages/web/runtime/renderer/src/types.ts` старого репозитория
// (`egor6-66/capsuleTech`), где форма схемы канонично лежала в `runtime/contract/src/schema.ts`.
// Что снято при переносе и почему — в README, раздел «Что снято».
//
// ## Форма: плоская карта с корнем
//
// Дерево хранится не вложенными объектами, а картой `id → узел` плюс имя корня. Так устроены
// и чужие механики того же предмета (`@json-render/*`, A2UI-стандарт), и наша прежняя, и
// причина у всех одна: редактор адресует узел, а не путь до него. По вложенному объекту
// «выдели узел X» стоит обхода всего дерева, по плоской карте — одного взятия по ключу.
//
// ## Два необязательных поля, и каждое отвечает за своё
//
//   • `parentId` — обратный ход. Редактор ходит по дереву в обе стороны: «чей это узел»,
//     «что можно вложить сюда», «куда переехать при удалении». Без обратной ссылки каждый
//     подъём — обход всей карты;
//   • `meta`    — место для того, что нужно редактору и не нужно отрисовке (свёрнут ли узел
//     в дереве, кем создан, подписи). Отдельное поле, чтобы редакторское не подмешивалось
//     к пропам компонента и не уезжало в разметку.
//
// Третьим полем здесь была `styles` — карта вида, приписанная узлу. Она СНЯТА (`PWEB-27`), и
// причин три, каждой достаточно: адресована идентификатором узла, а не координатой паспорта —
// то есть по определению не скин; плоская карта свойств не может быть рецептом (ни состояний,
// ни вариаций, ни пересечений); приезжала ПРОПОМ, а кит безголовый и такого пропа не имеет.
// Правка отдельного узла тоже станет ПРАВИЛОМ, порождённым тем же генератором, только с
// адресом по идентификатору узла, — а идентификатор теперь виден в разметке (см. `render.tsx`).
//
// ## Узлов ДВА рода, и второй — содержимое (`PWEB-83`)
//
// Содержимое потребителя — подпись кнопки, текст внутри раздела — это УЗЕЛ дерева наравне с
// частью, а не свойство узла. Прежде оно ехало пропом `children`, и отрисовка выражала одно из
// двух: «либо дети, либо текст». Паспорт при этом объявлял и то и другое сразу (`itemTrigger` →
// часть-указатель плюс содержимое рода `text`), правило допуска обе вставки подтверждало — а
// дерево вторую молча теряло. Плюс порядок содержимого относительно частей («подпись, потом
// стрелка») был невыразим в принципе: у пропа места среди детей нет.
//
// Оба изъяна закрываются одним движением — общим списком детей.
//
// ## Форма взята, а не придумана (сверено 2026-08-23)
//
// Слоистые редакторы решают это одинаково: у ProseMirror схема ОБЯЗАНА объявить тип `text`, и
// это inline-лист; у Slate текстовый узел — `{ text: … }`, лист без детей; у Lexical — `TextNode`,
// тоже лист; в DOM текст это отдельный тип узла (`Text`) в общем списке детей элемента. Везде
// одно и то же: текст — УЗЕЛ-лист в том же списке, что и элементы, а значение лежит полем узла.
// Берём эту форму. Расходимся в одном: значение названо РОДОМ (`genus`), а не типом `text`, —
// перечень родов принадлежит паспорту, и механика их не истолковывает (`passport-read.ts`).
//
// Дискриминант — наличие `genus`, как у Slate наличие `text`, а не новое обязательное поле у
// узла компонента. Заведи мы у элемента обязательный признак рода — сломалось бы прямое чтение
// деревьев формы A2UI, ради которого таблица соответствия ниже и держится.
//
// ## Совместимость с A2UI
//
// A2UI (Google) — стандарт формата, не библиотека: рендерера на Solid у него нет, поэтому
// как поставкой воспользоваться нечем, а как ориентиром — обязательно. Обе формы это плоская
// карта с корнем, и соответствие полей прямое: `root` ↔ `components.root`, `elements` ↔
// `components.nodes`, `type`/`props`/`children` — один в один. Наши добавки (`parentId`, `meta`)
// выводимы или необязательны, то есть расхождение не структурное. Таблица соответствия — в README.

import type { Genus } from "./passport-read.js";

/** Устойчивое имя узла в дереве. Уникально в пределах одного дерева. */
export type NodeId = string;

/**
 * Узел КОМПОНЕНТА — то, что рисуется компонентом из реестра.
 *
 * Узел БЕЗ состояния: ни «выделен», ни «только что создан», ни «свёрнут». Это состояние
 * редактора, а не дерева, — окажись оно здесь, две разные сессии редактора начали бы спорить
 * об одном поле, и оно уехало бы в сохранённое дерево вместе с чужим выделением.
 */
export interface AssemblyElement {
  readonly id: NodeId;
  /**
   * Адрес в реестре через точку: `button`, `ui.button`, `accordion.itemTrigger`.
   *
   * Адрес компонента целиком и адрес его корневой части — одно и то же место дерева, и
   * механика их отождествляет (см. `readAddress`).
   */
  readonly type: string;
  /**
   * Во что узел ВСТАВЛЕН — адрес внешнего компонента, если это композиция (`PWEB-33`).
   *
   * «Кнопка, вставленная в триггер всплывающего окна» — один узел с двумя принадлежностями:
   *
   * ```ts
   * { id: "настройки", type: "button", composedInto: "popover.trigger", … }
   * //                 ↑ вид и адрес           ↑ поведение и состояние
   * ```
   *
   * Адрес узла при этом НЕ меняется: он по-прежнему внутренний компонент — тот, чем вещь
   * является визуально (решение о композиции, страница «Паспорт компонента»). Иначе рушится
   * уже принятое, и сохранённые скины перестают попадать в узел.
   *
   * Поле пустует у обычного узла и тогда не значит ничего: путь отрисовки прежний, лишних
   * обёрток нет. Второго способа надеть внешний компонент не заводится — один узел, одна
   * композиция.
   *
   * Триггер — не краевой случай, а обычный способ пользоваться окном, меню, подсказкой и
   * раскрывашкой: без этого поля конструктор страниц не смог бы выразить диалог ВООБЩЕ, и
   * механика, заявленная одной на два применения, отказалась бы от второго.
   */
  readonly composedInto?: string;
  /** Кто владеет узлом. У корня — `null`. */
  readonly parentId: NodeId | null;
  /** Дети по порядку. Порядок значим — массив, а не множество. */
  readonly children: readonly NodeId[];
  /**
   * Пропы компонента — уезжают в него как есть.
   *
   * Содержимого здесь БОЛЬШЕ НЕТ (`PWEB-83`): подпись кнопки — это узел-содержимое среди детей,
   * а не проп `children`. Проп остался бы вторым ответом на тот же вопрос, и отрисовке снова
   * пришлось бы выбирать, какой из двух показать.
   *
   * При композиции пропы уезжают ВНЕШНЕМУ: он рисует узел и передаёт остаток внутреннему сам
   * (так устроена композиция кита). Второго набора пропов под внешний не заводится — узел
   * один, и разделение «эти пропы внешнему, эти внутреннему» пришлось бы держать руками.
   */
  readonly props?: Readonly<Record<string, unknown>>;
  /**
   * Пропы, чьё значение резолвится из данных при отрисовке (`PWEB-156`) — имя пропа → путь.
   *
   * Отдельное поле от `props`: тот остаётся ВСЕГДА литералом, угадывать по форме значения,
   * ссылка это или обычный объектный проп (`style`), не приходится. Резолвится `RenderTree` и
   * добавляется к `props` поверх — побеждает при совпадении имени.
   */
  readonly bind?: Readonly<Record<string, string>>;
  /**
   * Событие узла наружу (`PWEB-157`) — родное DOM-событие → что сказать вызывающему. Форма A2UI
   * (`Action`), узкая копия того же в `packages/skin/src/passport-assembly.ts` — тем же приёмом,
   * что и у `DataBinding`/`DynamicValue` в этом файле.
   */
  readonly on?: Readonly<Record<string, DispatchAction>>;
  /** Редакторское, в отрисовку не вмешивается. */
  readonly meta?: Readonly<Record<string, unknown>>;
}

/** Событие узла наружу — см. `AssemblyElement.on`. */
export interface DispatchAction {
  readonly event: {
    readonly name: string;
    readonly context?: Readonly<Record<string, DynamicValue>>;
  };
}

/** Одно отправленное событие — то, что получает `RenderTree`'s `dispatch` (`PWEB-157`). */
export interface DispatchedEvent {
  /** Имя события — из `action.event.name`, не имя DOM-события. */
  readonly name: string;
  /** Узел, на котором событие произошло. */
  readonly nodeId: NodeId;
  /** Адрес узла в реестре — тот же, что и `AssemblyElement.type`. */
  readonly address: string;
  /** ISO 8601 — когда событие произошло. */
  readonly timestamp: string;
  /** Данные вместе с событием — уже РЕЗОЛВЛЕННЫЕ (`action.event.context`, пути раскрыты). */
  readonly context: Readonly<Record<string, unknown>>;
}

/**
 * Ссылка на значение во ВНЕШНИХ данных — JSON Pointer (RFC 6901), тем же приёмом, что у A2UI
 * (`PWEB-156`, решение изучено и записано в README пакета — не изобретаем свою форму).
 *
 * Данные — не в дереве. Дерево остаётся тем же объявлением структуры, что и раньше; путь просто
 * ОТКЛАДЫВАЕТ значение до момента, когда `RenderTree` получит проп `data` и сможет его разрешить.
 * Без `data` (обычный показ кита, как сегодня) путь просто не резолвится ни во что — резолвится
 * он тем, кто данные принёс, а не тем, кто дерево объявил.
 */
export interface DataBinding {
  readonly path: string;
}

/**
 * Значение содержимого: готовый литерал ЛИБО ссылка на данные, разрешаемая при отрисовке.
 *
 * Форма — из того же словаря A2UI (`DynamicString`), урезанная до одного случая (без `call`,
 * вызова функции, — этот случай в кит не завозится, пока для него нет потребителя). Расширить до
 * `call` можно будет позже добавлением третьего варианта в union — этот код его не запрещает и
 * не предполагает.
 */
export type DynamicValue = string | DataBinding;

/** Ссылка ли это на данные — по наличию `path`, тем же приёмом, что различает содержимое (`isContent`, по наличию `genus`). */
export function isDataBinding(value: DynamicValue): value is DataBinding {
  return typeof value === "object" && value !== null && "path" in value;
}

/**
 * Значение по пути в данных — RFC 6901 JSON Pointer (`/a/b/0`, `~0`→`~`, `~1`→`/`).
 *
 * Не найдено (путь мимо, узел данных не дошёл, индекс вне массива) — `undefined`, а не бросок:
 * решение, что показать вместо, принимает вызывающий (`render.tsx`), не эта функция.
 *
 * @param data объект данных, отданный вызывающим `RenderTree`
 * @param path JSON Pointer; пустая строка указывает на сами данные целиком
 */
export function resolveDataBinding(data: unknown, path: string): unknown {
  if (path === "") return data;
  if (!path.startsWith("/")) return undefined;

  let current: unknown = data;
  for (const raw of path.slice(1).split("/")) {
    const segment = raw.replace(/~1/g, "/").replace(/~0/g, "~");
    if (current === null || current === undefined) return undefined;

    if (Array.isArray(current)) {
      const index = Number(segment);
      current = Number.isInteger(index) ? current[index] : undefined;
    } else if (typeof current === "object") {
      current = (current as Record<string, unknown>)[segment];
    } else {
      return undefined;
    }
  }

  return current;
}

/**
 * Узел СОДЕРЖИМОГО — значение потребителя, названное родом (`PWEB-83`).
 *
 * Место в дереве у него такое же, как у части: он лежит в общем списке детей, значит с частями
 * и сосуществует, и упорядочивается относительно них. Ровно этого не хватало: паспорт объявлял
 * «внутрь кнопки раздела — указатель, текст и значок», а выразить их вместе было нечем.
 *
 * Допустимость проверяется ТЕМ ЖЕ правилом допуска, что и у частей: кандидат
 * `{ kind: "content", genus }` был в паспорте с самого начала (`PWEB-24`) — не хватало только
 * места в дереве.
 */
export interface AssemblyContent {
  readonly id: NodeId;
  /**
   * Род — чем это содержимое является: `text` (подпись), и дальше тем, что объявит паспорт.
   *
   * Механика род не истолковывает и не сравнивает: она передаёт его правилу допуска, а решение
   * принимает правило (`passport-read.ts`). Значка среди родов узла содержимого нет и не будет:
   * значок это КОМПОНЕНТ, он приходит обычным узлом и опознаётся родом своего паспорта.
   */
  readonly genus: Genus;
  /**
   * Значение — то, что видно человеку. У рода `text` это подпись.
   *
   * Названо значением, а не текстом, потому что род называет, ЧЕМ это значение является:
   * заведи паспорт второй не-компонентный род — поле `text` соврало бы о нём, а поле значения
   * останется верным (`value` рядом с `genus`, как `text` рядом с типом `text` у Slate).
   *
   * Литерал ИЛИ ссылка на данные (`DynamicValue`, `PWEB-156`) — второе разрешается `RenderTree`
   * при отрисовке, не здесь: узел остаётся тем же объявлением, что и раньше.
   */
  readonly value: DynamicValue;
  /** Кто владеет узлом. У содержимого владелец есть всегда: корнем дерева оно не бывает. */
  readonly parentId: NodeId | null;
  /**
   * Детей у содержимого нет — оно лист.
   *
   * Тип говорит это прямо, а не примечанием: положить внутрь подписи узел нечем и незачем.
   * Пришедшее извне дерево типами не стережётся, поэтому то же самое отдельно называет
   * проверка целостности (`content-with-children`).
   */
  readonly children: readonly [];
  /** Редакторское, в отрисовку не вмешивается. */
  readonly meta?: Readonly<Record<string, unknown>>;
}

/**
 * Один узел дерева: либо компонент, либо содержимое.
 *
 * Список детей у владельца ОДИН, и в нём лежат оба рода узлов вперемешку — иначе порядок
 * содержимого относительно частей выразить было бы нечем.
 */
export type AssemblyNode = AssemblyElement | AssemblyContent;

/**
 * Содержимое ли это — по наличию рода.
 *
 * Дискриминант наличием поля, а не отдельным признаком у КАЖДОГО узла: так же отличает свои
 * текстовые узлы Slate (`{ text: … }`), и так же не ломается прямое чтение деревьев формы A2UI,
 * где у элемента полей ровно три.
 *
 * @param node узел
 */
export function isContent(node: AssemblyNode): node is AssemblyContent {
  return "genus" in node;
}

/**
 * Адрес, которым узел виден СНАРУЖИ — из своего владельца.
 *
 * У обычного узла это его собственный адрес. У составного — адрес внешнего: место в дереве
 * занимает триггер, а не кнопка, и допустимость этого места владелец проверяет по нему.
 * Внутрь же узел смотрит собственным адресом: содержимое определяет тот, кто рисует, — кнопка
 * пускает внутрь текст и значок независимо от того, во что она вставлена.
 *
 * У узла содержимого адреса нет вовсе — `undefined`: он опознаётся родом, а не адресом, и
 * выдумать ему адрес значило бы завести компонент, которого не существует.
 *
 * @param node узел
 */
export function outerTypeOf(node: AssemblyNode): string | undefined {
  return isContent(node) ? undefined : (node.composedInto ?? node.type);
}

/**
 * Дерево целиком.
 *
 * Обёртка `components` вокруг пары «корень и узлы» перенесена из прежней формы намеренно: по
 * ней сохранённые деревья старого репозитория читаются как есть. Поле `interactions`, которое
 * лежало рядом, снято — см. README.
 */
export interface AssemblyTree {
  readonly components: {
    readonly root: NodeId;
    readonly nodes: Readonly<Record<NodeId, AssemblyNode>>;
    /**
     * Пропы невидимого провайдера, оборачивающего корень (`PWEB-153`) — у компонентов вроде
     * поповера/меню корневая ЧАСТЬ не рисует настоящего DOM-узла сама по себе. Отсутствует у
     * компонентов, чей корень — реальный узел; `RenderTree` читает это поле, чтобы решить, нужна
     * ли обёртка.
     */
    readonly providerProps?: Readonly<Record<string, unknown>>;
  };
}

/**
 * Пустое дерево: корень указывает в никуда, узлов нет — рисуется ничего.
 *
 * Нужно не для красоты, а как цель приведения: потребитель законно отдаёт `undefined` в
 * первый кадр (дерево ещё не пришло), и отрисовка обязана в этот кадр промолчать, а не упасть.
 */
export const EMPTY_TREE: AssemblyTree = { components: { root: "", nodes: {} } };

/**
 * Узел по имени, либо `undefined`.
 *
 * @param tree дерево
 * @param id имя узла
 */
export function nodeOf(tree: AssemblyTree, id: NodeId): AssemblyNode | undefined {
  return tree.components.nodes[id];
}

/**
 * Корневой узел дерева, либо `undefined` — если корень не найден в карте.
 *
 * `undefined` здесь честнее исключения: дерево с недостающим корнем это состояние данных, а
 * не ошибка вызова, и назвать его должна проверка целостности (`checkTree`), а не падение
 * посреди отрисовки.
 *
 * @param tree дерево
 */
export function rootOf(tree: AssemblyTree): AssemblyNode | undefined {
  return tree.components.nodes[tree.components.root];
}

/**
 * Цепочка владельцев узла — от ближайшего к корню.
 *
 * Идёт по `parentId`, а не обходом карты: ради этого поле и перенесено. Оборвётся на узле,
 * которого нет в карте, — и это правильно: сломанную ссылку показывает `checkTree`, а не
 * бесконечный подъём.
 *
 * Защита от кольца обязательна: кольцо `parentId` в сохранённом дереве встречается (правка
 * извне, слияние двух версий), и без учёта пройденного подъём стал бы вечным.
 *
 * @param tree дерево
 * @param id имя узла, чьих владельцев ищем
 */
export function ancestorsOf(tree: AssemblyTree, id: NodeId): AssemblyNode[] {
  const chain: AssemblyNode[] = [];
  const seen = new Set<NodeId>([id]);

  let current = nodeOf(tree, id)?.parentId ?? null;
  while (current !== null && !seen.has(current)) {
    const owner = nodeOf(tree, current);
    if (!owner) break;
    chain.push(owner);
    seen.add(current);
    current = owner.parentId;
  }

  return chain;
}

/**
 * Имена узла и всего, что под ним, — сверху вниз.
 *
 * Нужно правкам: удаление узла уносит поддерево, перенос обязан отказать при попытке
 * положить узел внутрь самого себя.
 *
 * @param tree дерево
 * @param id имя корня поддерева
 */
export function subtreeOf(tree: AssemblyTree, id: NodeId): NodeId[] {
  const collected: NodeId[] = [];
  const seen = new Set<NodeId>();
  const queue: NodeId[] = [id];

  while (queue.length > 0) {
    const current = queue.shift() as NodeId;
    if (seen.has(current)) continue;
    seen.add(current);

    const node = nodeOf(tree, current);
    if (!node) continue;
    collected.push(current);
    queue.push(...node.children);
  }

  return collected;
}
