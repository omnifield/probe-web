import type { Linter } from "eslint";

/**
 * Канон Solid в виде карты правил `eslint-plugin-solid`.
 *
 * Карта выписана ЯВНО, а не взята из `solid.configs["flat/typescript"]`, хотя состав правил
 * оттуда и начинался. Причина не в стиле: пресет наследованием отдал бы уровень диагностик
 * чужому выпуску. Upstream держит `reactivity`, `components-return-once`, `no-react-deps`
 * (и ещё пять) на `warn` — проверено кодом 0.14.5, 2026-08-08. Унаследовав его, мы бы
 * объявляли канон и молча не проверяли его: `eslint` выходит с нулём, пока нет `error`.
 *
 * Отсюда единственная линия пресета: **включено ⇒ `error`**. Правило, из-за которого не
 * стоит ронять сборку, — это не правило, а абзац доки; такому место в `OFF`, а не в `warn`.
 * Промежуточного уровня в пресете нет намеренно, и ручки «понизить» тоже: капсула уже
 * прожила режим `warn` и получила канон, которому верили и который не работал.
 */

/** Уровень всех включённых правил. Один на весь пресет — см. шапку файла. */
const ERROR = "error" as const;

/**
 * Заморозка карты правил с проверкой формы на месте. Дженерик нужен ради контекстного типа:
 * без него запись с настройками (`[ERROR, { … }]`) выводится массивом, а не парой
 * «уровень + опции», и проверку приходилось бы глушить приведением.
 */
const ruleMap = <T extends Linter.RulesRecord>(record: T): Readonly<T> => Object.freeze(record);

/**
 * Четыре несущих правила — они названы в контракте зон (`PROBEWEB-4`) и обязаны быть
 * включены. Вынесены отдельной картой, чтобы «канон» был адресуемым перечнем, а не
 * растворялся среди сопутствующих проверок.
 */
export const canonRules = ruleMap({
  // Чтение реактивного (props/сигнал/мемо) вне отслеживаемой области — изменение
  // потеряется молча. Центральное правило: остальные лишь закрывают частные случаи.
  "solid/reactivity": ERROR,
  // Деструктуризация `props` рвёт связь с источником: реактивность держится на доступе
  // через свойство. Граница правила названа в README — ловится только список параметров.
  "solid/no-destructure": ERROR,
  // Массивы зависимостей у `createEffect`/`createMemo` — перенос привычки из React;
  // в Solid зависимости собираются сами, а массив создаёт ложное впечатление контроля.
  "solid/no-react-deps": ERROR,
  // Ранний `return` в компоненте: тело компонента исполняется ОДИН раз, поэтому условие
  // обязано жить внутри JSX (`<Show />`, фрагмент), а не перед ним.
  "solid/components-return-once": ERROR,
});

/**
 * Сопутствующие правила: те же реактивность и JSX, но частными случаями. Уровень тот же —
 * включено значит `error`.
 */
export const companionRules = ruleMap({
  // Обработчик на нативном элементе не реактивен, как прочие JSX-props: имя вида `onclick`
  // против `onClick` меняет способ привязки. Правило снимает двусмысленность имени.
  "solid/event-handlers": ERROR,
  // Импорт из неверного входа `solid-js` (`solid-js/web`, `solid-js/store`) — рабочая на
  // вид программа с неверным поведением. Автопочинка есть.
  "solid/imports": ERROR,
  // Повтор одного prop в JSX: побеждает последний, остальные молча теряются.
  "solid/jsx-no-duplicate-props": ERROR,
  // Необъявленный компонент в JSX. `typescriptEnabled: true` — проверку имён отдаём
  // компилятору TS, за правилом остаётся то, что TS не видит.
  "solid/jsx-no-undef": [ERROR, { typescriptEnabled: true }],
  // Помечает переменные, использованные ТОЛЬКО в JSX, как использованные — иначе
  // `no-unused-vars` (свой у ESLint или у TS) режет живые компоненты.
  "solid/jsx-uses-vars": ERROR,
  // `javascript:`-URL в JSX — исполнение строки как кода.
  "solid/jsx-no-script-url": ERROR,
  // `innerHTML` — вставка непроверенной разметки; в Solid для этого есть явные средства.
  "solid/no-innerhtml": ERROR,
  // `className`/`htmlFor` — React-props, помеченные устаревшими ещё в Solid v1.4.0.
  "solid/no-react-specific-props": ERROR,
  // `.map()` в JSX вместо `<For />`: `map` пересоздаёт узлы целиком, `For` держит их по
  // ссылке на элемент. Разница не стилистическая, а в том, что происходит с DOM.
  "solid/prefer-for": ERROR,
  // `style` строкой вместо объекта и kebab-case свойства — Solid ставит их через
  // `style.setProperty`, и форма записи меняет результат.
  "solid/style-prop": ERROR,
  // Пустой элемент без самозакрытия. Единственное здесь стилистическое правило; держим
  // его `error`, потому что оно чинится `--fix` целиком и не требует решения человека.
  "solid/self-closing-comp": ERROR,
});

/**
 * Правила, выключенные ОСОЗНАННО. Список существует, чтобы «не включено» отличалось от
 * «не рассмотрено»: тест сверяет, что каждое правило плагина попало ровно в одну из трёх
 * карт, и падает, когда выпуск плагина приносит новое.
 */
export const offRules = ruleMap({
  // Пространства имён (`use:`, `prop:`, `attr:`) в TS проверяет компилятор — правило
  // дублировало бы его и ошибалось на директивах потребителя.
  "solid/no-unknown-namespaces": "off",
  // Запрет инлайновых обработчиков-массивов (`onClick={[fn, arg]}`) — это рабочая форма
  // Solid, а не дефект; выключено и у upstream.
  "solid/no-array-handlers": "off",
  // Требование `<Show />` вместо `&&`: обе формы каноничны, выбор за автором.
  "solid/prefer-show": "off",
  // Запрет proxy-API нужен только тем, кто целится в окружения без Proxy. Не наш случай.
  "solid/no-proxy-apis": "off",
  // `classlist` помечен устаревшим в самом Solid — правило зовёт в обратную сторону.
  "solid/prefer-classlist": "off",
});

/**
 * Полная карта пресета: канон + сопутствующие + явные выключения. Отдаётся наружу, чтобы
 * потребитель мог собрать СВОЙ конфиг вокруг того же канона, не воспроизводя его руками.
 */
export const rules = ruleMap({
  ...canonRules,
  ...companionRules,
  ...offRules,
});
