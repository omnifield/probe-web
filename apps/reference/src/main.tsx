// Точка входа. Повторяет скелет потребителя (`packages/starter/template/main.tsx`) буква в
// букву по СОСТАВУ вызовов: те же два CSS-подпутя, тот же `mount`. Это не совпадение и не
// вкус — скелет едет к потребителю классом `placed-once` и больше не обновляется, поэтому
// ровно эта форма обязана быть проверена сборкой здесь, а не у него.
//
// Два CSS-подпутя, и это не дубль: `base.css` не держит ни одного литерального цвета (его
// инвариант), значения приходят темой. Один `base.css` дал бы страницу без цветов — браузер
// молча отбросил бы неразрешённые `var()`.
import "@omnifield/probe-web-style/base.css";
import "@omnifield/probe-web-style/themes.css";
// Третьей строкой — оформление ПОТРЕБИТЕЛЯ: кит безголовый, и без этого файла страница
// поднимется, но останется неодетой. У потребителя это место его собственного CSS.
import "./app.css";

import { mount } from "@omnifield/probe-web-runtime";

import { App } from "./app";

// Точку монтирования рантайм ищет сам — `#root` из `index.html`. В сигнатуре её нет, и
// приложение о ней не знает: знает только разметка.
mount(() => <App />);
