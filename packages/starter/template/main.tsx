// Точка входа скелета. Замерзает не файл, а ПОВЕРХНОСТЬ, которую он трогает: mount() и проверка
// порядка из рантайма, одна пара из стилевого слоя, один примитив из ui и один CSS-подпуть.
// Больше отсюда не зовут ничего — каждая лишняя строка застынет у потребителя навсегда, а обвес
// сюда уже не заглянет.

// ─── ПОРЯДОК ПОДКЛЮЧЕНИЯ. Он не декоративный ────────────────────────────────────────────────
//
//   1. базовый слой набора значений — ТОЛЬКО СБРОС: снятие решений браузера, ни одного
//      значения и ни одного запасного варианта. Он же предъявляет своё прибытие — по паре
//      «свойство и ожидаемое значение», которую спрашивает проверка в конце файла;
//   2. скин — вид целиком, и он твой. Необязателен. Значения (размеры, цвета, шрифты)
//      приезжают вместе с ним: второго пути, через общий лист, больше нет.
//
// Скин, подключённый ПЕРЕД базой, проигрывает ей в каскаде: получится вид, посчитанный от
// умолчаний, — «скин почти работает», а это хуже явной поломки, потому что чинить такое никто
// не идёт. Ровно этот случай ловит checkStyleOrder() в конце файла.

// ═══ НАБОР ЗНАЧЕНИЙ: ПОСТАВЩИК, А НЕ ФУНДАМЕНТ ══════════════════════════════════════════════
//
// Ступень 1 даёт ПОСТАВЩИК значений, и наш набор — один из них, а не основание приложения.
// Здесь он стоит умолчанием ровно потому, что приезжает зависимостью скелета: набором значений
// вправе быть чужой, и приложение на нём — исправное приложение, а не урезанное.
//
// ЧУЖОЙ НАБОР — законный путь, и вот он целиком: две строки ниже снимаются ВМЕСТЕ (побочка и
// строка имени), на их место встаёт файл твоего поставщика, а в конце файла проверка порядка
// получает маркерную пару этого поставщика либо снимается — там сказано, когда что.
//
// BASE_MARKER — ПАРА «свойство и его ожидаемое значение», а не имя. Приезжает она одним
// экспортом, и это не оформление: свойство без значения — проверка, которая врёт ЗЕЛЁНЫМ.
// Половины у пары не выковырять, поэтому и импорт один.
//
// Снять блок наполовину не выйдет МОЛЧА: BASE_MARKER приедет ниоткуда — `tsc` назовёт
// оставшуюся строку (TS2304), а собранное приложение упадёт на ней сразу. Именно упадёт:
// `vite build` типов не смотрит и такое соберёт. Громкий отказ на первом же запуске — то, чем
// этот блок отличается от тихого ложного крика в консоли исправного приложения.
import "@omnifield/probe-web-style/base.css";
import { BASE_MARKER } from "@omnifield/probe-web-style";
// import "<твой-набор-значений>/base.css";                  // 1 вместо нашего набора
// import "<твой-поставщик-оформлений>/skin.css";            // 2 — открой, когда скин появится

// ═══ ЦВЕТА У ПРИЛОЖЕНИЯ БЕЗ СКИНА НЕТ, И ЭТО НЕ ПОЛОМКА ═════════════════════════════════════
//
// Вид приходит СКИНОМ и больше ниоткуда: ни из базового слоя, ни из типографики документа, ни
// из умолчаний фреймворка. Скин — единица: переменные и правила вида вместе. Половин у него не
// бывает, поэтому надеваемого набора цветов «по умолчанию» поставка не везёт вовсе — футболку
// красят после того, как сшили.
//
// Отсюда два следствия, и оба видны прямо здесь:
//
//   • РЕЖИМ (светлая/тёмная пара) — половина скина, а не свойство документа. Нет скина — нет и
//     режима: ставить его на голое приложение некуда, и поэтому скелет не зовёт восстановление
//     режима до первого кадра. Вспышке светлой темы перед тёмной взяться неоткуда — вида нет
//     вовсе. Голая страница остаётся на умолчаниях браузера: он рисует своё, ровно как рисовал
//     бы без нас;
//   • ЗНАЧЕНИЙ ТОЖЕ НЕТ — ни цветовых ролей, ни размерных шкал: они уехали в скин целиком, и
//     общий лист их больше не печатает. Опираться в своём CSS не на что, пока скин не надет,
//     и блок оформления в index.html поэтому написан своими значениями.
//
// Надел скин — режим и вид приезжают вместе с ним, механикой из рантайма. Ставить их отсюда
// нечем: имя скина у тебя своё, а литерал чужого имени в этом файле замёрз бы навсегда.

import { checkStyleOrder, mount } from "@omnifield/probe-web-runtime";
import { Button } from "@omnifield/probe-web-ui";

// Кит безголовый: класса по умолчанию у кнопки нет, внешний вид целиком твой. Эту кнопку
// одевает блок <style> в index.html — через зацепку data-slot и размерные шкалы; там же
// сказано, как перенести оформление в свой файл.
//
// Второй путь — createStyle из инструментов стилизации, для класса, зависящего от состояния. В
// скелете он не показан намеренно: вызов заморозил бы у тебя ещё одну точку поверхности ради
// примера, а инструменты — отдельная необязательная поставка, и брать их ты не обязан.
function App() {
  return <Button>hello, web</Button>;
}

mount(() => <App />);

// ─── ПРОВЕРКА ПОРЯДКА ПОДКЛЮЧЕНИЯ ────────────────────────────────────────────────────────────
//
// Она спрашивает документ, стоит ли на корне то, что обязано приехать с базой подключённого
// набора значений, — и потому стоит ПОСЛЕ монтирования: ей нужны вычисленные стили, рано звать
// её бессмысленно.
//
// СПРАШИВАЕТ ПАРОЙ: свойство И его ожидаемое значение. Одного свойства мало — то, чем база
// предъявляет себя, у документа есть всегда, просто с браузерным умолчанием. Проверка на
// «свойство объявлено» была бы истинной ВСЕГДА и врала бы зелёным ровно там, где всё сломано.
//
// ЭТА СТРОКА — ХВОСТ БЛОКА «НАБОР ЗНАЧЕНИЙ», А НЕ ОБЩАЯ ДИАГНОСТИКА. Она спрашивает про базу
// ТОГО набора, чью пару ей передали: наш отдаёт свою экспортом BASE_MARKER, потому строка и
// стоит здесь умолчанием. Проверка сама ничьих пар не знает — что передали, про то и спросит.
//
// ВЗЯЛ ЗНАЧЕНИЯ НА СТОРОНЕ — решай здесь, и решение ровно одно из двух:
//   • у твоего поставщика есть, чем предъявить приезд базы, — назови его пару вместо
//     BASE_MARKER, и проверка продолжит ловить тот же дефект на его наборе;
//   • предъявить нечем — сними строку целиком. Спрашивать станет нечего, и оставленная
//     проверка кричала бы «базы нет» на исправном приложении — то самое ложное предупреждение,
//     ради которого этот блок и разведён с остальным скелетом.
// Забыть про строку, сняв блок выше, не получится: наш маркер приедет ниоткуда, и приложение
// откажет громко — а не соврёт тихо.
//
// ПОКА БАЗА ПОДКЛЮЧЕНА, ПРОВЕРКА НУЖНА, и выбрасывать её не за что: скин, вставший без базы,
// даёт вид, посчитанный от умолчаний, — «скин почти работает», а это хуже явной поломки.
// Ничего не роняет и ничего не красит: кричит в консоль и отдаёт разбор значением. Не нужна в
// проде — сними строку, приложение не изменится ни на пиксель.
checkStyleOrder({ marker: BASE_MARKER });
