// ТЕКУЧИЙ РАЗМЕР (`PWEB-80`): полюса объявляет палитра, выражение печатает механика.
//
// Здесь проверяется ЗАПИСЬ и ТЕКСТ: что выражение выводится из полюсов однозначно, что отказы
// названы, и что отчёт есть там, где отказывать не по чему. Живой вид — что значение и правда
// меняется с шириной окна и что посадка на сетку это переживает — проверяется настоящим браузером
// в эталоне: `jsdom` ни `vw`, ни `round()` не считает.

import { describe, expect, it } from "vitest";

import { generateSkinCss } from "../src/generate.js";
import {
  assemble,
  fluidExpression,
  fluidPoles,
  fluidRefusals,
  isFluid,
  type FluidSeed,
} from "../src/index.js";
import { lookup } from "./passports.js";
import { синяя, наряд, части } from "./looks.js";

/** Полюса интервалов: те же, что автор писал руками до `PWEB-80`. */
const интервал: FluidSeed = { narrow: "0.375rem", wide: "0.5rem", between: ["366px", "1200px"] };

describe("выражение ВЫВОДИТСЯ из полюсов, а не пишется руками", () => {
  it("наклон и свободный член посчитаны, а не выведены человеком", () => {
    // Сверено с тем, что автор считал руками: `clamp(0.375rem, 0.32rem + 0.24vw, 0.5rem)`.
    // Механика даёт те же числа с большей точностью — и, главное, даёт их САМА: ошибиться в
    // знаке наклона в записи полюсов попросту негде.
    expect(fluidExpression(интервал)).toBe("clamp(0.375rem, 0.3201rem + 0.2398vw, 0.5rem)");
  });

  it("запись читается обратно: видно, на каких ширинах значения согласованы", () => {
    // Вторая половина требования. По рукописному `clamp` диапазон ширин не восстановить вовсе —
    // а значит второй автор напишет свои `vw` от других полюсов, и в одном наряде окажутся две
    // разные сетки.
    expect(интервал.between).toEqual(["366px", "1200px"]);
    expect(isFluid(интервал)).toBe(true);
    expect(isFluid("0.5rem")).toBe(false);
  });

  it("зажим стоит краями наружу: между полюсами растёт, за ними — стоит", () => {
    const выражение = fluidExpression(интервал);

    expect(выражение.startsWith(`clamp(${интервал.narrow},`)).toBe(true);
    expect(выражение.endsWith(`${интервал.wide})`)).toBe(true);
  });
});

describe("отказы — там, где есть чем отказывать", () => {
  it("невозрастающая пара отвергается: это арифметика, а не вкус", () => {
    const [refusal] = fluidRefusals("space", { ...интервал, narrow: "0.5rem", wide: "0.375rem" });

    expect(refusal?.means).toContain("убывает");
  });

  it("невозрастающие ширины отвергаются: делить не на что", () => {
    const [refusal] = fluidRefusals("space", { ...интервал, between: ["1200px", "366px"] });

    expect(refusal?.means).toContain("не возрастают");
  });

  it("НОРМАТИВНЫЙ ПОЛ на узком полюсе: высота контрола", () => {
    // Пол взят из `AXES` вместе с причиной и ссылкой на критерий, а не переписан числом: там же
    // сказано, почему он именно такой и почему он подвижен.
    const [refusal] = fluidRefusals("control-height", {
      narrow: "1.5rem",
      wide: "2.5rem",
      between: ["366px", "1200px"],
    });

    expect(refusal?.means).toContain("1.875");
    expect(refusal?.means).toContain("2.5.8");
  });

  it("вторая ось с нормативным полом — плотность — текучей быть не может вовсе", () => {
    // Пол у неё есть (0.75, та же норма), но проверить его на текучем значении не на чем:
    // `vw` — длина, а плотность множитель, и `calc(0.9 + 0.05vw)` недействителен. Отвергается
    // раньше и по другой причине — невыразимости, а не нарушения нормы.
    const [refusal] = fluidRefusals("density", { narrow: "0.9", wide: "1", between: ["366px", "1200px"] });

    expect(refusal?.means).toContain("текучей быть не может");
    expect(refusal?.means).toContain("множитель");
  });

  it("единица полюса обязана быть единицей СВОЕЙ оси", () => {
    const [refusal] = fluidRefusals("space", { ...интервал, narrow: "6px" });

    expect(refusal?.means).toContain("измеряется в «rem»");
  });

  it("ширины объявляются в пикселях — ширина окна величина пиксельная", () => {
    const [refusal] = fluidRefusals("space", { ...интервал, between: ["20rem", "75rem"] });

    expect(refusal?.means).toContain("в пикселях");
  });
});

describe("КЕГЕЛЬ НЕ ОТВЕРГАЕТСЯ — вместо отказа отчёт", () => {
  /** Мелкий кегель: одиннадцать пикселей на узком полюсе. */
  const мелкий: FluidSeed = { narrow: "0.6875rem", wide: "1rem", between: ["366px", "1200px"] };

  it("отказа НЕТ: минимального размера текста у нормы не существует", () => {
    // У оси `font-size` пола нет, и это измеренный факт зоны значений, а не пробел. Назначить
    // порог самим значило бы решить за автора, каким должен быть вид, — этого фреймворк не делает.
    expect(fluidRefusals("font-size", мелкий)).toEqual([]);
  });

  it("но ЧИСЛО есть, и в пикселях: одиннадцать автор видит при записи", () => {
    // «0.6875rem» человеку не говорит ничего, «11 px» говорит сразу. Механика сообщает, а не
    // запрещает — то же правило, что для читаемости.
    const отчёт = fluidPoles("font-size", мелкий);

    expect(отчёт?.narrow.px).toBe(11);
    expect(отчёт?.wide.px).toBe(16);
  });

  it("отчёт доезжает до сборки — там его и увидит человек", () => {
    const текучая = { ...синяя, name: "текучая", dimensions: { ...синяя.dimensions, "font-size": мелкий } };
    const { report } = assemble(
      { ...наряд, palette: "текучая" },
      { ...части, palettes: [...части.palettes, текучая] },
    );

    expect(report.fluid.map((строка) => строка.seed)).toEqual(["font-size"]);
    expect(report.fluid[0]?.narrow.px).toBe(11);
  });

  it("палитра без полюсов отчёта не рождает: постоянное значение — её право", () => {
    // Умолчаний не заводим: не объявила полюсов — осталась при постоянном значении, и это не
    // пробел, а выбор.
    expect(assemble(наряд, части).report.fluid).toEqual([]);
  });
});

describe("текучесть НЕ ломает плотность и посадку на сетку", () => {
  const текучая = { ...синяя, name: "текучая", dimensions: { ...синяя.dimensions, space: интервал } };
  const css = generateSkinCss(
    assemble({ ...наряд, palette: "текучая" }, { ...части, palettes: [...части.palettes, текучая] }).skin,
    lookup,
  );

  it("семя стало выражением, а ступени этого не заметили", () => {
    // Текучесть входит ТРЕТЬИМ множителем в уже существующее выражение, а не заменяет его:
    // ступень по-прежнему множит семя на свой коэффициент и на плотность.
    expect(css).toContain(`--space: ${fluidExpression(интервал)};`);
    expect(css).toContain("--space-3: calc(var(--space) * 3 * var(--density));");
  });

  it("посадка на сетку осталась и стоит ПОВЕРХ текучего значения", () => {
    expect(css).toContain(
      "--space-3: round(nearest, calc(var(--space) * 3 * var(--density)), 0.25rem);",
    );
  });
});
