// РЕЕСТР — то, из чего собирают дерево: чем узел рисуется и что о нём объявлено.
//
// ## Реестр складывается из ПАР ПОСТАВЩИКА, а не из перечня, переписанного потребителем
//
// Поставщик отдаёт компонент ПАРОЙ: паспорт вместе с тем, чем рисуется каждая его часть
// (`PWEB-84` на стороне кита, `PWEB-85` здесь). Механика складывает эти пары по адресам и
// больше ничего о составе компонента не знает.
//
// Прежде входов было два — отдельно карта компонентов, отдельно паспорта, — и собирал их
// ПОТРЕБИТЕЛЬ. Собрать такую карту у себя может каждый за три строки, и именно поэтому её не
// должен собирать никто, кроме поставщика: двадцать потребителей напишут двадцать карт, ни одну
// из которых никто не сверит с анатомией. Добавит поставщик шестую часть — она молча останется
// неодетой у всех сразу.
//
// Отсюда же ушёл и второй изъян той формы: адреса частей потребитель складывал вложенной картой
// (`{ accordion: { item, itemTrigger } }`), и корень компонента оказывался адресуемым дважды —
// голым именем и веткой, лежащей по тому же ключу. Теперь адрес один (см. ниже).
//
// ## Кита здесь нет и не будет
//
// Механика знает ФОРМУ пары, а не её поставщика: кит стоит в `devDependencies` и в поставку не
// едет. Приедет второй поставщик компонентов — сложится ровно так же, без единой правки здесь.
//
// ## Адрес компонента и адрес его корневой части — ОДНО место, и запись у него одна
//
// `button` и `button.root` указывают на один и тот же узел дерева: узел компонента И ЕСТЬ его
// корневая часть. `readAddress` приводит обе записи к одной (`address: "button"`), а разрешение
// компонента идёт по РАЗОБРАННОЙ части (`parts[passport.root]`), а не по строке адреса. Двух
// способов достать корень не существует — иначе у одного узла было бы два источника правды об
// адресе, и сохранённые деревья разъехались бы по способу записи.

import type {
  Admission,
  AdmissionRule,
  ReadablePart,
  ReadablePassport,
} from "./passport-read.js";

/**
 * Компонент глазами механики: что он о себе объявил и чем рисуется каждая его часть.
 *
 * Узкая запись пары поставщика — ровно как `ReadablePassport` узкая запись паспорта. Ключи
 * `parts` — части анатомии; что именно по ним лежит, решает поставщик, а механика проверяет
 * только одно: это можно позвать.
 */
export interface ReadableComponent {
  /** Что компонент объявил о себе. */
  readonly passport: ReadablePassport;
  /**
   * Чем рисуется каждая часть: имя части анатомии → компонент.
   *
   * Значения `unknown` намеренно: компоненты поставщика обобщены по своему элементу, и узкая
   * подпись отвергла бы половину карты. Что лежит по ключу — дело поставщика; механика зовёт
   * только то, что оказалось функцией, а остальное называет изъяном (`checkRegistry`).
   */
  readonly parts: Readonly<Record<string, unknown>>;
  /**
   * Вспомогательные компоненты кита — БЕЗ адреса анатомии (`PWEB-152`): скрытый `<input>`
   * чекбокса/радиогруппы и подобные — реальные, но не адресованные Ark'ом узлы, без которых
   * поставленный клиенту компонент не работает. Отдельная карта, а не примесь к `parts`: ключи
   * `parts` сверяются с анатомией (`checkRegistry`), ключи extras — по построению вне неё, сверять
   * их с тем же перечнем значило бы отвергать их же как «часть, которой нет в анатомии».
   */
  readonly extras?: Readonly<Record<string, unknown>>;
  /**
   * Невидимый провайдер, оборачивающий корень (`PWEB-153`): у компонентов вроде поповера/меню
   * корневая ЧАСТЬ (`positioner`) не рисует настоящего DOM-узла сама по себе — состояние ей даёт
   * контекст, который раздаёт этот провайдер. Отсутствует у компонентов, чей корень — реальный узел.
   */
  readonly provider?: unknown;
}

/**
 * Реестр: пары поставщика по адресам плюс правило, по которому читается объявленное.
 *
 * Пары индексируются АДРЕСОМ, а не именем из паспорта. Имя (`data-scope`) у кнопки — `button`,
 * а лежать в реестре она может по адресу `ui.button`: пространство имён — дело того, кто реестр
 * складывает. Индекс по адресу снимает догадку «где же она лежит»; совпадение имени с адресом —
 * частный случай, а не правило.
 *
 * Правило допуска приезжает оттуда же, откуда паспорта, и по той же причине: оно принадлежит
 * форме паспорта, а не читателю (см. `passport-read.ts`).
 */
export interface Registry {
  /** Пары поставщика по адресу компонента. */
  readonly components: Readonly<Record<string, ReadableComponent>>;
  /**
   * Пускает ли часть внутрь себя кандидата. Метод, а не поле-функция, — причина в
   * `passport-read.ts`, `AdmissionRule`.
   */
  admits(part: ReadablePart, candidate: Admission): boolean;
}

/**
 * Разобранный адрес узла: какой компонент и какая его часть.
 *
 * `part` здесь всегда назван, даже когда в адресе его не было: узел компонента — это его
 * корневая часть, и дальше по коду частный случай «адрес без части» больше не всплывает.
 */
export interface Address {
  /** Адрес компонента в реестре — то, чем он проиндексирован. */
  readonly component: string;
  /** Паспорт этого компонента. */
  readonly passport: ReadablePassport;
  /** Имя части (или, при `kind: "extra"`, имя в карте `extras` — без ведущей `~`). */
  readonly part: string;
  /** Нормализованный адрес части: `<component>.<part>` либо сам `component` для корня. */
  readonly address: string;
  /**
   * Откуда доставать компонент — `parts` (часть анатомии, обычный случай) или `extras`
   * (вспомогательный компонент кита без адреса анатомии, `PWEB-152`). Корень компонента целиком
   * всегда `"part"`: у extras нет своего адреса, они не могут быть корнем.
   */
  readonly kind: "part" | "extra";
}

/** Из чего собирается реестр: пары поставщика и правило допуска. Механика не сочиняет ни одной. */
export interface RegistrySpec extends AdmissionRule {
  /** Пары «паспорт и части» по адресу компонента. */
  readonly components: Readonly<Record<string, ReadableComponent>>;
}

/**
 * Собирает реестр из пар поставщика и правила допуска.
 *
 * Функция намеренно тонкая: она ничего не выводит и ничем не дополняет входы. Появись здесь
 * хоть одно «а если паспорта нет, возьмём…» — механика начала бы сочинять правила вместо тех,
 * что объявлены, и первым же следствием стал бы редактор, разрешающий вложить недопустимое.
 *
 * Пробелы ВНУТРИ пары она не чинит и не бросает: расхождение карты с анатомией — это ЗНАЧЕНИЕ,
 * и называет его `checkRegistry`. Бросок там гасил бы весь редактор из-за одной незаполненной
 * части, а редактор обязан показать человеку, чего именно не хватает.
 *
 * А вот значение, которое парой НЕ ЯВЛЯЕТСЯ, — отказ собрать реестр, и здесь бросок на месте:
 * дальше ни один вопрос к такому реестру не имеет ответа, а падение случилось бы посреди
 * отрисовки, где его съест граница ошибок узла и человек увидит пустое место. Тем же приёмом
 * и по той же причине отвергает несобранную карту поставщик (`defineKitComponent` в ките).
 *
 * @param spec пары поставщика и правило допуска
 */
export function createRegistry(spec: RegistrySpec): Registry {
  for (const [address, entry] of Object.entries(spec.components)) {
    const pair = entry as Partial<ReadableComponent> | undefined;
    const passport = pair?.passport as Partial<ReadablePassport> | undefined;

    if (!passport || typeof passport.anatomy?.keys !== "function" || !pair?.parts) {
      throw new Error(
        `по адресу «${address}» лежит не пара «паспорт и части»: реестр складывается из того, ` +
          `что отдаёт поставщик (например, kitOf("button")), а не из карты компонентов`,
      );
    }
  }

  return {
    components: spec.components,
    admits: (part, candidate) => spec.admits(part, candidate),
  };
}

/**
 * Разбирает адрес узла в пару «компонент и часть», либо `undefined` — если такого компонента
 * реестр не знает.
 *
 * Разбор идёт СПРАВА: сначала пробуем весь адрес как компонент, потом отрезаем последний
 * сегмент и пробуем остаток. Именно в таком порядке, потому что пространство имён произвольной
 * глубины (`ui.forms.button`) неотличимо от части по одному лишь виду адреса — отличить их
 * может только паспорт.
 *
 * Части у анатомии плоские (`itemTrigger`, а не `item.trigger`), поэтому отрезается ровно один
 * сегмент. Адрес с двумя неизвестными хвостами — не «часть части», а неизвестный адрес.
 *
 * @param registry реестр
 * @param address адрес узла: `button`, `ui.button`, `accordion.itemTrigger`
 */
export function readAddress(registry: Registry, address: string): Address | undefined {
  if (!address) return undefined;

  const whole = registry.components[address];
  if (whole) {
    return {
      component: address,
      passport: whole.passport,
      part: whole.passport.root,
      address,
      kind: "part",
    };
  }

  const cut = address.lastIndexOf(".");
  if (cut <= 0) return undefined;

  const component = address.slice(0, cut);
  const segment = address.slice(cut + 1);
  const supplied = registry.components[component];
  if (!supplied) return undefined;

  const passport = supplied.passport;

  // Отдельный неймспейс для extras — та же тильда, что ставит `baseAssemblyOf` (`PWEB-152`):
  // часть с таким именем анатомия не заведёт никогда, коллизия исключена структурно.
  if (segment.startsWith("~")) {
    const extra = segment.slice(1);
    if (!supplied.extras || !Object.hasOwn(supplied.extras, extra)) return undefined;

    return { component, passport, part: extra, address, kind: "extra" };
  }

  // Часть, которой нет в анатомии, — не адрес, а опечатка. Молчаливое «ну пусть будет» здесь
  // означало бы узел, который отрисовка не найдёт, а проверка вложенности сочтёт законным.
  if (!passport.anatomy.keys().includes(segment)) return undefined;

  // Корневая часть, названная явно, — тот же узел, что компонент целиком. Приводим к одному
  // виду сразу, чтобы дальше по коду двух записей одного места не существовало.
  if (segment === passport.root) {
    return { component, passport, part: segment, address: component, kind: "part" };
  }

  return { component, passport, part: segment, address, kind: "part" };
}

/**
 * Компонент по адресу узла, либо `undefined`.
 *
 * Берётся ПО РАЗОБРАННОЙ части, а не по строке адреса: корень достаётся тем же ходом, что и
 * любая другая часть (`parts[passport.root]`), поэтому второго пути к нему не существует.
 *
 * Проверка «функция ли это» — не придирка типов: по части может лежать что угодно, а позвать
 * можно только функцию. Такой узел получает явный запасной вид, как и узел с несуществующим
 * адресом, — исход один, и путь к нему один. Назвать пробел ИМЕНЕМ (а не показать пустое место)
 * — работа `checkRegistry`.
 *
 * @param registry реестр
 * @param address адрес узла
 */
export function resolveComponent(registry: Registry, address: string): unknown {
  const read = readAddress(registry, address);
  if (!read) return undefined;

  const supplied = registry.components[read.component];
  const found = read.kind === "extra" ? supplied?.extras?.[read.part] : supplied?.parts[read.part];
  return typeof found === "function" ? found : undefined;
}

/**
 * Адреса компонентов, которые реестр знает.
 *
 * Перечень для того, кто предлагает выбор, — редактора. Что он с ним сделает и как покажет,
 * механику не касается: она отвечает на «откуда берётся перечень допустимого», а не на «что
 * из него выбрать».
 *
 * @param registry реестр
 */
export function knownComponents(registry: Registry): string[] {
  return Object.keys(registry.components).sort();
}

/**
 * Имя изъяна ПАРЫ — расхождения паспорта и карты частей:
 *
 *  • `part-uncharted`    — часть объявлена анатомией, а компонента для неё в карте нет: узел
 *                           такой части нарисовать нечем;
 *  • `part-not-callable` — по части лежит не функция: позвать нечего, и отрисовка молча отдаст
 *                           запасной вид — то есть часть окажется неодетой так же, как если бы
 *                           её в карте не было;
 *  • `part-astray`       — в карте есть часть, которой нет в анатомии: она не адресуема ничем,
 *                           и тот, кто увидел её в карте, будет искать в паспорте то, чего там
 *                           никогда не было.
 */
export type RegistryFlawName = "part-uncharted" | "part-not-callable" | "part-astray";

/** Один изъян пары: имя, чей компонент, какая часть и что это значит человеку. */
export interface RegistryFlaw {
  readonly flaw: RegistryFlawName;
  /** Адрес компонента в реестре. */
  readonly component: string;
  /** Часть, о которой речь. */
  readonly part: string;
  /** Что это значит человеку и редактору. */
  readonly means: string;
}

/**
 * Ищет расхождения паспорта и карты частей. Пустой ответ — пары сложились целиком.
 *
 * Поставщик, сверяющий ключи у себя, сюда ничего не принесёт — и это норма, а не повод убрать
 * проверку: сверку делает ТОТ поставщик, который её написал (кит — `defineKitComponent`), а
 * форма пары открыта любому. Приедет пара, собранная без сверки, — молчать о ней нельзя:
 * неодетая часть выглядит как пустое место в предпросмотре, и человек пойдёт чинить вёрстку.
 *
 * Значение, а не бросок: изъян одной части не должен гасить редактор целиком, а показать его
 * человеку обязан тот, кто редактор рисует. Тем же приёмом названы изъяны дерева (`checkTree`).
 *
 * @param registry реестр
 * @returns все изъяны сразу — чинить их по одному за проход значит столько же проходов
 */
export function checkRegistry(registry: Registry): RegistryFlaw[] {
  const flaws: RegistryFlaw[] = [];

  for (const [component, supplied] of Object.entries(registry.components)) {
    const declared = supplied.passport.anatomy.keys();

    for (const part of declared) {
      if (!Object.hasOwn(supplied.parts, part)) {
        flaws.push({
          flaw: "part-uncharted",
          component,
          part,
          means: `часть «${part}» объявлена анатомией «${supplied.passport.component}», но чем её рисовать — не названо`,
        });
        continue;
      }

      if (typeof supplied.parts[part] !== "function") {
        flaws.push({
          flaw: "part-not-callable",
          component,
          part,
          means: `часть «${part}» компонента «${supplied.passport.component}» названа не компонентом — позвать её нечем`,
        });
      }
    }

    for (const part of Object.keys(supplied.parts)) {
      if (declared.includes(part)) continue;
      flaws.push({
        flaw: "part-astray",
        component,
        part,
        means: `в карте «${supplied.passport.component}» есть часть «${part}», которой нет в анатомии — адресовать её нечем`,
      });
    }
  }

  return flaws;
}
