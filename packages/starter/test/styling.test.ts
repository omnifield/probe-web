// ОФОРМЛЕНИЕ БЕЗГОЛОВОГО КИТА. Решение user 2026-08-08: `@omnifield/probe-web-ui` не везёт
// ни одного класса по умолчанию, внешний вид целиком за потребителем. Значит скелет, который
// рендерит примитив, обязан показать, ЧЕМ за него цепляться, — иначе первое, что видит чужая
// команда, это неоформленная кнопка и никакой подсказки, с какой стороны к ней подойти.
//
// ЦВЕТА В ПРИМЕРЕ НЕТ, И ЭТО ПРОВЕРЯЕТСЯ. Цвет приходит скином — единицей из переменных и
// правил вида, — а скина у скелета нет: надеваемого набора цветов поставка больше не везёт.
// Цветовые роли до надетого скина ПУСТЫ, и правило, опирающееся на них, дало бы у потребителя
// не «почти правильный вид», а тихо пропавшие объявления. Размерные шкалы работают и без
// скина: у них есть подстраховки, и пример берёт только их.
//
// Пробы здесь сторожат две противоположные цены сразу:
//   • ничего не потреблённого — единственный CSS-подпуть скелета чем-то использован;
//   • ничего лишнего — пример остаётся приёмом. Скелет класса `placed-once`, обвес в него не
//     заглянет, и разросшееся оформление станет чужой дизайн-системой без права на выпуск.

import { describe, expect, it } from "vitest";

import { readTemplate } from "./source.js";

const html = readTemplate("index.html");
const main = readTemplate("main.tsx");

/** Содержимое единственного блока оформления в разметке. */
const styling = /<style>([\s\S]*?)<\/style>/.exec(html)?.[1] ?? "";

/** Объявления вида `свойство: значение;` внутри блока — мера объёма примера. */
const declarations = styling.match(/^\s*[a-z-]+\s*:/gm) ?? [];

describe("скелет одевает кит, а не оставляет его голым", () => {
  it("держит ровно один блок оформления, и он в разметке", () => {
    // В разметке, потому что состав `dest`'ов заморожен пятью файлами: шестого (своего
    // `.css`) скелет не кладёт. Место временное и названо таковым в самом файле.
    expect(html.match(/<style>/g)).toHaveLength(1);
    expect(styling.trim()).not.toBe("");
  });

  it("цепляется за зацепку примитива, а не за его внутренности", () => {
    // `data-slot` примитив ставит ДО спреда пропсов — это ДЕФОЛТ-зацепка открытого API.
    // Селектор по внутренностям kobalte замёрз бы у потребителя и сломался бы её выпуском.
    expect(styling).toMatch(/\[data-slot="button"\]/);
    expect(styling).not.toMatch(/\[data-kb-|\.kb-/);
  });

  it("кнопка в точке входа не носит класса", () => {
    // Класс в скелете означал бы, что оформление приезжает из кода, а не из зацепки, — и
    // потребитель, стирая наш CSS, остался бы с классом-сиротой.
    expect(main).toMatch(/<Button>[^<]+<\/Button>/);
    expect(main).not.toMatch(/<Button[^>]*\bclass=/);
  });
});

describe("нет импорта, который ничем не потреблён", () => {
  it("базовый слой потреблён: оформление берёт производную шкалу", () => {
    // Шкалу радиусов считает `base.css` из одного семени (`--radius`), и у семени есть
    // подстраховка — значение приезжает и без скина. Ссылка на `--radius-*` это и есть
    // потребление единственного CSS-подпутя скелета.
    expect(styling).toMatch(/var\(--radius-[a-z0-9]+\)/);
  });

  it("не опирается ни на одну цветовую роль", () => {
    // Роли пусты, пока скин не надет. Правило на них выглядело бы рабочим и молча теряло бы
    // объявления у потребителя без скина — то есть у КАЖДОГО, кто только что поставил скелет.
    expect(styling).not.toMatch(/var\(--(?:primary|secondary|accent|muted|border|foreground)/);
    // Цвет вообще не приходит из переменных набора значений: их там больше нет.
    expect(styling).not.toMatch(/(?:^|[^-\w])color\s*:\s*var\(/);
    expect(styling).not.toMatch(/background(?:-color)?\s*:/);
  });

  it("единственный CSS-подпуть точки входа назван с расширением", () => {
    // Иначе `declare module '*.css'` из `vite/client` не сопоставится с текстом
    // спецификатора и `tsc` у потребителя упадёт с TS2882 (дефект нашла зона `reference`).
    const css = [...main.matchAll(/import "(@omnifield\/probe-web-style\/[^"]+)";/g)].map(
      (match) => match[1],
    );
    expect(css).toHaveLength(1);
    for (const subpath of css) {
      expect(subpath, subpath).toMatch(/\.css$/);
    }
  });
});

describe("пример остаётся приёмом, а не дизайн-системой", () => {
  it("одевает один примитив одним правилом", () => {
    // Каждый следующий селектор замерзает у потребителя навсегда. Приём показывает первый;
    // остальные — уже оформление чужого приложения, которое мы не сможем ни обновить, ни
    // забрать назад.
    expect(styling.match(/\{/g)).toHaveLength(1);
  });

  it("укладывается в десяток объявлений", () => {
    expect(declarations.length).toBeLessThanOrEqual(10);
  });

  it("не держит ни одного литерального цвета", () => {
    // Литеральный цвет не следует ни за режимом, ни за скином: он всплыл бы светлым пятном в
    // тёмной паре. Своего цвета скелет не заводит вовсе — приложение без скина обязано быть
    // голым, и это его рабочее состояние, а не поломка.
    expect(styling).not.toMatch(/#[0-9a-fA-F]{3,8}\b|\b(?:rgb|rgba|hsl|hsla|oklch)\(/);
  });

  it("объясняет себя прямо в файле", () => {
    // Дока доезжает к потребителю только тем, что лежит рядом: README обвеса у него не
    // окажется, а этот файл окажется. Поэтому над блоком стоит пояснение — что это приём,
    // и куда переносить оформление, когда его станет больше одного правила.
    expect(html).toMatch(/<!--[\s\S]*?-->\s*<style>/);
  });
});
