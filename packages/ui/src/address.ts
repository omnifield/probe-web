// ИМЕНА адресных атрибутов — названы здесь ОДИН раз на всю зону.
//
// Пару даёт `@zag-js/anatomy`: `data-scope` — имя компонента, `data-part` — имя части. Читать их
// приходится раньше, чем становится известен паспорт (по ним компонент и узнаётся), поэтому
// строки где-то написать всё же надо. Вопрос только в том, сколько раз.
//
// Написанные трижды — в ките, в читателе паспорта и в форме — они разъехались бы молча: пакет
// поменяет начертание, две правки сделают, третью забудут, и узел останется адресуемым только
// наполовину. Здесь их одно объявление, и в нём нет ничего, кроме двух строк: модуль намеренно
// пустой, чтобы его мог ввозить и подпуть данных, куда Solid не пускают.

/** Имя компонента на узле. */
export const SCOPE = "data-scope";

/** Имя части на узле. */
export const PART = "data-part";

/**
 * Адрес целиком — ровно два атрибута.
 *
 * «Ровно два» — это обещание: кит отбрасывает пришедший снаружи адрес, и отбрасывать он обязан
 * ТОЛЬКО эту пару. Состояния внешнего звена выражены другими атрибутами и обязаны доезжать.
 */
export const ADDRESS = [SCOPE, PART] as const;
