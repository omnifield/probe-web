// ВХОД/ВЫХОД ЛИСТА — паспорт формы (`PWEB-180` продолжение), РАНТАЙМ, не редакторская проза.
//
// Здесь, а не в `playground/`, тем же водоразделом, что у `passport.ts` и у кнопки
// (`../../button/entity/io.ts`): `entity/` — контракт, по которому компонент работает,
// `playground/` — то, что видит и настраивает человек в редакторе.
//
// Схема пишется инструментом `packages/io` (`z`, реэкспорт `zod`), НЕ раскрытым `zod` заново.
//
// Форма снята с настоящего входа `Listbox` (`../components/index.tsx`), не выдумана заново:
// `items` — ровно то, что принимает корень после того, как `collection` перестал быть
// обязанностью вызывающего (`PWEB-187` продолжение, 2026-08-30 — «на входе всё равно данные, а
// живой объект строится внутри, если он вообще нужен»). `label` — то же самое поле, что у
// кнопки: подпись, которую `playground/assemblies.ts` читает по `/label`.
//
// `value` в выходе — ровно то, что несёт `ValueChangeDetails.value` у `onValueChange`
// (`@zag-js/listbox`): массив выбранных ключей, ЛИСТ не решает, что они значат — так же, как
// кнопка не решает, что лежит в её `payload`.

import { z } from "@omnifield/probe-web-io";

/** Одна запись — то же самое, что `CollectionItem` у Ark, но как ПЛОСКИЕ данные, не класс. */
const item = z.object({
  value: z.string(),
  label: z.string(),
});

/** Что лист ждёт на входе: подпись и плоский перечень пунктов. */
export const input = z.object({
  label: z.string(),
  items: z.array(item),
});

/** Что лист отдаёт наружу при смене выбора — ключи выбранных пунктов, как есть. */
export const output = z.object({
  value: z.array(z.string()),
});
