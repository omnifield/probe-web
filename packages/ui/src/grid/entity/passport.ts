// РАНТАЙМ-паспорт сетки (`PWEB-115`, разнесено `PWEB-127`) — срез РАНТАЙМА.
//
// Состояний нет, как и у потока: раскладка ничего не хранит. Число колонок сюда тоже не
// попадает — это ВИД, и живёт он в правиле скина, а не в паспорте и не в разметке.
//
// ЭТОТ ФАЙЛ ТОЛЬКО РАНТАЙМ — уезжает в бандл приложения. Срез РЕДАКТОРА — в `playground/index.ts`.
//
// ## Почему это ОТДЕЛЬНЫЙ компонент, а не вариация потока
//
// Соблазн ровно один: если направление и зазор — вид, то и «сеточность» вид, а значит хватило бы
// одного компонента раскладки с двумя именами вариаций. Соблазн ложный, и ломается он на
// МЕХАНИКЕ АДРЕСА, а не на вкусе.
//
// Правило скина адресуется координатой: компонент, часть, состояние, вариация и ПРЕДОК — часть-
// владелец вместе с её состоянием. Вариации у предка в адресе нет и не заводится (страница
// «Скин»). Значит правило «ячейка ведёт себя так, потому что лежит в сетке, а не в потоке» при
// одном компоненте выразить нечем: у ячейки и у элемента потока была бы одна и та же координата,
// а различала бы их вариация ПРЕДКА, которой в адресе не существует.
//
// Разные компоненты дают это различие даром: `grid.cell` и `flow.item` — разные координаты, и
// правило каждой пишется независимо.

import { defineSettings, definePassport } from "@omnifield/probe-web-skin/model";
// ТИП пропов — только тип: `import type` стирается сборкой, и подпуть `./passport`
// остаётся данными без Solid. Нужен, чтобы ключи настроек сверялись с настоящими пропами.
import type { GridProps } from "../components/index.jsx";
import { anatomy } from "./anatomy.js";

export const passport = definePassport({
  anatomy,
  root: "root",
  parts: [{ name: "root", states: [] }, { name: "cell", states: [] }],
  variantAxis: {
    mark: { kind: "attribute", name: "data-variant" },
  },
  // Настроек из закрытого перечня сетка не принимает: число колонок — раскладочное свойство,
  // то есть ВИД, и приезжает скином.
  settings: defineSettings<GridProps>({}),
});
