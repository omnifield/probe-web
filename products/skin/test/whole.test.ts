// ПРОБА ЦЕЛОСТНОСТИ CSS: файл не оборван и не содержит блока без правил.
//
// ОПЛАЧЕНО ЖИВЫМ СЛУЧАЕМ. `playground.css` уехал в коммит обрезанным на середине медиа-блока —
// и это ничем не выстрелило: прогон проб зелёный (они смотрят только поставку), сборка проходит,
// а дев-сервер продолжал отдавать прежнюю версию файла. Поломка всплыла через два захода, когда
// в конец файла добавились новые правила и postcss впервые сказал «Unclosed block».
//
// Проверка нарочно грубая — баланс скобок и пустые блоки. Полноценный парсер здесь стоил бы
// зависимости ради того же ответа, а этот класс поломок ловится счётом.

import { describe, expect, it } from "vitest";

import { allCssFiles, stripComments } from "./css.js";

describe("CSS зоны цел", () => {
  for (const file of allCssFiles()) {
    it(`${file.name}: блоки закрыты`, () => {
      const css = stripComments(file.text);
      const open = (css.match(/\{/g) ?? []).length;
      const close = (css.match(/\}/g) ?? []).length;

      expect(
        close,
        `${file.name}: ${open} открывающих скобок против ${close} закрывающих — файл оборван`,
      ).toBe(open);
    });

    it(`${file.name}: нет блока без объявлений`, () => {
      // Пустой блок — след недописанной правки: селектор поставили, правила не написали. Вреда
      // он не делает, но означает «работа не закончена», а такое лучше видеть прогоном.
      const css = stripComments(file.text);
      const empty = [...css.matchAll(/([^{}]+)\{\s*\}/g)].map(([, head]) => head.trim());

      expect(empty, `пустые блоки в ${file.name}`).toEqual([]);
    });
  }

  it("стенд действительно попал в проверку", () => {
    // Иначе проба однажды начнёт смотреть только поставку и снова пропустит обрыв стенда.
    const names = allCssFiles().map((file) => file.name);

    expect(names, "стенда нет в перечне — проверка потеряла половину зоны").toContain(
      "playground.css",
    );
    expect(names).toContain("skin.css");
  });
});
