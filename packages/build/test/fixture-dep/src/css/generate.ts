// Третья роль этого же пакета: сосед, который свой CSS ПОРОЖДАЕТ, а не хранит файлом.
//
// Форма повторяет настоящего соседа зоны `style`: чистая функция без файловой системы и без
// аргументов, вынесенная на поверхность подпутём `./generate`, и CSS-подпуть рядом
// (`./made.css`), названный так, что имя функции из него выводится. По этой паре дев-сервер и
// опознаёт способность пакета — не по имени пакета.
//
// Перечень приходит ОТДЕЛЬНЫМ модулем (`marks.ts`): проба правит его, а не этот файл, — то есть
// требует, чтобы до отданного CSS доезжала транзитивная правка, а не только правка того модуля,
// который дев-сервер грузит напрямую.

import { MARKS } from "./marks.js";

/**
 * Содержимое `made.css` — то, что дев-сервер обязан отдать по подпутю `./made.css`.
 *
 * @returns текст таблицы стилей
 */
export function madeCss(): string {
  const lines = MARKS.map((mark) => `  --fixture-${mark}: 1;`);
  return `/* порождено generate.ts */\n:root {\n${lines.join("\n")}\n}\n`;
}
