// РУЧНАЯ часть базового слоя — единственный его кусок, написанный руками. Остальное
// порождается из данных зоны (`src/css/generate.ts`).
//
// ПОЧЕМУ СТРОКОЙ В МОДУЛЕ, А НЕ ФАЙЛОМ `.css` РЯДОМ (`PWEB-20`). Базовый CSS обязан
// порождаться ПО ТРЕБОВАНИЮ — в момент запроса, отражая текущие исходники, а не результат
// прошлой сборки. Значит порождение зовёт не только наш сборочный сценарий, но и дев-сервер,
// а он живёт в другой зоне. Ручная часть отдельным файлом заставила бы каждого зовущего знать
// путь к ней и уметь его прочитать: знание нашей раскладки уехало бы наружу, а генерация
// перестала бы быть чистой функцией и стала бы зависеть от того, откуда её позвали — из
// исходников, из сборки или из установки потребителя.
//
// Цена решения названа честно: этот CSS редактор подсвечивает как строку, а не как CSS.
// Взамен генерация везде одна и та же, и второй копии правды не возникает ни в одном из
// трёх мест, откуда её зовут.
//
// ─────────────────────────────────────────────────────────────────────────────────────────
// БАЗОВЫЙ СЛОЙ НЕ ОДЕВАЕТ. Решение user по `PWEB-39`, 2026-08-21.
//
// Отсюда ушли шесть объявлений вида на `body`: фон, цвет текста, начертание, кегль, высота
// строки, трекинг. Ушли не потому, что ссылались на роли, которых без темы нет, — это было
// лишь то, чем дефект стал ВИДЕН. Ушли потому, что базовый слой ими ОДЕВАЛ.
//
// Пять из шести НАСЛЕДУЮТСЯ. Это и есть суть: база не просто красила документ, она через
// наследование одевала кит. Кнопка, которую не одевал никто, получала от нас цвет текста,
// шрифт, кегль, высоту строки и трекинг — сама собой, ничего не спросив. «Нет скина —
// приложение голое» (`kb:PROBEWEB-11`) держалось на бумаге: голым кит не был никогда, на нём
// была наша одежда, просто невидимая в перечне правил скина.
//
// Шестое, фон, не наследуется — оно делало другое: объявляло страницу НАШЕЙ. Кто красит
// страницу, базовый слой не решает; замер `PWEB-39` показал, что сегодня её не красит никто,
// и это отдельный вопрос с отдельным владельцем.
//
// ЧТО ОСТАЛОСЬ И ПОЧЕМУ ЭТО НЕ ОДЕЖДА:
//
//  • сброс (`box-sizing`, `margin: 0`) — снятие решений БРАУЗЕРА, а не внесение своих. Ничего
//    не наследуется, ни один цвет и ни один размер не приходит от нас;
//  • токены движения — ЗНАЧЕНИЯ, а не применения. Объявленный токен не надет ни на что, пока
//    его не позвали; ровно так же здесь живут производные шкалы;
//  • `color-scheme` — разобран ниже отдельно.
//
// ─────────────────────────────────────────────────────────────────────────────────────────
// `COLOR-SCHEME` ОБЪЯВЛЯЕТ СПОСОБНОСТЬ, А НЕ ВЫБОР. Решение архитектора 2026-08-22, страница
// «Скин», раздел «Режим — половина скина, а не свойство документа» (`PWEB-50`).
//
// Было — `light` на корне и `dark` при классе, то есть базовый слой называл КОНКРЕТНЫЙ режим.
// Обосновано это было тем, что режим выбирает приложение и несёт классом, а мы лишь переводим
// его выбор на язык браузера. Довод держался на предпосылке, которой больше нет: режим
// принадлежал документу.
//
// Теперь режим принадлежит СКИНУ — обе половины его половины, и «нет скина — нет и режима».
// Назвать режим базе нечем: скина она не знает. Но и молчать нельзя — молчание браузер читает
// как выбор светлого, то есть молчание тоже выбор, просто необъявленный.
//
// Остаётся третье: `light dark` — «страница умеет обе, следуй за человеком». Это не вид от
// фреймворка, а его отсутствие: браузер рисует своё, ровно как рисовал бы без нас.
//
// СЛЕДСТВИЕ, названное прямо: голое приложение теперь следует за настройкой СИСТЕМЫ, а не за
// классом. Переключатель режима на приложении без скина не меняет ничего — это и есть гейт
// задачи, и держит его `test/mode.test.ts` живым документом, а не чтением.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ ЭТО НЕ НАШ ПРОБЕЛ: надетый скин обязан назвать браузеру свою
// половину сам — иначе системные элементы (полосы прокрутки, галочки, автозаполнение) пойдут
// за системой, а компоненты за скином, и на одном экране окажутся две правды. Объявить это
// может только тот, кто знает, какая половина надета, то есть механика скина. Заявка туда
// поднята; здесь этого места нет по построению.
//
// ─────────────────────────────────────────────────────────────────────────────────────────
// ИНВАРИАНТ, ставший сильнее прежнего: здесь нет не только литеральных цветов, но и ни одного
// объявления вида на документ. Держит `test/base-css.test.ts`, а не обещание в шапке.
//
// Текст работает без чего угодно рядом: своих значений он не ждёт вовсе, а размерные шкалы
// (порождённый блок ниже) несут дефолт прямо в `var(--семя, …)`, поэтому геометрия считается и
// без палитры.

