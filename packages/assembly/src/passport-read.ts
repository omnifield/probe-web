// ЧТЕНИЕ паспорта — самая узкая запись того, что механике сборки нужно от компонента.
//
// ## Почему здесь тип, а не импорт формы
//
// Форма паспорта живёт в ките (`@omnifield/probe-web-ui`, `passport-form.ts`), и дом у неё
// сегодня там потому, что там выписан первый паспорт. Механика сборки паспорт только ЧИТАЕТ —
// и зависеть в поставке на кит она не вправе: зависимость в поставку это cross-zone решение
// architect, а не правка владельца зоны. (Кит сам называет нейтральный дом формы открытым
// вопросом; механика — второй её читатель, и этим вопрос только подтверждается.)
//
// Поэтому здесь объявлено не второе описание паспорта, а ровно то, что механика с него
// снимает: имя компонента, его род, части, корневая часть и правило вложенности. Состояния,
// назначения и ось вариаций — предмет скина и редактора, механике они не нужны.
//
// ## Чего здесь НЕТ намеренно: самого правила допуска
//
// Решение «пускает ли часть внутрь себя вот это» принимает функция `admits`, живущая РЯДОМ С
// ФОРМОЙ, в ките. Там же и записано, почему: правило одно на всех читателей паспорта, а
// написанное вторым читателем разъезжается с написанным первым молча — оба остаются зелёными.
//
// Механика этому подчиняется буквально: своего правила не пишет, а ПРИНИМАЕТ его вместе с
// паспортами (см. `createRegistry`). Знание об иерархии родов — что значок подходит под место
// «любой компонент», а обратное неверно — остаётся в одном месте, и это место не здесь.
//
// Совпадение с настоящей формой стережёт не договорённость, а машина: проба
// `test/passport.test.ts` берёт НАСТОЯЩИЙ паспорт кнопки и настоящее правило допуска из кита
// (кит стоит в devDependencies, в поставку не едет) и проверяет, что они подходят сюда как
// есть. Разъедется форма — проба покраснеет в тот же прогон, а не у потребителя.

/**
 * Род — чем узел является, когда его кладут внутрь чужого узла.
 *
 * Перечень принадлежит паспорту, а не механике: новый род заводится решением там же, где
 * форма. Здесь он назван строкой намеренно — механика роды не сравнивает и не упорядочивает,
 * она их только передаёт правилу допуска.
 */
export type Genus = string;

/**
 * Кандидат на вложение: своя часть компонента либо содержимое потребителя, названное родом.
 *
 * Перечень ОДИН, потому что уровень один: часть компонента и есть вложенный компонент,
 * увиденный с другой стороны.
 */
export type Admission =
  | { readonly kind: "part"; readonly name: string }
  | { readonly kind: "content"; readonly genus: Genus };

/**
 * Часть компонента глазами механики сборки.
 *
 * Одно поле, и оно про вложенность. Состояния и назначение части адресуют ВИД, а вид — не
 * предмет этой механики.
 */
export interface ReadablePart {
  /** Имя части — ключ анатомии; из него собирается адрес узла `<компонент>.<часть>`. */
  readonly name: string;
  /**
   * Что допустимо внутри. Три состояния, и все три разные (форма паспорта, `PWEB-24`):
   * не объявлено — не запрещает ничего; пустой перечень — не пускает ничего; перечень —
   * допустимо ровно перечисленное.
   *
   * Механика это поле не истолковывает — передаёт правилу допуска целиком.
   */
  readonly accepts?: readonly Admission[];
}

/**
 * Паспорт компонента глазами механики сборки.
 *
 * `anatomy.keys()` здесь не роскошь рядом с `parts`: анатомия — ИСТОЧНИК перечня частей, а
 * `parts` лишь добавка к нему. Часть, объявленная анатомией и забытая в добавке, — это пробел
 * паспорта, и механика обязана его увидеть, а не молча считать, что частей меньше.
 */
export interface ReadablePassport {
  /** Имя компонента, оно же `data-scope` на каждом его узле. */
  readonly component: string;
  /** Чем компонент является, когда его кладут внутрь чужого узла. */
  readonly genus: Genus;
  /** Перечень частей, читаемый машиной. */
  readonly anatomy: { keys: () => string[] };
  /** Имя корневой части — с неё начинается компонент. */
  readonly root: string;
  /** Добавка к каждой части анатомии. */
  readonly parts: readonly ReadablePart[];
}

/**
 * Правило допуска — то, что механика НЕ пишет, а принимает вместе с паспортами.
 *
 * Объявлено МЕТОДОМ, а не полем-функцией, и это осознанно: параметры метода TypeScript сверяет
 * бивариантно, поэтому сюда подходит настоящая `admits` кита, объявленная над полной формой
 * части. Объяви мы поле-функцию — строгая проверка потребовала бы, чтобы наша узкая запись
 * части несла ВСЕ поля полной формы, то есть перестала быть узкой записью и стала копией.
 */
export interface AdmissionRule {
  /**
   * Пускает ли часть внутрь себя кандидата.
   *
   * @param part часть, ВНУТРЬ которой кладут
   * @param candidate что кладут
   */
  admits(part: ReadablePart, candidate: Admission): boolean;
}

/**
 * Часть паспорта по имени, либо `undefined` — если такой части компонент не объявлял.
 *
 * Обход массива, а не карта: частей у компонента единицы (у кнопки одна, у самого крупного
 * компонента Ark — полтора десятка), и карта здесь стоила бы дороже, чем экономила.
 *
 * @param passport паспорт компонента
 * @param name имя части
 */
export function partOf(passport: ReadablePassport, name: string): ReadablePart | undefined {
  return passport.parts.find((part) => part.name === name);
}
